function context = stage8_k2_snr_build_context(repo_dir)
%STAGE8_K2_SNR_BUILD_CONTEXT Load frozen models, registry, and evidence identity.

if nargin < 1 || isempty(repo_dir)
    [status, repo_dir] = system('git rev-parse --show-toplevel');
    if status ~= 0
        error('stage8_k2_snr_build_context:Repository', ...
            'Unable to locate the repository root.');
    end
    repo_dir = strtrim(repo_dir);
end
repo_dir = char(java.io.File(char(string(repo_dir))).getCanonicalPath());
constants = stage8_k2_snr_constants();
tp_context = stage8_k2_tp_build_context(repo_dir);
original_registry = stage8_k2_tp_build_registry( ...
    tp_context.plan.local_domain, tp_context.constants);
frozen_path = fullfile(repo_dir, 'innovation-mining', ...
    '31_stage8_k2_tangent_profile_trials.csv');
if ~isfile(frozen_path)
    error('stage8_k2_snr_build_context:Evidence', ...
        'Frozen evidence 31 is missing.');
end
frozen = readtable(frozen_path, 'TextType', 'string');
required = {'trial_id','method_id','noise_profile_id','L','snr_db', ...
    'profile_id','source_seed','noise_seed','element_trial_hash', ...
    'fit_valid','joint_RMSE_deg','truth_used_in_fit_flag'};
if height(frozen) ~= constants.method_row_count || ...
        ~all(ismember(required, frozen.Properties.VariableNames)) || ...
        any(logical(frozen.truth_used_in_fit_flag))
    error('stage8_k2_snr_build_context:FrozenEvidenceSchema', ...
        'Evidence 31 violates its frozen row or truth-isolation contract.');
end

identity_rows = cell(constants.trial_count, 1);
for index = 1:height(original_registry)
    spec = original_registry(index, :);
    rows = frozen(frozen.trial_id == spec.trial_id, :);
    hashes = unique(rows.element_trial_hash);
    if height(rows) ~= numel(constants.method_ids) || numel(hashes) ~= 1 || ...
            any(rows.noise_profile_id ~= spec.noise_profile_id) || ...
            any(double(rows.L) ~= spec.L) || ...
            any(double(rows.snr_db) ~= spec.snr_db) || ...
            any(rows.profile_id ~= spec.profile_id) || ...
            any(double(rows.source_seed) ~= spec.source_seed) || ...
            any(double(rows.noise_seed) ~= spec.noise_seed)
        error('stage8_k2_snr_build_context:FrozenTrialIdentity', ...
            'Evidence 31 and the frozen 72-trial registry disagree.');
    end
    identity_rows{index} = struct('trial_id', spec.trial_id, ...
        'element_trial_hash', hashes(1));
end
identity = struct2table(vertcat(identity_rows{:}));
if height(identity) ~= constants.trial_count || ...
        numel(unique(identity.trial_id)) ~= constants.trial_count
    error('stage8_k2_snr_build_context:TrialCount', ...
        'Frozen evidence does not contain 72 unique trial identities.');
end

context = struct('repo_dir', repo_dir, 'constants', constants, ...
    'tp_context', tp_context, 'plan', tp_context.plan, ...
    'stage5_locked', tp_context.stage5_locked, ...
    'primary_measurement_config_id', ...
    constants.primary_measurement_config_id, ...
    'original_registry', original_registry, ...
    'frozen_method_rows', frozen, ...
    'frozen_trial_identity', identity, ...
    'frozen_trials_path', frozen_path);
context.context_hash = stage8_k2_snr_stable_hash(constants.protocol, ...
    tp_context.context_hash, identity);
end
