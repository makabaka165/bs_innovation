function output = stage8_k2_snr_summarize( ...
    audit, registry, white_snr_trials, method_rows, context, ...
    runtime_root, test_output, timing)
%STAGE8_K2_SNR_SUMMARIZE Validate and write the registered evidence bundle.

constants = context.constants;
validate_inputs_local(audit, registry, white_snr_trials, method_rows, constants);
phase_a_summary = phase_a_summary_local(audit);
phase_b_summary = phase_b_summary_local(method_rows, constants);
comparison = comparison_local(audit, method_rows, context);
evidence_dir = fullfile(context.repo_dir, 'innovation-mining');
paths = struct( ...
    'audit_trials', fullfile(evidence_dir, ...
    '42_stage8_k2_original_snr_audit_trials.csv'), ...
    'audit_summary', fullfile(evidence_dir, ...
    '42_stage8_k2_original_snr_audit_summary.csv'), ...
    'white_registry', fullfile(evidence_dir, ...
    '42_stage8_k2_white_beamspace_control_registry.csv'), ...
    'white_snr_trials', fullfile(evidence_dir, ...
    '42_stage8_k2_white_beamspace_control_snr_trials.csv'), ...
    'method_results', fullfile(evidence_dir, ...
    '42_stage8_k2_white_beamspace_control_method_results.csv'), ...
    'white_summary', fullfile(evidence_dir, ...
    '42_stage8_k2_white_beamspace_control_summary.csv'), ...
    'comparison', fullfile(evidence_dir, ...
    '42_stage8_k2_snr_control_comparison.csv'), ...
    'report', fullfile(evidence_dir, ...
    '42_stage8_k2_snr_domain_validation.md'), ...
    'manifest', fullfile(evidence_dir, ...
    '42_stage8_k2_snr_runtime_manifest.json'));

writetable(audit, paths.audit_trials);
writetable(phase_a_summary, paths.audit_summary);
writetable(registry, paths.white_registry);
writetable(white_snr_trials, paths.white_snr_trials);
writetable(method_rows, paths.method_results);
writetable(phase_b_summary, paths.white_summary);
writetable(comparison, paths.comparison);
write_report_local(paths.report, audit, registry, ...
    phase_b_summary, constants, timing);

artifact_names = { ...
    'audit_trials','audit_summary','white_registry','white_snr_trials', ...
    'method_results','white_summary','comparison','report'};
artifacts = repmat(struct('artifact_id', '', 'path', '', 'sha256', ''), ...
    numel(artifact_names), 1);
for index = 1:numel(artifact_names)
    name = artifact_names{index};
    artifacts(index) = struct('artifact_id', name, ...
        'path', relative_path_local(paths.(name), context.repo_dir), ...
        'sha256', stage8_k2_snr_file_sha256(paths.(name)));
end
manifest = struct( ...
    'status', 'STAGE8_K2_SNR_DOMAIN_VALIDATION_COMPLETE', ...
    'protocol', constants.protocol, 'authorization', constants.authorization, ...
    'branch', constants.branch, 'starting_head', constants.starting_commit, ...
    'prompt_commit', git_output_local(context.repo_dir, ...
    'log -1 --format=%H --grep="docs(stage8-k2): define SNR domain validation"'), ...
    'tool_commit', git_output_local(context.repo_dir, ...
    'log -1 --format=%H --grep="analysis(stage8-k2): add beamspace SNR audit and control"'), ...
    'formal_run_head', git_output_local(context.repo_dir, 'rev-parse HEAD'), ...
    'matlab_release', version('-release'), ...
    'max_computational_threads', maxNumCompThreads, ...
    'runtime_root', runtime_root, ...
    'test_count', test_output.test_count, ...
    'original_hash_match_count', constants.trial_count, ...
    'white_registry_count', height(registry), ...
    'white_unique_hash_count', numel(unique(registry.element_trial_hash)), ...
    'method_row_count', height(method_rows), ...
    'truth_leakage_count', nnz(method_rows.truth_used_in_fit_flag), ...
    'max_white_target_error_db', max(abs( ...
    white_snr_trials.white_beam_snr_expected_db - ...
    white_snr_trials.white_beamspace_snr_target_db)), ...
    'phase_a_runtime_sec', timing.phase_a_runtime_sec, ...
    'smoke_runtime_sec', timing.smoke_runtime_sec, ...
    'phase_b_runtime_sec', timing.phase_b_runtime_sec, ...
    'total_runtime_sec', timing.total_runtime_sec, ...
    'tangent_algorithm_modified', false, 'whitening_removed', false, ...
    'monte_carlo_executed', false, ...
    'next_monte_carlo_authorized', false, ...
    'artifacts', artifacts);
write_json_local(paths.manifest, manifest);
copy_runtime_evidence_local(paths, runtime_root);
output = struct('status', manifest.status, 'phase_a_summary', phase_a_summary, ...
    'phase_b_summary', phase_b_summary, 'comparison', comparison, ...
    'manifest', manifest, 'evidence_paths', paths);
end

function validate_inputs_local(audit, registry, white_snr, methods, constants)
if height(audit) ~= constants.trial_count || ...
        height(registry) ~= constants.trial_count || ...
        height(white_snr) ~= constants.trial_count || ...
        height(methods) ~= constants.method_row_count || ...
        numel(unique(audit.trial_id)) ~= constants.trial_count || ...
        numel(unique(registry.trial_id)) ~= constants.trial_count || ...
        numel(unique(registry.element_trial_hash)) ~= constants.trial_count || ...
        numel(unique(methods.trial_id + "|" + methods.method_id)) ~= ...
        constants.method_row_count
    error('stage8_k2_snr_summarize:Cardinality', ...
        'Result rows are missing, duplicated, or have nonunique hashes.');
end
if any(methods.truth_used_in_fit_flag) || ...
        any(~isfinite(white_snr.white_beam_snr_expected_db)) || ...
        any(abs(white_snr.white_beam_snr_expected_db - ...
        white_snr.white_beamspace_snr_target_db) > constants.snr_db_tolerance)
    error('stage8_k2_snr_summarize:Integrity', ...
        'Truth isolation or expected-white-SNR integrity failed.');
end
valid = methods.fit_valid;
if any(valid & (~isfinite(methods.RSS) | ~isfinite(methods.loglik) | ...
        ~isfinite(methods.joint_RMSE_deg)))
    error('stage8_k2_snr_summarize:FiniteValidRows', ...
        'A valid method row contains a nonfinite registered output.');
end
end

