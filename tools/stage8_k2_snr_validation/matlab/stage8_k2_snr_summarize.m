function scopes = scopes_local(table_now, snr_name)
scopes = repmat(struct('type', "", 'value', "", 'mask', false(0, 1)), 0, 1);
scopes(end + 1) = struct('type', "ALL", 'value', "ALL", ...
    'mask', true(height(table_now), 1));
snr_values = unique(table_now.(snr_name), 'stable');
for value = reshape(snr_values, 1, [])
    scopes(end + 1) = struct('type', "SNR", 'value', string(value), ...
        'mask', table_now.(snr_name) == value); %#ok<AGROW>
end
for value = reshape(unique(table_now.profile_id, 'stable'), 1, [])
    scopes(end + 1) = struct('type', "PROFILE", 'value', value, ...
        'mask', table_now.profile_id == value); %#ok<AGROW>
end
for value = reshape(unique(table_now.noise_profile_id, 'stable'), 1, [])
    scopes(end + 1) = struct('type', "NOISE", 'value', value, ...
        'mask', table_now.noise_profile_id == value); %#ok<AGROW>
end
for value = reshape(unique(table_now.L, 'stable'), 1, [])
    scopes(end + 1) = struct('type', "L", 'value', string(value), ...
        'mask', table_now.L == value); %#ok<AGROW>
end
for snr = reshape(snr_values, 1, [])
    for profile = reshape(unique(table_now.profile_id, 'stable'), 1, [])
        scopes(end + 1) = struct('type', "SNR_X_PROFILE", ...
            'value', string(snr) + "|" + profile, ...
            'mask', table_now.(snr_name) == snr & ...
            table_now.profile_id == profile); %#ok<AGROW>
    end
    for noise = reshape(unique(table_now.noise_profile_id, 'stable'), 1, [])
        scopes(end + 1) = struct('type', "SNR_X_NOISE", ...
            'value', string(snr) + "|" + noise, ...
            'mask', table_now.(snr_name) == snr & ...
            table_now.noise_profile_id == noise); %#ok<AGROW>
    end
end
end

function write_report_local(path_now, audit, registry, summary, constants, timing)
fid = fopen(path_now, 'w');
if fid < 0
    error('stage8_k2_snr_summarize:ReportOpen', ...
        'Unable to open the validation report.');
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '# Stage8 K2 SNR Domain Validation\n\n');
fprintf(fid, 'Status: `STAGE8_K2_SNR_DOMAIN_VALIDATION_COMPLETE`\n\n');
fprintf(fid, 'Protocol: `%s`\n\n', constants.protocol);
fprintf(fid, '## Integrity\n\n');
fprintf(fid, '- Original element hashes: `72/72 exact`.\n');
fprintf(fid, '- White-control registry: `72/72`, unique hashes: `72/72`.\n');
fprintf(fid, '- Method rows: `216/216`; truth leakage: `0`.\n');
fprintf(fid, '- Maximum white-target error: `%.3g dB`.\n', max(abs( ...
    registry.resulting_white_beamspace_snr_expected_db - ...
    registry.white_beamspace_snr_target_db)));
fprintf(fid, '- Maximum raw covariance residual: `%.3g`.\n', ...
    max(audit.raw_covariance_residual));
fprintf(fid, '- Maximum whitening residual: `%.3g`.\n\n', ...
    max(audit.whitening_covariance_residual));
fprintf(fid, '## Original element-SNR mapping\n\n');
fprintf(fid, '| Element label (dB) | White SNR min | median | max |\n');
fprintf(fid, '|---:|---:|---:|---:|\n');
for label = constants.white_snr_targets_db
    rows = audit(audit.original_element_snr_label_db == label, :);
    fprintf(fid, '| %g | %.6f | %.6f | %.6f |\n', label, ...
        min(rows.white_beam_snr_expected_db), ...
        median(rows.white_beam_snr_expected_db), ...
        max(rows.white_beam_snr_expected_db));
end
fprintf(fid, '\nOverall raw peak-beam expected SNR: median `%.6f dB`, ', ...
    median(audit.raw_peak_beam_snr_expected_db));
fprintf(fid, 'p90 `%.6f dB`. Overall white receive gain: median ', ...
    percentile_local(audit.raw_peak_beam_snr_expected_db, 90));
fprintf(fid, '`%.6f dB`, range `[%.6f, %.6f] dB`.\n\n', ...
    median(audit.white_receive_gain_db), min(audit.white_receive_gain_db), ...
    max(audit.white_receive_gain_db));
fprintf(fid, '## White-beamspace-controlled results\n\n');
fprintf(fid, '| Method | Valid rate | Joint RMSE median | p90 | Fallback rate | Runtime median (s) |\n');
