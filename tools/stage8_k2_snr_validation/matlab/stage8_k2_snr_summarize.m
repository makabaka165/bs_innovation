function comparison = comparison_local(audit, method_rows, context)
rows = repmat(comparison_template_local(), 0, 1);
labels = context.constants.white_snr_targets_db;
methods = context.constants.method_ids;
for label = labels
    for method_index = 1:numel(methods)
        method_id = methods(method_index);
        frozen = context.frozen_method_rows( ...
            context.frozen_method_rows.snr_db == label & ...
            context.frozen_method_rows.method_id == method_id, :);
        [found, positions] = ismember(frozen.trial_id, audit.trial_id);
        if ~all(found)
            error('stage8_k2_snr_summarize:OriginalJoin', ...
                'Evidence 31 could not be joined to the Phase A audit.');
        end
        joined = audit(positions, :);
        row = comparison_template_local();
        row.experiment_id = "ORIGINAL_ELEMENT_CONTROL";
        row.control_domain = "ELEMENT_INPUT_EXPECTED_TOTAL_SNR";
        row.numeric_snr_label_db = label;
        row.method_id = method_id;
        row.trial_count = height(frozen);
        row.valid_rate = mean(double(frozen.fit_valid));
        row.element_snr_expected_median_db = median( ...
            joined.element_snr_expected_db);
        row.element_snr_expected_min_db = min(joined.element_snr_expected_db);
        row.element_snr_expected_max_db = max(joined.element_snr_expected_db);
        row.white_snr_expected_median_db = median( ...
            joined.white_beam_snr_expected_db);
        row.white_snr_expected_min_db = min(joined.white_beam_snr_expected_db);
        row.white_snr_expected_max_db = max(joined.white_beam_snr_expected_db);
        valid = logical(frozen.fit_valid);
        row.joint_RMSE_median_deg = finite_stat_local( ...
            frozen.joint_RMSE_deg(valid), 'median');
        row.joint_RMSE_p90_deg = percentile_local( ...
            frozen.joint_RMSE_deg(valid), 90);
        row.interpretation_note = ...
            "HISTORICAL_LABEL_CONTROLS_ELEMENT_INPUT_SNR";
        rows(end + 1, 1) = row; %#ok<AGROW>

        current = method_rows( ...
            method_rows.white_beamspace_snr_target_db == label & ...
            method_rows.method_id == method_id, :);
        row = comparison_template_local();
        row.experiment_id = "PAIRED_WHITE_BEAMSPACE_CONTROL";
        row.control_domain = string(context.constants.control_domain);
        row.numeric_snr_label_db = label;
        row.method_id = method_id;
        row.trial_count = height(current);
        row.valid_rate = mean(double(current.fit_valid));
        row.element_snr_expected_median_db = median( ...
            current.element_snr_expected_db);
        row.element_snr_expected_min_db = min(current.element_snr_expected_db);
        row.element_snr_expected_max_db = max(current.element_snr_expected_db);
        row.white_snr_expected_median_db = median( ...
            current.white_beam_snr_expected_db);
        row.white_snr_expected_min_db = min(current.white_beam_snr_expected_db);
        row.white_snr_expected_max_db = max(current.white_beam_snr_expected_db);
        valid = current.fit_valid;
        row.joint_RMSE_median_deg = finite_stat_local( ...
            current.joint_RMSE_deg(valid), 'median');
        row.joint_RMSE_p90_deg = percentile_local( ...
            current.joint_RMSE_deg(valid), 90);
        row.interpretation_note = ...
            "LABEL_CONTROLS_EXPECTED_WHITENED_BEAMSPACE_SNR";
        rows(end + 1, 1) = row; %#ok<AGROW>
    end
end
comparison = struct2table(rows);
end

