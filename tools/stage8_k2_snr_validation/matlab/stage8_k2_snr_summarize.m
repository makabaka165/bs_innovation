function summary = phase_b_summary_local(method_rows, constants)
scopes = scopes_local(method_rows, 'white_beamspace_snr_target_db');
rows = repmat(phase_b_template_local(), 0, 1);
for scope_index = 1:numel(scopes)
    scope = scopes(scope_index);
    for method_index = 1:numel(constants.method_ids)
        method_id = constants.method_ids(method_index);
        subset = method_rows(scope.mask & method_rows.method_id == method_id, :);
        valid = subset.fit_valid;
        row = phase_b_template_local();
        row.row_type = "METHOD";
        row.scope_type = scope.type;
        row.scope_value = scope.value;
        row.method_id = method_id;
        row.total_count = height(subset);
        row.valid_count = nnz(valid);
        row.valid_rate = nnz(valid) / max(1, height(subset));
        row = assign_method_stats_local(row, subset, valid);
        rows(end + 1, 1) = row; %#ok<AGROW>
    end
    for reference = ["CORE_LITE", "CORE_PLUS"]
        tangent = method_rows(scope.mask & ...
            method_rows.method_id == "TANGENT_PROFILE_SAFE", :);
        baseline = method_rows(scope.mask & method_rows.method_id == reference, :);
        tangent = sortrows(tangent, 'trial_id');
        baseline = sortrows(baseline, 'trial_id');
        if height(tangent) ~= height(baseline) || ...
                any(tangent.trial_id ~= baseline.trial_id)
            error('stage8_k2_snr_summarize:Pairing', ...
                'A paired method comparison lost trial identity.');
        end
        common = tangent.fit_valid & baseline.fit_valid & ...
            isfinite(tangent.joint_RMSE_deg) & ...
            isfinite(baseline.joint_RMSE_deg);
        delta = tangent.joint_RMSE_deg(common) - ...
            baseline.joint_RMSE_deg(common);
        row = phase_b_template_local();
        row.row_type = "PAIRWISE";
        row.scope_type = scope.type;
        row.scope_value = scope.value;
        row.method_id = "TANGENT_PROFILE_SAFE";
        row.reference_method_id = reference;
        row.comparison_id = "TANGENT_VS_" + reference;
        row.paired_count = nnz(common);
        row.wins = nnz(delta < -constants.paired_tie_tolerance_deg);
        row.ties = nnz(abs(delta) <= constants.paired_tie_tolerance_deg);
        row.losses = nnz(delta > constants.paired_tie_tolerance_deg);
        rows(end + 1, 1) = row; %#ok<AGROW>
    end
end
summary = struct2table(rows);
end

function row = assign_method_stats_local(row, subset, valid)
metric_names = {'joint_RMSE_deg','center_error_deg', ...
    'direction_axis_error_deg','rho_error_deg','rho_relative_error', ...
    'separation_vector_error_deg','runtime_sec'};
prefixes = {'joint_RMSE_deg','center_error_deg', ...
    'axis_error_deg','rho_error_deg','rho_relative_error', ...
    'separation_vector_error_deg','runtime_sec'};
for index = 1:numel(metric_names)
    values = subset.(metric_names{index})(valid);
    row.(['median_', prefixes{index}]) = finite_stat_local(values, 'median');
    row.(['p90_', prefixes{index}]) = percentile_local(values, 90);
end
row.upgrade_rate = mean(double(subset.upgrade_flag));
row.fallback_rate = mean(double(subset.fallback_flag));
row.mean_score_call_count = mean(double(subset.score_call_count));
row.mean_SVD_call_count = mean(double(subset.SVD_call_count));
row.resulting_element_snr_median_db = finite_stat_local( ...
    subset.element_snr_expected_db, 'median');
row.resulting_element_snr_min_db = finite_stat_local( ...
    subset.element_snr_expected_db, 'min');
row.resulting_element_snr_max_db = finite_stat_local( ...
    subset.element_snr_expected_db, 'max');
row.realized_white_snr_median_db = finite_stat_local( ...
    subset.white_beam_snr_realized_db, 'median');
row.realized_white_snr_p90_db = percentile_local( ...
    subset.white_beam_snr_realized_db, 90);
end

