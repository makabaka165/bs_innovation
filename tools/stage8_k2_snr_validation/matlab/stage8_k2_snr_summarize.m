clear cleanup
end

function copy_runtime_evidence_local(paths, runtime_root)
names = fieldnames(paths);
for index = 1:numel(names)
    source = paths.(names{index});
    [~, name, extension] = fileparts(source);
    destination = fullfile(runtime_root, [name, extension]);
    [ok, message] = copyfile(source, destination, 'f');
    if ~ok
        error('stage8_k2_snr_summarize:RuntimeEvidence', '%s', message);
    end
end
end

function value = finite_stat_local(values, operation)
values = double(values(isfinite(values)));
if isempty(values)
    value = NaN;
else
    value = feval(operation, values);
end
end

function value = percentile_local(values, percentile)
values = sort(double(values(isfinite(values))));
if isempty(values)
    value = NaN;
elseif numel(values) == 1
    value = values(1);
else
    position = 1 + (numel(values) - 1) * percentile / 100;
    lower_index = floor(position);
    upper_index = ceil(position);
    weight = position - lower_index;
    value = (1 - weight) * values(lower_index) + ...
        weight * values(upper_index);
end
end

function relative = relative_path_local(path_now, repo_dir)
prefix = [char(java.io.File(repo_dir).getCanonicalPath()), filesep];
canonical = char(java.io.File(path_now).getCanonicalPath());
if startsWith(lower(canonical), lower(prefix))
    relative = strrep(canonical(numel(prefix) + 1:end), filesep, '/');
else
    relative = canonical;
end
end

