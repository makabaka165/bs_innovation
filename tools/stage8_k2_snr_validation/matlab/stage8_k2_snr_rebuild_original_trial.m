function trial = stage8_k2_snr_rebuild_original_trial(spec, context)
%STAGE8_K2_SNR_REBUILD_ORIGINAL_TRIAL Mechanically reconstruct one TP1 trial.

fixture = stage8_k2_snr_build_source_fixture(spec, context);
unscaled_signal = fixture.manifold.A * fixture.source_unscaled;
target_energy = 10 ^ (spec.snr_db / 10) * numel(unscaled_signal);
source_scale = sqrt(target_energy / ...
    max(norm(unscaled_signal, 'fro') ^ 2, realmin));
source = fixture.source_unscaled * source_scale;
signal = fixture.manifold.A * source;
[noise, noise_debug] = generate_stage8_element_noise( ...
    fixture.model, spec.L, 1, spec.noise_seed);
Y_element = signal + noise;
element_trial_hash = stage8_k2_tp_stable_hash( ...
    'ELEMENT_TRIAL', char(spec.trial_id), Y_element, ...
    fixture.truth_angles_deg, double(spec.L), double(spec.snr_db), ...
    double(spec.source_seed), double(spec.noise_seed), ...
    char(spec.noise_profile_id));
identity = context.frozen_trial_identity( ...
    context.frozen_trial_identity.trial_id == spec.trial_id, :);
hash_match = height(identity) == 1 && ...
    identity.element_trial_hash == string(element_trial_hash);
if ~hash_match
    error('stage8_k2_snr_rebuild_original_trial:ElementHashMismatch', ...
        ['STAGE8_K2_SNR_DOMAIN_VALIDATION_INVALID: reconstructed ', ...
        'element data does not match frozen evidence 31.']);
end
trial = struct('Y_element', Y_element, ...
    'truth_angles_deg', fixture.truth_angles_deg, ...
    'model', fixture.model, 'source_matrix', source, ...
    'source_unscaled', fixture.source_unscaled, ...
    'source_scale', source_scale, 'signal_element', signal, ...
    'noise_element', noise, 'source_phase_rad', fixture.source_phase_rad, ...
    'source_info', fixture.source_info, 'noise_debug', noise_debug, ...
    'element_trial_hash', string(element_trial_hash), ...
    'element_hash_match_flag', hash_match, ...
    'truth_used_in_fit_flag', false);
end
