function result = test_expected_vs_realized_noise_contract(context)
%TEST_EXPECTED_VS_REALIZED_NOISE_CONTRACT Prove alpha ignores noise realization.

registry = stage8_k2_snr_test_fixture(context).white_registry;
selected = registry.profile_id == "P1" & ...
    registry.noise_profile_id == "WHITE" & registry.L == 4 & ...
    registry.white_beamspace_snr_target_db == 0;
spec_a = registry(selected, :);
spec_b = spec_a;
spec_b.trial_id = "SW1_TEST_ALTERNATE_NOISE";
spec_b.noise_seed = spec_a.noise_seed + 100000;
trial_a = stage8_k2_snr_generate_white_control_trial(spec_a, context);
trial_b = stage8_k2_snr_generate_white_control_trial(spec_b, context);
metric_a = stage8_k2_snr_compute_metrics(trial_a);
metric_b = stage8_k2_snr_compute_metrics(trial_b);
assert(abs(trial_a.source_scale - trial_b.source_scale) <= ...
    context.constants.source_scale_relative_tolerance * ...
    max(1, abs(trial_a.source_scale)), ...
    'test_expected_vs_realized_noise_contract:Scale', ...
    'Changing only noise seed changed the signal scale.');
assert(norm(trial_a.noise_element - trial_b.noise_element, 'fro') > 0 && ...
    abs(metric_a.white_beam_snr_realized_db - ...
    metric_b.white_beam_snr_realized_db) > 1e-12, ...
    'test_expected_vs_realized_noise_contract:Realized', ...
    'Changing noise did not change the realized white SNR.');
result = struct('pass', true, ...
    'alpha_absolute_difference', abs(trial_a.source_scale - ...
    trial_b.source_scale), ...
    'realized_snr_difference_db', abs( ...
    metric_a.white_beam_snr_realized_db - ...
    metric_b.white_beam_snr_realized_db));
end
