function result = test_stage8_k2_mc_W_C_T_equivalence(~, outputs)
%TEST_STAGE8_K2_MC_W_C_T_EQUIVALENCE Check production thresholds.
rows = outputs.static.production;
pass = height(rows) == 16 && all(rows.pass) && ...
    max(rows.W_error) <= 1e-11 && max(rows.C_error) <= 1e-11 && ...
    max(rows.T_error) <= 1e-10;
assert(pass, 'test_stage8_k2_mc_W_C_T_equivalence:Failed');
result = struct('pass',pass,'model_count',height(rows), ...
    'max_W_error',max(rows.W_error),'max_C_error',max(rows.C_error), ...
    'max_T_error',max(rows.T_error));
end
