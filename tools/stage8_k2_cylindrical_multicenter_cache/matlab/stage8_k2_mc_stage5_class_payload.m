function payload = stage8_k2_mc_stage5_class_payload(locked, physical_center)
%STAGE8_K2_MC_STAGE5_CLASS_PAYLOAD Remove absolute azimuth placement.

required = {'conventional_center_deg','az_beam_deg','el_beam_deg', ...
    'azimuth_offsets_deg','elevation_offsets_deg','max_iter', ...
    'relative_score_tolerance','angle_tolerance_deg', ...
    'main_num_multi_start','direct_num_multi_start', ...
    'success_gate_az_deg','success_gate_el_deg', ...
    'wrong_peak_gate_pair_deg','penalty_pair_error_deg','phase_factor'};
if ~(isstruct(locked) && isscalar(locked) && all(isfield(locked, required)))
    error('stage8_k2_mc_stage5_class_payload:Config', ...
        'The Stage5 configuration is incomplete.');
end
payload = struct( ...
    'relative_conventional_center_deg', ...
        [locked.conventional_center_deg(1) - physical_center, ...
        locked.conventional_center_deg(2)], ...
    'relative_az_beam_deg',locked.az_beam_deg - physical_center, ...
    'el_beam_deg',locked.el_beam_deg, ...
    'azimuth_offsets_deg',locked.azimuth_offsets_deg, ...
    'elevation_offsets_deg',locked.elevation_offsets_deg, ...
    'max_iter',locked.max_iter, ...
    'relative_score_tolerance',locked.relative_score_tolerance, ...
    'angle_tolerance_deg',locked.angle_tolerance_deg, ...
    'main_num_multi_start',locked.main_num_multi_start, ...
    'direct_num_multi_start',locked.direct_num_multi_start, ...
    'success_gate_az_deg',locked.success_gate_az_deg, ...
    'success_gate_el_deg',locked.success_gate_el_deg, ...
    'wrong_peak_gate_pair_deg',locked.wrong_peak_gate_pair_deg, ...
    'penalty_pair_error_deg',locked.penalty_pair_error_deg, ...
    'phase_factor',locked.phase_factor);
payload = round_numeric_local(payload);
end

function value = round_numeric_local(value)
names = fieldnames(value);
for index = 1:numel(names)
    item = value.(names{index});
    if isnumeric(item)
        value.(names{index}) = round(double(item), 12);
    end
end
end
