function value = fallback_status_local(whitener)
value = 'NOT_APPLICABLE';
if ~whitener.all_full_row_rank
    value = gate_status_local(whitener.max_row_space_projector_error, ...
        whitener.thresholds.row_space_projector_error);
end
end

function value = gate_status_local(metric,threshold)
value = 'FAIL';
if metric <= threshold
    value = 'PASS';
end
end

function value = exact_status_local(metric,expected)
value = 'FAIL';
if metric == expected
    value = 'PASS';
end
end
