        'GATED_CONDITIONING_INVESTIGATED_COORDINATE_MAP', ...
        whitener.thresholds.Q_unitarity_error, ...
        gate_status_local(whitener.max_Q_unitarity_error, ...
        whitener.thresholds.Q_unitarity_error); ...
    'MAX_WHITENER_ALIGNMENT_ERROR',whitener.max_alignment_error, ...
        'GATED_BASIS_INVARIANT_COORDINATE_MAP', ...
        whitener.thresholds.alignment_error, ...
