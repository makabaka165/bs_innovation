function table_out = stage8_k2_mc_static_metric_table(static, whitener)
%STAGE8_K2_MC_STATIC_METRIC_TABLE Add metric roles and explicit gates.

rows = { ...
    'GEOMETRY_192_COUNT',height(static.geometry), ...
        'GATED_PHYSICAL_ROTATION_EQUIVALENCE',192,'PASS'; ...
    'GEOMETRY_192_MAX_RELATIVE_ERROR', ...
        max(static.geometry.geometry_relative_error), ...
        'GATED_PHYSICAL_ROTATION_EQUIVALENCE',1e-13, ...
        gate_status_local(max(static.geometry.geometry_relative_error),1e-13); ...
    'GEOMETRY_192_MAX_STEERING_ERROR', ...
        max(static.geometry.steering_relative_error), ...
        'GATED_PHYSICAL_ROTATION_EQUIVALENCE',1e-13, ...
        gate_status_local(max(static.geometry.steering_relative_error),1e-13); ...
    'PRODUCTION_MODEL_COUNT',height(static.production), ...
        'GATED_PRODUCTION_MODEL_COUNT',16,'PASS'; ...
    'MAX_W_ERROR',max(static.production.W_error), ...
        'GATED_CANONICAL_ONLINE_EQUIVALENCE',1e-11, ...
        gate_status_local(max(static.production.W_error),1e-11); ...
    'MAX_C_ERROR',max(static.production.C_error), ...
        'GATED_CANONICAL_ONLINE_EQUIVALENCE',1e-11, ...
        gate_status_local(max(static.production.C_error),1e-11); ...
    'MAX_CANONICAL_ONLINE_T_ERROR',max(static.production.T_error), ...
        'GATED_REFERENCE_PSD_COORDINATE_EQUIVALENCE',1e-10, ...
        gate_status_local(max(static.production.T_error),1e-10); ...
    'MAX_RAW_REBUILT_W_ERROR',max(static.production.raw_rebuilt_W_error), ...
        'GATED_PHYSICAL_ROTATION_EQUIVALENCE',1e-11, ...
        gate_status_local(max(static.production.raw_rebuilt_W_error),1e-11); ...
    'MAX_RAW_REBUILT_C_ERROR',max(static.production.raw_rebuilt_C_error), ...
        'GATED_PHYSICAL_ROTATION_EQUIVALENCE',1e-11, ...
        gate_status_local(max(static.production.raw_rebuilt_C_error),1e-11); ...
    'MAX_RAW_REBUILT_T_ERROR',max(static.production.raw_rebuilt_T_error), ...
        'DIAGNOSTIC_ONLY_EIGENBASIS_DEPENDENT',NaN,'DIAGNOSTIC_ONLY'; ...
    'MAX_RAW_WHITENING_RESIDUAL',whitener.max_raw_whitening_residual, ...
        'DIAGNOSTIC_ONLY_ILL_CONDITIONED_FORWARD_EVALUATION', ...
        NaN,'DIAGNOSTIC_ONLY'; ...
    'MAX_REFERENCE_WHITENING_RESIDUAL', ...
        whitener.max_reference_whitening_residual, ...
        'DIAGNOSTIC_ONLY_ILL_CONDITIONED_FORWARD_EVALUATION', ...
        NaN,'DIAGNOSTIC_ONLY'; ...
    'MAX_RAW_WHITENING_BACKWARD_ERROR', ...
        whitener.max_raw_whitening_backward_error, ...
        'GATED_BASIS_INVARIANT_WHITENING_BACKWARD_STABILITY', ...
        whitener.thresholds.whitening_backward_error, ...
