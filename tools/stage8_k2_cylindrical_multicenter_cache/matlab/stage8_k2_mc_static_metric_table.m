        whitener.max_row_space_projector_error, ...
        'FALLBACK_ONLY_RANK_DEFICIENT_COORDINATE_MAP', ...
        whitener.thresholds.row_space_projector_error, ...
        fallback_status_local(whitener); ...
    'MAX_G_ERROR',max(static.production.G_error), ...
