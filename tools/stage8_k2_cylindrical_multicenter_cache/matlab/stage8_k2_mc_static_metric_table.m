        whitener.thresholds.whitening_backward_error); ...
    'MAX_REFERENCE_WHITENING_BACKWARD_ERROR', ...
        whitener.max_reference_whitening_backward_error, ...
        'GATED_BASIS_INVARIANT_WHITENING_BACKWARD_STABILITY', ...
        whitener.thresholds.whitening_backward_error, ...
