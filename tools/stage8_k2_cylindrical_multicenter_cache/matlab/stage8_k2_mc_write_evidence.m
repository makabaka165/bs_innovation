    runtime.status,runtime.case_count,runtime.pair_count,runtime.root_call_count);
fprintf(fid,'## Direct Answers\n\n');
fprintf(fid,['1. Reference requested center = %.1f deg; actual physical ', ...
    'center = %.1f deg; reference column = %d. Values come from ', ...
    '`stage8_k2_mc_reference_spec(repo_dir)`.\n'], ...
    spec.reference_requested_center_az_deg, ...
    spec.reference_physical_center_az_deg,spec.reference_center_column);
fprintf(fid,'2. Selected physical center offsets = `%s`; runtime sentinel uses `%s`, read from the saved runtime rows/schedule.\n', ...
    vector_text_local(spec.selected_center_offsets), ...
    vector_text_local(runtime_offsets_local(runtime,schedule)));
