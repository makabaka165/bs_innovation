    'Independently rebuilt W and C agree at double-precision scale. ', ...
    'The independently eig-rebuilt T has elementwise diagnostic %.17g and may differ in basis under clustered eigenvalues. ', ...
    'The online rotation class selects the reference PSD-whitening coordinate; this canonical T value is not independent eig-rebuild elementwise equality.\n'], ...
    max(static.production.W_error),max(static.production.C_error), ...
    max(static.production.T_error),max(static.production.raw_rebuilt_T_error));
fprintf(fid,['6. Raw/reference whitener diagnostics pass across %d bundles: ', ...
    'direct forward residuals %.17g / %.17g are conditioning diagnostics ', ...
    '(maximum covariance condition number %.17g), while basis-invariant ', ...
    'covariance backward errors %.17g / %.17g pass at 1e-10. ', ...
    'The near-unitary Q error %.17g passes the investigated 1e-7 limit ', ...
    '(10x the default), and alignment residual %.17g passes at 1e-10.\n'], ...
    whitener.case_count,whitener.max_raw_whitening_residual, ...
    whitener.max_reference_whitening_residual, ...
    whitener.max_covariance_condition_number, ...
    whitener.max_raw_whitening_backward_error, ...
    whitener.max_reference_whitening_backward_error, ...
    whitener.max_Q_unitarity_error,whitener.max_alignment_error);
