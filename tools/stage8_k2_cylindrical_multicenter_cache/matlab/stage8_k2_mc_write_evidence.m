function manifest = stage8_k2_mc_write_evidence(repo_dir, runtime_root)
%STAGE8_K2_MC_WRITE_EVIDENCE Write corrected aggregate repository evidence.

if nargin < 1 || isempty(repo_dir)
    [status, repo_dir] = system('git rev-parse --show-toplevel');
    if status ~= 0
        error('stage8_k2_mc_write_evidence:Repository', ...
            'Unable to locate the repository root.');
    end
    repo_dir = strtrim(repo_dir);
end
if nargin < 2 || isempty(runtime_root)
    runtime_root = ...
        'E:\bs_innovation_runtime\stage8_k2_cylindrical_multicenter_cache_v1';
end
repo_dir = char(java.io.File(char(string(repo_dir))).getCanonicalPath());
runtime_root = char(java.io.File(char(string(runtime_root))).getCanonicalPath());
scope = stage8_k2_mc_add_paths(repo_dir); %#ok<NASGU>
assert_runtime_provenance_local(repo_dir);

static_loaded = load(fullfile(runtime_root,'static','static_output.mat'),'output');
semantics_loaded = load(fullfile(runtime_root,'semantics','semantics_output.mat'),'output');
lifecycle_loaded = load(fullfile(runtime_root,'lifecycle','lifecycle_output.mat'),'output');
runtime_loaded = load(fullfile(runtime_root,'runtime_sentinel','runtime_output.mat'),'output');
schedule = readtable(fullfile(runtime_root,'runtime_sentinel', ...
    'runtime_schedule.csv'),'TextType','string');
static = static_loaded.output;
semantics = semantics_loaded.output;
lifecycle = lifecycle_loaded.output;
runtime = runtime_loaded.output;
validate_reused_outputs_local(static,semantics,lifecycle,runtime,schedule);

spec = stage8_k2_mc_reference_spec(repo_dir);
validate_reference_spec_local(spec);
whitener = stage8_k2_mc_whitener_basis_diagnostics(repo_dir,spec);
original_tests = stage8_k2_mc_run_tests(repo_dir,runtime_root);

evidence_dir = fullfile(repo_dir,'innovation-mining');
static_path = fullfile(evidence_dir, ...
    '55_stage8_k2_cylindrical_multicenter_cache_static.csv');
semantics_path = fullfile(evidence_dir, ...
    '55_stage8_k2_cylindrical_multicenter_cache_semantics.csv');
lifecycle_path = fullfile(evidence_dir, ...
    '55_stage8_k2_cylindrical_multicenter_cache_lifecycle.csv');
runtime_path = fullfile(evidence_dir, ...
    '55_stage8_k2_cylindrical_multicenter_cache_runtime_sentinel.csv');
validation_path = fullfile(evidence_dir, ...
    '55_stage8_k2_cylindrical_multicenter_cache_validation.md');
manifest_path = fullfile(evidence_dir, ...
    '55_stage8_k2_cylindrical_multicenter_cache_manifest.json');

static_metrics = stage8_k2_mc_static_metric_table(static,whitener);
writetable(static_metrics,static_path);
writetable(semantics.semantics,semantics_path);
writetable(lifecycle.summary,lifecycle_path);
writetable(runtime.summary,runtime_path);
write_validation_local(validation_path,repo_dir,runtime_root, ...
    spec,runtime,schedule,static,semantics,lifecycle,whitener,original_tests);
manifest = build_manifest_local(repo_dir,runtime_root,spec,runtime,schedule, ...
    static,semantics,lifecycle,whitener,original_tests, ...
    static_path,semantics_path,lifecycle_path,runtime_path, ...
    validation_path,manifest_path);
write_json_local(manifest_path,manifest);
end

function assert_runtime_provenance_local(repo_dir)
runtime_code_commit = 'ad6a015ca53185552ebda1b95e645be057559c99';
[status,~] = system(sprintf( ...
    'git -C "%s" merge-base --is-ancestor %s HEAD', ...
    repo_dir,runtime_code_commit));
if status ~= 0
    error('stage8_k2_mc_write_evidence:RuntimeProvenance', ...
        'BLOCKED_RUNTIME_PROVENANCE_NOT_ANCESTOR.');
end
end

function validate_reference_spec_local(spec)
cfg = sim_cfg();
if abs(spec.reference_requested_center_az_deg - ...
        cfg.beam.azSectorCenter) > 1e-12 || ...
        spec.reference_center_column ~= 5 || ...
        abs(spec.reference_physical_center_az_deg - 7.5) > 1e-12 || ...
        abs(stage8_k2_mc_periodic_difference( ...
        spec.reference_requested_center_az_deg, ...
        spec.reference_physical_center_az_deg)) <= 1e-12
    error('stage8_k2_mc_write_evidence:ReferenceIdentity', ...
        'BLOCKED_FIXED_REFERENCE_CENTER_UNRESOLVED.');
end
end

function validate_reused_outputs_local(static,semantics,lifecycle,runtime,schedule)
runtime_offsets = sort(runtime_offsets_local(runtime,schedule));
schedule_offsets = sort(unique(double(schedule.center_offset))).';
valid = strcmp(static.status, ...
        'STAGE8_K2_MULTICENTER_STATIC_ROTATION_PASS') && ...
    strcmp(semantics.status, ...
        'STAGE8_K2_MULTICENTER_SEMANTIC_PASS_24_OF_24') && ...
    strcmp(lifecycle.status, ...
        'STAGE8_K2_MULTICENTER_LIFECYCLE_POSITIVE') && ...
    strcmp(runtime.status,'ONLINE_SENTINEL_POSITIVE') && ...
    semantics.case_count == 24 && semantics.semantic_pass_count == 24 && ...
    semantics.t4_cache_query_count == 0 && ...
    semantics.truth_leakage_count == 0 && ...
    runtime.case_count == 12 && runtime.pair_count == 48 && ...
    runtime.root_call_count == 96 && height(schedule) == 48 && ...
    numel(runtime_offsets) == 3 && isequal(runtime_offsets,schedule_offsets);
if ~valid
    error('stage8_k2_mc_write_evidence:ReusedOutputIdentity', ...
        'BLOCKED_EXISTING_GATE_OUTPUT_IDENTITY_MISMATCH.');
end
end

