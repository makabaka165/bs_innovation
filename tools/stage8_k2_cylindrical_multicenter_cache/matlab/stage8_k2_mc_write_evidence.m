function offsets = runtime_offsets_local(runtime,schedule)
if isfield(runtime,'raw') && istable(runtime.raw) && ...
        ismember('center_offset',runtime.raw.Properties.VariableNames)
    offsets = unique(double(runtime.raw.center_offset),'stable').';
elseif isfield(runtime,'raw') && isstruct(runtime.raw) && ...
        isfield(runtime.raw,'center_offset')
    offsets = unique(double(runtime.raw.center_offset),'stable').';
elseif ismember('center_offset',schedule.Properties.VariableNames)
    offsets = unique(double(schedule.center_offset),'stable').';
else
    error('stage8_k2_mc_write_evidence:RuntimeOffsets', ...
        'Runtime center offsets are absent from the reused evidence.');
end
end

function value = overall_value_local(runtime,name)
row = runtime.summary(runtime.summary.row_type == "OVERALL",:);
value = row.(name);
end

function write_json_local(path_now,value)
fid = fopen(path_now,'w','n','UTF-8');
if fid < 0
    error('stage8_k2_mc_write_evidence:ManifestOpen', ...
        'Unable to open the manifest output file.');
end
cleanup = onCleanup(@() fclose(fid));
fwrite(fid,jsonencode(value,'PrettyPrint',true),'char');
fwrite(fid,newline,'char');
end

function write_validation_local(path_now,repo_dir,runtime_root, ...
    spec,runtime,schedule,static,semantics,lifecycle,whitener,tests)
