    error('stage8_k2_mc_write_evidence:ValidationOpen', ...
        'Unable to open the validation output file.');
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid,'# Stage8 K2 Cylindrical Multi-Center Cache Validation\n\n');
fprintf(fid,'Runtime root: `%s`\n\n',strrep(runtime_root,'\','/'));
fprintf(fid,'Evidence reuse: `REUSED_EXISTING_GATE_A_B_C_D_OUTPUTS_NO_LARGE_RERUN`.\n\n');
fprintf(fid,'## Gate Status\n\n');
fprintf(fid,'- Gate A: `%s` (`%d/192` geometry, `%d/16` production, `%d/3` negative controls).\n', ...
    static.status,nnz(static.geometry.pass),nnz(static.production.pass), ...
    nnz(static.negative_controls.pass));
fprintf(fid,'- Gate B: `%s` (`%d/24`, controls `%d/6`, covariance `%d/8`).\n', ...
    semantics.status,semantics.semantic_pass_count, ...
    semantics.control_pass_count,semantics.covariance_pass_count);
