function result = test_music_l1_not_applicable()
%TEST_MUSIC_L1_NOT_APPLICABLE Verify L=1 is N/A rather than a failure.

entry = struct('G_beamspace', complex(zeros(3, 1)), ...
    'A_element_white', complex(zeros(4, 1)), ...
    'standalone_precompute_runtime_sec', 0);
resources = struct('grid_size', [1, 1], 'grid_point_count', 1, ...
    'az_grid_deg', 0, 'el_grid_deg', 0);
result = stage8_k2_cb_music(complex(zeros(3, 1)), entry, ...
    resources, 'BEAMSPACE', 1, stage8_k2_cb_constants());
assert(~result.applicable && ~result.fit_valid && ...
    result.applicability_status == ...
    "NOT_APPLICABLE_INSUFFICIENT_SAMPLE_SUBSPACE_RANK" && ...
    result.eig_call_count == 0, ...
    'test_music_l1_not_applicable:Status', ...
    'L=1 MUSIC must be N/A without an eigendecomposition.');
fprintf('test_music_l1_not_applicable PASS\n');
end
