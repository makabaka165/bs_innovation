function registry = stage8_k2_cb_build_registry(context)
%STAGE8_K2_CB_BUILD_REGISTRY Reuse and verify the frozen TP1 registry.

if nargin < 1 || ~isstruct(context)
    error('stage8_k2_cb_build_registry:Context', ...
        'A classical-baseline context is required.');
end
registry = stage8_k2_tp_build_registry( ...
    context.plan.local_domain, stage8_k2_tp_constants());
identity = context.frozen_trial_identity;
if height(registry) ~= context.constants.trial_count || ...
        ~isequal(registry.trial_id, identity.trial_id)
    error('stage8_k2_cb_build_registry:Identity', ...
        'The TP1 registry no longer matches frozen evidence order.');
end
checks = registry.noise_profile_id == identity.noise_profile_id & ...
    registry.L == identity.L & registry.snr_db == identity.snr_db & ...
    registry.profile_id == identity.profile_id & ...
    registry.source_seed == identity.source_seed & ...
    registry.noise_seed == identity.noise_seed;
if ~all(checks)
    error('stage8_k2_cb_build_registry:FactorMismatch', ...
        'A frozen registry factor or seed differs from evidence 31.');
end
end
