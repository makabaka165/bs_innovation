function output = stage8_k2_wacb_verify(repo_dir, runtime_root)
%STAGE8_K2_WACB_VERIFY Independently audit without rerunning estimators.

if nargin < 1 || isempty(repo_dir)
    [status, repo_dir] = system('git rev-parse --show-toplevel');
    if status ~= 0
        error('stage8_k2_wacb_verify:Repository', ...
            'Unable to locate the repository root.');
    end
    repo_dir = strtrim(repo_dir);
end
constants = stage8_k2_wacb_constants();
if nargin < 2 || isempty(runtime_root)
    runtime_root = constants.runtime_root;
end
repo_dir = char(java.io.File(char(string(repo_dir))).getCanonicalPath());
runtime_root = char(java.io.File(char(string(runtime_root))).getCanonicalPath());
if ~strcmp(runtime_root, char(java.io.File(constants.runtime_root).getCanonicalPath()))
    error('stage8_k2_wacb_verify:RuntimeRoot', ...
        'Independent audit requires the fixed runtime root.');
end
if ~strcmp(version('-release'), '2022b') || maxNumCompThreads ~= 1
    error('stage8_k2_wacb_verify:MATLABRuntime', ...
        'Independent audit requires R2022b with -singleCompThread.');
end
try, pool = gcp('nocreate'); catch, pool = []; end
if ~isempty(pool)
    error('stage8_k2_wacb_verify:ParallelPool', ...
        'Independent audit forbids an active parallel pool.');
end
scope = stage8_k2_wacb_add_paths(repo_dir); %#ok<NASGU>
context = stage8_k2_wacb_build_context(repo_dir);
preflight = stage8_k2_wacb_preflight(repo_dir, constants, true);
if ~preflight.pass
    error('stage8_k2_wacb_verify:Preflight', '%s', preflight.last_error);
end
registry_loaded = load(fullfile(runtime_root, 'registry', ...
    'registry.mat'), 'registry', 'registry_hash', '-mat');
formal_loaded = load(fullfile(runtime_root, ...
    'formal_execution_state.mat'), 'formal_state', '-mat');
registry = registry_loaded.registry;
registry_hash = registry_loaded.registry_hash;
formal = formal_loaded.formal_state;
expected_hash = stage8_k2_wacb_stable_hash('FORMAL_REGISTRY', registry, ...
    context.evidence44.identity, context.evidence46.identity, ...
    constants.protocol);
if ~strcmp(registry_hash, expected_hash) || ...
        ~strcmp(formal.protocol, constants.protocol) || ...
        ~strcmp(formal.formal_head, preflight.head) || ...
        ~strcmp(formal.context_hash, context.context_hash) || ...
        ~strcmp(formal.code_identity, context.code_identity.tree_hash) || ...
        ~strcmp(formal.registry_hash, registry_hash) || formal.test_count ~= 13
    error('stage8_k2_wacb_verify:FormalIdentity', ...
        'Formal registry, code, head, or tests changed.');
end
merged = stage8_k2_wacb_merge( ...
    runtime_root, registry, context, registry_hash);
maximum_target_error = 0;
for index = 1:height(registry)
    [trial, ~, identity] = stage8_k2_wacb_reconstruct_trial( ...
        registry(index, :), context);
    maximum_target_error = max(maximum_target_error, ...
        identity.white_target_error_db);
    clear trial
    if mod(index, 240) == 0
        fprintf('Independent reconstruction %d/1680\n', index);
    end
end
if maximum_target_error > constants.snr_db_tolerance
    error('stage8_k2_wacb_verify:WhiteTarget', ...
        'Independent white-SNR target audit failed.');
end
root = fullfile(repo_dir, 'innovation-mining');
manifest_path = fullfile(root, ...
    '48_stage8_k2_white_snr_all_classical_runtime_manifest.json');
results_path = fullfile(root, ...
    '48_stage8_k2_white_snr_new_classical_method_results.csv');
diagnostics_path = fullfile(root, ...
    '48_stage8_k2_white_snr_new_classical_diagnostics.csv');
plot_path = fullfile(root, ...
    '48_stage8_k2_white_snr_all_method_plot_data.csv');
spectra_path = fullfile(root, ...
    '48_stage8_k2_white_snr_representative_spectra.mat');
index_path = fullfile(root, ...
    '48_stage8_k2_white_snr_representative_spectra_index.csv');
required = {manifest_path, results_path, diagnostics_path, plot_path, ...
    spectra_path, index_path, fullfile(runtime_root, 'complete_run.mat')};
if ~all(cellfun(@isfile, required))
    error('stage8_k2_wacb_verify:Missing', ...
        'A finalized output or complete marker is missing.');
end
manifest = jsondecode(fileread(manifest_path));
if ~strcmp(manifest.status, 'FINALIZED_AWAITING_INDEPENDENT_AUDIT') || ...
        ~strcmp(manifest.independent_audit_status, 'PENDING') || ...
        manifest.registry_count ~= 1680 || manifest.checkpoint_count ~= 1680 || ...
        manifest.new_method_row_count ~= 6720 || ...
        manifest.diagnostic_row_count ~= 6720 || ...
        manifest.all_method_row_count ~= 16800 || ...
        manifest.element_music_applicable_count ~= 1120 || ...
        manifest.gfbss_applicable_count ~= 1260 || ...
        manifest.root_music_applicable_count ~= 630 || ...
        manifest.ls_esprit_applicable_count ~= 630 || ...
        manifest.truth_leakage_count ~= 0 || ...
        manifest.profile_leakage_count ~= 0 || ...
        manifest.existing_method_rerun_count ~= 0 || ...
        numel(manifest.artifacts) ~= 30
    error('stage8_k2_wacb_verify:ManifestSchema', ...
        'Finalized manifest counts or isolation are invalid.');
end
for index = 1:numel(manifest.artifacts)
    artifact = manifest.artifacts(index);
    path_now = fullfile(repo_dir, strrep(artifact.path, '/', filesep));
    if ~isfile(path_now) || ...
            ~strcmpi(stage8_k2_wacb_file_sha256(path_now), artifact.sha256)
        error('stage8_k2_wacb_verify:ArtifactHash', ...
            'Independent artifact hash failed: %s', artifact.path);
    end
end
results = readtable(results_path, 'TextType', 'string');
diagnostics = readtable(diagnostics_path, 'TextType', 'string');
plot_data = readtable(plot_path, 'TextType', 'string');
index_table = readtable(index_path, 'TextType', 'string');
loaded_spectra = load(spectra_path, 'representative_spectra', '-mat');
if height(results) ~= 6720 || height(diagnostics) ~= 6720 || ...
        height(plot_data) ~= 16800 || height(index_table) ~= 56 || ...
        numel(loaded_spectra.representative_spectra) ~= 56 || ...
        ~strcmp(stage8_k2_wacb_stable_hash( ...
        loaded_spectra.representative_spectra), ...
        stage8_k2_wacb_stable_hash(merged.representative_spectra)) || ...
        any(results.truth_used_in_fit_flag) || ...
        any(results.profile_used_in_fit_flag) || ...
        any(results.tangent_used_in_start_flag) || ...
        any(results.core_used_in_start_flag) || ...
        any(results.full4d_used_in_start_flag)
    error('stage8_k2_wacb_verify:CommittedTables', ...
        'Committed table or representative-spectrum integrity failed.');
end
audit = struct('status', ...
    'STAGE8_K2_WHITE_SNR_ALL_CLASSICAL_BASELINE_INDEPENDENT_AUDIT_PASS', ...
    'protocol', constants.protocol, 'formal_head', preflight.head, ...
    'code_identity', context.code_identity.tree_hash, ...
    'registry_hash', registry_hash, ...
    'evidence44_identity', context.evidence44.identity, ...
    'evidence46_identity', context.evidence46.identity, ...
    'checkpoint_count', merged.scan.completed_count, ...
    'new_method_row_count', height(results), ...
    'diagnostic_row_count', height(diagnostics), ...
    'all_method_row_count', height(plot_data), ...
    'reconstruction_match_count', height(registry), ...
    'representative_spectra_match_count', 56, ...
    'maximum_white_target_error_db', maximum_target_error, ...
    'artifact_hash_match_count', numel(manifest.artifacts), ...
    'existing_method_rerun_count', 0, ...
    'completed_utc', stage8_k2_mc_utc_now());
stage8_k2_wacb_write_json_atomic(fullfile(runtime_root, 'audit', ...
    'independent_audit.json'), audit);
save(fullfile(runtime_root, 'audit', 'independent_audit.mat'), ...
    'audit', '-mat');
manifest.status = ...
    'STAGE8_K2_WHITE_SNR_ALL_CLASSICAL_BASELINE_COMPARISON_COMPLETE';
manifest.terminal_status = manifest.status;
manifest.independent_audit_status = 'PASS';
manifest.independent_audit_utc = audit.completed_utc;
manifest.independent_reconstruction_match_count = height(registry);
manifest.independent_checkpoint_count = merged.scan.completed_count;
manifest.independent_new_method_row_count = height(results);
manifest.independent_diagnostic_row_count = height(diagnostics);
manifest.independent_all_method_row_count = height(plot_data);
manifest.independent_representative_spectra_match_count = 56;
manifest.independent_artifact_hash_match_count = numel(manifest.artifacts);
manifest.independent_existing_method_rerun_count = 0;
manifest.next = 'READY_FOR_GIT_CLOSEOUT';
stage8_k2_wacb_write_json_atomic(manifest_path, manifest);
output = struct('status', manifest.status, 'audit', audit, ...
    'manifest_path', manifest_path, 'next', 'READY_FOR_GIT_CLOSEOUT');
fprintf('%s\n', output.status);
end
