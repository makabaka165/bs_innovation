function state = stage8_k2_wacb_registry_prepare( ...
    runtime_root, registry, context, preflight)
%STAGE8_K2_WACB_REGISTRY_PREPARE Create or validate resumable runtime state.

registry_hash = stage8_k2_wacb_stable_hash('FORMAL_REGISTRY', registry, ...
    context.evidence44.identity, context.evidence46.identity, ...
    context.constants.protocol);
directories = {'controller','registry','checkpoints','status','merged', ...
    'audit','logs'};
if isfile(runtime_root)
    error('stage8_k2_wacb_registry_prepare:RuntimeFile', ...
        'The fixed runtime root is an existing file.');
end
if ~isfolder(runtime_root) && ~mkdir(runtime_root)
    error('stage8_k2_wacb_registry_prepare:RuntimeCreate', ...
        'Unable to create the fixed runtime root.');
end
for index = 1:numel(directories)
    path_now = fullfile(runtime_root, directories{index});
    if ~isfolder(path_now) && ~mkdir(path_now)
        error('stage8_k2_wacb_registry_prepare:Directory', ...
            'Unable to create runtime directory: %s', path_now);
    end
end
registry_path = fullfile(runtime_root, 'registry', 'registry.mat');
formal_path = fullfile(runtime_root, 'formal_execution_state.mat');
if ~isfile(registry_path) && ~isfile(formal_path)
    temporary = [registry_path, '.tmp'];
    save(temporary, 'registry', 'registry_hash', '-mat');
    [ok, message] = movefile(temporary, registry_path);
    if ~ok, error('stage8_k2_wacb_registry_prepare:Move', '%s', message); end
    writetable(registry, fullfile(runtime_root, 'registry', 'registry.csv'));
    stage8_k2_wacb_write_text_atomic(fullfile(runtime_root, 'registry', ...
        'registry_hash.txt'), [registry_hash, newline]);
    stage8_k2_wacb_write_text_atomic(fullfile(runtime_root, 'registry', ...
        'code_identity.txt'), [context.code_identity.tree_hash, newline]);
    formal_state = struct('protocol', context.constants.protocol, ...
        'formal_head', preflight.head, 'context_hash', context.context_hash, ...
        'code_identity', context.code_identity.tree_hash, ...
        'registry_hash', registry_hash, ...
        'evidence44_identity', context.evidence44.identity, ...
        'evidence46_identity', context.evidence46.identity, ...
        'test_count', 13, 'test_status', '13/13 PASS', ...
        'created_utc', stage8_k2_mc_utc_now());
    temporary = [formal_path, '.tmp'];
    save(temporary, 'formal_state', '-mat');
    [ok, message] = movefile(temporary, formal_path);
    if ~ok, error('stage8_k2_wacb_registry_prepare:Move', '%s', message); end
    mode = "NEW";
elseif xor(isfile(registry_path), isfile(formal_path))
    error('stage8_k2_wacb_registry_prepare:PartialState', ...
        'Existing runtime has a partial scientific identity.');
else
    loaded = load(registry_path, 'registry', 'registry_hash', '-mat');
    formal_loaded = load(formal_path, 'formal_state', '-mat');
    formal_state = formal_loaded.formal_state;
    if ~strcmp(loaded.registry_hash, registry_hash) || ...
            ~strcmp(stage8_k2_wacb_stable_hash('FORMAL_REGISTRY', ...
            loaded.registry, context.evidence44.identity, ...
            context.evidence46.identity, context.constants.protocol), ...
            registry_hash) || ...
            ~strcmp(formal_state.protocol, context.constants.protocol) || ...
            ~strcmp(formal_state.formal_head, preflight.head) || ...
            ~strcmp(formal_state.context_hash, context.context_hash) || ...
            ~strcmp(formal_state.code_identity, ...
            context.code_identity.tree_hash) || ...
            ~strcmp(formal_state.registry_hash, registry_hash) || ...
            string(formal_state.evidence44_identity) ~= ...
            context.evidence44.identity || ...
            string(formal_state.evidence46_identity) ~= ...
            context.evidence46.identity || formal_state.test_count ~= 13
        error('stage8_k2_wacb_registry_prepare:Identity', ...
            'Stored formal registry, code, evidence, or tests changed.');
    end
    mode = "RESUME";
end
state = struct('mode', mode, 'registry_hash', registry_hash, ...
    'formal_state', formal_state);
end
