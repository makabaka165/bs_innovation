    "# Stage8 K2 Unified White-SNR All-Classical Comparison"; ""; ...
    "Status: `FINALIZED_AWAITING_INDEPENDENT_AUDIT`"; ""; ...
    "The comparison reconstructed 1680 immutable evidence-44 trials and ran"; ...
    "only the four preregistered new methods. The six evidence-44/46 methods"; ...
    "were read without refitting (`existing_method_rerun_count = 0`)."; ""; ...
    "## Integrity"; ""; ...
    "- checkpoints: `1680/1680`;"; ...
    "- new method rows: `6720`;"; ...
    "- new diagnostic rows: `6720`;"; ...
    "- unified plot rows: `16800`;"; ...
    "- representative spectra: `56`;"; ...
    "- truth/profile/start leakage: `0`;"; ...
    "- Element MUSIC applicable: `1120`;"; ...
    "- GFBSS-MUSIC applicable: `1260`;"; ...
    "- Root-MUSIC applicable: `630`;"; ...
    "- LS-ESPRIT applicable: `630`."; ""; ...
    "## Interpretation boundary"; ""; ...
    "White SNR is the common experimental coordinate, not an estimator input"; ...
    "for element-domain methods. Structural N/A rows are excluded from RMSE"; ...
    "and are not counted as Tangent wins. Pairwise statements use common-valid"; ...
    "trials only. Exact-cell P90 values with N=10 are descriptive, not stable"; ...
    "tail estimates. The three comparison tiers are not interchangeable"; ...
    "hardware interfaces. No global superiority claim, online selector, or"; ...
    "production threshold is created."; ""; ...
    "## New-method scientific states"; ""];
for index = 1:numel(interpretation)
    lines(end + 1) = "- `" + string(interpretation(index).method_id) + ...
        "`: `" + string(interpretation(index).scientific_state) + "`."; %#ok<AGROW>
end
lines = [lines; ""; "Next: `INDEPENDENT_AUDIT`"];
if height(merged.new_rows) ~= constants.new_method_row_count || ...
        height(summaries.overall) ~= 70
    error('stage8_k2_wacb_summarize:ReportIntegrity', ...
        'Report inputs are incomplete.');
end
stage8_k2_wacb_write_text_atomic(path_now, join(lines, newline) + newline);
end

function controller = controller_counts_local(runtime_root)
controller = struct('trial_launch_count', 0, 'resume_launch_count', 0, ...
    'finalization_launch_count', 0, 'audit_launch_count', 0);
path_now = fullfile(runtime_root, 'controller', 'controller_state.json');
if ~isfile(path_now), return; end
stored = jsondecode(fileread(path_now));
names = fieldnames(controller);
for index = 1:numel(names)
    if isfield(stored, names{index})
        controller.(names{index}) = double(stored.(names{index}));
    end
end
end

function path_relative = relative_path_local(path_now, repo_dir)
canonical = char(java.io.File(char(string(path_now))).getCanonicalPath());
prefix = [char(java.io.File(repo_dir).getCanonicalPath()), filesep];
if ~startsWith(lower(canonical), lower(prefix))
    error('stage8_k2_wacb_summarize:ArtifactScope', ...
        'Artifact is outside the repository.');
end
path_relative = strrep(canonical(numel(prefix) + 1:end), filesep, '/');
end
