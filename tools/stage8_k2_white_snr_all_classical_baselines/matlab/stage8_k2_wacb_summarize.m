function interpretation = interpretation_local(overall, constants)
methods = constants.method_ids;
items = repmat(struct('method_id', '', 'scientific_state', '', ...
    'first_valid_rate_ge_050_snr_db', NaN, ...
    'first_robustly_comparable_snr_db', NaN), numel(methods), 1);
for index = 1:numel(methods)
    selected = sortrows(overall(overall.method_id == methods(index), :), ...
        'white_beamspace_snr_target_db');
    first_valid = find(selected.valid_rate >= 0.5, 1);
    first_robust = find(selected.comparability_class == ...
        "ROBUSTLY_COMPARABLE", 1);
    if isempty(first_valid), valid_snr = NaN; else
        valid_snr = selected.white_beamspace_snr_target_db(first_valid); end
    if isempty(first_robust), robust_snr = NaN; else
        robust_snr = selected.white_beamspace_snr_target_db(first_robust); end
    if any(selected.comparability_class == "ROBUSTLY_COMPARABLE")
        state = 'ROBUST_REGION_IDENTIFIED';
    elseif any(selected.valid_count > 0)
        state = 'APPLICABILITY_LIMITED';
    elseif any(selected.applicable_count > 0)
        state = 'NO_VALID_REGION';
    else
        state = 'STRUCTURAL_REFERENCE_ONLY';
    end
    items(index) = struct('method_id', char(methods(index)), ...
        'scientific_state', state, ...
        'first_valid_rate_ge_050_snr_db', valid_snr, ...
        'first_robustly_comparable_snr_db', robust_snr);
end
interpretation = items;
end

