function row = stage8_k2_wacb_result_row( ...
    spec, trial, snr_row, result, constants)
%STAGE8_K2_WACB_RESULT_ROW Join identity and post-fit evaluation metrics.

row = template_local();
row.trial_id = string(spec.trial_id);
row.global_trial_index = double(spec.global_trial_index);
row.element_trial_hash = string(trial.element_trial_hash);
row.measurement_hash = string(trial.measurement_hash);
row.method_id = string(result.method_id);
if row.method_id == "ELEMENT_MUSIC_K2"
    row.method_family = "MUSIC";
    row.comparison_tier = "TIER_B_FULL_ELEMENT_2D_MANIFOLD";
    row.uses_full_2d_cylinder_manifold = true;
else
    row.method_family = "VERTICAL_SUBSPACE_PLUS_AZ_CML";
    row.comparison_tier = "TIER_C_VERTICAL_ULA_PLUS_AZ_CML";
    row.uses_vertical_ula_stage = true;
end
row.observation_domain = "ELEMENT";
row.same_hardware_interface_to_tangent = false;
row.white_beamspace_snr_target_db = ...
    double(spec.white_beamspace_snr_target_db);
copy_snr = {'element_snr_expected_db','element_snr_realized_db', ...
    'raw_beam_snr_expected_db','raw_beam_snr_realized_db', ...
    'white_beam_snr_expected_db','white_beam_snr_realized_db', ...
    'raw_peak_beam_snr_expected_db','k2_projected_snr_expected_db', ...
    'k2_projected_snr_realized_db','white_receive_gain_db'};
for index = 1:numel(copy_snr)
    if ismember(copy_snr{index}, snr_row.Properties.VariableNames)
        row.(copy_snr{index}) = double(snr_row.(copy_snr{index}));
    end
end
row.noise_profile_id = string(spec.noise_profile_id);
row.L = double(spec.L);
row.profile_id = string(spec.profile_id);
row.replicate_id = double(spec.replicate_id);
row.base_realization_index = double(spec.base_realization_index);
row.source_seed = double(spec.source_seed);
row.noise_seed = double(spec.noise_seed);
row.applicable = logical(result.applicable);
row.applicability_status = string(result.applicability_status);
row.applicability_uses_registered_scenario_flag = logical(get_local( ...
    result, 'applicability_uses_registered_scenario_flag', false));
row.fit_valid = logical(result.fit_valid);
row.fit_status = string(result.fit_status);
row.failure_stage = string(get_local(result, 'failure_stage', ...
    failure_stage_local(row)));
row.angles_hat_deg = string(mat2str(result.angles_hat_deg, 17));
if isequal(size(result.angles_hat_deg), [2, 2])
    row.azimuths_hat_deg = string(mat2str(result.angles_hat_deg(:, 1).', 17));
    row.elevations_hat_deg = string(mat2str(result.angles_hat_deg(:, 2).', 17));
end
row.RSS = double(get_local(result, 'rss', NaN));
row.loglik = double(get_local(result, 'loglik_concentrated', NaN));
row.effective_rank = double(get_local(result, 'effective_rank', 0));
row.score_call_count = double(get_local(result, 'score_call_count', 0));
row.SVD_call_count = double(get_local(result, 'svd_call_count', 0));
row.eig_call_count = double(get_local(result, 'eig_call_count', 0));
row.runtime_sec = double(get_local(result, 'runtime_sec', 0));
row.preprocess_runtime_sec = double(get_local(result, ...
    'preprocess_runtime_sec', 0));
row.elevation_runtime_sec = double(get_local(result, ...
    'elevation_runtime_sec', 0));
row.conditional_az_runtime_sec = double(get_local(result, ...
    'conditional_az_runtime_sec', 0));
row.truth_used_in_fit_flag = logical(get_local(result, ...
    'truth_used_in_fit_flag', false));
row.profile_used_in_fit_flag = logical(get_local(result, ...
    'profile_used_in_fit_flag', false));
row.tangent_used_in_start_flag = logical(get_local(result, ...
    'tangent_used_in_start_flag', false));
row.core_used_in_start_flag = logical(get_local(result, ...
    'core_used_in_start_flag', false));
row.full4d_used_in_start_flag = logical(get_local(result, ...
    'full4d_used_in_start_flag', false));
if row.fit_valid
    metrics = stage8_k2_cb_metrics(result.angles_hat_deg, ...
        trial.truth_angles_deg, constants);
    row.joint_RMSE_deg = metrics.joint_RMSE_deg;
    row.azimuth_RMSE_deg = metrics.azimuth_RMSE_deg;
    row.elevation_RMSE_deg = metrics.elevation_RMSE_deg;
    row.center_error_deg = metrics.center_error_deg;
    row.axis_error_deg = metrics.axis_error_deg;
    row.rho_error_deg = metrics.separation_error_deg;
    row.rho_relative_error = metrics.separation_error_deg / ...
        max(metrics.separation_true_deg, realmin('double'));
    row.separation_vector_error_deg = metrics.separation_vector_error_deg;
end
end

function value = failure_stage_local(row)
if ~row.applicable
    value = "STRUCTURAL_NA";
elseif row.fit_valid
    value = "NONE";
elseif row.method_id == "ELEMENT_MUSIC_K2"
    value = "ELEMENT_MUSIC";
else
    value = "ELEVATION_OR_CONDITIONAL_AZIMUTH";
end
end

function row = template_local()
row = struct('trial_id', "", 'global_trial_index', 0, ...
    'element_trial_hash', "", 'measurement_hash', "", ...
    'method_id', "", 'method_family', "", 'observation_domain', "", ...
    'comparison_tier', "", 'same_hardware_interface_to_tangent', false, ...
    'uses_full_2d_cylinder_manifold', false, ...
    'uses_vertical_ula_stage', false, ...
    'white_beamspace_snr_target_db', NaN, ...
    'element_snr_expected_db', NaN, 'element_snr_realized_db', NaN, ...
    'raw_beam_snr_expected_db', NaN, 'raw_beam_snr_realized_db', NaN, ...
    'white_beam_snr_expected_db', NaN, ...
    'white_beam_snr_realized_db', NaN, ...
    'raw_peak_beam_snr_expected_db', NaN, ...
    'k2_projected_snr_expected_db', NaN, ...
    'k2_projected_snr_realized_db', NaN, ...
    'white_receive_gain_db', NaN, 'noise_profile_id', "", ...
    'L', 0, 'profile_id', "", 'replicate_id', 0, ...
    'base_realization_index', 0, 'source_seed', 0, 'noise_seed', 0, ...
    'applicable', false, 'applicability_status', "NOT_RUN", ...
    'applicability_uses_registered_scenario_flag', false, ...
    'fit_valid', false, 'fit_status', "NOT_RUN", ...
    'failure_stage', "NOT_RUN", 'angles_hat_deg', "[NaN NaN;NaN NaN]", ...
    'azimuths_hat_deg', "[NaN NaN]", ...
    'elevations_hat_deg', "[NaN NaN]", 'RSS', NaN, 'loglik', NaN, ...
    'effective_rank', 0, 'joint_RMSE_deg', NaN, ...
    'azimuth_RMSE_deg', NaN, 'elevation_RMSE_deg', NaN, ...
    'center_error_deg', NaN, 'axis_error_deg', NaN, ...
    'rho_error_deg', NaN, 'rho_relative_error', NaN, ...
    'separation_vector_error_deg', NaN, 'score_call_count', 0, ...
    'SVD_call_count', 0, 'eig_call_count', 0, 'runtime_sec', 0, ...
    'preprocess_runtime_sec', 0, 'elevation_runtime_sec', 0, ...
    'conditional_az_runtime_sec', 0, 'truth_used_in_fit_flag', false, ...
    'profile_used_in_fit_flag', false, 'tangent_used_in_start_flag', false, ...
    'core_used_in_start_flag', false, 'full4d_used_in_start_flag', false);
end

function value = get_local(input, field, default)
if isfield(input, field)
    value = input.(field);
else
    value = default;
end
end
