function output = stage8_k2_wacb_run_tests(repo_dir, attestation_runtime)
%STAGE8_K2_WACB_RUN_TESTS Run the twelve registered MATLAB contract tests.

if nargin < 1 || isempty(repo_dir)
    [status, repo_dir] = system('git rev-parse --show-toplevel');
    if status ~= 0
        error('stage8_k2_wacb_run_tests:Repository', ...
            'Unable to locate the repository root.');
    end
    repo_dir = strtrim(repo_dir);
end
if nargin < 2, attestation_runtime = ''; end
scope = stage8_k2_wacb_add_paths(repo_dir); %#ok<NASGU>
context = stage8_k2_wacb_build_context(repo_dir);
registry = stage8_k2_wacb_build_registry(context);
fixture = struct('repo_dir', repo_dir, 'context', context, ...
    'registry', registry, 'registry_hash', ...
    stage8_k2_wacb_stable_hash('TEST_REGISTRY', registry));
tests = { ...
    @() test_evidence44_46_identity(fixture), ...
    @() test_1680_trial_reconstruction(fixture), ...
    @() test_frozen_constants_identity(fixture), ...
    @() test_element_music_direct_equivalence(fixture), ...
    @() test_structured_direct_equivalence(fixture), ...
    @() test_applicability_counts(fixture), ...
    @() test_truth_isolation(fixture), ...
    @() test_representative_spectra_consistency(fixture), ...
    @() test_checkpoint_roundtrip(fixture), ...
    @() test_all_method_plot_fixture(fixture), ...
    @() test_plot_only_regeneration(fixture), ...
    @() test_eight_trial_smoke(fixture)};
names = ["T1_EVIDENCE44_46_IDENTITY"; ...
    "T2_1680_TRIAL_RECONSTRUCTION"; "T3_FROZEN_CONSTANTS_IDENTITY"; ...
    "T4_ELEMENT_MUSIC_DIRECT_EQUIVALENCE"; ...
    "T5_STRUCTURED_DIRECT_EQUIVALENCE"; "T6_APPLICABILITY_COUNTS"; ...
    "T7_TRUTH_ISOLATION"; "T8_REPRESENTATIVE_SPECTRA_CONSISTENCY"; ...
    "T9_CHECKPOINT_ROUNDTRIP"; "T10_ALL_METHOD_PLOT_FIXTURE"; ...
    "T11_PLOT_ONLY_REGENERATION"; "T12_EIGHT_TRIAL_SMOKE"];
results = cell(numel(tests), 1);
for index = 1:numel(tests)
    clock = tic;
    results{index} = tests{index}();
    if ~isstruct(results{index}) || ~isfield(results{index}, 'pass') || ...
            ~results{index}.pass
        error('stage8_k2_wacb_run_tests:Failure', ...
            'Registered test failed: %s', names(index));
    end
    results{index}.runtime_sec = toc(clock);
    fprintf('%s PASS (%.3f s)\n', names(index), results{index}.runtime_sec);
end
clear stage8_k2_wacb_test_resources
output = struct('pass', true, 'status', ...
    'STAGE8_K2_WHITE_SNR_ALL_CLASSICAL_BASELINE_MATLAB_TESTS_PASS', ...
    'test_count', numel(tests), 'test_names', names, ...
    'results', {results}, 'context_hash', context.context_hash, ...
    'code_identity', context.code_identity.tree_hash, ...
    'registry_hash', fixture.registry_hash, ...
    'completed_utc', stage8_k2_mc_utc_now());
if strlength(string(attestation_runtime)) > 0
    controller_dir = fullfile(attestation_runtime, 'controller');
    if ~isfolder(attestation_runtime), mkdir(attestation_runtime); end
    if ~isfolder(controller_dir), mkdir(controller_dir); end
    stage8_k2_wacb_write_json_atomic(fullfile(controller_dir, ...
        'matlab_tests_pass.json'), output);
end
fprintf('STAGE8_K2_WHITE_SNR_ALL_CLASSICAL_BASELINE_MATLAB_TESTS_PASS 12/12\n');
end
