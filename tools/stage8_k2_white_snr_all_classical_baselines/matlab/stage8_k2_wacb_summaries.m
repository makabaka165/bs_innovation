    'algorithmic_invalid_count', 0, 'applicability_rate', NaN, ...
    'valid_rate', NaN, 'comparability_class', "", ...
    'joint_RMSE_deg_median', NaN, 'joint_RMSE_deg_p90', NaN, ...
    'azimuth_RMSE_deg_median', NaN, 'azimuth_RMSE_deg_p90', NaN, ...
    'elevation_RMSE_deg_median', NaN, 'elevation_RMSE_deg_p90', NaN, ...
    'center_error_deg_median', NaN, 'center_error_deg_p90', NaN, ...
    'axis_error_deg_median', NaN, 'axis_error_deg_p90', NaN, ...
    'rho_error_deg_median', NaN, 'rho_error_deg_p90', NaN, ...
    'rho_relative_error_median', NaN, 'rho_relative_error_p90', NaN, ...
    'separation_vector_error_deg_median', NaN, ...
    'separation_vector_error_deg_p90', NaN, ...
    'runtime_sec_median', NaN, 'runtime_sec_p90', NaN, ...
    'score_call_count_median', NaN, 'SVD_call_count_median', NaN, ...
    'eig_call_count_median', NaN);
end

function value = ratio_local(numerator, denominator)
if denominator == 0
    value = NaN;
else
    value = double(numerator) / double(denominator);
end
end

function values = finite_local(values)
values = values(isfinite(values));
end

function value = median_or_nan_local(values)
values = values(isfinite(values));
if isempty(values), value = NaN; else, value = median(values); end
end

function value = percentile_local(values, percentile)
values = sort(values(isfinite(values)));
if isempty(values)
    value = NaN;
    return;
end
position = 1 + (numel(values) - 1) * percentile / 100;
lower = floor(position);
upper = ceil(position);
if lower == upper
    value = values(lower);
else
    value = values(lower) + (position - lower) * ...
        (values(upper) - values(lower));
end
end
