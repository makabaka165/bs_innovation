function process = process_snapshot_local(pass_id)
[status, text] = system([ ...
    'powershell -NoProfile -Command "', ...
    '(Get-Process -Name MATLAB -ErrorAction SilentlyContinue | ', ...
    'Measure-Object).Count"']);
count = str2double(strtrim(text));
if status ~= 0 || ~isfinite(count), count = NaN; end
process = struct('schema_version','STAGE8_K2_TECS_PROCESS_SNAPSHOT_V1', ...
    'pass',pass_id,'active_MATLAB_process_count',count, ...
    'formal_MATLAB_process_limit',1,'parallel_pool_enabled',false, ...
    'singleCompThread',true,'captured_at_utc', ...
        char(datetime('now','TimeZone','UTC', ...
        'Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')));
end

