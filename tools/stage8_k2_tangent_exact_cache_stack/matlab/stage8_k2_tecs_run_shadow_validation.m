function row = mode_for_alias_local(modes, alias)
match = modes.aliases.variant_alias_id == string(alias);
assert(nnz(match) == 1, ...
    'stage8_k2_tecs_run_shadow_validation:ModeAlias');
row = modes.aliases(match, :);
end

function row = correctness_template_local()
row = struct('schema_version', "STAGE8_K2_TECS_CORRECTNESS_V1", ...
    'cache_candidate_canonical_mode_id', "", 'cache_layer', "", ...
    'fixed_measurement_hash', "", 'trial_id', "", ...
    'continuous_numeric_pass', false, 'G_rel_error', NaN, ...
    'rank_match', false, 'score_match', false, ...
    'candidate_order_match', false, 'tie_match', false, ...
    'best_index_match', false, 'accepted_update_match', false, ...
    'trajectory_match', false, 'selected_start_match', false, ...
    'nested_pass_match', false, 'final_selector_match', false, ...
    'truth_isolation_pass', false, ...
    'cache_off_baseline_match', false, ...
    'cache_hit_count', 0, 'cache_miss_count', 0, ...
    'physical_producer_call_count', 0, ...
    'logical_score_call_count', 0, 'logical_svd_call_count', 0, ...
    'bytes_peak', 0, 'key_collision_count', 0, ...
    'truth_leakage_count', 0, 'correctness_pass', false, ...
    'failure_reason', "NOT_RUN");
end

function reason = failure_reason_local(off, decision, trajectory, ...
    mismatch, counters, shadow, truth)
flags = [off, decision, trajectory, mismatch, counters, shadow, truth];
names = ["CACHE_OFF_BASELINE","DECISION","TRAJECTORY", ...
    "AUDIT_MISMATCH","COUNTERS","SHADOW","TRUTH"];
reason = strjoin(cellstr(names(~flags)), '|');
end

function atomic_checkpoint_local(path_now, checkpoint)
temporary = [path_now, '.tmp'];
save(temporary, 'checkpoint', '-v7.3');
movefile(temporary, path_now, 'f');
end
