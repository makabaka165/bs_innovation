function registry = stage8_k2_tecs_read_c1_artifact_registry(runtime_root)
%STAGE8_K2_TECS_READ_C1_ARTIFACT_REGISTRY Load the frozen C1 registry.

path_now = fullfile(runtime_root, 'freeze', 'c1_artifact_registry.csv');
registry = readtable(path_now, 'TextType', 'string', ...
    'Delimiter', ',', 'VariableNamingRule', 'preserve');
expected = {'fixed_measurement_hash','artifact_path','artifact_hash', ...
    'artifact_file_sha256','entry_count','value_bytes','status'};
assert(isequal(registry.Properties.VariableNames, expected) && ...
    height(registry) == 2 && ...
    numel(unique(registry.fixed_measurement_hash)) == 2, ...
    'stage8_k2_tecs_read_c1_artifact_registry:Schema', ...
    'The frozen C1 artifact registry schema or identity count is invalid.');
end
