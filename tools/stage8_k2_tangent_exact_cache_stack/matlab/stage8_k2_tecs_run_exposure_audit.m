function checkpoint_count = write_checkpoints_local(directory, events, ...
    aggregate, registry, ...
    design, code_hash, ledger_hash)
checkpoint_count = 0;
for trial_index = 1:height(registry)
    trial_id = registry.trial_id(trial_index);
    trial_identity = unique(events.fixed_measurement_hash( ...
        events.trial_id == trial_id));
    assert(numel(trial_identity) == 1 && strlength(trial_identity) > 0, ...
        'Each AUDIT_TRIAL checkpoint requires one measurement identity.');
    registry_row_hash = stage8_k2_tcc_stable_hash( ...
        'TECS_FROZEN_REGISTRY_ROW', registry(trial_index, :));
    layers = ["C1","C2","C3","C4","C5R","C5P","C6","C7"];
    for layer_index = 1:numel(layers)
        checkpoint = checkpoint_base_local(design, ledger_hash, ...
            code_hash, layers(layer_index), trial_identity, trial_id, ...
            trial_index, registry_row_hash);
        checkpoint.payload.events = events(events.trial_id == trial_id & ...
            events.cache_layer == layers(layer_index), :);
        checkpoint.payload.aggregate = aggregate( ...
            aggregate.trial_id == trial_id & ...
            aggregate.cache_layer == layers(layer_index), :);
        checkpoint.payload_hash = stage8_k2_tcc_stable_hash( ...
            'TECS_PASS_A_CHECKPOINT_PAYLOAD', checkpoint.payload);
        path_now = fullfile(directory, sprintf('%03d_%s_%s.mat', ...
            trial_index, char(trial_id), char(layers(layer_index))));
        atomic_checkpoint_local(path_now, checkpoint);
        checkpoint_count = checkpoint_count + 1;
    end
end
end

