end

function aggregate = aggregate_local(events, purity)
layers = ["C1","C2","C3","C4","C5R","C5P","C6","C7"];
trials = unique(events.trial_id, 'stable');
rows = repmat(aggregate_template_local(), 0, 1);
for trial_index = 1:numel(trials)
    for layer_index = 1:numel(layers)
        select = events.trial_id == trials(trial_index) & ...
            events.cache_layer == layers(layer_index);
        current = events(select, :);
        row = aggregate_template_local();
        row.cache_layer = layers(layer_index);
        row.trial_id = trials(trial_index);
        if isempty(current)
            row.exposure_status = "NO_EXACT_REUSE_EXPOSURE";
            rows(end + 1, 1) = row; %#ok<AGROW>
            continue;
        end
        row.function_role = current.function_role(1);
        row.producer_stage = current.producer_stage(1);
        row.consumer_stage = current.consumer_stage(1);
        row.legal_scope = current.legal_scope(1);
        row.fixed_measurement_hash = current.fixed_measurement_hash(1);
        row.call_count = height(current);
        [keys, ~, group] = unique(current.complete_key_hash, 'stable');
        row.unique_key_count = numel(keys);
        row.hit_opportunity_count = row.call_count - row.unique_key_count;
        row.hit_ratio = row.hit_opportunity_count / max(row.call_count, 1);
        row.cache_population_class = current.cache_population_class(1);
        row.covered_lookup_count = nnz(current.prebuilt_covered_lookup);
        row.coverage_ratio = row.covered_lookup_count / max(row.call_count, 1);
        repeat_cost = 0;
        total_cost = sum(current.original_compute_sec, 'omitnan');
        distances = [];
        for key_index = 1:numel(keys)
            positions = find(group == key_index);
            if numel(positions) > 1
                repeat_cost = repeat_cost + sum( ...
                    current.original_compute_sec(positions(2:end)), 'omitnan');
                distances = [distances; diff(positions)]; %#ok<AGROW>
            end
        end
        row.original_compute_sec = total_cost;
        row.gross_avoidable_compute_upper_sec = repeat_cost;
        row.cost_weighted_hit_ratio = repeat_cost / max(total_cost, realmin);
        if ~isempty(distances)
            sorted = sort(distances);
            row.reuse_distance_median = median(sorted);
            row.reuse_distance_p90 = sorted(ceil(0.9 * numel(sorted)));
            row.reuse_distance_max = max(sorted);
        end
        purity_rows = purity(purity.cache_layer == layers(layer_index), :);
        row.purity_status = string(ternary_local( ...
            ~isempty(purity_rows) && all(purity_rows.purity_status == "PASS"), ...
            'PASS','FAIL'));
        if strcmp(row.cache_population_class, 'PREBUILT_FINITE_DOMAIN')
            row.exposure_status = string(ternary_local( ...
                row.covered_lookup_count > 0, ...
                'PREBUILT_COVERAGE_PRESENT','NO_EXACT_REUSE_EXPOSURE'));
        else
            row.exposure_status = string(ternary_local( ...
                row.hit_opportunity_count > 0, ...
                'EXACT_REUSE_EXPOSURE_PRESENT','NO_EXACT_REUSE_EXPOSURE'));
        end
        rows(end + 1, 1) = row; %#ok<AGROW>
    end
end
aggregate = struct2table(rows);
end

