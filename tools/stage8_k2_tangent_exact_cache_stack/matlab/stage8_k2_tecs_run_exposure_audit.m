function event = make_event_local(layer, role, producer, scope, identity, ...
    trial, key, call_index, compute_sec, output_bytes, state_hash, ...
    population, covered)
[key_hash, payload] = stage8_k2_tecs_sha256( ...
    ['TECS_PASS_A_', layer, '_COMPLETE_KEY'], key);
event = event_template_local();
event.cache_layer = string(layer);
event.function_role = string(role);
event.producer_stage = string(producer);
event.consumer_stage = string(producer);
event.legal_scope = string(scope);
event.fixed_measurement_hash = string(identity);
event.trial_id = string(trial);
event.complete_key_hash = string(key_hash);
event.full_key_payload_hash = string(stage8_k2_tecs_sha256( ...
    'TECS_PASS_A_FULL_KEY_PAYLOAD_BYTES', payload, true));
event.call_index = double(call_index);
event.original_compute_sec = double(compute_sec);
event.output_bytes = double(output_bytes);
event.RNG_before_hash = string(state_hash);
event.RNG_after_hash = string(state_hash);
event.global_state_before_hash = string(state_hash);
event.global_state_after_hash = string(state_hash);
event.cache_population_class = string(population);
event.prebuilt_covered_lookup = logical(covered);
end

