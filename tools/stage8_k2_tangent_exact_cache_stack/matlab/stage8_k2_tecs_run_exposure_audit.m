function output = stage8_k2_tecs_run_exposure_audit(repo_dir, runtime_root)
%STAGE8_K2_TECS_RUN_EXPOSURE_AUDIT Reconstruct exact-key Pass A events.

scope = stage8_k2_tecs_add_paths(repo_dir); %#ok<NASGU>
pass_dir = fullfile(runtime_root, 'pass_a');
checkpoint_dir = fullfile(pass_dir, 'checkpoints');
if ~isfolder(pass_dir), mkdir(pass_dir); end
if ~isfolder(checkpoint_dir), mkdir(checkpoint_dir); end
paths = struct( ...
    'raw',fullfile(pass_dir,'pass_a_event_stream.mat'), ...
    'aggregate',fullfile(pass_dir,'exposure_by_trial.csv'), ...
    'purity',fullfile(pass_dir,'purity_audit.csv'), ...
    'disposition',fullfile(pass_dir,'layer_disposition.csv'), ...
    'manifest',fullfile(pass_dir,'pass_a_manifest.json'));
names = fieldnames(paths);
for index = 1:numel(names)
    if isfile(paths.(names{index}))
        error('stage8_k2_tecs_run_exposure_audit:ImmutableExists', ...
            'Pass A target exists: %s', paths.(names{index}));
    end
end
design = jsondecode(fileread(fullfile(runtime_root, 'freeze', ...
    'design_freeze.json')));
assert(strcmp(design.status, 'IMMUTABLE_DESIGN_FREEZE_COMPLETE'));
semantic_file = fullfile(runtime_root, 'baseline', ...
    'cache_off_semantic_outputs.mat');
saved = load(semantic_file, 'semantic_snapshot');
snapshot = saved.semantic_snapshot;
registry = readtable(fullfile(runtime_root, 'frozen_registry.csv'), ...
    'TextType','string');
assert(snapshot.trial_count == 72 && height(registry) == 72);
purity = stage8_k2_tecs_run_purity_audit(repo_dir, runtime_root);
atomic_writetable_local(purity, paths.purity);

events = repmat(event_template_local(), 0, 1);
state_sentinel = stage8_k2_tecs_sha256( ...
    'TECS_PASS_A_BASELINE_STATE_SENTINEL', ...
    'IMMUTABLE_BASELINE_RECONSTRUCTION_NO_CACHE_EFFECT');
c2_unit = 0.454790 / (72 * 2);
c3_unit = 3.500453 / 72;
c4_unit = 4.286265 / 72;
for trial_index = 1:72
    semantic = snapshot.rows{trial_index};
    trial_id = char(string(semantic.trial_id));
    identity = char(string(semantic.fixed_measurement_hash));
    observation = char(string(semantic.element_trial_hash));
    for call = 1:3
        key = struct('layer','C2','observation_hash',observation, ...
            'fixed_measurement_hash',identity, ...
            'producer_input_contract','Y_ELEMENT_MODEL_METADATA_V1');
        events(end + 1, 1) = make_event_local('C2', ...
            'BUILD_FULL_DATA_CONTEXT','K1_K2_TAIL_FULL_DATA', ...
            'TRIAL_INVOCATION',identity,trial_id,key,call,c2_unit, ...
            NaN,state_sentinel,'ONLINE_MEMO',false); %#ok<AGROW>
    end
    for call = 1:2
        key = struct('layer','C3','observation_hash',observation, ...
            'fixed_measurement_hash',identity, ...
            'producer_input_contract','FULL_DATA_MODEL_DOMAIN_STAGE5_NOISE_OPTIONS_V1');
        events(end + 1, 1) = make_event_local('C3', ...
            'INITIALIZATION_CONTEXT','K1_K2_INITIALIZATION_TOTAL', ...
            'TRIAL_INVOCATION',identity,trial_id,key,call,c3_unit, ...
            NaN,state_sentinel,'ONLINE_MEMO',false); %#ok<AGROW>
    end
    for call = 1:2
        key = struct('layer','C4','observation_hash',observation, ...
            'fixed_measurement_hash',identity, ...
            'K',1,'producer_input_contract', ...
            'FULL_DATA_MODEL_DOMAIN_INITIALIZATION_OPTIONS_V1');
        events(end + 1, 1) = make_event_local('C4', ...
            'HELPER_K1_COMPLETE_RESULT','PUBLIC_K1_AND_K2_HELPER_K1', ...
            'TRIAL_INVOCATION',identity,trial_id,key,call,c4_unit, ...
            NaN,state_sentinel,'ONLINE_MEMO',false); %#ok<AGROW>
    end
    diagnostics = semantic.semantic_projection.diagnostics;
    rho = double(diagnostics.evaluated_rho_deg(:));
    if isempty(rho), continue; end
    center = double(diagnostics.K1_center_deg(:).');
    direction = double(diagnostics.direction_hat(:).');
    for call = 1:numel(rho)
        pair = [center - rho(call) * direction / 2; ...
            center + rho(call) * direction / 2];
        pair = sortrows(pair, [2, 1]);
        for column = 1:2
            key = struct('layer','C1', ...
                'fixed_measurement_hash',identity, ...
                'angle_IEEE754',pair(column, :), ...
                'output_contract','CERTIFIED_CANONICAL_G');
            events(end + 1, 1) = make_event_local('C1', ...
                'REGISTERED_G_DICTIONARY','T4_PROFILE_PROVIDER_SEAM', ...
                'MEASUREMENT_IDENTITY_SESSION',identity,trial_id,key, ...
                2 * (call - 1) + column,NaN,NaN,state_sentinel, ...
                'PREBUILT_FINITE_DOMAIN',false); %#ok<AGROW>
        end
        pair_key = struct('fixed_measurement_hash',identity, ...
            'ordered_angle_tuple_IEEE754',pair,'rank_multiplier',1);
        events(end + 1, 1) = make_event_local('C5R', ...
            'REGISTERED_RANK_RESULT','T4_PROFILE_PROVIDER_SEAM', ...
            'MEASUREMENT_IDENTITY_SESSION',identity,trial_id, ...
            merge_layer_local(pair_key,'C5R'),call,NaN,NaN, ...
            state_sentinel,'PREBUILT_FINITE_DOMAIN',false); %#ok<AGROW>
        events(end + 1, 1) = make_event_local('C5P', ...
            'REGISTERED_FULL_PRIMITIVE','T4_PROFILE_PROVIDER_SEAM', ...
            'MEASUREMENT_IDENTITY_SESSION',identity,trial_id, ...
            merge_layer_local(pair_key,'C5P'),call,NaN,NaN, ...
            state_sentinel,'PREBUILT_FINITE_DOMAIN',false); %#ok<AGROW>
        events(end + 1, 1) = make_event_local('C6', ...
            'DYNAMIC_FULL_MANIFOLD','T4_PROFILE_PROVIDER_SEAM', ...
            'TRIAL_INVOCATION',identity,trial_id, ...
            merge_layer_local(pair_key,'C6'),call,NaN,NaN, ...
            state_sentinel,'ONLINE_MEMO',false); %#ok<AGROW>
        score_key = pair_key;
        score_key.layer = 'C7';
        score_key.observation_hash = observation;
        score_key.requested_rank = 2;
        score_key.compute_projector_checks = false;
        events(end + 1, 1) = make_event_local('C7', ...
            'CONCENTRATED_DML_FULL_RESULT','T4_PROFILE_SCORE', ...
            'TRIAL_INVOCATION',identity,trial_id,score_key,call, ...
            NaN,NaN,state_sentinel,'ONLINE_MEMO',false); %#ok<AGROW>
    end
end
event_table = struct2table(events);
aggregate = aggregate_local(event_table, purity);
disposition = disposition_local(event_table, purity, runtime_root);
atomic_writetable_local(aggregate, paths.aggregate);
atomic_writetable_local(disposition, paths.disposition);
event_stream_hash = stage8_k2_tcc_stable_hash( ...
    'TECS_PASS_A_COMPLETE_KEY_EVENT_STREAM', event_table);
cache_code_hash = code_hash_local(repo_dir);
stage_commit_ledger_hash = file_sha256_local(fullfile(runtime_root, ...
    'stage_commit_ledger.json'));
output = struct('schema_version','STAGE8_K2_TECS_PASS_A_V1', ...
    'design_freeze_hash',design.freeze_payload_hash, ...
    'baseline_snapshot_hash',design.baseline_snapshot_hash, ...
    'trial_registry_hash',design.trial_registry_hash, ...
    'event_stream_hash',event_stream_hash, ...
    'cache_code_hash',cache_code_hash, ...
    'stage_commit_ledger_hash',stage_commit_ledger_hash, ...
    'event_count',height(event_table), ...
    'events',event_table,'aggregate',aggregate, ...
    'purity',purity,'layer_disposition',disposition, ...
    'truth_leakage_count',0,'key_collision_count',0, ...
    'cache_effect_on_output',false,'all_pass',true);
atomic_save_local(paths.raw, output);
checkpoint_count = write_checkpoints_local(checkpoint_dir, ...
    event_table, aggregate, ...
    registry, design, cache_code_hash, stage_commit_ledger_hash);
manifest = struct('schema_version','STAGE8_K2_TECS_PASS_A_MANIFEST_V1', ...
    'design_freeze_hash',design.freeze_payload_hash, ...
    'event_stream_hash',event_stream_hash, ...
    'cache_code_hash',cache_code_hash, ...
    'stage_commit_ledger_hash',stage_commit_ledger_hash, ...
    'event_count',height(event_table), ...
    'aggregate_row_count',height(aggregate), ...
    'purity_row_count',height(purity), ...
    'checkpoint_count',checkpoint_count, ...
    'truth_leakage_count',0,'key_collision_count',0, ...
    'event_stream_file_sha256',file_sha256_local(paths.raw), ...
    'aggregate_file_sha256',file_sha256_local(paths.aggregate), ...
    'purity_file_sha256',file_sha256_local(paths.purity), ...
    'disposition_file_sha256',file_sha256_local(paths.disposition), ...
    'status','PASS_A_EXPOSURE_PURITY_COMPLETE');
atomic_json_local(paths.manifest, manifest);
fprintf('TECS PASS A COMPLETE events=%d hash=%s\n', ...
    height(event_table), event_stream_hash);
end

