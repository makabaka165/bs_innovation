function freeze = stage8_k2_tecs_close_component_freeze(repo_dir, runtime_root)
%STAGE8_K2_TECS_CLOSE_COMPONENT_FREEZE Freeze replay inputs after commit 1.

scope = stage8_k2_tecs_add_paths(repo_dir); %#ok<NASGU>
repo_dir = char(java.io.File(char(string(repo_dir))).getCanonicalPath());
assert_pushed_clean_prototype_local(repo_dir);
freeze_dir = fullfile(runtime_root, 'freeze');
paths = struct( ...
    'protocol',fullfile(freeze_dir, 'component_protocol.json'), ...
    'schedule',fullfile(freeze_dir, 'component_schedule.csv'), ...
    'registry',fullfile(freeze_dir, 'component_prototype_registry.csv'), ...
    'admission',fullfile(freeze_dir, 'component_admission_rule.json'), ...
    'freeze',fullfile(freeze_dir, 'component_freeze.json'));
names = fieldnames(paths);
for index = 1:numel(names)
    if isfile(paths.(names{index}))
        error('stage8_k2_tecs_close_component_freeze:ImmutableExists', ...
            'Component-freeze target exists: %s', paths.(names{index}));
    end
end
design = jsondecode(fileread(fullfile(freeze_dir, 'design_freeze.json')));
pass_a = jsondecode(fileread(fullfile(runtime_root, 'pass_a', ...
    'pass_a_manifest.json')));
static = jsondecode(fileread(fullfile(runtime_root, 'pass_b', ...
    'static_test_manifest.json')));
disposition = readtable(fullfile(runtime_root, 'pass_a', ...
    'layer_disposition.csv'), 'TextType','string');
[complete_code_manifest, cache_code_hash] = ...
    stage8_k2_tecs_code_manifest(repo_dir, 'ALL');
[component_code_manifest, prototype_code_hash] = ...
    stage8_k2_tecs_code_manifest(repo_dir, 'COMPONENT_CORE');
assert(strcmp(static.cache_code_hash, cache_code_hash) && ...
    strcmp(static.component_prototype_code_hash, prototype_code_hash), ...
    'stage8_k2_tecs_close_component_freeze:StaticCodeDrift', ...
    'Static-certified source hashes differ from the current prototype.');
[~, fixture] = stage8_k2_tecs_build_c1_replay_fixture( ...
    repo_dir, runtime_root);

layers = ["C1";"C2";"C3";"C4";"C5R";"C5P";"C6";"C7"];
assert(isequal(disposition.cache_layer, layers));
prototype_implemented = [true;false(7, 1)];
static_status = repmat("NOT_RUN_REJECTED_PASS_A", 8, 1);
static_status(1) = "PASS";
component_replay_required = prototype_implemented;
implementation_hash = repmat("NOT_APPLICABLE", 8, 1);
implementation_hash(1) = string(prototype_code_hash);
prototype_registry = table(layers, prototype_implemented, static_status, ...
    component_replay_required, implementation_hash, ...
    disposition.audit_eligibility_status, disposition.integration_status, ...
    'VariableNames',{'cache_layer','prototype_implemented', ...
    'static_certification_status','component_replay_required', ...
    'component_implementation_hash','audit_eligibility_status', ...
    'integration_status_at_component_freeze'});
prototype_registry_hash = stage8_k2_tcc_stable_hash( ...
    'TECS_COMPONENT_PROTOTYPE_REGISTRY_V1', prototype_registry);

admission = struct( ...
    'schema_version','STAGE8_K2_TECS_COMPONENT_ADMISSION_RULE_V1', ...
    'C1_rule','REQUIRED_TO_INTEGRATE_INDEPENDENT_OF_COMPONENT_SIGN', ...
    'optional_static_rule','ALL_STATIC_AND_CORRECTNESS_GATES_PASS', ...
    'optional_identity_rule','BOTH_IDENTITY_COMPONENT_POINTS_GE_ZERO', ...
    'optional_overall_rule','SUM_IDENTITY_COMPONENT_POINTS_GT_ZERO', ...
    'optional_cost_rule','LOOKUP_STORE_COPY_MEASURED_NOT_ESTIMATED', ...
    'memory_rule','BYTES_PEAK_LE_536870912', ...
    'nonpositive_status','NOT_INTEGRATED_COMPONENT_NONPOSITIVE', ...
    'pass_a_rejected_layers',{cellstr(layers(~prototype_implemented))}, ...
    'component_replay_layers',{{'C1'}});
admission.component_admission_rule_hash = stage8_k2_tcc_stable_hash( ...
    'TECS_COMPONENT_ADMISSION_RULE_V1', admission);

schedule = stage8_k2_tecs_build_component_schedule(design, {'C1'});
component_schedule_hash = stage8_k2_tcc_stable_hash( ...
    'TECS_COMPONENT_SCHEDULE_V1', schedule);
protocol = struct( ...
    'schema_version','STAGE8_K2_TECS_COMPONENT_PROTOCOL_V1', ...
    'design_freeze_hash',design.freeze_payload_hash, ...
    'prototype_code_hash',prototype_code_hash, ...
    'cache_code_hash',cache_code_hash, ...
    'pass_a_event_stream_hash',pass_a.event_stream_hash, ...
    'pass_a_event_stream_file_sha256',pass_a.event_stream_file_sha256, ...
    'C1_paired_fixture_manifest_hash',fixture.fixture_manifest_hash, ...
    'component_replay_layers',{{'C1'}}, ...
    'population_class','PREBUILT_FINITE_DOMAIN', ...
    'scope','MEASUREMENT_IDENTITY_SESSION', ...
    'timer_boundary', ...
    'EXTERNAL_TIC_TOC_AROUND_ONE_COMPLETE_36_TRIAL_IDENTITY_EVENT_STREAM', ...
    'A','FROZEN_LEGACY_PRODUCER_REPLAY_CACHE_OFF', ...
    'B','EXACT_C1_COMPONENT_REPLAY_CACHE_ON', ...
    'pair_sign','TIME_A_MINUS_TIME_B_POSITIVE_MEANS_CACHE_FASTER', ...
    'warmup_pairs_per_identity',5, ...
    'measured_pairs_per_identity',30, ...
    'measured_AB_per_identity',15,'measured_BA_per_identity',15, ...
    'component_pair_order_seed',2026080906, ...
    'schedule_algorithm_hash',design.schedule_generation_algorithm_hash, ...
    'state_rule', ...
    'ARTIFACT_READY_OUTSIDE_TIMER_SESSION_COUNTERS_CLEAR_BEFORE_EACH_EDGE', ...
    'event_pairing_rule', ...
    'ADJACENT_C1_COLUMN_EVENTS_BY_TRIAL_CALL_INDEX_FORM_ORDERED_PAIR', ...
    'online_memo_initial_state','EMPTY_NOT_USED_BY_C1', ...
    'instrumentation_enabled',{{'external root timer','scalar counters'}}, ...
    'instrumentation_disabled',{{'per-call timing','per-call logging', ...
    'filesystem writes','shadow comparison'}}, ...
    'aggregation', ...
    'IDENTITY_POINT_MEDIAN_OF_30_PAIRED_DIFFERENCES_OVERALL_SUM_OF_TWO', ...
    'memory_limit_bytes',536870912, ...
    'component_core_files',{cellstr(component_code_manifest.relative_path)}, ...
    'component_replay_runner_sha256',stage8_k2_tecs_sha256_file( ...
    fullfile(repo_dir, 'tools','stage8_k2_tangent_exact_cache_stack', ...
    'matlab','stage8_k2_tecs_run_component_replay.m')), ...
    'fixture_builder_sha256',stage8_k2_tecs_sha256_file( ...
    fullfile(repo_dir, 'tools','stage8_k2_tangent_exact_cache_stack', ...
    'matlab','stage8_k2_tecs_build_c1_replay_fixture.m')));
protocol.component_protocol_hash = stage8_k2_tcc_stable_hash( ...
    'TECS_COMPONENT_PROTOCOL_V1', protocol);

stage8_k2_tecs_atomic_writetable(prototype_registry, paths.registry);
stage8_k2_tecs_atomic_write_json(paths.admission, admission);
stage8_k2_tecs_atomic_write_json(paths.protocol, protocol);
stage8_k2_tecs_atomic_writetable(schedule, paths.schedule);
[~, component_commit] = system(sprintf( ...
    'git -C "%s" rev-parse HEAD', repo_dir));
component_commit = strtrim(component_commit);
ledger_hash = stage8_k2_tecs_sha256_file(fullfile(runtime_root, ...
    'stage_commit_ledger.json'));
layer_disposition_hash = stage8_k2_tcc_stable_hash( ...
    'TECS_PASS_A_LAYER_DISPOSITION_V1', disposition);
freeze = struct( ...
    'schema_version','STAGE8_K2_TECS_COMPONENT_FREEZE_V1', ...
    'freeze_phase','COMPONENT_FREEZE', ...
    'parent_freeze_hash',design.freeze_payload_hash, ...
    'run_id',design.run_id, ...
    'component_prototype_commit',component_commit, ...
    'stage_commit_ledger_hash_at_component_freeze',ledger_hash, ...
    'prototype_code_hash',prototype_code_hash, ...
    'cache_code_hash',cache_code_hash, ...
    'pass_a_event_stream_hash',pass_a.event_stream_hash, ...
    'component_schedule_hash',component_schedule_hash, ...
    'component_protocol_hash',protocol.component_protocol_hash, ...
    'component_schedule_file_sha256', ...
    stage8_k2_tecs_sha256_file(paths.schedule), ...
    'component_protocol_file_sha256', ...
    stage8_k2_tecs_sha256_file(paths.protocol), ...
    'prototype_registry_file_sha256', ...
    stage8_k2_tecs_sha256_file(paths.registry), ...
    'component_admission_rule_file_sha256', ...
    stage8_k2_tecs_sha256_file(paths.admission), ...
    'pass_a_layer_disposition_hash',layer_disposition_hash, ...
    'semantic_output_projection_hash', ...
    design.semantic_output_projection_hash, ...
    'prototype_registry_hash',prototype_registry_hash, ...
    'component_admission_rule_hash', ...
    admission.component_admission_rule_hash, ...
    'C1_paired_fixture_manifest_hash',fixture.fixture_manifest_hash, ...
    'static_certification_hash',static.manifest_payload_hash, ...
    'complete_code_file_count',height(complete_code_manifest), ...
    'component_core_file_count',height(component_code_manifest), ...
    'status','IMMUTABLE_COMPONENT_FREEZE_COMPLETE');
freeze.freeze_payload_hash = stage8_k2_tcc_stable_hash( ...
    'TECS_COMPONENT_FREEZE_V1', freeze);
stage8_k2_tecs_atomic_write_json(paths.freeze, freeze);
append_repo_freeze_local(repo_dir, paths, freeze);
for index = 1:numel(names)
    set_read_only_local(paths.(names{index}));
end
fprintf('TECS COMPONENT FREEZE COMPLETE hash=%s commit=%s\n', ...
    freeze.freeze_payload_hash, component_commit);
end

function assert_pushed_clean_prototype_local(repo_dir)
[status_head, head] = system(sprintf('git -C "%s" rev-parse HEAD', repo_dir));
[status_upstream, upstream] = system(sprintf( ...
    'git -C "%s" rev-parse "@{u}"', repo_dir));
assert(status_head == 0 && status_upstream == 0 && ...
    strcmp(strtrim(head), strtrim(upstream)), ...
    'stage8_k2_tecs_close_component_freeze:UnpushedCommit', ...
    'Commit 1 must be pushed and equal to its upstream before freeze.');
[status_diff, ~] = system(sprintf( ...
    'git -C "%s" diff --quiet -- tools/stage8_k2_tangent_exact_cache_stack', ...
    repo_dir));
[~, untracked] = system(sprintf([ ...
    'git -C "%s" ls-files --others --exclude-standard -- ', ...
    'tools/stage8_k2_tangent_exact_cache_stack'], repo_dir));
assert(status_diff == 0 && isempty(strtrim(untracked)), ...
    'stage8_k2_tecs_close_component_freeze:DirtyPrototype', ...
    'The TECS prototype tree must be clean before COMPONENT_FREEZE.');
end

function append_repo_freeze_local(repo_dir, paths, freeze)
csv_path = fullfile(repo_dir, 'innovation-mining', ...
    '53_stage8_k2_tangent_exact_cache_stack_freeze.csv');
current = readtable(csv_path, 'TextType','string');
assert(~any(current.freeze_phase == "COMPONENT_FREEZE"), ...
    'Component freeze rows already exist in repo aggregate.');
roles = ["COMPONENT_PROTOCOL";"COMPONENT_SCHEDULE"; ...
    "COMPONENT_PROTOTYPE_REGISTRY";"COMPONENT_ADMISSION_RULE"; ...
    "COMPONENT_FREEZE_RECORD"];
ordered_paths = {paths.protocol;paths.schedule;paths.registry; ...
    paths.admission;paths.freeze};
rows = current([],:);
for index = 1:numel(ordered_paths)
    row = current(1,:);
    row.schema_version(:) = "STAGE8_K2_TECS_FREEZE_CSV_V1";
    row.freeze_phase(:) = "COMPONENT_FREEZE";
    row.parent_freeze_hash(:) = string(freeze.parent_freeze_hash);
    row.freeze_payload_hash(:) = string(freeze.freeze_payload_hash);
    row.created_before_pass(:) = "PASS_B_COMPONENT_REPLAY";
    row.path(:) = string(strrep(ordered_paths{index}, '\', '/'));
    row.role(:) = roles(index);
    row.baseline_hash(:) = "NOT_APPLICABLE_NEW_FREEZE_ARTIFACT";
    row.post_implementation_hash(:) = string( ...
        stage8_k2_tecs_sha256_file(ordered_paths{index}));
    row.frozen_flag(:) = 1;
    row.allowed_change_flag(:) = 0;
    row.status(:) = "IMMUTABLE_COMPONENT_ARTIFACT";
    rows = [rows; row]; %#ok<AGROW>
end
stage8_k2_tecs_atomic_writetable([current; rows], csv_path);
end

function set_read_only_local(path_now)
[status, message] = fileattrib(path_now, '-w');
if ~status
    error('stage8_k2_tecs_close_component_freeze:ReadOnly', '%s', message);
end
end
