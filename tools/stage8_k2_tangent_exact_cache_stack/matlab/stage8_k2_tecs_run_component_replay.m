function [runtime, checksum] = time_off_local(angles, model)
clock = tic;
checksum = batch_off_local(angles, model);
runtime = toc(clock);
end

function [runtime, checksum] = time_on_local(angles, model, provider)
clock = tic;
checksum = batch_on_local(angles, model, provider);
runtime = toc(clock);
end

function checksum = batch_off_local(angles, model)
checksum = [0, 0, 0];
for index = 1:size(angles, 1)
    pair = [angles(index, 1:2); angles(index, 3:4)];
    [G, ~, info] = build_full_sequential_local_manifold( ...
        pair, model, struct('rank_multiplier',1));
    checksum = checksum + [sum(real(G(:))), sum(imag(G(:))), ...
        double(info.rank_Gseq)];
end
end

function checksum = batch_on_local(angles, model, provider)
checksum = [0, 0, 0];
for index = 1:size(angles, 1)
    pair = [angles(index, 1:2); angles(index, 3:4)];
    [G, info] = stage8_k2_tecs_provider_pair( ...
        pair, model, provider, struct('rank_multiplier',1));
    checksum = checksum + [sum(real(G(:))), sum(imag(G(:))), ...
        double(info.rank_Gseq)];
end
end

function summary = summarize_local(raw)
rows = repmat(summary_template_local(), 3, 1);
for identity = 1:2
    selected = raw.included_in_statistics & raw.identity_index == identity;
    current = raw(selected, :);
    rows(identity) = summary_row_local(current, ...
        current.fixed_measurement_hash(1));
end
rows(3) = summary_template_local();
rows(3).schema_version = "STAGE8_K2_TECS_COMPONENT_SUMMARY_V1";
rows(3).cache_layer = "C1";
rows(3).fixed_measurement_hash = "OVERALL_2_IDENTITIES";
rows(3).measured_pair_count = sum([rows(1:2).measured_pair_count]);
rows(3).AB_count = sum([rows(1:2).AB_count]);
rows(3).BA_count = sum([rows(1:2).BA_count]);
rows(3).component_point_sec = sum([rows(1:2).component_point_sec]);
rows(3).bytes_peak = max([rows(1:2).bytes_peak]);
rows(3).both_identity_nonnegative = all( ...
    [rows(1:2).component_point_sec] >= 0);
rows(3).overall_positive = rows(3).component_point_sec > 0;
rows(3).performance_status = string(ternary_local( ...
    rows(3).both_identity_nonnegative && rows(3).overall_positive, ...
    'C1_COMPONENT_POSITIVE','C1_COMPONENT_NONPOSITIVE'));
rows(3).integration_status = ...
    "REQUIRED_C1_COMPONENT_COMPLETE_INTEGRATION_PENDING";
summary = struct2table(rows);
end

function row = summary_row_local(current, identity)
row = summary_template_local();
row.schema_version = "STAGE8_K2_TECS_COMPONENT_SUMMARY_V1";
row.cache_layer = "C1";
row.fixed_measurement_hash = string(identity);
row.measured_pair_count = height(current);
row.AB_count = nnz(current.pair_order == "AB");
row.BA_count = nnz(current.pair_order == "BA");
row.component_point_sec = median(current.paired_difference_sec);
row.paired_min_sec = min(current.paired_difference_sec);
row.paired_max_sec = max(current.paired_difference_sec);
row.bytes_peak = max(current.bytes_peak);
row.both_identity_nonnegative = row.component_point_sec >= 0;
row.overall_positive = false;
row.performance_status = "IDENTITY_COMPONENT_POINT";
row.integration_status = ...
    "REQUIRED_C1_COMPONENT_COMPLETE_INTEGRATION_PENDING";
end

function disposition = disposition_local(summary, freeze)
overall = summary(end, :);
disposition = table("C1",true,overall.component_point_sec, ...
    overall.both_identity_nonnegative,overall.overall_positive, ...
    "REQUIRED_TO_INTEGRATE_INDEPENDENT_OF_COMPONENT_SIGN", ...
    "INTEGRATION_PENDING_PASS_C_D",string(freeze.prototype_code_hash), ...
    'VariableNames',{'cache_layer','component_correctness_pass', ...
    'component_point_sec','both_identity_nonnegative','overall_positive', ...
    'component_performance_status','integration_status', ...
    'component_implementation_hash_at_replay'});
end

