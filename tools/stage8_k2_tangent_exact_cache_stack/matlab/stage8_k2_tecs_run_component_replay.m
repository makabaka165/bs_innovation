function atomic_checkpoint_local(path_now, checkpoint)
temporary = [path_now, '.tmp'];
save(temporary, 'checkpoint', '-v7.3');
[moved, message] = movefile(temporary, path_now, 'f');
if ~moved, error('stage8_k2_tecs_run_component_replay:Checkpoint', ...
        '%s', message); end
end

function output = ternary_local(condition, yes, no)
if condition, output = yes; else, output = no; end
end
