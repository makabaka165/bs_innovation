function output = stage8_k2_tecs_build_final_schedules( ...
    fixture, candidate_mode_id, candidate_enabled_hash, precedence_hash)
%STAGE8_K2_TECS_BUILD_FINAL_SCHEDULES Freeze WARM and COLD pair orders.

modes = stage8_k2_tecs_build_mode_registry(fixture.runtime_root);
m0 = modes.aliases(modes.aliases.variant_alias_id == "M0", :);
final_comparison_id = "FINAL_CMP_" + string(stage8_k2_tecs_sha256( ...
    'TECS_FINAL_COMPARISON_V1', struct( ...
    'baseline_canonical_mode_id',char(m0.candidate_canonical_mode_id), ...
    'candidate_canonical_mode_id',char(candidate_mode_id), ...
    'enabled_layer_set_hash',char(candidate_enabled_hash), ...
    'precedence_hash',char(precedence_hash))));
warm_rows = repmat(warm_template_local(), 72 * 20, 1);
cursor = 0;
for trial_index = 1:72
    spec = fixture.registry(trial_index, :);
    nominal = [repmat("AB", 10, 1); repmat("BA", 10, 1)];
    keys = strings(20, 1);
    for local_index = 1:20
        keys(local_index) = stage8_k2_tecs_sha256('PAIR_ORDER', struct( ...
            'seed',2026080904,'pass','PASS_F', ...
            'comparison_id',char(final_comparison_id), ...
            'trial_id',char(spec.trial_id), ...
            'local_repeat_index',local_index, ...
            'nominal_direction',char(nominal(local_index))));
    end
    [~, order] = sort(keys);
    for repeat_index = 1:20
        nominal_index = order(repeat_index);
        cursor = cursor + 1;
        row = warm_template_local();
        row.comparison_id = final_comparison_id;
        row.comparison_kind = "FINAL_TOTAL";
        row.baseline_canonical_mode_id = ...
            m0.candidate_canonical_mode_id;
        row.candidate_canonical_mode_id = string(candidate_mode_id);
        row.enabled_layer_set_hash = string(candidate_enabled_hash);
        row.precedence_hash = string(precedence_hash);
        row.fixed_measurement_hash = string( ...
            fixture.semantic_snapshot.rows{trial_index}.fixed_measurement_hash);
        row.global_trial_index = double(spec.global_trial_index);
        row.trial_id = string(spec.trial_id);
        row.repeat_index = repeat_index;
        row.nominal_repeat_index = nominal_index;
        row.pair_order = nominal(nominal_index);
        row.pair_order_key = keys(nominal_index);
        row.trial_order_key = stage8_k2_tecs_sha256( ...
            'TRIAL_ORDER', struct('seed',2026080902,'pass','PASS_F', ...
            'comparison_id',char(final_comparison_id), ...
            'repeat_index',repeat_index,'trial_id',char(spec.trial_id)));
        warm_rows(cursor) = row;
    end
end
warm = struct2table(warm_rows);
warm = sortrows(warm, ...
    {'repeat_index','trial_order_key','global_trial_index'});
warm.schedule_row_id = (1:height(warm)).';
warm = movevars(warm, 'schedule_row_id', 'Before', 1);
warm.schedule_row_hash = row_hashes_local( ...
    warm, 'TECS_FINAL_WARM_SCHEDULE_ROW_V1');

cold_rows = repmat(cold_template_local(), 2 * 2 * 10 + 2 * 10 * 35, 1);
cursor = 0;
settings = ["COLD_BUILD";"COLD_LOAD"];
for setting_index = 1:numel(settings)
    setting = settings(setting_index);
    cold_comparison_id = setting + "_CMP_" + string( ...
        stage8_k2_tecs_sha256('TECS_COLD_COMPARISON_V1', struct( ...
        'lifecycle_setting',char(setting), ...
        'baseline_canonical_mode_id',char(m0.candidate_canonical_mode_id), ...
        'candidate_canonical_mode_id',char(candidate_mode_id))));
    for identity_index = 1:2
        identity = string(fixture.identities(identity_index). ...
            fixed_measurement_hash);
        nominal = [repmat("AB", 5, 1); repmat("BA", 5, 1)];
        keys = strings(10, 1);
        for repeat_index = 1:10
            keys(repeat_index) = stage8_k2_tecs_sha256( ...
                'PAIR_ORDER', struct('seed',2026080905, ...
                'pass',char(setting), ...
                'comparison_id',char(cold_comparison_id), ...
                'identity_batch_id',char(identity), ...
                'local_repeat_index',repeat_index, ...
                'nominal_direction',char(nominal(repeat_index))));
        end
        [~, order] = sort(keys);
        for batch_repeat = 1:10
            nominal_index = order(batch_repeat);
            cursor = cursor + 1;
            row = cold_template_local();
            row.schedule_unit_kind = "COLD_BATCH_PAIR";
            row.comparison_id = cold_comparison_id;
            row.comparison_kind = setting + "_TOTAL";
            row.baseline_canonical_mode_id = ...
                m0.candidate_canonical_mode_id;
            row.candidate_canonical_mode_id = string(candidate_mode_id);
            row.enabled_layer_set_hash = string(candidate_enabled_hash);
            row.precedence_hash = string(precedence_hash);
            row.fixed_measurement_hash = identity;
            row.identity_batch_id = "IDENTITY_" + ...
                compose('%02d', identity_index) + "_36_TRIALS";
            row.identity_index = identity_index;
            row.batch_repeat_index = batch_repeat;
            row.pair_order = nominal(nominal_index);
            row.pair_order_key = keys(nominal_index);
            row.lifecycle_setting = setting;
            cold_rows(cursor) = row;
        end
    end
end
operations = ["build";"load";"validate";"setup";"reset"; ...
    "hash";"lookup_hit";"lookup_miss";"store";"copy"];
operation_rows = repmat(cold_template_local(), 2 * numel(operations) * 35, 1);
operation_cursor = 0;
for identity_index = 1:2
    identity = string(fixture.identities(identity_index). ...
        fixed_measurement_hash);
    for operation_index = 1:numel(operations)
        operation = operations(operation_index);
        for repeat_index = 1:35
            operation_cursor = operation_cursor + 1;
            row = cold_template_local();
            row.schedule_unit_kind = "LIFECYCLE_OPERATION";
            row.candidate_canonical_mode_id = string(candidate_mode_id);
            row.enabled_layer_set_hash = string(candidate_enabled_hash);
            row.precedence_hash = string(precedence_hash);
            row.fixed_measurement_hash = identity;
            row.identity_batch_id = "IDENTITY_" + ...
                compose('%02d', identity_index);
            row.identity_index = identity_index;
            row.lifecycle_setting = "WARM";
            row.lifecycle_operation = operation;
            row.operation_repeat_index = repeat_index;
            if repeat_index <= 5
                row.operation_phase = "WARMUP";
                row.included_in_statistics = false;
            else
                row.operation_phase = "MEASURED";
                row.included_in_statistics = true;
            end
            row.operation_order_key = stage8_k2_tecs_sha256( ...
                'LIFECYCLE_OPERATION_ORDER', struct('seed',2026080907, ...
                'identity',char(identity),'operation',char(operation), ...
                'repeat_index',repeat_index));
            operation_rows(operation_cursor) = row;
        end
    end
end
operation_table = sortrows(struct2table(operation_rows), ...
    {'operation_order_key','identity_index','lifecycle_operation', ...
    'operation_repeat_index'});
cold = [struct2table(cold_rows(1:cursor)); operation_table];
cold.schedule_row_id = (1:height(cold)).';
cold = movevars(cold, 'schedule_row_id', 'Before', 1);
cold.schedule_row_hash = row_hashes_local( ...
    cold, 'TECS_COLD_LIFECYCLE_SCHEDULE_ROW_V1');
output = struct('final_warm',warm,'cold_lifecycle',cold, ...
    'final_comparison_id',char(final_comparison_id));
end

function hashes = row_hashes_local(value, domain)
hashes = strings(height(value), 1);
for index = 1:height(value)
    hashes(index) = stage8_k2_tecs_sha256( ...
        domain, table2struct(value(index, :)));
end
end

function row = warm_template_local()
row = struct('comparison_id',"",'comparison_kind',"FINAL_TOTAL", ...
    'baseline_canonical_mode_id',"", ...
    'candidate_canonical_mode_id',"",'enabled_layer_set_hash',"", ...
    'precedence_hash',"",'fixed_measurement_hash',"", ...
    'global_trial_index',0,'trial_id',"",'repeat_index',0, ...
    'nominal_repeat_index',0,'pair_order',"", ...
    'pair_order_key',"",'trial_order_key',"", ...
    'lifecycle_setting',"WARM",'included_in_statistics',true);
end

function row = cold_template_local()
row = struct('schedule_unit_kind',"", ...
    'comparison_id',"NOT_APPLICABLE",'comparison_kind',"NOT_APPLICABLE", ...
    'baseline_canonical_mode_id',"", ...
    'candidate_canonical_mode_id',"",'enabled_layer_set_hash',"", ...
    'precedence_hash',"",'fixed_measurement_hash',"", ...
    'identity_batch_id',"",'identity_index',0, ...
    'batch_repeat_index',0,'pair_order',"",'pair_order_key',"", ...
    'lifecycle_setting',"",'lifecycle_operation',"NOT_APPLICABLE", ...
    'operation_repeat_index',0,'operation_phase',"NOT_APPLICABLE", ...
    'operation_order_key',"",'included_in_statistics',true);
end
