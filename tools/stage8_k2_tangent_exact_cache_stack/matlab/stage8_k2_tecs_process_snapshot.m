function process = stage8_k2_tecs_process_snapshot(pass_id)
%STAGE8_K2_TECS_PROCESS_SNAPSHOT Count formal MATLAB engine processes.

[status, text] = system([ ...
    'powershell -NoProfile -Command "', ...
    '(Get-Process -Name MATLAB -ErrorAction SilentlyContinue | ', ...
    'Where-Object { $_.Path -like ''*\bin\win64\MATLAB.exe'' } | ', ...
    'Measure-Object).Count"']);
count = str2double(strtrim(text));
if status ~= 0 || ~isfinite(count), count = NaN; end
process = struct( ...
    'schema_version','STAGE8_K2_TECS_PROCESS_SNAPSHOT_V1', ...
    'pass',char(string(pass_id)), ...
    'active_MATLAB_process_count',count, ...
    'formal_MATLAB_process_limit',1, ...
    'parallel_pool_enabled',false, ...
    'singleCompThread',true, ...
    'process_count_scope','BIN_WIN64_MATLAB_ENGINE_EXECUTABLES', ...
    'captured_at_utc',char(datetime('now','TimeZone','UTC', ...
        'Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')));
end
