function [recommendation,retention,mode]=decision_local(status,final,fixture,runtime_root)
if strcmp(status,'MEASURED_CACHE_STACK_ROBUST_POSITIVE')
    recommendation='RECOMMEND_PRODUCTIONIZATION_STUDY';
    retention='RETAIN_ALL_LAYERS_IN_FROZEN_CANDIDATE';
    mode=final.final_measurement_candidate_canonical_mode_id;
elseif strcmp(status,'MEASURED_CACHE_STACK_INCONCLUSIVE')
    recommendation='RETAIN_EXPERIMENTAL_EXACT_CACHE_STACK';
    retention='NO_RUNTIME_CACHE_LAYER_RETAINED';
    modes=stage8_k2_tecs_build_mode_registry(runtime_root);
    mode=char(modes.aliases.candidate_canonical_mode_id( ...
        modes.aliases.variant_alias_id=="M0"));
else
    recommendation='DO_NOT_RETAIN_NONPOSITIVE_LAYERS';
    retention='NO_RUNTIME_CACHE_LAYER_RETAINED';
    modes=stage8_k2_tecs_build_mode_registry(runtime_root);
    mode=char(modes.aliases.candidate_canonical_mode_id( ...
        modes.aliases.variant_alias_id=="M0"));
end
assert(strcmp(fixture.design.production_default_cache_setting,'CACHE_OFF'));
end

