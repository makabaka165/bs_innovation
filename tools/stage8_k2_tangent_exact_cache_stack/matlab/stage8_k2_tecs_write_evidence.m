function exposure=build_exposure_local(runtime_root)
exposure=readtable(fullfile(runtime_root,'pass_a','exposure_by_trial.csv'), ...
    'TextType','string');
disposition=readtable(fullfile(runtime_root,'pass_a','layer_disposition.csv'), ...
    'TextType','string');
component=readtable(fullfile(runtime_root,'pass_b','component_summary.csv'), ...
    'TextType','string');
n=height(exposure);exposure.predicted_net_saving_sec=NaN(n,1);
exposure.predicted_net_saving_source=repmat("NOT_MEASURED_PER_TRIAL",n,1);
exposure.component_repeat_count=zeros(n,1);exposure.component_AB_count=zeros(n,1);
exposure.component_BA_count=zeros(n,1);exposure.component_point_sec=NaN(n,1);
exposure.audit_eligibility_status=strings(n,1);exposure.integration_status=strings(n,1);
for index=1:height(disposition)
    member=exposure.cache_layer==disposition.cache_layer(index);
    exposure.audit_eligibility_status(member)= ...
        disposition.audit_eligibility_status(index);
    exposure.integration_status(member)=disposition.integration_status(index);
end
member=exposure.cache_layer=="C1";
overall=component.fixed_measurement_hash=="OVERALL_2_IDENTITIES";
exposure.component_repeat_count(member)=30;
exposure.component_AB_count(member)=15;exposure.component_BA_count(member)=15;
exposure.component_point_sec(member)=component.component_point_sec(overall);
exposure.predicted_net_saving_sec(member)=component.component_point_sec(overall);
exposure.predicted_net_saving_source(member)= ...
    "FROZEN_COMPONENT_REPLAY_OVERALL_POINT";
exposure.integration_status(member)="INTEGRATED";
end

