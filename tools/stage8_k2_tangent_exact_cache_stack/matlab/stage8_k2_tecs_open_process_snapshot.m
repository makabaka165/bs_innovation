function process = stage8_k2_tecs_open_process_snapshot(path_now, pass_id)
%STAGE8_K2_TECS_OPEN_PROCESS_SNAPSHOT Create or validate a pass snapshot.

current = stage8_k2_tecs_process_snapshot(pass_id);
assert(current.active_MATLAB_process_count == 1, ...
    'stage8_k2_tecs_open_process_snapshot:ProcessLimit', ...
    'Formal timing requires exactly one MATLAB engine process.');
if isfile(path_now)
    process = jsondecode(fileread(path_now));
    valid = strcmp(process.schema_version, ...
        'STAGE8_K2_TECS_PROCESS_SNAPSHOT_V1') && ...
        strcmp(process.pass, char(string(pass_id))) && ...
        process.active_MATLAB_process_count == 1 && ...
        process.formal_MATLAB_process_limit == 1 && ...
        ~process.parallel_pool_enabled && process.singleCompThread && ...
        strcmp(process.process_count_scope, ...
        'BIN_WIN64_MATLAB_ENGINE_EXECUTABLES');
    assert(valid, ...
        'stage8_k2_tecs_open_process_snapshot:ResumeMismatch', ...
        'Existing formal process snapshot does not match this pass.');
else
    process = current;
    stage8_k2_tecs_atomic_write_json(path_now, process);
end
end
