function freeze = stage8_k2_tecs_close_timing_freeze(repo_dir, runtime_root)
%STAGE8_K2_TECS_CLOSE_TIMING_FREEZE Freeze commit-2 timing protocol.

scope = stage8_k2_tecs_add_paths(repo_dir); %#ok<NASGU>
repo_dir = char(java.io.File(char(string(repo_dir))).getCanonicalPath());
assert_commit2_pushed_local(repo_dir, runtime_root);
fixture = stage8_k2_tecs_build_runtime_fixture(repo_dir, runtime_root);
pass_cd = jsondecode(fileread(fullfile(runtime_root, 'pass_c_d', ...
    'correctness_manifest.json')));
[integration_manifest, integration_hash] = ...
    stage8_k2_tecs_integration_manifest(repo_dir);
assert(strcmp(pass_cd.integration_implementation_hash, integration_hash) && ...
    pass_cd.M1_correctness_pass_count == 72 && ...
    pass_cd.post_hook_cache_off_qualification_pass_count == 72, ...
    'stage8_k2_tecs_close_timing_freeze:CorrectnessDrift', ...
    'Post-hook qualification does not match the committed integration.');
assert(strcmp(fixture.component.prototype_code_hash, ...
    integration_manifest.component_core_hash), ...
    'stage8_k2_tecs_close_timing_freeze:ComponentDrift', ...
    'COMPONENT_FREEZE_INVALIDATED_STOP');

freeze_dir = fullfile(runtime_root, 'freeze');
paths = struct( ...
    'mode', fullfile(freeze_dir, 'canonical_mode_registry.csv'), ...
    'alias', fullfile(freeze_dir, 'mode_alias_registry.csv'), ...
    'comparison_raw', fullfile(freeze_dir, ...
        'screening_raw_comparison_registry.csv'), ...
    'comparison_views', fullfile(freeze_dir, ...
        'screening_comparison_view_registry.csv'), ...
    'warmup', fullfile(freeze_dir, 'formal_warmup_registry.csv'), ...
    'artifact', fullfile(freeze_dir, 'c1_artifact_registry.csv'), ...
    'model', fullfile(freeze_dir, 'candidate_model_registry.csv'), ...
    'protocol', fullfile(freeze_dir, 'timing_protocol.json'), ...
    'schedule', fullfile(freeze_dir, 'screening_schedule.csv'), ...
    'freeze', fullfile(freeze_dir, 'timing_freeze.json'));
names = fieldnames(paths);
for index = 1:numel(names)
    if isfile(paths.(names{index}))
        error('stage8_k2_tecs_close_timing_freeze:ImmutableExists', ...
            'Timing-freeze target exists: %s', paths.(names{index}));
    end
end

artifact_registry = stage8_k2_tecs_build_c1_artifacts( ...
    repo_dir, runtime_root);
