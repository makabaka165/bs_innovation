append_repo_freeze_local(repo_dir, paths, freeze);
for index = 1:numel(names), set_read_only_local(paths.(names{index})); end
fprintf('TECS TIMING FREEZE COMPLETE hash=%s commit=%s rows=%d\n', ...
    freeze.freeze_payload_hash, head, height(schedule));
end

function registry = build_model_registry_local( ...
    runtime_root, fixture, modes, integration_hash)
component = readtable(fullfile(runtime_root, 'pass_b', ...
    'component_summary.csv'), 'TextType', 'string');
overall = component.fixed_measurement_hash == "OVERALL_2_IDENTITIES";
assert(nnz(overall) == 1);
m1 = modes.aliases(modes.aliases.variant_alias_id == "M1", :);
delta = double(component.component_point_sec(overall));
registry = table( ...
    "PENDING", string(m1.candidate_canonical_mode_id), ...
    string('["C1"]'), "PREBUILT_FINITE_DOMAIN", ...
    "MEASUREMENT_IDENTITY_SESSION", 5904, delta, ...
    NaN, NaN, NaN, NaN, ...
    "NO_OVERLAP_SINGLE_LAYER", NaN, NaN, ...
    string(fixture.design.baseline_commit), ...
    string(fixture.design.baseline_snapshot_hash), ...
    string(fixture.design.trial_registry_hash), ...
    string(integration_hash), "PENDING", ...
    "NOT_MATCHABLE_INCOMPLETE_COMPONENT_COST", "PENDING", ...
    'VariableNames',{'model_id','matched_candidate_mode', ...
    'ordered_enabled_layer_set','population_class','scope', ...
    'component_exposure_count','measured_component_delta_sec', ...
    'measured_component_lookup_sec','measured_component_miss_sec', ...
    'measured_component_store_sec','measured_component_copy_sec', ...
    'overlap_partition_status','frozen_model_delta_sec', ...
    'historical_baseline_model_percent','baseline_commit', ...
    'baseline_semantic_snapshot_hash','trial_registry_hash', ...
    'integration_implementation_hash','timing_protocol_hash', ...
    'model_status','model_hash'});
end

function registry = bind_model_registry_local(registry, timing_hash)
registry.timing_protocol_hash(:) = string(timing_hash);
for index = 1:height(registry)
    payload = table2struct(removevars(registry(index, :), ...
        {'model_id','model_hash'}));
    hash = stage8_k2_tecs_sha256('TECS_FROZEN_MODEL_V1', payload);
    registry.model_hash(index) = string(hash);
    registry.model_id(index) = "MODEL_" + string(hash);
end
end

function assert_commit2_pushed_local(repo_dir, runtime_root)
head = git_output_local(repo_dir, 'rev-parse HEAD');
upstream = git_output_local(repo_dir, 'rev-parse @{u}');
assert(strcmp(head, upstream), ...
    'stage8_k2_tecs_close_timing_freeze:UnpushedCommit', ...
    'Commit 2 must be pushed and local/remote equal before timing freeze.');
ledger = jsondecode(fileread(fullfile(runtime_root, ...
    'stage_commit_ledger.json')));
assert(strcmp(ledger.pushed_commit, head), ...
    'stage8_k2_tecs_close_timing_freeze:Ledger', ...
    'RESUME_PROVENANCE_MISMATCH_STOP: ledger does not confirm commit 2.');
[status, ~] = system(sprintf(['git -C "%s" diff --quiet -- ', ...
    'tools/stage8_k2_tangent_exact_cache_stack ', ...
    'tools/stage8_k2_tangent_canonical_cache/matlab/', ...
    'stage8_k2_tcc_get_pair_manifold.m'], repo_dir));
assert(status == 0, ...
    'stage8_k2_tecs_close_timing_freeze:DirtyCode', ...
    'Timed source must be clean before TIMING_FREEZE.');
end

function value = git_output_local(repo_dir, command)
[status, value] = system(sprintf('git -C "%s" %s', repo_dir, command));
if status ~= 0, error('stage8_k2_tecs_close_timing_freeze:Git'); end
value = strtrim(value);
end

function append_repo_freeze_local(repo_dir, paths, freeze)
csv_path = fullfile(repo_dir, 'innovation-mining', ...
    '53_stage8_k2_tangent_exact_cache_stack_freeze.csv');
current = readtable(csv_path, 'TextType', 'string');
assert(~any(current.freeze_phase == "TIMING_FREEZE"));
roles = ["CANONICAL_MODE_REGISTRY";"MODE_ALIAS_REGISTRY"; ...
    "SCREENING_RAW_COMPARISON_REGISTRY"; ...
    "SCREENING_COMPARISON_VIEW_REGISTRY"; ...
    "FORMAL_WARMUP_REGISTRY";"C1_ARTIFACT_REGISTRY"; ...
    "CANDIDATE_MODEL_REGISTRY";"TIMING_PROTOCOL"; ...
    "SCREENING_SCHEDULE";"TIMING_FREEZE_RECORD"];
ordered = {paths.mode;paths.alias;paths.comparison_raw; ...
    paths.comparison_views;paths.warmup;paths.artifact;paths.model; ...
    paths.protocol;paths.schedule;paths.freeze};
rows = current([],:);
for index = 1:numel(ordered)
    row = current(1,:);
    row.schema_version(:) = "STAGE8_K2_TECS_FREEZE_CSV_V1";
    row.freeze_phase(:) = "TIMING_FREEZE";
    row.parent_freeze_hash(:) = string(freeze.parent_freeze_hash);
    row.freeze_payload_hash(:) = string(freeze.freeze_payload_hash);
    row.created_before_pass(:) = "PASS_E_SCREENING";
    row.path(:) = string(strrep(ordered{index}, '\', '/'));
    row.role(:) = roles(index);
    row.baseline_hash(:) = "NOT_APPLICABLE_NEW_FREEZE_ARTIFACT";
    row.post_implementation_hash(:) = string( ...
        stage8_k2_tecs_sha256_file(ordered{index}));
    row.frozen_flag(:) = 1; row.allowed_change_flag(:) = 0;
    row.status(:) = "IMMUTABLE_TIMING_ARTIFACT";
    rows = [rows; row]; %#ok<AGROW>
end
stage8_k2_tecs_atomic_writetable([current; rows], csv_path);
end

function set_read_only_local(path_now)
[status, message] = fileattrib(path_now, '-w');
if ~status, error('stage8_k2_tecs_close_timing_freeze:ReadOnly', ...
        '%s', message); end
end
