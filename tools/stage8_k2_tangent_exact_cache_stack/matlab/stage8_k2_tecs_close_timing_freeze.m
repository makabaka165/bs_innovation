comparison = stage8_k2_tecs_build_comparison_registry(runtime_root);
schedule = stage8_k2_tecs_build_screening_schedule( ...
    comparison, fixture.registry);
warmup = stage8_k2_tecs_build_formal_warmup_registry(fixture);
model_registry = build_model_registry_local( ...
    runtime_root, fixture, modes, integration_hash);

schedule_hash = stage8_k2_tecs_sha256( ...
    'TECS_SCREENING_SCHEDULE_V1', table2struct(schedule));
warmup_hash = stage8_k2_tecs_sha256( ...
    'TECS_FORMAL_WARMUP_REGISTRY_V1', table2struct(warmup));
artifact_registry_hash = stage8_k2_tecs_sha256( ...
    'TECS_C1_ARTIFACT_REGISTRY_V1', table2struct(artifact_registry));
reset_payload = struct( ...
    'make_session_sha256', stage8_k2_tecs_sha256_file(fullfile(repo_dir, ...
        'tools','stage8_k2_tangent_exact_cache_stack','matlab', ...
        'stage8_k2_tecs_make_session.m')), ...
    'session_core_sha256', stage8_k2_tecs_sha256_file(fullfile(repo_dir, ...
        'tools','stage8_k2_tangent_exact_cache_stack','matlab', ...
        'stage8_k2_tecs_cache_session.m')), ...
    'root_runner_sha256', stage8_k2_tecs_sha256_file(fullfile(repo_dir, ...
        'tools','stage8_k2_tangent_exact_cache_stack','matlab', ...
        'stage8_k2_tecs_run_root.m')), ...
    'rule', 'NEW_PRISTINE_SESSION_BEFORE_EACH_CACHE_ON_PAIR_EDGE');
reset_hash = stage8_k2_tecs_sha256( ...
    'TECS_CACHE_STATE_RESET_IMPLEMENTATION_V1', reset_payload);
no_op_hash = stage8_k2_tecs_sha256('TECS_NOOP_CONTROL_V1', struct( ...
    'A','M0_FROZEN_CACHE_OFF_ENTRY','B','SAME_M0_ENTRY_DISTINCT_LABEL', ...
    'label_inside_timed_region',false, ...
    'same_function_parameters_statement_order',true));

protocol = struct( ...
    'schema_version','STAGE8_K2_TECS_TIMING_PROTOCOL_V1', ...
    'MATLAB_release','R2022b','singleCompThread',true, ...
    'parallel_pool',false,'formal_MATLAB_processes',1, ...
    'root_timer','EXTERNAL_TIC_TOC_ONE_STAGE8_K2_TP_FIT_SAFE_CALL', ...
    'root_entry_path', ...
        'tools/stage8_k2_tangent_exact_cache_stack/matlab/stage8_k2_tecs_run_root.m', ...
    'root_entry_sha256',reset_payload.root_runner_sha256, ...
    'screening_paired_repeats',6,'screening_AB',3,'screening_BA',3, ...
    'final_WARM_paired_repeats',20,'final_WARM_AB',10, ...
    'final_WARM_BA',10,'COLD_batch_repeats',10, ...
    'COLD_AB',5,'COLD_BA',5, ...
    'component_warmup_pairs',5,'component_measured_pairs',30, ...
    'lifecycle_operation_warmup',5, ...
    'lifecycle_operation_measured',30, ...
    'formal_root_warmup_pairs_per_registry_row',2, ...
    'formal_root_warmup_order','AB_THEN_BA_DISCARDED', ...
    'formal_warmup_registry_hash',warmup_hash, ...
    'trial_order_seed',2026080902, ...
    'screening_pair_order_seed',2026080903, ...
    'final_pair_order_seed',2026080904, ...
    'cold_pair_order_seed',2026080905, ...
    'component_pair_order_seed',2026080906, ...
    'lifecycle_operation_order_seed',2026080907, ...
    'bootstrap_seed',2026080901,'bootstrap_resamples',10000, ...
    'bootstrap_lower_order_statistic_index',500, ...
    'descriptive_p10','SORTED_INDEX_CEIL_0_10_N', ...
    'descriptive_p90','SORTED_INDEX_CEIL_0_90_N', ...
    'median','MATLAB_MEDIAN_EVEN_MEAN_TWO_CENTERS', ...
    'memory_bound_bytes',536870912, ...
    'primary_cache_state','PRIMARY_WARM_ARTIFACT_READY_ONLINE_MEMO_EMPTY', ...
    'cache_state_reset_implementation_hash',reset_hash, ...
    'minimal_counters',{{'hit','miss','physical_producer_call', ...
        'entry','bytes_current','bytes_peak'}}, ...
    'no_op_control_hash',no_op_hash, ...
    'screening_comparison_set_hash', ...
        comparison.screening_comparison_set_hash, ...
    'candidate_selection_rule', ...
        'POSITIVE_POOL_THEN_DMAX_RHO_LAYER_COUNT_BYTES_MODE_ID;_FALLBACK_SAME_WITHOUT_POSITIVITY', ...
    'instrumentation_disabled',{{'shadow','raw_query_logging', ...
        'trajectory_capture','per_call_timing','stage_timing', ...
        'cache_debug_logging','filesystem_write_inside_timed_region'}}, ...
    'screening_schedule_algorithm_hash', ...
        fixture.design.schedule_generation_algorithm_hash, ...
    'final_schedule_algorithm_hash', ...
        fixture.design.schedule_generation_algorithm_hash, ...
    'cold_schedule_algorithm_hash', ...
        fixture.design.schedule_generation_algorithm_hash, ...
    'artifact_registry_hash',artifact_registry_hash, ...
    'integration_implementation_hash',integration_hash);
protocol.timing_protocol_hash = stage8_k2_tecs_sha256( ...
    'TECS_TIMING_PROTOCOL_V1', protocol);
model_registry = bind_model_registry_local( ...
    model_registry, protocol.timing_protocol_hash);
model_registry_hash = stage8_k2_tecs_sha256( ...
    'TECS_CANDIDATE_MODEL_REGISTRY_V1', table2struct(model_registry));

stage8_k2_tecs_atomic_writetable(modes.canonical, paths.mode);
stage8_k2_tecs_atomic_writetable(modes.aliases, paths.alias);
stage8_k2_tecs_atomic_writetable(comparison.raw, paths.comparison_raw);
stage8_k2_tecs_atomic_writetable(comparison.views, paths.comparison_views);
stage8_k2_tecs_atomic_writetable(warmup, paths.warmup);
stage8_k2_tecs_atomic_writetable(artifact_registry, paths.artifact);
stage8_k2_tecs_atomic_writetable(model_registry, paths.model);
stage8_k2_tecs_atomic_write_json(paths.protocol, protocol);
stage8_k2_tecs_atomic_writetable(schedule, paths.schedule);

head = git_output_local(repo_dir, 'rev-parse HEAD');
ledger_hash = stage8_k2_tecs_sha256_file(fullfile( ...
    runtime_root, 'stage_commit_ledger.json'));
component_result = jsondecode(fileread(fullfile(runtime_root, ...
    'pass_b', 'component_replay_manifest.json')));
freeze = struct( ...
    'schema_version','STAGE8_K2_TECS_TIMING_FREEZE_V1', ...
    'freeze_phase','TIMING_FREEZE', ...
    'parent_freeze_hash',fixture.component.freeze_payload_hash, ...
    'created_before_pass','PASS_E_SCREENING', ...
    'integration_code_commit',head, ...
    'stage_commit_ledger_hash_at_timing_freeze',ledger_hash, ...
    'cache_code_hash',integration_hash, ...
    'cache_state_reset_implementation_hash',reset_hash, ...
    'timing_protocol_hash',protocol.timing_protocol_hash, ...
    'screening_schedule_hash',schedule_hash, ...
    'screening_comparison_set_hash', ...
        comparison.screening_comparison_set_hash, ...
    'formal_warmup_registry_hash',warmup_hash, ...
    'component_result_disposition_hash', ...
        component_result.component_result_disposition_hash, ...
    'component_implementation_hashes_at_replay', ...
        fixture.component.prototype_code_hash, ...
    'component_implementation_hashes_at_integration', ...
        integration_manifest.component_core_hash, ...
