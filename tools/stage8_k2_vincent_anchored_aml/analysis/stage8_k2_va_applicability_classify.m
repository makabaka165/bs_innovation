function classification = stage8_k2_va_applicability_classify(metrics, claim_authorized)
%STAGE8_K2_VA_APPLICABILITY_CLASSIFY Apply the frozen closure rules.

if nargin < 2
    claim_authorized = true;
end
if ~claim_authorized
    classification = "DESCRIPTIVE_ONLY";
    return;
end
required = {'N', 'anchored_valid_count', ...
    'median_joint_tangent', 'median_joint_anchored', ...
    'p90_joint_tangent', 'p90_joint_anchored', ...
    'wins', 'losses', 'median_rho_tangent', ...
    'median_rho_anchored', 'median_vector_tangent', ...
    'median_vector_anchored'};
for index = 1:numel(required)
    if ~isfield(metrics, required{index})
        error('stage8_k2_va_applicability_classify:Field', ...
            'Missing classification field: %s.', required{index});
    end
end
supported = metrics.N >= 18 && ...
    metrics.anchored_valid_count == metrics.N && ...
    metrics.median_joint_anchored <= metrics.median_joint_tangent && ...
    metrics.p90_joint_anchored <= metrics.p90_joint_tangent && ...
    metrics.wins > metrics.losses && ...
    metrics.median_vector_anchored <= metrics.median_vector_tangent;
median_gain_unstable = ...
    metrics.median_joint_anchored < metrics.median_joint_tangent && ...
    (metrics.p90_joint_anchored > metrics.p90_joint_tangent || ...
    metrics.wins <= metrics.losses);
separation_only = ...
    metrics.median_joint_anchored > metrics.median_joint_tangent && ...
    metrics.median_rho_anchored < metrics.median_rho_tangent && ...
    metrics.median_vector_anchored < metrics.median_vector_tangent;
if supported
    classification = "SUPPORTED_ENDPOINT_AND_SEPARATION";
elseif median_gain_unstable
    classification = "MEDIAN_GAIN_BUT_TAIL_UNSTABLE";
elseif separation_only
    classification = "SEPARATION_STRUCTURE_ONLY";
else
    classification = "NOT_SUPPORTED";
end
end
