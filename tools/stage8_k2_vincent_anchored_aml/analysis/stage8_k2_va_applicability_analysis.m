function output = stage8_k2_va_applicability_analysis(repo_dir, write_outputs)
%STAGE8_K2_VA_APPLICABILITY_ANALYSIS Offline closure of anchored AML scope.

if nargin < 1 || isempty(repo_dir)
    repo_dir = derive_repo_root_local();
end
if nargin < 2 || isempty(write_outputs)
    write_outputs = true;
end
repo_dir = char(repo_dir);
paths = paths_local(repo_dir);
trials = read_table_local(paths.trials);
diagnostics = read_table_local(paths.diagnostics);
historical_summary = read_table_local(paths.summary);
historical_profile = read_table_local(paths.profile_summary);
historical_complexity = read_table_local(paths.complexity);
historical_report = fileread(paths.experiment_report);

integrity = validate_integrity_local(trials, diagnostics);
[summary_max_error, summary_ok] = reconstruct_summary_local( ...
    trials, historical_summary);
profile_ok = validate_profile_summary_local( ...
    historical_summary, historical_profile);
complexity_ok = validate_complexity_local( ...
    trials, historical_complexity);
report_ok = contains(historical_report, ...
    'STAGE8_K2_VINCENT_ANCHORED_AML_NOT_RETAINED') && ...
    contains(historical_report, 'Production integration authorized: false');
integrity.summary_reconstruction_max_abs_error = summary_max_error;
integrity.summary_reconstruction_ok = summary_ok;
integrity.profile_summary_ok = profile_ok;
integrity.complexity_summary_ok = complexity_ok;
integrity.historical_report_ok = report_ok;
integrity.pass = integrity.count_contract_ok && ...
    integrity.method_contract_ok && integrity.hash_contract_ok && ...
    integrity.truth_isolation_ok && summary_ok && profile_ok && ...
    complexity_ok && report_ok;
if ~integrity.pass
    error('stage8_k2_va_applicability_analysis:Integrity', ...
        'The committed 36-series evidence failed an integrity contract.');
end

paired_trials = build_paired_trials_local(trials, diagnostics);
group_summary = build_group_summary_local(paired_trials);
diagnostic_quartiles = build_diagnostic_quartiles_local(paired_trials);
claim_matrix = build_claim_matrix_local( ...
    paired_trials, group_summary, diagnostic_quartiles);
final_state = determine_final_state_local(group_summary);
positioning = positioning_local(final_state);

output = struct( ...
    'protocol', ...
    "STAGE8_K2_VINCENT_ANCHORED_APPLICABILITY_AND_CLOSURE_V1", ...
    'analysis_only_flag', true, 'fitting_rerun', false, ...
    'new_trial_count', 0, 'new_seed_count', 0, ...
    'external_runtime_inputs_required', false, ...
    'integrity', integrity, 'paired_trials', paired_trials, ...
    'group_summary', group_summary, ...
    'diagnostic_quartiles', diagnostic_quartiles, ...
    'claim_matrix', claim_matrix, 'final_state', final_state, ...
    'positioning', positioning, 'output_paths', paths.outputs);
if write_outputs
    write_outputs_local(output, paths);
end
end

