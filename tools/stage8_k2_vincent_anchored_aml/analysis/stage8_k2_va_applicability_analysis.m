            subset.delta_vector_error_deg);
        row.raw_candidate_valid_rate = mean(double( ...
            subset.raw_candidate_valid));
        row.fallback_rate = mean(double(subset.fallback_flag));
        rows(end + 1, 1) = row; %#ok<AGROW>
    end
end
quartiles = struct2table(rows);
