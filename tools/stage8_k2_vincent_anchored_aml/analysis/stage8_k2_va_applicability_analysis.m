function claims = build_claim_matrix_local(paired, groups, quartiles)
rows = repmat(claim_template_local(), 0, 1);
for index = 1:height(groups)
    row = claim_template_local();
    fields = fieldnames(row);
    for field_index = 1:numel(fields)
        field = fields{field_index};
        if ismember(field, groups.Properties.VariableNames)
            row.(field) = groups.(field)(index);
        end
    end
    rows(end + 1, 1) = row; %#ok<AGROW>
end
for index = 1:height(quartiles)
    q = quartiles(index, :);
    diagnostic_values = paired.(char(q.diagnostic_name));
    valid_indices = find(isfinite(diagnostic_values));
    [~, order] = sort(diagnostic_values(valid_indices), 'ascend');
    ordered_indices = valid_indices(order);
    numbers = ceil((1:numel(ordered_indices)).' * 4 / ...
        numel(ordered_indices));
    numbers = min(numbers, 4);
    q_number = str2double(extractAfter(q.quartile, 1));
    subset = paired(ordered_indices(numbers == q_number), :);
    metrics = group_row_local("QUARTILE", ...
        q.diagnostic_name + ":" + q.quartile, subset, false);
    row = claim_template_local();
    fields = fieldnames(row);
    for field_index = 1:numel(fields)
        field = fields{field_index};
        if isfield(metrics, field)
            row.(field) = metrics.(field);
        end
    end
    rows(end + 1, 1) = row; %#ok<AGROW>
end
claims = struct2table(rows);
end

