    'mean_SVD_calls', mean_finite_local(rows.SVD_call_count), ...
    'median_runtime_sec', median_finite_local(rows.runtime_sec), ...
    'p90_runtime_sec', percentile_local(rows.runtime_sec, 90));
end

function paired = build_paired_trials_local(trials, diagnostics)
tangent = sortrows(trials(trials.method_id == ...
    "TANGENT_PROFILE_SAFE", :), 'trial_id');
anchored = sortrows(trials(trials.method_id == ...
    "VINCENT_ANCHORED_PROJECTOR_AML_SAFE", :), 'trial_id');
diagnostics = sortrows(diagnostics, 'trial_id');
if height(tangent) ~= 72 || height(anchored) ~= 72 || ...
        height(diagnostics) ~= 72 || ...
        ~isequal(tangent.trial_id, anchored.trial_id) || ...
        ~isequal(tangent.trial_id, diagnostics.trial_id)
    error('stage8_k2_va_applicability_analysis:Pairing', ...
        'Tangent, anchored, and diagnostic trial identities differ.');
end

profile_specs = profile_specs_local();
n = height(tangent);
secondary_power = NaN(n, 1);
registered_correlation = NaN(n, 1);
effective_correlation = NaN(n, 1);
rho_true = NaN(n, 1);
direction_true = NaN(n, 1);
center_true_az = NaN(n, 1);
center_true_el = NaN(n, 1);
k1_center_az = NaN(n, 1);
k1_center_el = NaN(n, 1);
axis_az = NaN(n, 1);
axis_el = NaN(n, 1);
alpha_true = NaN(n, 1);
b_parallel = NaN(n, 1);
b_perp = NaN(n, 1);
alpha_error = NaN(n, 1);
kappa = NaN(n, 1);
for index = 1:n
    spec = profile_specs(profile_specs.profile_id == ...
        tangent.profile_id(index), :);
    if height(spec) ~= 1
        error('stage8_k2_va_applicability_analysis:Profile', ...
            'Unknown frozen profile.');
    end
    secondary_power(index) = spec.secondary_power_db;
    registered_correlation(index) = spec.correlation_magnitude;
    effective_correlation(index) = spec.correlation_magnitude;
    if tangent.L(index) == 1
        effective_correlation(index) = 1;
    end
    rho_true(index) = spec.rho_true_deg;
    direction_true(index) = spec.direction_true_deg;
    center_true_az(index) = spec.center_az_deg;
    center_true_el(index) = spec.center_el_deg;
    if abs(tangent.separation_true_deg(index) - rho_true(index)) > 1e-12
        error('stage8_k2_va_applicability_analysis:Truth', ...
            'Serialized separation differs from the frozen profile.');
    end
    k1_center = stage8_k2_va_parse_numeric_vector( ...
        diagnostics.K1_center_deg(index), 2);
    axis_hat = stage8_k2_va_parse_numeric_vector( ...
        diagnostics.tangent_axis_hat(index), 2);
    k1_center_az(index) = k1_center(1);
    k1_center_el(index) = k1_center(2);
    axis_az(index) = axis_hat(1);
    axis_el(index) = axis_hat(2);
    geometry = stage8_k2_va_geometry_metrics( ...
        [spec.center_az_deg, spec.center_el_deg], k1_center, axis_hat, ...
        rho_true(index), diagnostics.selected_alpha_deg(index));
    alpha_true(index) = geometry.alpha_true_deg;
    b_parallel(index) = geometry.b_parallel_abs;
    b_perp(index) = geometry.b_perp;
    alpha_error(index) = ...
        geometry.alpha_correction_error_normalized;
    if isfinite(diagnostics.q0(index)) && ...
            isfinite(diagnostics.q2(index)) && diagnostics.q2(index) < 0
        kappa(index) = -diagnostics.q2(index) * rho_true(index)^2 / ...
            max(abs(diagnostics.q0(index)), eps);
    end
end

