    "K1_center_error_over_rho", "diagnostic_axis_error_deg", ...
    "anchor_valid_ratio", "kappa_rho_selected"];
rows = repmat(quartile_template_local(), 0, 1);
for diagnostic_name = diagnostic_names
    values = paired.(char(diagnostic_name));
    valid_indices = find(isfinite(values));
    [~, order] = sort(values(valid_indices), 'ascend');
    ordered_indices = valid_indices(order);
    quartile_number = ceil((1:numel(ordered_indices)).' * 4 / ...
        numel(ordered_indices));
    quartile_number = min(quartile_number, 4);
    for number = 1:4
        selected = ordered_indices(quartile_number == number);
        subset = paired(selected, :);
        row = quartile_template_local();
