function state = determine_final_state_local(groups)
profiles = groups(groups.scope_type == "PROFILE", :);
broad = groups(ismember(groups.scope_type, ["L", "SNR", "NOISE"]), :);
supported = "SUPPORTED_ENDPOINT_AND_SEPARATION";
if nnz(profiles.classification == supported) >= 2 || ...
        any(broad.classification == supported)
    state = ...
        "STAGE8_K2_VINCENT_ANCHORED_APPLICABILITY_CLOSED_BROADER_REGIME_SUPPORTED";
elseif any(profiles.scope_value == "P1" & ...
        profiles.classification == supported)
    state = ...
        "STAGE8_K2_VINCENT_ANCHORED_APPLICABILITY_CLOSED_P1_LIKE_ONLY";
elseif ~any(profiles.classification == supported)
    state = ...
        "STAGE8_K2_VINCENT_ANCHORED_APPLICABILITY_CLOSED_NO_ROBUST_REGIME";
else
    error('stage8_k2_va_applicability_analysis:ClosureState', ...
        'The frozen closure rules do not produce a unique state.');
end
end

function value = positioning_local(state)
switch char(state)
    case 'STAGE8_K2_VINCENT_ANCHORED_APPLICABILITY_CLOSED_BROADER_REGIME_SUPPORTED'
        value = "BROAD RESEARCH OPTION";
    case 'STAGE8_K2_VINCENT_ANCHORED_APPLICABILITY_CLOSED_P1_LIKE_ONLY'
        value = "P1-LIKE FAVORABLE-REGIME RESEARCH VARIANT";
    case 'STAGE8_K2_VINCENT_ANCHORED_APPLICABILITY_CLOSED_NO_ROBUST_REGIME'
        value = "NO ROBUST APPLICABILITY REGIME";
    otherwise
        error('stage8_k2_va_applicability_analysis:Positioning', ...
            'Unknown closure state.');
end
end

function write_outputs_local(output, paths)
names = fieldnames(paths.outputs);
for index = 1:numel(names)
    if isfile(paths.outputs.(names{index}))
        error('stage8_k2_va_applicability_analysis:ExistingOutput', ...
            'Refusing to overwrite: %s', paths.outputs.(names{index}));
    end
end
created = strings(0, 1);
try
    writetable(output.paired_trials, paths.outputs.trials);
    created(end + 1) = string(paths.outputs.trials);
    writetable(output.group_summary, paths.outputs.group_summary);
    created(end + 1) = string(paths.outputs.group_summary);
    writetable(output.diagnostic_quartiles, ...
        paths.outputs.diagnostic_quartiles);
    created(end + 1) = string(paths.outputs.diagnostic_quartiles);
    writetable(output.claim_matrix, paths.outputs.claim_matrix);
    created(end + 1) = string(paths.outputs.claim_matrix);
    write_report_local(paths.outputs.report, output);
    created(end + 1) = string(paths.outputs.report);
catch exception
    for index = 1:numel(created)
        if isfile(created(index))
            delete(created(index));
        end
    end
    rethrow(exception);
end
end

