function table_now = read_table_local(path_now)
if ~isfile(path_now)
    error('stage8_k2_va_applicability_analysis:MissingInput', ...
        'Missing committed evidence: %s', path_now);
end
options = detectImportOptions(path_now, 'TextType', 'string');
