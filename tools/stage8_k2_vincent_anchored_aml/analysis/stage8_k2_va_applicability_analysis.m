        row.quartile = "Q" + string(number);
        row.N = height(subset);
        row.value_min = min(values(selected));
        row.value_max = max(values(selected));
        row.wins = nnz(subset.pair_label == "WIN");
        row.ties = nnz(subset.pair_label == "TIE");
        row.losses = nnz(subset.pair_label == "LOSS");
        row.median_delta_joint_RMSE_deg = median_finite_local( ...
            subset.delta_joint_RMSE_deg);
        row.p90_delta_joint_RMSE_deg = percentile_local( ...
            subset.delta_joint_RMSE_deg, 90);
