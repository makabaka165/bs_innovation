    'trial_count', height(rows), ...
    'valid_count', nnz(logical(rows.fit_valid)), ...
    'median_joint_RMSE_deg', median_finite_local( ...
    rows.joint_RMSE_deg(valid)), ...
    'p90_joint_RMSE_deg', percentile_local( ...
    rows.joint_RMSE_deg(valid), 90), ...
    'median_center_error_deg', median_finite_local( ...
    rows.center_error_deg(valid)), ...
    'p90_center_error_deg', percentile_local( ...
    rows.center_error_deg(valid), 90), ...
    'median_axis_error_deg', median_finite_local( ...
    rows.axis_error_deg(valid)), ...
    'p90_axis_error_deg', percentile_local( ...
    rows.axis_error_deg(valid), 90), ...
    'median_rho_error_deg', median_finite_local( ...
    rows.separation_error_deg(valid)), ...
    'p90_rho_error_deg', percentile_local( ...
    rows.separation_error_deg(valid), 90), ...
    'median_separation_vector_error_deg', median_finite_local( ...
    rows.separation_vector_error_deg(valid)), ...
    'p90_separation_vector_error_deg', percentile_local( ...
    rows.separation_vector_error_deg(valid), 90), ...
