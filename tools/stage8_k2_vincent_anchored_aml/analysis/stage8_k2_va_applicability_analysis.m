function groups = build_group_summary_local(paired)
rows = repmat(group_template_local(), 0, 1);
profiles = ["P1", "P2", "P3", "P4"];
L_values = [1, 4, 8];
snr_values = [-6, 0, 6];
noise_values = ["WHITE", "STAGE5_TOEPLITZ_CORRELATED"];
for value = profiles
    rows(end + 1, 1) = group_row_local("PROFILE", value, ...
        paired(paired.profile_id == value, :), true); %#ok<AGROW>
end
for value = L_values
    rows(end + 1, 1) = group_row_local("L", string(value), ...
        paired(paired.L == value, :), true); %#ok<AGROW>
end
for value = snr_values
    rows(end + 1, 1) = group_row_local("SNR", string(value), ...
        paired(paired.SNR == value, :), true); %#ok<AGROW>
end
for value = noise_values
    rows(end + 1, 1) = group_row_local("NOISE", value, ...
        paired(paired.noise_profile_id == value, :), true); %#ok<AGROW>
end
for profile = profiles
    for value = L_values
        scope_value = profile + "|L=" + string(value);
        rows(end + 1, 1) = group_row_local("PROFILE_X_L", ...
            scope_value, paired(paired.profile_id == profile & ...
            paired.L == value, :), false); %#ok<AGROW>
    end
    for value = snr_values
        scope_value = profile + "|SNR=" + string(value);
        rows(end + 1, 1) = group_row_local("PROFILE_X_SNR", ...
            scope_value, paired(paired.profile_id == profile & ...
            paired.SNR == value, :), false); %#ok<AGROW>
    end
    for value = noise_values
        scope_value = profile + "|NOISE=" + value;
        rows(end + 1, 1) = group_row_local("PROFILE_X_NOISE", ...
            scope_value, paired(paired.profile_id == profile & ...
            paired.noise_profile_id == value, :), false); %#ok<AGROW>
    end
end
groups = struct2table(rows);
end

