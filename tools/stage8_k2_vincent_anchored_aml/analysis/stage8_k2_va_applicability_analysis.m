function integrity = validate_integrity_local(trials, diagnostics)
expected_methods = sort(["CORE_LITE"; "TANGENT_PROFILE_SAFE"; ...
    "VINCENT_ANCHORED_PROJECTOR_AML_SAFE"; ...
    "FULL4D_BEAMSPACE_CML_MULTISTART"]);
trial_ids = unique(trials.trial_id);
integrity = struct( ...
    'method_rows', height(trials), ...
    'unique_trials', numel(trial_ids), ...
    'diagnostic_rows', height(diagnostics), ...
    'count_contract_ok', height(trials) == 288 && ...
    numel(trial_ids) == 72 && height(diagnostics) == 72 && ...
    numel(unique(diagnostics.trial_id)) == 72, ...
    'method_contract_ok', true, 'hash_contract_ok', true, ...
    'truth_isolation_ok', ...
    ~any(logical(trials.truth_used_in_fit_flag)) && ...
    ~any(logical(diagnostics.truth_used_in_fit_flag)));
if ~integrity.count_contract_ok
    integrity.method_contract_ok = false;
    integrity.hash_contract_ok = false;
    return;
end
for index = 1:numel(trial_ids)
    id = trial_ids(index);
    method_rows = trials(trials.trial_id == id, :);
    diagnostic = diagnostics(diagnostics.trial_id == id, :);
    integrity.method_contract_ok = integrity.method_contract_ok && ...
        height(method_rows) == 4 && ...
        isequal(sort(method_rows.method_id), expected_methods);
    integrity.hash_contract_ok = integrity.hash_contract_ok && ...
        height(diagnostic) == 1 && ...
        numel(unique(method_rows.element_trial_hash)) == 1 && ...
        method_rows.element_trial_hash(1) == diagnostic.element_trial_hash;
end
end

function [maximum_error, pass] = reconstruct_summary_local(trials, serialized)
rows = serialized(serialized.row_type == "METHOD", :);
numeric_fields = { ...
    'trial_count', 'valid_count', 'median_joint_RMSE_deg', ...
    'p90_joint_RMSE_deg', 'median_center_error_deg', ...
    'p90_center_error_deg', 'median_axis_error_deg', ...
    'p90_axis_error_deg', 'median_rho_error_deg', ...
    'p90_rho_error_deg', 'median_separation_vector_error_deg', ...
    'p90_separation_vector_error_deg', 'mean_score_calls', ...
    'mean_SVD_calls', 'median_runtime_sec', 'p90_runtime_sec'};
maximum_error = 0;
pass = height(rows) == 52;
for index = 1:height(rows)
    subset = trials(trials.method_id == rows.method_id(index), :);
    subset = select_scope_local(subset, rows.scope_type(index), ...
        rows.scope_value(index));
    recomputed = method_metrics_local(subset);
    for field_index = 1:numel(numeric_fields)
        field = numeric_fields{field_index};
        expected = rows.(field)(index);
        actual = recomputed.(field);
        if isnan(expected) && isnan(actual)
            error_now = 0;
        elseif isfinite(expected) && isfinite(actual)
            error_now = abs(expected - actual);
        else
            error_now = Inf;
        end
        maximum_error = max(maximum_error, error_now);
        pass = pass && error_now <= 1e-10;
    end
end
end

function pass = validate_profile_summary_local(summary, profile)
expected = summary(summary.row_type == "METHOD" & ...
    summary.scope_type == "PROFILE", :);
expected = sortrows(expected, {'method_id', 'scope_value'});
actual = sortrows(profile, {'method_id', 'scope_value'});
pass = height(expected) == 16 && height(actual) == 16 && ...
    isequal(expected.method_id, actual.method_id) && ...
    isequal(expected.scope_value, actual.scope_value);
fields = {'trial_count', 'valid_count', 'median_joint_RMSE_deg', ...
    'p90_joint_RMSE_deg', 'median_center_error_deg', ...
    'p90_center_error_deg', 'median_axis_error_deg', ...
    'p90_axis_error_deg', 'median_rho_error_deg', ...
    'p90_rho_error_deg', 'median_separation_vector_error_deg', ...
    'p90_separation_vector_error_deg', 'mean_score_calls', ...
    'mean_SVD_calls', 'median_runtime_sec', 'p90_runtime_sec'};
for index = 1:numel(fields)
    pass = pass && all(abs(expected.(fields{index}) - ...
        actual.(fields{index})) <= 1e-10);
end
end

function pass = validate_complexity_local(trials, complexity)
methods = unique(trials.method_id);
pass = height(complexity) == 4 && ...
    isequal(sort(methods), sort(complexity.method_id));
for index = 1:numel(methods)
    subset = trials(trials.method_id == methods(index), :);
    row = complexity(complexity.method_id == methods(index), :);
    pass = pass && height(row) == 1 && ...
        row.applicable_count == nnz(logical(subset.applicable)) && ...
        row.valid_count == nnz(logical(subset.fit_valid)) && ...
        abs(row.mean_score_calls - mean_finite_local( ...
        subset.score_call_count)) <= 1e-10 && ...
        abs(row.mean_SVD_calls - mean_finite_local( ...
        subset.SVD_call_count)) <= 1e-10 && ...
        abs(row.median_runtime_sec - median_finite_local( ...
        subset.runtime_sec)) <= 1e-10 && ...
        abs(row.p90_runtime_sec - percentile_local( ...
        subset.runtime_sec, 90)) <= 1e-10;
end
end

function subset = select_scope_local(rows, scope_type, scope_value)
switch char(scope_type)
    case 'ALL'
        subset = rows;
    case 'PROFILE'
        subset = rows(rows.profile_id == scope_value, :);
    case 'L'
        subset = rows(rows.L == str2double(scope_value), :);
    case 'SNR_DB'
        subset = rows(rows.snr_db == str2double(scope_value), :);
    case 'NOISE'
        subset = rows(rows.noise_profile_id == scope_value, :);
    otherwise
        error('stage8_k2_va_applicability_analysis:Scope', ...
            'Unknown historical scope: %s.', scope_type);
end
end

