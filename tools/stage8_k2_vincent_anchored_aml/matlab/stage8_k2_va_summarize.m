function output = stage8_k2_va_summarize( ...
    method_rows, diagnostics, registry, repo_dir, runtime_root, ...
    theory_tests, preflight)
%STAGE8_K2_VA_SUMMARIZE Write the fixed V1 evidence and decision.

if nargin < 6 || isempty(theory_tests)
    theory_tests = struct2table(struct('test_name', "NOT_RECORDED", ...
        'pass', false));
end
if nargin < 7 || isempty(preflight)
    preflight = struct('pass', false, 'last_error', 'NOT_RECORDED');
end
constants = stage8_k2_va_constants();
validate_inputs_local(method_rows, diagnostics, registry, constants);
summary_rows = build_summary_rows_local(method_rows, constants);
paired = build_paired_rows_local(method_rows, constants);
summary_rows = [summary_rows; paired.rows];
summary_table = struct2table(summary_rows);
complexity = build_complexity_local(method_rows, constants);
integrity = integrity_local(method_rows, diagnostics, registry, ...
    constants, preflight);
conclusion = decision_local(summary_table, paired.records, integrity, ...
    constants);
decision_row = summary_template_local();
decision_row.row_type = "DECISION";
decision_row.scope_type = "ALL";
decision_row.scope_value = "ALL";
decision_row.decision = string(conclusion);
summary_table = [summary_table; struct2table(decision_row)];
profile_summary = summary_table(summary_table.row_type == "METHOD" & ...
    summary_table.scope_type == "PROFILE", :);
overall = build_overall_local(summary_table, diagnostics, complexity, ...
    paired.records, constants);

evidence_dir = fullfile(repo_dir, 'innovation-mining');
paths = evidence_paths_local(evidence_dir);
path_names = fieldnames(paths);
for index = 1:numel(path_names)
    if isfile(paths.(path_names{index}))
        error('stage8_k2_va_summarize:ExistingEvidence', ...
            'Refusing to overwrite existing evidence: %s', ...
            paths.(path_names{index}));
    end
end
if ~isfolder(runtime_root)
    mkdir(runtime_root);
end
writetable(method_rows, fullfile(runtime_root, ...
    '36_stage8_k2_vincent_anchored_aml_trials.csv'));
writetable(summary_table, fullfile(runtime_root, ...
    '36_stage8_k2_vincent_anchored_aml_summary.csv'));
writetable(profile_summary, fullfile(runtime_root, ...
    '36_stage8_k2_vincent_anchored_aml_profile_summary.csv'));
writetable(diagnostics, fullfile(runtime_root, ...
    '36_stage8_k2_vincent_anchored_aml_diagnostics.csv'));
writetable(complexity, fullfile(runtime_root, ...
    '36_stage8_k2_vincent_anchored_aml_complexity.csv'));
writetable(theory_tests, fullfile(runtime_root, 'theory_tests.csv'));
writetable(method_rows, paths.trials);
writetable(summary_table, paths.summary);
writetable(profile_summary, paths.profile_summary);
writetable(diagnostics, paths.diagnostics);
writetable(complexity, paths.complexity);
write_report_local(paths.report, method_rows, diagnostics, profile_summary, ...
    complexity, theory_tests, overall, integrity, conclusion, constants, ...
    runtime_root);
output = struct('summary_table', summary_table, ...
    'profile_summary', profile_summary, 'complexity', complexity, ...
    'overall', overall, 'paired', paired, 'integrity', integrity, ...
    'conclusion', conclusion, 'evidence_paths', paths);
end

function rows = build_summary_rows_local(method_rows, constants)
rows = repmat(summary_template_local(), 0, 1);
scope_types = ["ALL"; "PROFILE"; "L"; "SNR_DB"; "NOISE"];
scope_values = {["ALL"], ["P1", "P2", "P3", "P4"], ...
    ["1", "4", "8"], ["-6", "0", "6"], ...
    ["WHITE", "STAGE5_TOEPLITZ_CORRELATED"]};
for method_index = 1:numel(constants.method_ids)
    method_id = constants.method_ids(method_index);
    method_subset = method_rows(method_rows.method_id == method_id, :);
    for scope_index = 1:numel(scope_types)
        for value_index = 1:numel(scope_values{scope_index})
            scope_value = scope_values{scope_index}(value_index);
            subset = select_scope_local(method_subset, ...
                scope_types(scope_index), scope_value);
            rows(end + 1, 1) = metric_row_local(scope_types(scope_index), ...
                scope_value, method_id, subset); %#ok<AGROW>
        end
    end
end
end

function subset = select_scope_local(rows, scope_type, scope_value)
switch char(scope_type)
    case 'ALL'
        subset = rows;
    case 'PROFILE'
        subset = rows(rows.profile_id == scope_value, :);
    case 'L'
        subset = rows(rows.L == str2double(scope_value), :);
    case 'SNR_DB'
        subset = rows(rows.snr_db == str2double(scope_value), :);
    case 'NOISE'
        subset = rows(rows.noise_profile_id == scope_value, :);
    otherwise
        error('stage8_k2_va_summarize:Scope', ...
            'Unknown summary scope.');
end
end

function row = metric_row_local(scope_type, scope_value, method_id, subset)
row = summary_template_local();
row.row_type = "METHOD";
row.scope_type = string(scope_type);
row.scope_value = string(scope_value);
row.method_id = string(method_id);
row.trial_count = height(subset);
row.valid_count = nnz(subset.fit_valid);
valid = subset.fit_valid & isfinite(subset.joint_RMSE_deg);
row.median_joint_RMSE_deg = median_or_nan_local( ...
    subset.joint_RMSE_deg(valid));
row.p90_joint_RMSE_deg = percentile_or_nan_local( ...
    subset.joint_RMSE_deg(valid), 90);
row.median_center_error_deg = median_or_nan_local( ...
    subset.center_error_deg(valid));
row.p90_center_error_deg = percentile_or_nan_local( ...
    subset.center_error_deg(valid), 90);
row.median_axis_error_deg = median_or_nan_local( ...
    subset.axis_error_deg(valid));
row.p90_axis_error_deg = percentile_or_nan_local( ...
    subset.axis_error_deg(valid), 90);
row.median_rho_error_deg = median_or_nan_local( ...
    subset.separation_error_deg(valid));
row.p90_rho_error_deg = percentile_or_nan_local( ...
    subset.separation_error_deg(valid), 90);
row.median_separation_vector_error_deg = median_or_nan_local( ...
    subset.separation_vector_error_deg(valid));
row.p90_separation_vector_error_deg = percentile_or_nan_local( ...
    subset.separation_vector_error_deg(valid), 90);
row.mean_score_calls = mean_or_nan_local(subset.score_call_count);
row.mean_SVD_calls = mean_or_nan_local(subset.SVD_call_count);
row.median_runtime_sec = median_or_nan_local(subset.runtime_sec);
row.p90_runtime_sec = percentile_or_nan_local(subset.runtime_sec, 90);
end

function paired = build_paired_rows_local(method_rows, constants)
specifications = { ...
    "ALL", "ALL", "VINCENT_ANCHORED_PROJECTOR_AML_SAFE", ...
        "TANGENT_PROFILE_SAFE"; ...
    "PROFILE", "P2", "VINCENT_ANCHORED_PROJECTOR_AML_SAFE", ...
        "TANGENT_PROFILE_SAFE"; ...
    "PROFILE", "P4", "VINCENT_ANCHORED_PROJECTOR_AML_SAFE", ...
        "TANGENT_PROFILE_SAFE"; ...
    "ALL", "ALL", "VINCENT_ANCHORED_PROJECTOR_AML_SAFE", ...
        "FULL4D_BEAMSPACE_CML_MULTISTART"};
rows = repmat(summary_template_local(), size(specifications, 1), 1);
records = repmat(struct('comparison_id', "", 'scope_type', "", ...
    'scope_value', "", 'pairs', 0, 'wins', 0, 'ties', 0, 'losses', 0), ...
    size(specifications, 1), 1);
for index = 1:size(specifications, 1)
    scope_type = specifications{index, 1};
    scope_value = specifications{index, 2};
    method_a = specifications{index, 3};
    method_b = specifications{index, 4};
    a = select_scope_local(method_rows( ...
        method_rows.method_id == method_a, :), scope_type, scope_value);
    b = select_scope_local(method_rows( ...
        method_rows.method_id == method_b, :), scope_type, scope_value);
    a = sortrows(a, 'trial_id');
    b = sortrows(b, 'trial_id');
    if ~isequal(a.trial_id, b.trial_id)
        error('stage8_k2_va_summarize:Pairing', ...
            'Paired method rows do not share trial identities.');
    end
    delta = a.joint_RMSE_deg - b.joint_RMSE_deg;
    finite_pair = isfinite(delta);
    tie = finite_pair & abs(delta) <= constants.paired_tie_tolerance_deg;
    win = finite_pair & delta < -constants.paired_tie_tolerance_deg;
    loss = finite_pair & delta > constants.paired_tie_tolerance_deg;
    comparison_id = method_a + "_vs_" + method_b;
    rows(index).row_type = "PAIRED";
    rows(index).scope_type = scope_type;
    rows(index).scope_value = scope_value;
    rows(index).method_id = method_a;
    rows(index).comparison_id = comparison_id;
    rows(index).trial_count = nnz(finite_pair);
    rows(index).paired_count = nnz(finite_pair);
    rows(index).wins = nnz(win);
    rows(index).ties = nnz(tie);
    rows(index).losses = nnz(loss);
    records(index) = struct('comparison_id', comparison_id, ...
        'scope_type', scope_type, 'scope_value', scope_value, ...
        'pairs', nnz(finite_pair), 'wins', nnz(win), ...
        'ties', nnz(tie), 'losses', nnz(loss));
end
paired = struct('rows', rows, 'records', records);
end

function complexity = build_complexity_local(method_rows, constants)
rows = cell(numel(constants.method_ids), 1);
for index = 1:numel(constants.method_ids)
    method_id = constants.method_ids(index);
    subset = method_rows(method_rows.method_id == method_id, :);
    rows{index} = struct('method_id', string(method_id), ...
        'applicable_count', nnz(subset.applicable), ...
        'valid_count', nnz(subset.fit_valid), ...
        'mean_score_calls', mean_or_nan_local(subset.score_call_count), ...
        'mean_SVD_calls', mean_or_nan_local(subset.SVD_call_count), ...
        'median_runtime_sec', median_or_nan_local(subset.runtime_sec), ...
        'p90_runtime_sec', percentile_or_nan_local(subset.runtime_sec, 90));
end
complexity = struct2table(vertcat(rows{:}));
end

function overall = build_overall_local(summary, diagnostics, complexity, ...
    paired_records, constants)
overall = struct();
for index = 1:numel(constants.method_ids)
    method_id = constants.method_ids(index);
    summary_row = lookup_metric_local(summary, method_id, "ALL", "ALL");
    cost = complexity(complexity.method_id == method_id, :);
    field = method_field_local(method_id);
    overall.(field) = struct('valid_count', summary_row.valid_count, ...
        'median_joint_RMSE_deg', summary_row.median_joint_RMSE_deg, ...
        'p90_joint_RMSE_deg', summary_row.p90_joint_RMSE_deg, ...
        'median_center_error_deg', summary_row.median_center_error_deg, ...
        'p90_center_error_deg', summary_row.p90_center_error_deg, ...
        'mean_score_calls', cost.mean_score_calls, ...
        'mean_SVD_calls', cost.mean_SVD_calls, ...
        'median_runtime_sec', cost.median_runtime_sec, ...
        'p90_runtime_sec', cost.p90_runtime_sec);
end
selected_alpha = diagnostics.selected_alpha_deg( ...
    isfinite(diagnostics.selected_alpha_deg));
p2 = diagnostics(diagnostics.profile_id == "P2", :);
p2_alpha = p2.selected_alpha_deg(isfinite(p2.selected_alpha_deg));
overall.anchored_diagnostics = struct( ...
    'raw_valid_count', nnz(diagnostics.raw_candidate_valid), ...
    'upgrade_count', nnz(diagnostics.upgrade_flag), ...
    'fallback_count', nnz(diagnostics.fallback_flag), ...
    'conditional_invalid_count', sum(diagnostics.conditional_invalid_count), ...
    'q2_nonconcave_count', sum(diagnostics.q2_nonconcave_count), ...
    'rho_out_of_contract_count', ...
    sum(diagnostics.rho_out_of_contract_count), ...
    'selected_alpha_median_deg', median_or_nan_local(selected_alpha), ...
    'selected_alpha_p90_deg', percentile_or_nan_local(selected_alpha, 90), ...
    'P2_alpha_median_deg', median_or_nan_local(p2_alpha), ...
    'P2_alpha_p90_deg', percentile_or_nan_local(p2_alpha, 90), ...
    'median_axis_error_deg', median_or_nan_local( ...
        diagnostics.axis_error_deg), ...
    'p90_axis_error_deg', percentile_or_nan_local( ...
        diagnostics.axis_error_deg, 90), ...
    'median_rho_error_deg', median_or_nan_local( ...
        diagnostics.rho_error_deg), ...
    'p90_rho_error_deg', percentile_or_nan_local( ...
        diagnostics.rho_error_deg, 90), ...
    'median_vector_error_deg', median_or_nan_local( ...
        diagnostics.separation_vector_error_deg), ...
    'p90_vector_error_deg', percentile_or_nan_local( ...
        diagnostics.separation_vector_error_deg, 90));
overall.paired = paired_records;
end

function integrity = integrity_local(method_rows, diagnostics, registry, ...
    constants, preflight)
pair_ids = method_rows.trial_id + "|" + method_rows.method_id;
count_ok = height(registry) == constants.trial_count && ...
    height(method_rows) == constants.method_row_count && ...
    height(diagnostics) == constants.trial_count && ...
    numel(unique(pair_ids)) == constants.method_row_count && ...
    numel(unique(diagnostics.trial_id)) == constants.trial_count;
truth_ok = ~any(method_rows.truth_used_in_fit_flag) && ...
    ~any(diagnostics.truth_used_in_fit_flag);
scenario_ok = all(method_rows.single_cpi_flag) && ...
    all(method_rows.same_range_doppler_cell_flag) && ...
    ~any(method_rows.cross_cpi_data_used_flag) && ...
    ~any(method_rows.tracking_input_used_flag) && ...
    ~any(method_rows.K_estimated_inside_module_flag);
hash_ok = true;
registry_ok = true;
for index = 1:height(registry)
    subset = method_rows(method_rows.trial_id == registry.trial_id(index), :);
    diagnostic = diagnostics(diagnostics.trial_id == ...
        registry.trial_id(index), :);
    hash_ok = hash_ok && height(subset) == 4 && height(diagnostic) == 1 && ...
        numel(unique(subset.element_trial_hash)) == 1 && ...
        unique(subset.element_trial_hash) == diagnostic.element_trial_hash;
    registry_ok = registry_ok && height(subset) == 4 && ...
        all(subset.noise_profile_id == registry.noise_profile_id(index)) && ...
        all(subset.L == registry.L(index)) && ...
        all(subset.snr_db == registry.snr_db(index)) && ...
        all(subset.profile_id == registry.profile_id(index)) && ...
        all(subset.source_seed == registry.source_seed(index)) && ...
        all(subset.noise_seed == registry.noise_seed(index));
end
m2 = method_rows(method_rows.method_id == ...
    "VINCENT_ANCHORED_PROJECTOR_AML_SAFE", :);
m2_safe = height(m2) == constants.trial_count && all(m2.fit_valid) && ...
    all(isfinite(m2.RSS)) && all(isfinite(m2.loglik)) && ...
    all(isfinite(m2.joint_RMSE_deg));
required = method_rows(method_rows.method_id ~= ...
    "FULL4D_BEAMSPACE_CML_MULTISTART", :);
finite_required = all(isfinite(required.loglik(required.fit_valid)));
integrity = struct('count_ok', count_ok, 'truth_isolation_ok', truth_ok, ...
    'scenario_ok', scenario_ok, 'element_pairing_ok', hash_ok, ...
    'registry_pairing_ok', registry_ok, 'm2_safe_return_ok', m2_safe, ...
    'finite_required_outputs_ok', finite_required, ...
    'preflight_ok', logical(get_local(preflight, 'pass', false)), ...
    'experiment_valid', count_ok && truth_ok && scenario_ok && hash_ok && ...
    registry_ok && m2_safe && finite_required && ...
    logical(get_local(preflight, 'pass', false)));
end

function conclusion = decision_local(summary_rows, paired_records, ...
    integrity, constants)
if ~integrity.experiment_valid
    conclusion = 'STAGE8_K2_VINCENT_ANCHORED_AML_EXPERIMENT_INVALID';
    return;
end
m2 = lookup_metric_local(summary_rows, ...
    "VINCENT_ANCHORED_PROJECTOR_AML_SAFE", "ALL", "ALL");
m1 = lookup_metric_local(summary_rows, ...
    "TANGENT_PROFILE_SAFE", "ALL", "ALL");
m3 = lookup_metric_local(summary_rows, ...
    "FULL4D_BEAMSPACE_CML_MULTISTART", "ALL", "ALL");
p2_m2 = lookup_metric_local(summary_rows, ...
    "VINCENT_ANCHORED_PROJECTOR_AML_SAFE", "PROFILE", "P2");
p2_m1 = lookup_metric_local(summary_rows, ...
    "TANGENT_PROFILE_SAFE", "PROFILE", "P2");
overall_pair = paired_records(1);
retain = m2.valid_count == constants.trial_count && ...
    m2.median_joint_RMSE_deg <= m1.median_joint_RMSE_deg && ...
    m2.p90_joint_RMSE_deg <= m1.p90_joint_RMSE_deg && ...
    overall_pair.wins >= overall_pair.losses && ...
    p2_m2.median_joint_RMSE_deg < p2_m1.median_joint_RMSE_deg && ...
    p2_m2.median_center_error_deg < p2_m1.median_center_error_deg && ...
    m2.mean_score_calls < m3.mean_score_calls && ...
    m2.mean_SVD_calls < m3.mean_SVD_calls;
if retain
    conclusion = 'STAGE8_K2_VINCENT_ANCHORED_AML_RETAIN';
else
    conclusion = 'STAGE8_K2_VINCENT_ANCHORED_AML_NOT_RETAINED';
end
end

function row = lookup_metric_local(rows, method_id, scope_type, scope_value)
selected = rows(rows.row_type == "METHOD" & rows.method_id == method_id & ...
    rows.scope_type == scope_type & rows.scope_value == scope_value, :);
if height(selected) ~= 1
    error('stage8_k2_va_summarize:MetricLookup', ...
        'Expected exactly one metric row.');
end
row = selected;
end

