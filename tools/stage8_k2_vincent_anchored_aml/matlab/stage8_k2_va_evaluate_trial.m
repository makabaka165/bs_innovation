function [method_rows, diagnostic_row, trial] = ...
    stage8_k2_va_evaluate_trial(spec, context)
%STAGE8_K2_VA_EVALUATE_TRIAL Generate once and evaluate four methods.

if ~(istable(spec) && height(spec) == 1)
    error('stage8_k2_va_evaluate_trial:Spec', ...
        'spec must be exactly one registered trial row.');
end
trial = stage8_k2_va_generate_trial(spec, context);
domain = context.plan.local_domain;
noise_model = trial.model.noise_factorization;
base_opts = struct('mode', 'CORE_LITE', 'return_diagnostics', true);
core_lite = estimate_stage8_known_k_local_cell( ...
    trial.Y_element, trial.model, domain, context.stage5_locked, ...
    noise_model, 2, base_opts);
[tangent, tangent_diagnostics] = stage8_k2_tp_fit_safe( ...
    trial.Y_element, trial.model, context.tangent_context);
[anchored, anchored_diagnostics] = stage8_k2_va_fit_safe( ...
    trial.Y_element, trial.model, context);
full_data = build_stage8_full_data_from_element( ...
    trial.Y_element, trial.model, ...
    struct('data_role', 'SINGLE_CPI_SINGLE_RANGE_DOPPLER_CELL'));
full4d = stage8_k2_cb_full4d_cml(full_data.Zseq_white, trial.model, ...
    domain, 'BEAMSPACE', struct(), context.classical_constants);
full4d.selected_source = 'FULL4D_NUMERICAL_MULTISTART';
full4d.full_manifold_used_flag = true;

rows = repmat(row_template_local(), 4, 1);
rows(1) = result_row_local(spec, trial, core_lite, 'CORE_LITE', ...
    'FROZEN_CORE_LITE', true);
rows(2) = result_row_local(spec, trial, tangent, ...
    'TANGENT_PROFILE_SAFE', 'FROZEN_TANGENT_PROFILE', true);
rows(3) = result_row_local(spec, trial, anchored, ...
    'VINCENT_ANCHORED_PROJECTOR_AML_SAFE', ...
    'VINCENT_ANCHORED_AML', true);
rows(4) = result_row_local(spec, trial, full4d, ...
    'FULL4D_BEAMSPACE_CML_MULTISTART', ...
    'FROZEN_CLASSICAL_FULL4D', true);
method_rows = struct2table(rows);
diagnostic_row = struct2table(diagnostic_row_local( ...
    spec, trial, anchored_diagnostics, anchored, ...
    tangent_diagnostics));
end

function row = result_row_local(spec, trial, result, method_id, source, applicable)
row = row_template_local();
row.global_trial_index = double(spec.global_trial_index);
row.trial_id = string(spec.trial_id);
row.method_id = string(method_id);
row.method_source = string(source);
row.noise_profile_id = string(spec.noise_profile_id);
row.L = double(spec.L);
row.SNR = double(spec.snr_db);
row.snr_db = double(spec.snr_db);
row.profile_id = string(spec.profile_id);
row.source_seed = double(spec.source_seed);
row.noise_seed = double(spec.noise_seed);
row.element_trial_hash = string(trial.element_trial_hash);
row.applicable = logical(applicable);
row.fit_valid = logical(get_local(result, 'fit_valid', false));
row.fit_status = string(get_local(result, 'fit_status', 'NOT_RUN'));
row.selected_source = string(get_local(result, 'selected_source', method_id));
row.selected_start_id = string(get_local(result, 'selected_start_id', ''));
angles = get_local(result, 'angles_hat_deg', NaN(2, 2));
row.angles_hat_deg = string(mat2str(angles, 17));
row.RSS = double(get_local(result, 'rss', NaN));
row.loglik = double(get_local(result, 'loglik_concentrated', NaN));
row.effective_rank = double(get_local(result, 'effective_rank', 0));
row.score_call_count = double(get_local(result, 'score_call_count', 0));
row.SVD_call_count = double(get_local(result, 'svd_call_count', 0));
row.runtime_sec = double(get_local(result, 'runtime_sec', 0));
row.full_manifold_used_flag = logical(get_local(result, ...
    'full_manifold_used_flag', false));
row.truth_used_in_fit_flag = logical(get_local(result, ...
    'truth_used_in_fit_flag', false));
row.single_cpi_flag = logical(get_local(result, ...
    'single_cpi_flag', true));
row.same_range_doppler_cell_flag = logical(get_local(result, ...
    'same_range_doppler_cell_flag', true));
row.cross_cpi_data_used_flag = logical(get_local(result, ...
    'cross_cpi_data_used_flag', false));
row.tracking_input_used_flag = logical(get_local(result, ...
    'tracking_input_used_flag', false));
row.K_estimated_inside_module_flag = logical(get_local(result, ...
    'K_estimated_inside_module_flag', false));
if row.fit_valid
    metrics = stage8_k2_va_metrics(angles, trial.truth_angles_deg);
    names = {'joint_RMSE_deg','azimuth_RMSE_deg', ...
        'elevation_RMSE_deg','center_error_deg','axis_error_deg', ...
        'separation_true_deg','separation_hat_deg', ...
        'separation_error_deg','separation_vector_error_deg'};
    for index = 1:numel(names)
        row.(names{index}) = metrics.(names{index});
    end
end
end

function row = row_template_local()
row = struct('global_trial_index', 0, 'trial_id', "", ...
    'method_id', "", 'method_source', "", 'noise_profile_id', "", ...
    'L', 0, 'SNR', NaN, 'snr_db', NaN, 'profile_id', "", ...
    'source_seed', 0, 'noise_seed', 0, 'element_trial_hash', "", ...
    'applicable', false, 'fit_valid', false, 'fit_status', "NOT_RUN", ...
    'selected_source', "", 'selected_start_id', "", 'angles_hat_deg', "", ...
    'RSS', NaN, 'loglik', NaN, 'effective_rank', 0, ...
    'joint_RMSE_deg', NaN, 'azimuth_RMSE_deg', NaN, ...
    'elevation_RMSE_deg', NaN, 'center_error_deg', NaN, ...
    'axis_error_deg', NaN, 'separation_true_deg', NaN, ...
    'separation_hat_deg', NaN, 'separation_error_deg', NaN, ...
    'separation_vector_error_deg', NaN, 'score_call_count', 0, ...
    'SVD_call_count', 0, 'runtime_sec', 0, ...
    'full_manifold_used_flag', false, 'truth_used_in_fit_flag', false, ...
    'single_cpi_flag', true, 'same_range_doppler_cell_flag', true, ...
    'cross_cpi_data_used_flag', false, ...
    'tracking_input_used_flag', false, ...
    'K_estimated_inside_module_flag', false);
end

function row = diagnostic_row_local(spec, trial, diagnostics, anchored, ...
    tangent_diagnostics)
truth = trial.truth_angles_deg;
true_center = mean(truth, 1);
true_axis = truth(2, :) - truth(1, :);
true_axis = true_axis / norm(true_axis);
if true_axis(2) < -1e-12 || ...
        (abs(true_axis(2)) <= 1e-12 && true_axis(1) < 0)
    true_axis = -true_axis;
end
axis_error = NaN;
if all(isfinite(diagnostics.tangent_axis_hat))
    axis_error = stage8_k2_tp_axis_error_deg( ...
        diagnostics.tangent_axis_hat, true_axis);
end
k1_center_error = NaN;
if all(isfinite(diagnostics.K1_center_deg(:)))
    k1_center_error = norm(reshape(diagnostics.K1_center_deg, 1, 2) - ...
        true_center);
end
anchored_metrics = stage8_k2_va_metrics( ...
    anchored.angles_hat_deg, truth);
rho_true = norm(truth(2, :) - truth(1, :));
rho_error = NaN;
rho_relative_error = NaN;
if isfinite(diagnostics.selected_rho_deg)
    rho_error = abs(diagnostics.selected_rho_deg - rho_true);
    rho_relative_error = rho_error / rho_true;
end
row = struct('trial_id', string(spec.trial_id), ...
    'element_trial_hash', string(trial.element_trial_hash), ...
    'noise_profile_id', string(spec.noise_profile_id), ...
    'L', double(spec.L), 'SNR', double(spec.snr_db), ...
    'snr_db', double(spec.snr_db), 'profile_id', string(spec.profile_id), ...
    'K1_center_deg', string(mat2str(diagnostics.K1_center_deg, 17)), ...
    'K1_center_error_deg', double(k1_center_error), ...
    'tangent_axis_hat', ...
    string(mat2str(diagnostics.tangent_axis_hat, 17)), ...
    'axis_status', string(diagnostics.axis_status), ...
    'axis_error_deg', double(axis_error), ...
    'line_t_min_deg', double(diagnostics.line_t_min_deg), ...
    'line_t_max_deg', double(diagnostics.line_t_max_deg), ...
    'raw_anchor_valid_count', double(diagnostics.raw_anchor_valid_count), ...
    'anchor_scan_node_count', double(diagnostics.anchor_scan_node_count), ...
    'selected_t_deg', double(diagnostics.selected_t_deg), ...
    'selected_rho_deg', double(diagnostics.selected_rho_deg), ...
    'selected_alpha_deg', double(diagnostics.selected_alpha_deg), ...
    'q0', double(diagnostics.q0), 'q1', double(diagnostics.q1), ...
    'q2', double(diagnostics.q2), ...
    'curvature_valid_flag', logical(diagnostics.curvature_valid_flag), ...
    'B0_rank', double(diagnostics.B0_rank), ...
    'B0_condition', double(diagnostics.B0_condition), ...
    'projector_expansion_status', ...
    string(diagnostics.projector_expansion_status), ...
    'conditional_status', string(diagnostics.conditional_status), ...
    'conditional_invalid_count', ...
    double(diagnostics.conditional_invalid_count), ...
    'q2_nonconcave_count', double(diagnostics.q2_nonconcave_count), ...
    'rho_out_of_contract_count', ...
    double(diagnostics.rho_out_of_contract_count), ...
    'raw_candidate_valid', logical(diagnostics.raw_candidate_valid), ...
    'raw_candidate_angles', ...
    string(mat2str(diagnostics.raw_candidate_angles, 17)), ...
    'raw_candidate_loglik', double(diagnostics.raw_candidate_loglik), ...
    'raw_candidate_RSS', double(diagnostics.raw_candidate_RSS), ...
    'upgrade_flag', logical(diagnostics.upgrade_flag), ...
    'fallback_flag', logical(diagnostics.fallback_flag), ...
    'fallback_reason', string(diagnostics.fallback_reason), ...
    'center_error_deg', double(anchored_metrics.center_error_deg), ...
    'rho_error_deg', double(rho_error), ...
    'rho_relative_error', double(rho_relative_error), ...
    'separation_vector_error_deg', ...
    double(anchored_metrics.separation_vector_error_deg), ...
    'joint_RMSE_deg', double(anchored_metrics.joint_RMSE_deg), ...
    'score_call_count', double(anchored.score_call_count), ...
    'SVD_call_count', double(anchored.svd_call_count), ...
    'runtime_sec', double(anchored.runtime_sec), ...
    'tangent_raw_candidate_valid', ...
    logical(tangent_diagnostics.raw_tangent_candidate_valid), ...
    'truth_used_in_fit_flag', false);
end

function value = get_local(input, field, default)
if isfield(input, field)
    value = input.(field);
else
    value = default;
end
end
