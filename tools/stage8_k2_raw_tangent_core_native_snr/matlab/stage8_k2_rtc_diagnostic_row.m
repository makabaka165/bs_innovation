function row = stage8_k2_rtc_diagnostic_row(spec, diagnostic, method_row)
row = struct('scenario_id',spec.scenario_id,'profile_id',spec.profile_id, ...
    'L',spec.L,'replicate_id',spec.replicate_id,'nominal_snr_db',spec.nominal_snr_db, ...
    'K1_center_az_deg',diagnostic.k1.angles_hat_deg(1), ...
    'K1_center_el_deg',diagnostic.k1.angles_hat_deg(2), ...
    'K1_fit_valid',diagnostic.k1.fit_valid,'K1_status',string(diagnostic.k1.fit_status), ...
    'K1_coarse_count',diagnostic.k1.coarse_count,'metric_rank',NaN, ...
    'metric_condition',NaN,'direction_az',NaN,'direction_el',NaN, ...
    'rho_hat_deg',NaN,'rho_max_deg',NaN,'profile_node_count',0, ...
    'fit_valid',method_row.fit_valid,'fit_status',method_row.fit_status, ...
    'axis_error_deg',method_row.axis_error_deg,'rho_error_deg',method_row.rho_error_deg);
if isfield(diagnostic.direction,'metric_rank')
    row.metric_rank=diagnostic.direction.metric_rank;
    row.metric_condition=diagnostic.direction.metric_condition;
    if diagnostic.direction.valid
        row.direction_az=diagnostic.direction.direction_hat(1);
        row.direction_el=diagnostic.direction.direction_hat(2);
    end
end
if isfield(diagnostic.scale,'rho_hat_deg')
    row.rho_hat_deg=diagnostic.scale.rho_hat_deg;
    row.rho_max_deg=diagnostic.scale.rho_max_deg;
    row.profile_node_count=numel(diagnostic.scale.trace);
end
end
