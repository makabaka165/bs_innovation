function output = stage8_k2_sb_summarize( ...
    new_rows, elevation_diagnostics, context, resources, runtime_root)
%STAGE8_K2_SB_SUMMARIZE Validate and write all registered evidence tables.

constants = context.constants;
integrity = validate_new_rows_local(new_rows, elevation_diagnostics, context);
references = stage8_k2_sb_frozen_reference_rows(context, new_rows);
rows = [references; new_rows];
rows = sortrows(rows, {'global_trial_index','method_id'});
summary = summary_local(rows, constants);
profile_summary = profile_summary_local(rows, constants);
applicability = applicability_local(rows, constants);
complexity = complexity_local(rows);
structure = stage8_k2_sb_structure_diagnostics(context);

runtime_paths = evidence_paths_local(runtime_root);
repo_paths = evidence_paths_local(fullfile(context.repo_dir, ...
    'innovation-mining'));
write_tables_local(rows, summary, profile_summary, applicability, ...
    complexity, elevation_diagnostics, runtime_paths);
write_tables_local(rows, summary, profile_summary, applicability, ...
    complexity, elevation_diagnostics, repo_paths);
write_report_local(runtime_paths.report, rows, summary, profile_summary, ...
    elevation_diagnostics, integrity, structure, resources, constants, ...
    runtime_root);
write_report_local(repo_paths.report, rows, summary, profile_summary, ...
    elevation_diagnostics, integrity, structure, resources, constants, ...
    runtime_root);
output = struct('rows', rows, 'new_rows', new_rows, ...
    'references', references, 'summary', summary, ...
    'profile_summary', profile_summary, ...
    'applicability', applicability, 'complexity', complexity, ...
    'elevation_diagnostics', elevation_diagnostics, ...
    'integrity', integrity, 'structure', structure, ...
    'runtime_paths', runtime_paths, 'repo_paths', repo_paths);
end

function integrity = validate_new_rows_local(rows, diagnostics, context)
constants = context.constants;
counts_ok = height(rows) == constants.new_method_row_count && ...
    height(diagnostics) == constants.new_method_row_count;
for index = 1:numel(constants.method_ids)
    counts_ok = counts_ok && ...
        nnz(rows.method_id == constants.method_ids(index)) == ...
        constants.trial_count;
end
hash_ok = all(rows.element_hash_match_flag) && ...
    numel(unique(rows.trial_id)) == constants.trial_count;
for index = 1:height(context.registry)
    selected = rows.trial_id == context.registry.trial_id(index);
    expected = context.cb_context.frozen_trial_identity.element_trial_hash(index);
    hash_ok = hash_ok && nnz(selected) == numel(constants.method_ids) && ...
        all(rows.element_trial_hash(selected) == expected);
end
truth_ok = ~any(rows.truth_used_in_fit_flag) && ...
    ~any(rows.profile_used_in_fit_flag) && ...
    ~any(rows.tangent_used_in_start_flag) && ...
    ~any(rows.core_used_in_start_flag) && ...
    ~any(diagnostics.truth_used_in_fit_flag) && ...
    ~any(diagnostics.profile_used_in_fit_flag);
expected_applicable = [54, 27, 27];
applicability_ok = true;
outcomes_ok = true;
for index = 1:numel(constants.method_ids)
    subset = rows(rows.method_id == constants.method_ids(index), :);
    applicability_ok = applicability_ok && ...
        nnz(subset.applicable) == expected_applicable(index);
    outcomes_ok = outcomes_ok && ...
        all(subset.fit_status(subset.applicable) ~= "NOT_RUN") && ...
        all(~subset.fit_valid(~subset.applicable)) && ...
        all(subset.applicability_status(subset.applicable) == "APPLICABLE") && ...
        all(subset.applicability_status(~subset.applicable) ~= "APPLICABLE");
end
p2 = rows.profile_id == "P2";
applicability_ok = applicability_ok && all(~rows.applicable(p2)) && ...
    all(rows.applicability_status(p2) == ...
    "NOT_APPLICABLE_EQUAL_ELEVATION_MULTIPLICITY");
root_colored = rows.method_id == ...
    "ELEMENT_VERTICAL_FBSS_ROOT_MUSIC_AZ_CML" & ...
    rows.noise_profile_id ~= "WHITE" & ~p2;
esprit_colored = rows.method_id == ...
    "ELEMENT_VERTICAL_FBSS_LS_ESPRIT_AZ_CML" & ...
    rows.noise_profile_id ~= "WHITE" & ~p2;
applicability_ok = applicability_ok && all(~rows.applicable(root_colored)) && ...
    all(rows.applicability_status(root_colored) == ...
    "NOT_APPLICABLE_COLORED_NOISE_STANDARD_ROOT_MUSIC") && ...
    all(~rows.applicable(esprit_colored)) && ...
    all(rows.applicability_status(esprit_colored) == ...
    "NOT_APPLICABLE_COLORED_NOISE_STANDARD_ESPRIT");
integrity = struct('counts_ok', counts_ok, 'element_hashes_ok', hash_ok, ...
    'truth_isolation_ok', truth_ok, ...
    'applicability_contract_ok', applicability_ok, ...
    'explicit_outcomes_ok', outcomes_ok, ...
    'experiment_integrity_ok', counts_ok && hash_ok && truth_ok && ...
    applicability_ok && outcomes_ok);
if ~integrity.experiment_integrity_ok
    error('stage8_k2_sb_summarize:Integrity', ...
        'Formal subspace comparison failed a protocol integrity contract.');
end
end

function summary = summary_local(rows, constants)
items = repmat(summary_template_local(), 0, 1);
all_methods = [constants.reference_method_ids; constants.method_ids];
for index = 1:numel(all_methods)
    subset = rows(rows.method_id == all_methods(index), :);
    item = metric_item_local(subset);
    item.row_type = "METHOD";
    item.method_id = all_methods(index);
    items(end + 1, 1) = item; %#ok<AGROW>
end
for new_index = 1:numel(constants.method_ids)
    for reference_index = 1:numel(constants.reference_method_ids)
        items(end + 1, 1) = pair_item_local(rows, ...
            constants.method_ids(new_index), ...
            constants.reference_method_ids(reference_index), ...
            constants); %#ok<AGROW>
    end
end
for first = 1:numel(constants.method_ids)-1
    for second = first+1:numel(constants.method_ids)
        items(end + 1, 1) = pair_item_local(rows, ...
            constants.method_ids(first), constants.method_ids(second), ...
            constants); %#ok<AGROW>
    end
end
summary = struct2table(items);
end

function item = metric_item_local(subset)
item = summary_template_local();
valid = subset(subset.applicable & subset.fit_valid, :);
item.total_row_count = height(subset);
item.applicable_count = nnz(subset.applicable);
item.valid_count = height(valid);
item.applicable_but_invalid_count = ...
    nnz(subset.applicable & ~subset.fit_valid);
metrics = {'joint_RMSE_deg','azimuth_RMSE_deg','elevation_RMSE_deg', ...
    'center_error_deg','axis_error_deg','separation_error_deg', ...
    'separation_vector_error_deg','runtime_sec'};
for index = 1:numel(metrics)
    name = metrics{index};
    item.(['median_', name]) = median_local(valid.(name));
    item.(['p90_', name]) = percentile_local(valid.(name), 90);
end
item.mean_score_calls = mean_local(subset.score_call_count(subset.applicable));
item.mean_svd_calls = mean_local(subset.svd_call_count(subset.applicable));
item.mean_eig_calls = mean_local(subset.eig_call_count(subset.applicable));
end

function item = pair_item_local(rows, left_id, right_id, constants)
item = summary_template_local();
item.row_type = "PAIRED";
item.method_id = left_id;
item.reference_method_id = right_id;
item.comparison_id = left_id + "_vs_" + right_id;
left = rows(rows.method_id == left_id, :);
right = rows(rows.method_id == right_id, :);
[~, left_index, right_index] = intersect( ...
    left.trial_id, right.trial_id, 'stable');
selected = left.applicable(left_index) & left.fit_valid(left_index) & ...
    right.applicable(right_index) & right.fit_valid(right_index);
left_index = left_index(selected);
right_index = right_index(selected);
delta = left.joint_RMSE_deg(left_index) - ...
    right.joint_RMSE_deg(right_index);
item.paired_count = numel(delta);
item.wins = nnz(delta < -constants.paired_tie_tolerance_deg);
item.ties = nnz(abs(delta) <= constants.paired_tie_tolerance_deg);
item.losses = nnz(delta > constants.paired_tie_tolerance_deg);
end

function item = summary_template_local()
item = struct('row_type', "", 'comparison_id', "", ...
    'method_id', "", 'reference_method_id', "", ...
    'total_row_count', 0, 'applicable_count', 0, 'valid_count', 0, ...
    'applicable_but_invalid_count', 0, ...
    'median_joint_RMSE_deg', NaN, 'p90_joint_RMSE_deg', NaN, ...
    'median_azimuth_RMSE_deg', NaN, 'p90_azimuth_RMSE_deg', NaN, ...
    'median_elevation_RMSE_deg', NaN, 'p90_elevation_RMSE_deg', NaN, ...
    'median_center_error_deg', NaN, 'p90_center_error_deg', NaN, ...
    'median_axis_error_deg', NaN, 'p90_axis_error_deg', NaN, ...
    'median_separation_error_deg', NaN, ...
    'p90_separation_error_deg', NaN, ...
    'median_separation_vector_error_deg', NaN, ...
    'p90_separation_vector_error_deg', NaN, ...
    'median_runtime_sec', NaN, 'p90_runtime_sec', NaN, ...
    'mean_score_calls', NaN, 'mean_svd_calls', NaN, ...
    'mean_eig_calls', NaN, 'paired_count', 0, ...
    'wins', 0, 'ties', 0, 'losses', 0);
end

function output = profile_summary_local(rows, constants)
items = repmat(profile_template_local(), 0, 1);
methods = [constants.reference_method_ids; constants.method_ids];
definitions = ["PROFILE", "P1"; "PROFILE", "P2"; ...
    "PROFILE", "P3"; "PROFILE", "P4"; ...
    "L", "1"; "L", "4"; "L", "8"; ...
    "SNR_DB", "-6"; "SNR_DB", "0"; "SNR_DB", "6"; ...
    "NOISE", "WHITE"; "NOISE", "STAGE5_TOEPLITZ_CORRELATED"];
for method_index = 1:numel(methods)
    method_rows = rows(rows.method_id == methods(method_index), :);
    for definition_index = 1:size(definitions, 1)
        scope_type = definitions(definition_index, 1);
        scope_value = definitions(definition_index, 2);
        if scope_type == "PROFILE"
            selected = method_rows.profile_id == scope_value;
        elseif scope_type == "L"
            selected = method_rows.L == str2double(scope_value);
        elseif scope_type == "SNR_DB"
            selected = method_rows.snr_db == str2double(scope_value);
        else
            selected = method_rows.noise_profile_id == scope_value;
        end
        metric = metric_item_local(method_rows(selected, :));
        item = profile_template_local();
        item.method_id = methods(method_index);
        item.scope_type = scope_type;
        item.scope_value = scope_value;
        copy_names = setdiff(fieldnames(item), ...
            {'method_id','scope_type','scope_value'});
        for name_index = 1:numel(copy_names)
            item.(copy_names{name_index}) = metric.(copy_names{name_index});
        end
        items(end + 1, 1) = item; %#ok<AGROW>
    end
end
output = struct2table(items);
end

function item = profile_template_local()
metric = summary_template_local();
remove = {'row_type','comparison_id','method_id','reference_method_id', ...
    'paired_count','wins','ties','losses'};
metric = rmfield(metric, remove);
item = struct('method_id', "", 'scope_type', "", 'scope_value', "");
names = fieldnames(metric);
for index = 1:numel(names)
    item.(names{index}) = metric.(names{index});
end
end

function output = applicability_local(rows, constants)
items = cell(0, 1);
methods = [constants.reference_method_ids; constants.method_ids];
for method_index = 1:numel(methods)
    method_rows = rows(rows.method_id == methods(method_index), :);
    scopes = {"ALL", "ALL", true(height(method_rows), 1)};
    for profile = constants.profile_ids.'
        scopes(end + 1, :) = {"PROFILE", profile, ...
            method_rows.profile_id == profile}; %#ok<AGROW>
    end
    for noise = constants.noise_profile_ids.'
        scopes(end + 1, :) = {"NOISE", noise, ...
            method_rows.noise_profile_id == noise}; %#ok<AGROW>
    end
    for scope_index = 1:size(scopes, 1)
        subset = method_rows(scopes{scope_index, 3}, :);
        statuses = unique(subset.applicability_status, 'stable');
        if isempty(statuses)
            statuses = "NO_REGISTERED_ROWS";
        end
        for status_index = 1:numel(statuses)
            status = statuses(status_index);
            if status == "NO_REGISTERED_ROWS"
                status_rows = subset;
            else
                status_rows = subset(subset.applicability_status == status, :);
            end
            items{end + 1, 1} = struct('method_id', methods(method_index), ...
                'scope_type', string(scopes{scope_index, 1}), ...
                'scope_value', string(scopes{scope_index, 2}), ...
                'applicability_status', status, ...
                'row_count', height(status_rows), ...
                'applicable_count', nnz(status_rows.applicable), ...
                'valid_count', nnz(status_rows.fit_valid)); %#ok<AGROW>
        end
    end
end
output = struct2table(vertcat(items{:}));
end

function output = complexity_local(rows)
methods = unique(rows.method_id, 'stable');
items = cell(numel(methods), 1);
for index = 1:numel(methods)
    subset = rows(rows.method_id == methods(index) & rows.applicable, :);
    items{index} = struct('method_id', methods(index), ...
        'applicable_count', height(subset), ...
        'valid_count', nnz(subset.fit_valid), ...
        'mean_score_calls', mean_local(subset.score_call_count), ...
        'mean_svd_calls', mean_local(subset.svd_call_count), ...
        'mean_eig_calls', mean_local(subset.eig_call_count), ...
        'mean_coarse_candidates', ...
        mean_local(subset.coarse_candidate_count), ...
        'mean_continuous_starts', ...
        mean_local(subset.continuous_start_count), ...
        'median_runtime_sec', median_local(subset.runtime_sec), ...
        'p90_runtime_sec', percentile_local(subset.runtime_sec, 90));
end
output = struct2table(vertcat(items{:}));
end

