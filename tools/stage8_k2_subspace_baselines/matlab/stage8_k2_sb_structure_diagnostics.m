function diagnostics = stage8_k2_sb_structure_diagnostics(context)
%STAGE8_K2_SB_STRUCTURE_DIAGNOSTICS Measure exact array/noise identities.

constants = context.constants;
model = context.models(1).model;
azimuths = linspace(constants.azimuth_domain_deg(1) + 0.03, ...
    constants.azimuth_domain_deg(2) - 0.03, 8).';
elevations = linspace(constants.elevation_domain_deg(1) + 0.01, ...
    constants.elevation_domain_deg(2) - 0.01, 8).';
angles = [azimuths, elevations];
manifold = build_stage8_element_manifold(angles, model);
k0 = 2 * pi / model.lambda;
z = (0:constants.N_el - 1).' * ...
    model.array_configuration.arr.dz;
phi = model.array_meta.phiAct;
factorization_residuals = zeros(8, 1);
shift_residuals = zeros(8, 1);
for index = 1:8
    theta = angles(index, 2);
    azimuth = angles(index, 1);
    vertical = exp(1j * k0 * z * sind(theta));
    azimuth_factor = exp(1j * k0 * ...
        model.array_configuration.arr.R * cosd(theta) * ...
        cosd(azimuth - phi));
    expected = vertical * azimuth_factor;
    actual = reshape(manifold.A(:, index), ...
        constants.N_el, constants.N_az);
    factorization_residuals(index) = norm(actual - expected, 'fro') / ...
        max(1, norm(actual, 'fro'));
    phase = exp(1j * k0 * ...
        model.array_configuration.arr.dz * sind(theta));
    shift_residuals(index) = norm(actual(2:end, :) - ...
        phase * actual(1:end-1, :), 'fro') / ...
        max(1, norm(actual(2:end, :), 'fro'));
end
noise_errors = [context.models.noise_factors];
covariance_errors = [noise_errors.covariance_error];
az_whitening_errors = [noise_errors.az_whitening_error];
colored_index = find([context.models.noise_profile_id] == ...
    "STAGE5_TOEPLITZ_CORRELATED", 1);
diagnostics = struct( ...
    'kronecker_factorization_residual_max', max(factorization_residuals), ...
    'vertical_shift_residual_max', max(shift_residuals), ...
    'noise_kronecker_residual_max', max(covariance_errors), ...
    'azimuth_whitening_residual_max', max(az_whitening_errors), ...
    'colored_noise_factorization_residual', ...
    covariance_errors(colored_index), ...
    'factorization_residuals', factorization_residuals, ...
    'shift_residuals', shift_residuals);
end
