function result = test_tangent_backward_compatibility()
%TEST_TANGENT_BACKWARD_COMPATIBILITY Re-run the four captured parent trials.

fixture = stage8_k2_tcc_test_fixture();
context = fixture.context;
registry = stage8_k2_tp_build_registry( ...
    context.plan.local_domain, context.constants);
selected = registry.noise_profile_id == "WHITE" & registry.L == 8 & ...
    registry.snr_db == 6 & ismember(registry.profile_id, ...
    ["P1", "P2", "P3", "P4"]);
specs = registry(selected, :);
expected = expected_parent_rows_local();
assert(height(specs) == numel(expected), ...
    'test_tangent_backward_compatibility:Registry', ...
    'The four parent reference trials were not found.');
max_rho_error = 0;
max_angle_error = 0;
max_rss_error = 0;
max_loglik_error = 0;
for index = 1:height(specs)
    [rows, diagnostics, trial] = ...
        stage8_k2_tp_evaluate_trial(specs(index, :), context);
    tangent = rows(rows.method_id == "TANGENT_PROFILE_SAFE", :);
    actual_k1 = str2num(char(diagnostics.K1_center_deg)); %#ok<ST2NM>
    actual_direction = str2num(char(diagnostics.direction_hat)); %#ok<ST2NM>
    actual_angles = str2num(char(tangent.angles_hat_deg)); %#ok<ST2NM>
    rho_error = abs(double(diagnostics.rho_hat_deg) - expected(index).rho);
    angle_error = max(abs(actual_angles(:) - expected(index).angles(:)));
    rss_error = abs(double(tangent.RSS) - expected(index).rss);
    loglik_error = abs(double(tangent.loglik) - expected(index).loglik);
    max_rho_error = max(max_rho_error, rho_error);
    max_angle_error = max(max_angle_error, angle_error);
    max_rss_error = max(max_rss_error, rss_error);
    max_loglik_error = max(max_loglik_error, loglik_error);
    assert(string(specs.trial_id(index)) == expected(index).trial_id && ...
        string(trial.element_trial_hash) == expected(index).element_hash && ...
        max(abs(actual_k1(:) - expected(index).k1(:))) <= 1e-12 && ...
        max(abs(actual_direction(:) - expected(index).direction(:))) <= 1e-12 && ...
        double(diagnostics.metric_rank) == expected(index).metric_rank && ...
        abs(double(diagnostics.metric_condition) - expected(index).condition) <= 1e-10 && ...
        rho_error <= max(2 * context.constants.fminbnd_TolX_deg, 2e-4) && ...
        angle_error <= max(2 * context.constants.fminbnd_TolX_deg, 2e-4) && ...
        rss_error <= 1e-8 * max(1, abs(expected(index).rss)) && ...
        loglik_error <= 1e-8 * max(1, abs(expected(index).loglik)) && ...
        logical(diagnostics.raw_tangent_candidate_valid) == expected(index).raw_valid && ...
        logical(diagnostics.upgrade_flag) == expected(index).upgrade && ...
        logical(diagnostics.fallback_flag) == expected(index).fallback && ...
        string(diagnostics.fallback_reason) == expected(index).fallback_reason && ...
        string(tangent.selected_source) == expected(index).selected_source && ...
        double(tangent.effective_rank) == expected(index).effective_rank && ...
        double(tangent.score_call_count) == expected(index).score_calls && ...
        double(tangent.SVD_call_count) == expected(index).svd_calls, ...
        'test_tangent_backward_compatibility:Mismatch', ...
        'The no-provider legacy Tangent path changed for trial %s.', ...
        char(specs.trial_id(index)));
end
result = struct('pass', true, 'trial_count', height(specs), ...
    'max_rho_error_deg', max_rho_error, ...
    'max_angle_error_deg', max_angle_error, ...
    'max_rss_error', max_rss_error, 'max_loglik_error', max_loglik_error);
fprintf(['test_tangent_backward_compatibility PASS rho=%.17g ', ...
    'angle=%.17g\n'], max_rho_error, max_angle_error);
end

