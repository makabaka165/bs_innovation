function result = test_cache_identity_rejection()
%TEST_CACHE_IDENTITY_REJECTION Verify fail-closed direct fallback.

fixture = stage8_k2_tcc_test_fixture();
model = fixture.model;
query = [7.8, 10.0];
mutations = { ...
    'fixed_measurement_hash', 'BAD_FIXED_HASH'; ...
    'phase_factor', 2; ...
    'lambda', fixture.cache.identity.lambda * (1 + 1e-6); ...
    'canonical_element_order', 'BAD_ORDER'; ...
    'W_hash', 'BAD_W_HASH'; ...
    'T_hash', 'BAD_T_HASH'; ...
    'measurement_center_az_deg', ...
        fixture.cache.identity.measurement_center_az_deg + 0.1; ...
    'canonical_geometry_hash', 'BAD_GEOMETRY_HASH'; ...
    'delta_grid_hash', 'BAD_DELTA_GRID_HASH'; ...
    'numeric_class', 'single'};
for index = 1:size(mutations, 1)
    bad_cache = fixture.cache;
    bad_cache.identity.(mutations{index, 1}) = mutations{index, 2};
    provider = stage8_k2_tcc_build_provider( ...
        'EXACT_CACHE_OR_DIRECT', model, bad_cache, struct());
    [candidate, info] = stage8_k2_tcc_get_single_target_g( ...
        query, model, provider);
    reference = stage8_k2_tcc_build_g_direct(query, model, struct());
    assert(strcmp(info.source, 'DIRECT_FALLBACK') && ...
        ~info.cache_hit && ~info.identity_valid && ...
        info.identity_rejection_count == 1 && ...
        norm(candidate - reference) <= 1e-12 * max(1, norm(reference)), ...
        'test_cache_identity_rejection:UnsafeHit', ...
        'A mutated cache identity returned CACHE_EXACT.');
end
strict_cache = fixture.cache;
strict_cache.identity.lambda = strict_cache.identity.lambda * 2;
strict_failed = false;
try
    stage8_k2_tcc_lookup_exact(strict_cache, query, model, ...
        struct('strict', true));
catch exception
    strict_failed = contains(exception.identifier, ...
        'stage8_k2_tcc_validate_cache_identity');
end
assert(strict_failed, 'test_cache_identity_rejection:Strict', ...
    'Strict identity validation did not throw a clear error.');
result = struct('pass', true, 'mutation_count', size(mutations, 1), ...
    'identity_rejection_count', size(mutations, 1));
fprintf('test_cache_identity_rejection PASS mutations=%d\n', ...
    size(mutations, 1));
end
