function result = test_tangent_profile_provider_equivalence()
%TEST_TANGENT_PROFILE_PROVIDER_EQUIVALENCE Verify provider-level T4 parity.

fixture = stage8_k2_tcc_test_fixture();
model = fixture.model;
context = fixture.context;
center = [8.0, 10.0];
direction = [1.0, 0.0];
constants = context.constants;
domain = context.plan.local_domain;
% These keys are fixed by the fixture, not inferred from a direct run.
cache_options = struct( ...
    'global_az_grid_deg', [7.4, 7.9995, 8.0005, 8.6], ...
    'el_grid_deg', [9.8, 10.0, 10.2]);
cache = stage8_k2_tcc_build_cache(model, cache_options);
direct_provider = stage8_k2_tcc_build_provider( ...
    'DIRECT_ONLY', model, [], struct());
hybrid_provider = stage8_k2_tcc_build_provider( ...
    'EXACT_CACHE_OR_DIRECT', model, cache, struct());
direct = stage8_k2_tp_profile_scale(fixture.Z_white, model, center, ...
    direction, domain, constants, direct_provider);
hybrid = stage8_k2_tp_profile_scale(fixture.Z_white, model, center, ...
    direction, domain, constants, hybrid_provider);

loglik_error = max(abs(direct.evaluated_loglik - hybrid.evaluated_loglik));
rho_sequence_error = max(abs(direct.evaluated_rho_deg - ...
    hybrid.evaluated_rho_deg));
angle_error = max(abs(direct.angles_hat_deg(:) - ...
    hybrid.angles_hat_deg(:)));
assert(strcmp(direct.manifold_provider_mode, 'DIRECT_ONLY') && ...
    strcmp(hybrid.manifold_provider_mode, 'EXACT_CACHE_OR_DIRECT') && ...
    isequal(direct.evaluated_rho_deg, hybrid.evaluated_rho_deg) && ...
    isequal(direct.evaluated_valid, hybrid.evaluated_valid) && ...
    isequal(direct.evaluated_status, hybrid.evaluated_status) && ...
    loglik_error <= 1e-8 * max(1, max(abs(direct.evaluated_loglik))) && ...
    abs(direct.rho_hat_deg - hybrid.rho_hat_deg) <= constants.fminbnd_TolX_deg && ...
    angle_error <= constants.fminbnd_TolX_deg && ...
    abs(direct.rss - hybrid.rss) <= 1e-8 * max(1, abs(direct.rss)) && ...
    abs(direct.loglik_concentrated - hybrid.loglik_concentrated) <= ...
    1e-8 * max(1, abs(direct.loglik_concentrated)) && ...
    direct.effective_rank == hybrid.effective_rank && ...
    isequal(direct.bracket_deg, hybrid.bracket_deg) && ...
    direct.cache_hit_count == 0 && hybrid.cache_hit_count > 0, ...
    'test_tangent_profile_provider_equivalence:Mismatch', ...
    'DIRECT_ONLY and hybrid profile decisions diverged.');
result = struct('pass', true, 'evaluated_count', ...
    numel(direct.evaluated_rho_deg), 'max_loglik_error', loglik_error, ...
    'max_rho_sequence_error', rho_sequence_error, ...
    'max_angle_error_deg', angle_error, ...
    'cache_hit_count', hybrid.cache_hit_count, ...
    'cache_miss_count', hybrid.cache_miss_count, ...
    'direct_fallback_count', hybrid.direct_fallback_count);
fprintf(['test_tangent_profile_provider_equivalence PASS ', ...
    'hits=%d loglik=%.17g\n'], hybrid.cache_hit_count, loglik_error);
end
