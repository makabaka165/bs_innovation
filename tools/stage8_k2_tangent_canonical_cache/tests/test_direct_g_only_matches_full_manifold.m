function result = test_direct_g_only_matches_full_manifold()
%TEST_DIRECT_G_ONLY_MATCHES_FULL_MANIFOLD Verify exact G reproduction.

fixture = stage8_k2_tcc_test_fixture();
model = fixture.model;
cases = { ...
    [7.4, 9.8], ...
    [8.0, 10.0], ...
    [8.6, 10.2], ...
    [7.45, 9.85; 8.55, 10.15], ...
    [7.4, 10.2; 8.6, 9.8]};
max_relative_error = 0;
max_absolute_error = 0;
for index = 1:numel(cases)
    angles = cases{index};
    [candidate, candidate_info] = stage8_k2_tcc_build_g_direct( ...
        angles, model, struct('compute_rank', true));
    [reference, ~, reference_info] = ...
        build_full_sequential_local_manifold( ...
        angles, model, struct('rank_multiplier', 1));
    relative_error = norm(candidate - reference, 'fro') / ...
        max(norm(reference, 'fro'), realmin);
    absolute_error = max(abs(candidate(:) - reference(:)));
    max_relative_error = max(max_relative_error, relative_error);
    max_absolute_error = max(max_absolute_error, absolute_error);
    assert(relative_error <= 1e-12 && ...
        absolute_error <= 1e-12 * max(1, max(abs(reference(:)))) && ...
        candidate_info.rank_Gseq == reference_info.rank_Gseq, ...
        'test_direct_g_only_matches_full_manifold:Mismatch', ...
        'Direct G-only did not match the frozen full manifold.');
end
result = struct('pass', true, ...
    'max_relative_error', max_relative_error, ...
    'max_absolute_error', max_absolute_error);
fprintf(['test_direct_g_only_matches_full_manifold PASS ', ...
    'relative=%.17g absolute=%.17g\n'], ...
    max_relative_error, max_absolute_error);
end
