function [dictionary, info] = stage8_k2_tcc_build_registered_dictionary( ...
    model, local_domain, options)
%STAGE8_K2_TCC_BUILD_REGISTERED_DICTIONARY Build the 21-key audit shadow.
%
% This artifact is deliberately diagnostic-only.  It is not a production
% provider and it does not support interpolation or nearest-neighbour use.

if nargin < 3 || isempty(options)
    options = struct();
end
validate_inputs_local(model, local_domain, options);
clock = tic;
cache_options = struct( ...
    'global_az_grid_deg', double(local_domain.az_grid_deg(:).'), ...
    'el_grid_deg', double(local_domain.el_grid_deg(:).'), ...
    'domain_bounds_deg', double(local_domain.domain_bounds_deg), ...
    'grid_step_deg', grid_step_local(local_domain), ...
    'measurement_config_id', char(string(model.measurement_config_id)), ...
    'noise_profile_id', char(string(model.noise_profile_id)), ...
    'strict', true, 'rank_multiplier', 1);
[cache, cache_info] = stage8_k2_tcc_build_cache(model, cache_options);
validate_clock = tic;
[identity_valid, ~] = stage8_k2_tcc_validate_cache_identity( ...
    cache, model, cache_options);
validate_runtime_sec = toc(validate_clock);
if ~identity_valid
    error('stage8_k2_tcc_build_registered_dictionary:Identity', ...
        'The freshly built diagnostic dictionary failed identity validation.');
end

key_angles = sortrows(double(local_domain.candidate_points_deg), [1, 2]);
key_count = size(key_angles, 1);
G = complex(zeros(size(cache.G_grid, 1), key_count));
delta_index = zeros(key_count, 1);
el_index = zeros(key_count, 1);
key_error = zeros(key_count, 1);
single_pair_accumulation_rel_error = zeros(key_count, 1);
for index = 1:key_count
    [pair_column, lookup] = stage8_k2_tcc_lookup_exact( ...
        cache, key_angles(index, :), model, cache_options);
    if ~lookup.cache_hit
        error('stage8_k2_tcc_build_registered_dictionary:Lookup', ...
            'A registered key was absent from the diagnostic dictionary.');
    end
    single_column = stage8_k2_tcc_build_g_direct( ...
        key_angles(index, :), model, struct());
    % A shared K1/K2 dictionary has one numeric representative for two
    % frozen BLAS accumulation shapes.  Their deterministic midpoint keeps
    % the representative inside the inherited 1e-10 contract for both.
    G(:, index) = 0.5 * (single_column(:, 1) + pair_column(:, 1));
    single_pair_accumulation_rel_error(index) = ...
        norm(single_column(:, 1) - pair_column(:, 1)) / ...
        max(norm(single_column(:, 1)), realmin);
    delta_index(index) = lookup.matched_delta_index;
    el_index(index) = lookup.matched_el_index;
    key_error(index) = max(lookup.delta_key_error_deg, ...
        lookup.el_key_error_deg);
end
key_ids = compose('OMEGA_%02d', (1:key_count).');
key_table = table(key_ids, key_angles(:, 1), key_angles(:, 2), ...
    delta_index, el_index, key_error, 'VariableNames', ...
    {'key_id','az_deg','el_deg','delta_index','el_index', ...
    'exact_key_error_deg'});

dictionary = struct();
dictionary.dictionary_version = ...
    'STAGE8_K2_TCC_DIAGNOSTIC_REGISTERED_DICTIONARY_V1';
dictionary.diagnostic_only_flag = true;
dictionary.production_integrated_flag = false;
dictionary.lookup_mode = 'EXACT_REGISTERED_ONLY';
dictionary.numeric_representative = ...
    'BALANCED_SINGLE_PAIR_DIRECT_ACCUMULATION_MIDPOINT';
dictionary.supports_interpolation = false;
dictionary.validate_once_status = 'VALIDATE_ONCE_COMPLETE';
dictionary.G = G;
dictionary.key_table = key_table;
dictionary.key_count = key_count;
dictionary.az_grid_deg = double(local_domain.az_grid_deg(:).');
dictionary.el_grid_deg = double(local_domain.el_grid_deg(:).');
dictionary.domain_hash = char(string(local_domain.domain_hash));
dictionary.fixed_measurement_hash = ...
    char(string(model.fixed_measurement_hash));
dictionary.measurement_config_id = ...
    char(string(model.measurement_config_id));
dictionary.noise_profile_id = char(string(model.noise_profile_id));
dictionary.phase_factor = double(model.phase_factor);
dictionary.lambda = double(model.lambda);
dictionary.W_hash = cache.W_hash;
dictionary.T_hash = cache.T_hash;
dictionary.element_order = cache.canonical_element_order;
dictionary.measurement_center_az_deg = ...
    double(cache.measurement_center_az_deg);
dictionary.numeric_class = class(G);
dictionary.cache_identity_hash = cache.cache_identity_hash;
dictionary.identity = cache.identity;
dictionary.cheap_guard = struct( ...
    'fixed_measurement_hash', dictionary.fixed_measurement_hash, ...
    'domain_hash', dictionary.domain_hash, ...
    'phase_factor', dictionary.phase_factor, ...
    'numeric_class', dictionary.numeric_class);
dictionary.dictionary_hash = stage8_k2_tcc_stable_hash( ...
    dictionary.dictionary_version, dictionary.fixed_measurement_hash, ...
    dictionary.domain_hash, dictionary.key_table, dictionary.G);
dictionary.build_runtime_sec = toc(clock);
dictionary.cache_build_runtime_sec = cache_info.cache_build_time_sec;
dictionary.validate_once_runtime_sec = validate_runtime_sec;
dictionary.single_pair_accumulation_rel_error = ...
    single_pair_accumulation_rel_error;

info = struct('dictionary_hash', dictionary.dictionary_hash, ...
    'key_count', key_count, 'build_runtime_sec', ...
    dictionary.build_runtime_sec, 'cache_build_runtime_sec', ...
    dictionary.cache_build_runtime_sec, ...
    'validate_once_runtime_sec', dictionary.validate_once_runtime_sec, ...
    'identity_valid', identity_valid, ...
    'max_exact_key_error_deg', max(key_error), ...
    'max_single_pair_accumulation_rel_error', ...
    max(single_pair_accumulation_rel_error), ...
    'status', 'DIAGNOSTIC_21_KEY_DICTIONARY_READY');
end

function validate_inputs_local(model, domain, options)
required_model = {'Wseq','Tseq','array_meta','lambda','phase_factor', ...
    'fixed_measurement_hash','measurement_config_id','noise_profile_id'};
required_domain = {'az_grid_deg','el_grid_deg','candidate_points_deg', ...
    'domain_bounds_deg','domain_hash'};
if ~(isstruct(model) && isscalar(model) && ...
        all(isfield(model, required_model)) && model.phase_factor == 1)
    error('stage8_k2_tcc_build_registered_dictionary:Model', ...
        'model does not satisfy the fixed factor-1 identity contract.');
end
if ~(isstruct(domain) && isscalar(domain) && ...
        all(isfield(domain, required_domain)))
    error('stage8_k2_tcc_build_registered_dictionary:Domain', ...
        'local_domain is incomplete.');
end
if ~(isstruct(options) && isscalar(options))
    error('stage8_k2_tcc_build_registered_dictionary:Options', ...
        'options must be a scalar struct.');
end
if size(domain.candidate_points_deg, 1) ~= ...
        numel(domain.az_grid_deg) * numel(domain.el_grid_deg)
    error('stage8_k2_tcc_build_registered_dictionary:Cardinality', ...
        'candidate_points_deg is not the Cartesian registered domain.');
end
end

function step = grid_step_local(domain)
increments = [diff(double(domain.az_grid_deg(:))); ...
    diff(double(domain.el_grid_deg(:)))];
increments = increments(isfinite(increments) & increments > 0);
if isempty(increments)
    error('stage8_k2_tcc_build_registered_dictionary:GridStep', ...
        'The registered domain does not expose a positive grid step.');
end
step = min(increments);
end
