    'MATLAB_release', version('-release'), 'singleCompThread', true, ...
    'timing_configuration_hash', protocol.timing_configuration_hash, ...
    'pair_block_id', pair_block_id, 'pair_order', char(order_code), ...
    'runtime_session_id', session_id);
end

function path_now = unit_path_local(root, spec, repeat_index, mode)
folder = fullfile(root, char(spec.trial_id));
if ~isfolder(folder), mkdir(folder); end
path_now = fullfile(folder, sprintf('R%02d_%s.mat', ...
    repeat_index, upper(mode)));
end

function output = aggregate_local(registry, protocol, checkpoint_root, runtime_dir)
pair_order = pair_order_local(height(registry), protocol);
mode_rows = cell(height(registry) * protocol.repeat_target * 2, 1);
stage_tables = cell(height(registry) * protocol.repeat_target, 1);
pair_rows = cell(height(registry) * protocol.repeat_target, 1);
mode_index = 0;
pair_index = 0;
for trial_index = 1:height(registry)
    spec = registry(trial_index, :);
    for repeat_index = 1:protocol.repeat_target
        [reusable, off_unit, stage_unit] = read_pair_local( ...
            spec, struct('fixed_measurement_hash', ...
            off_identity_local(checkpoint_root, spec, repeat_index)), ...
            repeat_index, pair_order(trial_index, repeat_index), ...
            protocol, checkpoint_root);
        if ~reusable
            error('stage8_k2_tcc_run_runtime_audit:Incomplete', ...
                'Pass C pair is incomplete: %s repeat %d.', ...
                char(spec.trial_id), repeat_index);
        end
        units = {off_unit,stage_unit};
        for current = 1:2
            mode_index = mode_index + 1;
            unit = units{current};
            mode_rows{mode_index} = mode_row_local(spec, unit);
        end
        pair_index = pair_index + 1;
        stage_tables{pair_index} = stage_table_local(spec, stage_unit);
        pair_rows{pair_index} = pair_row_local(spec, off_unit, stage_unit);
    end
end
raw_timing = struct2table(vertcat(mode_rows{:}));
stage_samples = vertcat(stage_tables{:});
paired_deltas = struct2table(vertcat(pair_rows{:}));
runtime_summary = summarize_runtime_local( ...
    raw_timing, stage_samples, paired_deltas, registry, protocol);
output = struct('raw_timing', raw_timing, ...
    'stage_samples', stage_samples, 'paired_deltas', paired_deltas, ...
    'runtime_summary', runtime_summary, ...
    'paired_block_count', height(paired_deltas), ...
    'all_pairs_complete', height(paired_deltas) == ...
    height(registry) * protocol.repeat_target);
atomic_value_save_local(fullfile(runtime_dir, 'pass_c_runtime_audit.mat'), ...
    output);
end

