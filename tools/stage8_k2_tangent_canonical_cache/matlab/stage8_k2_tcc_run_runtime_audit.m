function summary = summarize_runtime_local(raw, stages, pairs, registry, protocol)
rows = cell(height(registry), 1);
for trial_index = 1:height(registry)
    spec = registry(trial_index, :);
    trial_raw = raw(raw.trial_id == spec.trial_id, :);
    trial_stages = stages(stages.trial_id == spec.trial_id, :);
    trial_pairs = pairs(pairs.trial_id == spec.trial_id, :);
    stage_ids = unique(trial_stages.stage_id, 'stable');
    current = cell(numel(stage_ids) + 2, 1);
    index = 0;
    for mode = ["OFF","TIMING_STAGE"]
        index = index + 1;
        samples = trial_raw.root_runtime_sec(trial_raw.timing_mode == mode);
        current{index} = summary_row_local(spec, mode, ...
            "ROOT_TANGENT_PROFILE_SAFE", samples, ones(size(samples)), ...
            NaN(size(samples)), trial_stages, trial_pairs, protocol);
    end
    for stage_index = 1:numel(stage_ids)
        index = index + 1;
        stage_id = stage_ids(stage_index);
        subset = trial_stages(trial_stages.stage_id == stage_id, :);
        current{index} = summary_row_local(spec, "TIMING_STAGE", stage_id, ...
            subset.inclusive_runtime_sec, subset.stage_share, ...
            subset.exclusive_runtime_sec, subset, trial_pairs, protocol);
    end
    rows{trial_index} = struct2table(vertcat(current{:}));
end
trial_summary = vertcat(rows{:});
summary = [trial_summary;aggregate_trial_summaries_local(trial_summary)];
end

function row = summary_row_local(spec, mode, stage_id, samples, shares, ...
    exclusive, stage_rows, pairs, protocol)
repeat_count = numel(samples);
if repeat_count >= 10
    p90 = prctile(samples, 90);
    share_p90 = prctile(shares, 90);
    overhead_p90 = prctile(pairs.instrumentation_overhead_sec, 90);
else
    p90 = NaN; share_p90 = NaN; overhead_p90 = NaN;
end
row = struct('trial_id', string(spec.trial_id), ...
    'aggregation_level', "TRIAL", ...
    'scenario_aggregate', string(spec.trial_id), ...
    'fixed_measurement_hash', string(pairs.fixed_measurement_hash(1)), ...
    'noise_profile_id', string(spec.noise_profile_id), ...
    'L', double(spec.L), 'snr_db', double(spec.snr_db), ...
    'profile_id', string(spec.profile_id), ...
    'timing_mode', string(mode), 'stage_id', string(stage_id), ...
    'repeat_count', repeat_count, ...
    'median_runtime_sec', median(samples), ...
    'p90_runtime_sec', p90, 'min_runtime_sec', min(samples), ...
    'max_runtime_sec', max(samples), ...
    'median_stage_share', median(shares), ...
    'p90_stage_share', share_p90, 'min_stage_share', min(shares), ...
    'max_stage_share', max(shares), ...
    'median_exclusive_runtime_sec', median(exclusive, 'omitnan'), ...
    'median_unattributed_sec', median(stage_rows.unattributed_sec, 'omitnan'), ...
    'median_reconciliation_error_sec', ...
    median(stage_rows.reconciliation_error_sec, 'omitnan'), ...
    'pair_order_ab_count', nnz(pairs.pair_order == "AB"), ...
    'pair_order_ba_count', nnz(pairs.pair_order == "BA"), ...
    'paired_repeat_count', height(pairs), ...
    'paired_instrumentation_overhead_median_sec', ...
    median(pairs.instrumentation_overhead_sec), ...
    'paired_instrumentation_overhead_p90_sec', overhead_p90, ...
    'paired_instrumentation_overhead_min_sec', ...
    min(pairs.instrumentation_overhead_sec), ...
    'paired_instrumentation_overhead_max_sec', ...
    max(pairs.instrumentation_overhead_sec), ...
    'timing_configuration_hash', string(protocol.timing_configuration_hash));
end

function aggregate = aggregate_trial_summaries_local(summary)
definitions = cell(0, 2);
for value = unique(summary.noise_profile_id(summary.aggregation_level == ...
        "TRIAL"), 'stable').'
    definitions(end + 1, :) = {"NOISE_IDENTITY", value}; %#ok<AGROW>
end
for value = unique(summary.L(summary.aggregation_level == "TRIAL")).'
    definitions(end + 1, :) = {"L", value}; %#ok<AGROW>
end
for value = unique(summary.snr_db(summary.aggregation_level == "TRIAL")).'
    definitions(end + 1, :) = {"SNR", value}; %#ok<AGROW>
end
for value = unique(summary.profile_id(summary.aggregation_level == ...
        "TRIAL"), 'stable').'
    definitions(end + 1, :) = {"PROFILE", value}; %#ok<AGROW>
end
definitions(end + 1, :) = {"OVERALL", "ALL_72_TRIALS"};
keys = unique(summary(:, {'timing_mode','stage_id'}), 'rows', 'stable');
rows = cell(height(keys) * size(definitions, 1), 1);
row_index = 0;
for key_index = 1:height(keys)
    base = summary(summary.timing_mode == keys.timing_mode(key_index) & ...
        summary.stage_id == keys.stage_id(key_index) & ...
        summary.aggregation_level == "TRIAL", :);
    for definition_index = 1:size(definitions, 1)
        level = definitions{definition_index, 1};
        value = definitions{definition_index, 2};
        subset = aggregate_subset_local(base, level, value);
        if isempty(subset), continue; end
        row_index = row_index + 1;
        rows{row_index} = aggregate_row_local(subset, level, value);
    end
end
rows = rows(1:row_index);
if isempty(rows)
    aggregate = summary([],:);
else
    aggregate = struct2table(vertcat(rows{:}));
    aggregate = aggregate(:, summary.Properties.VariableNames);
end
end

function subset = aggregate_subset_local(base, level, value)
switch char(level)
    case 'NOISE_IDENTITY'
        subset = base(base.noise_profile_id == string(value), :);
    case 'L'
        subset = base(base.L == double(value), :);
    case 'SNR'
        subset = base(base.snr_db == double(value), :);
    case 'PROFILE'
        subset = base(base.profile_id == string(value), :);
    otherwise
        subset = base;
end
end

function row = aggregate_row_local(subset, level, value)
row = table2struct(subset(1, :));
token = sprintf('AGG_%s_%s', char(level), ...
    regexprep(char(string(value)), '[^A-Za-z0-9]+', '_'));
row.trial_id = string(token);
row.aggregation_level = string(level);
row.scenario_aggregate = string(value);
if numel(unique(subset.fixed_measurement_hash)) == 1
    row.fixed_measurement_hash = subset.fixed_measurement_hash(1);
else
    row.fixed_measurement_hash = "MULTIPLE_IDENTITIES";
end
if ~strcmp(level, 'NOISE_IDENTITY'), row.noise_profile_id = "ALL"; end
if ~strcmp(level, 'L'), row.L = NaN; end
if ~strcmp(level, 'SNR'), row.snr_db = NaN; end
if ~strcmp(level, 'PROFILE'), row.profile_id = "ALL"; end
row.repeat_count = height(subset);
row.median_runtime_sec = median(subset.median_runtime_sec);
row.p90_runtime_sec = prctile(subset.median_runtime_sec, 90);
row.min_runtime_sec = min(subset.median_runtime_sec);
row.max_runtime_sec = max(subset.median_runtime_sec);
row.median_stage_share = median(subset.median_stage_share);
row.p90_stage_share = prctile(subset.median_stage_share, 90);
row.min_stage_share = min(subset.median_stage_share);
row.max_stage_share = max(subset.median_stage_share);
row.median_exclusive_runtime_sec = ...
    median(subset.median_exclusive_runtime_sec, 'omitnan');
row.median_unattributed_sec = median(subset.median_unattributed_sec);
row.median_reconciliation_error_sec = ...
    median(subset.median_reconciliation_error_sec);
row.pair_order_ab_count = sum(subset.pair_order_ab_count);
row.pair_order_ba_count = sum(subset.pair_order_ba_count);
row.paired_repeat_count = sum(subset.paired_repeat_count);
overhead = subset.paired_instrumentation_overhead_median_sec;
row.paired_instrumentation_overhead_median_sec = median(overhead);
row.paired_instrumentation_overhead_p90_sec = prctile(overhead, 90);
row.paired_instrumentation_overhead_min_sec = min(overhead);
row.paired_instrumentation_overhead_max_sec = max(overhead);
end

