    'metric_rank', diagnostics.metric_rank, ...
    'metric_condition', diagnostics.metric_condition, ...
    'rho_hat_deg', diagnostics.rho_hat_deg, ...
    'raw_valid', diagnostics.raw_tangent_candidate_valid, ...
    'raw_loglik', diagnostics.raw_tangent_loglik, ...
    'upgrade', diagnostics.upgrade_flag, ...
    'fallback', diagnostics.fallback_flag, ...
    'fallback_reason', diagnostics.fallback_reason);
end

function [rows, unattributed, reconciliation] = ...
    reconcile_stages_local(raw_rows, root_runtime)
ids = string({raw_rows.stage_id});
values = [raw_rows.inclusive_runtime_sec];
time = containers.Map('KeyType', 'char', 'ValueType', 'double');
for index = 1:numel(ids)
    time(char(ids(index))) = double(values(index));
end
time('ROOT_TANGENT_PROFILE_SAFE') = root_runtime;
edges = hierarchy_edges_local();
all_ids = unique([string(keys(time)), edges(:, 1).', edges(:, 2).'], 'stable');
inclusive = zeros(numel(all_ids), 1);
exclusive = zeros(numel(all_ids), 1);
for index = 1:numel(all_ids)
    id = char(all_ids(index));
    if isKey(time, id), inclusive(index) = time(id); end
    children = edges(edges(:, 1) == all_ids(index), 2);
    child_sum = 0;
    for child_index = 1:numel(children)
        child = char(children(child_index));
        if isKey(time, child), child_sum = child_sum + time(child); end
    end
    exclusive(index) = inclusive(index) - child_sum;
end
root_index = find(all_ids == "ROOT_TANGENT_PROFILE_SAFE", 1);
unattributed = exclusive(root_index);
keep = (1:numel(all_ids)).' ~= root_index & ...
    (inclusive ~= 0 | exclusive ~= 0);
rows = repmat(struct('stage_id', "", 'inclusive_runtime_sec', 0, ...
    'exclusive_runtime_sec', 0, 'stage_share', 0), nnz(keep) + 1, 1);
indices = find(keep);
for row_index = 1:numel(indices)
    index = indices(row_index);
    rows(row_index) = struct('stage_id', all_ids(index), ...
        'inclusive_runtime_sec', inclusive(index), ...
        'exclusive_runtime_sec', exclusive(index), ...
        'stage_share', inclusive(index) / root_runtime);
end
rows(end) = struct('stage_id', "UNATTRIBUTED", ...
    'inclusive_runtime_sec', unattributed, ...
    'exclusive_runtime_sec', unattributed, ...
    'stage_share', unattributed / root_runtime);
reconciliation = root_runtime - ...
    (sum(exclusive(keep)) + unattributed);
end

