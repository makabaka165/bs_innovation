function output = stage8_k2_tcc_run_runtime_audit( ...
    context, registry, protocol, runtime_dir, options)
%STAGE8_K2_TCC_RUN_RUNTIME_AUDIT Run/resume paired OFF/STAGE timing.

if nargin < 5 || isempty(options), options = struct(); end
options = normalize_options_local(options, height(registry));
checkpoint_root = fullfile(runtime_dir, 'checkpoints', 'pass_c');
if ~isfolder(checkpoint_root), mkdir(checkpoint_root); end
if strcmp(options.mode, 'AGGREGATE')
    output = aggregate_local(registry, protocol, checkpoint_root, runtime_dir);
    return;
end

runtime_session_id = char(java.util.UUID.randomUUID());
pair_order = pair_order_local(height(registry), protocol);
trial_orders = trial_orders_local(height(registry), protocol);
trials = cell(height(options.trial_indices), 1);
for local_index = 1:numel(options.trial_indices)
    trial_index = options.trial_indices(local_index);
    trials{local_index} = stage8_k2_tcc_generate_frozen_trial( ...
        registry(trial_index, :), context);
end

for local_index = 1:numel(options.trial_indices)
    trial_index = options.trial_indices(local_index);
    if trial_has_incomplete_pair_local(registry(trial_index, :), ...
            trial_index, protocol, pair_order, checkpoint_root)
        warmup_trial_local(trials{local_index}, context, protocol);
    end
end

completed = 0;
for repeat_index = 1:protocol.repeat_target
    order = trial_orders(repeat_index, :);
    order = order(ismember(order, options.trial_indices));
    for order_index = 1:numel(order)
        trial_index = order(order_index);
        local_index = find(options.trial_indices == trial_index, 1);
        spec = registry(trial_index, :);
        trial = trials{local_index};
        order_code = pair_order(trial_index, repeat_index);
        [reusable, ~, ~] = read_pair_local(spec, trial.model, ...
            repeat_index, order_code, protocol, checkpoint_root);
        if reusable
            completed = completed + 1;
            fprintf('PASSC RESUME shard=%d r=%d trial=%s\n', ...
                options.shard_id, repeat_index, char(spec.trial_id));
            continue;
        end
        run_pair_local(spec, trial, context, repeat_index, order_code, ...
            runtime_session_id, protocol, checkpoint_root);
        completed = completed + 1;
        fprintf('PASSC RUN shard=%d %d/%d r=%d trial=%s order=%s\n', ...
            options.shard_id, completed, ...
            numel(options.trial_indices) * protocol.repeat_target, ...
            repeat_index, char(spec.trial_id), order_code);
    end
end
output = struct('mode', 'WORKER', 'shard_id', options.shard_id, ...
    'trial_indices', options.trial_indices, ...
    'completed_pair_count', completed, ...
    'runtime_session_id', runtime_session_id, ...
    'timing_configuration_hash', protocol.timing_configuration_hash);
atomic_value_save_local(fullfile(runtime_dir, sprintf( ...
    'pass_c_worker_%02d.mat', options.shard_id)), output);
if options.aggregate_after_worker
    output = aggregate_local(registry, protocol, checkpoint_root, runtime_dir);
end
end

function options = normalize_options_local(options, trial_count)
defaults = struct('mode', 'WORKER', 'trial_indices', 1:trial_count, ...
    'shard_id', 1, 'aggregate_after_worker', false);
names = fieldnames(defaults);
for index = 1:numel(names)
    if ~isfield(options, names{index})
        options.(names{index}) = defaults.(names{index});
    end
end
options.mode = upper(char(string(options.mode)));
options.trial_indices = double(options.trial_indices(:).');
if ~ismember(options.mode, {'WORKER','AGGREGATE'}) || ...
        any(options.trial_indices < 1 | options.trial_indices > trial_count) || ...
        numel(unique(options.trial_indices)) ~= numel(options.trial_indices)
    error('stage8_k2_tcc_run_runtime_audit:Options', ...
        'Runtime worker options are invalid.');
end
end

function orders = trial_orders_local(trial_count, protocol)
orders = zeros(protocol.repeat_target, trial_count);
rng_state = rng;
cleanup = onCleanup(@() rng(rng_state));
rng(protocol.trial_order_seed, 'twister');
for repeat_index = 1:protocol.repeat_target
    orders(repeat_index, :) = randperm(trial_count);
end
clear cleanup
end

function order = pair_order_local(trial_count, protocol)
rng_state = rng;
cleanup = onCleanup(@() rng(rng_state));
rng(protocol.pair_order_seed, 'twister');
trial_permutation = randperm(trial_count);
position = zeros(trial_count, 1);
position(trial_permutation) = 1:trial_count;
order = strings(trial_count, protocol.repeat_target);
for trial_index = 1:trial_count
    for repeat_index = 1:protocol.repeat_target
        if mod(position(trial_index) + repeat_index, 2) == 0
            order(trial_index, repeat_index) = "AB";
        else
            order(trial_index, repeat_index) = "BA";
        end
    end
end
clear cleanup
end

function warmup_trial_local(trial, context, protocol)
modes = {'OFF','TIMING_STAGE'};
for mode_index = 1:numel(modes)
    for warmup_index = 1:protocol.warmup_count
        stage8_k2_tcc_audit_state('CONFIGURE', ...
            struct('mode', modes{mode_index}));
        stage8_k2_tp_fit_safe(trial.Y_element, trial.model, context);
    end
end
end

function incomplete = trial_has_incomplete_pair_local(spec, trial_index, ...
    protocol, pair_order, checkpoint_root)
incomplete = false;
for repeat_index = 1:protocol.repeat_target
    dummy_model = struct('fixed_measurement_hash', 'NOT_CHECKED');
    [reusable, ~, ~] = read_pair_local(spec, dummy_model, repeat_index, ...
        pair_order(trial_index, repeat_index), protocol, checkpoint_root, ...
        true);
    if ~reusable
        incomplete = true;
        return;
    end
end
end

function run_pair_local(spec, trial, context, repeat_index, order_code, ...
    session_id, protocol, checkpoint_root)
pair_block_id = sprintf('%s_R%02d', char(spec.trial_id), repeat_index);
if order_code == "AB"
    modes = {'OFF','TIMING_STAGE'};
else
    modes = {'TIMING_STAGE','OFF'};
end
units = cell(2, 1);
for mode_index = 1:2
    mode = modes{mode_index};
    record = run_mode_local(mode, trial, context);
    metadata = unit_metadata_local(protocol, spec, trial.model, ...
        repeat_index, mode, pair_block_id, order_code, session_id);
    unit = struct('metadata', metadata, 'record', record, ...
        'unit_complete', true, 'paired_block_complete', false, ...
        'paired_block_contiguous', false, ...
        'pair_sequence_index', mode_index);
    atomic_checkpoint_local(unit_path_local(checkpoint_root, spec, ...
        repeat_index, mode), unit);
    units{mode_index} = unit;
end
if ~strcmp(units{1}.record.estimator_signature_hash, ...
        units{2}.record.estimator_signature_hash)
    error('stage8_k2_tcc_run_runtime_audit:EstimatorChanged', ...
        'OFF/STAGE changed an estimator output for %s repeat %d.', ...
        char(spec.trial_id), repeat_index);
end
for mode_index = 1:2
    units{mode_index}.paired_block_complete = true;
    units{mode_index}.paired_block_contiguous = true;
end
% Write the second unit first.  A crash before replacing the first leaves
% the pair incomplete, so resume reruns the entire contiguous block.
atomic_checkpoint_local(unit_path_local(checkpoint_root, spec, ...
    repeat_index, modes{2}), units{2});
atomic_checkpoint_local(unit_path_local(checkpoint_root, spec, ...
    repeat_index, modes{1}), units{1});
end

function record = run_mode_local(mode, trial, context)
stage8_k2_tcc_audit_state('CONFIGURE', struct('mode', mode));
root_clock = tic;
[result, diagnostics] = stage8_k2_tp_fit_safe( ...
    trial.Y_element, trial.model, context);
root_runtime = toc(root_clock);
if strcmp(mode, 'TIMING_STAGE')
    timing = stage8_k2_tcc_audit_state('GET_TIMING');
    [stage_rows, unattributed, reconciliation] = ...
        reconcile_stages_local(timing.stage_rows, root_runtime);
else
    stage_rows = struct([]);
    unattributed = NaN;
    reconciliation = NaN;
end
signature = estimator_signature_local(result, diagnostics, ...
    trial.element_trial_hash);
record = struct('timing_mode', string(mode), ...
    'root_runtime_sec', double(root_runtime), ...
    'stage_rows', stage_rows, ...
    'unattributed_sec', double(unattributed), ...
    'reconciliation_error_sec', double(reconciliation), ...
    'estimator_signature_hash', ...
    stage8_k2_tcc_stable_hash('PASS_C_ESTIMATOR_SIGNATURE', signature));
end

