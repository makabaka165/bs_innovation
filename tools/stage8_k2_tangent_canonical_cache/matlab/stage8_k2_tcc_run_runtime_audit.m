    'fit_valid', result.fit_valid, 'fit_status', result.fit_status, ...
    'selected_source', result.selected_source, ...
    'selected_start_id', result.selected_start_id, 'rss', result.rss, ...
    'loglik', result.loglik_concentrated, 'rank', result.effective_rank, ...
