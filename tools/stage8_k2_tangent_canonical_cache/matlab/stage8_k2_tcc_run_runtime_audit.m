function [reusable, off_unit, stage_unit] = read_pair_local(spec, model, ...
    repeat_index, order_code, protocol, checkpoint_root, ignore_identity)
if nargin < 8, ignore_identity = false; end
off_unit = read_unit_local(unit_path_local( ...
    checkpoint_root, spec, repeat_index, 'OFF'));
stage_unit = read_unit_local(unit_path_local( ...
    checkpoint_root, spec, repeat_index, 'TIMING_STAGE'));
reusable = validate_unit_local(off_unit, spec, model, repeat_index, ...
    'OFF', order_code, protocol, ignore_identity) && ...
    validate_unit_local(stage_unit, spec, model, repeat_index, ...
    'TIMING_STAGE', order_code, protocol, ignore_identity);
if reusable
    reusable = off_unit.paired_block_complete && ...
        stage_unit.paired_block_complete && ...
        off_unit.paired_block_contiguous && ...
        stage_unit.paired_block_contiguous && ...
        strcmp(off_unit.metadata.runtime_session_id, ...
        stage_unit.metadata.runtime_session_id) && ...
        strcmp(off_unit.metadata.pair_block_id, ...
        stage_unit.metadata.pair_block_id) && ...
        strcmp(off_unit.record.estimator_signature_hash, ...
        stage_unit.record.estimator_signature_hash);
end
end

function unit = read_unit_local(path_now)
unit = struct();
if ~isfile(path_now), return; end
loaded = load(path_now, 'unit');
if isfield(loaded, 'unit'), unit = loaded.unit; end
end

function pass = validate_unit_local(unit, spec, model, repeat_index, mode, ...
    order_code, protocol, ignore_identity)
pass = isstruct(unit) && isscalar(unit) && ...
    all(isfield(unit, {'metadata','record','unit_complete', ...
    'paired_block_complete','paired_block_contiguous'})) && ...
    logical(unit.unit_complete);
if ~pass, return; end
m = unit.metadata;
pass = strcmp(m.pass, 'PASS_C_RUNTIME') && ...
    strcmp(m.trial_id, char(spec.trial_id)) && ...
    isequal(m.repeat_index, repeat_index) && strcmp(m.timing_mode, mode) && ...
    strcmp(m.pair_order, char(order_code)) && ...
    strcmp(m.level_a_closure_commit, protocol.level_a_closure_commit) && ...
    strcmp(m.audit_start_commit, protocol.audit_start_commit) && ...
    strcmp(m.audit_code_hash, protocol.audit_code_hash) && ...
    strcmp(m.registry_hash, protocol.registry_hash) && ...
    strcmp(m.MATLAB_release, version('-release')) && ...
    logical(m.singleCompThread) && ...
    strcmp(m.timing_configuration_hash, ...
    protocol.timing_configuration_hash);
if pass && ~ignore_identity
    pass = strcmp(m.measurement_identity, model.fixed_measurement_hash);
end
end

