function manifest = stage8_k2_tcc_write_evidence(repo_dir, static_output, ...
    query_output, runtime_output, micro_output, economics_output, ...
    protocol, git_metadata)
%STAGE8_K2_TCC_WRITE_EVIDENCE Write only the six committed 52_* artifacts.

innovation_dir = fullfile(repo_dir, 'innovation-mining');
paths = struct( ...
    'report', fullfile(innovation_dir, ...
    '52_stage8_k2_tangent_pipeline_cache_placement_audit.md'), ...
    'static', fullfile(innovation_dir, ...
    '52_stage8_k2_tangent_pipeline_cache_static_certification.csv'), ...
    'query', fullfile(innovation_dir, ...
    '52_stage8_k2_tangent_pipeline_cache_query_audit.csv'), ...
    'runtime', fullfile(innovation_dir, ...
    '52_stage8_k2_tangent_pipeline_runtime_summary.csv'), ...
    'economics', fullfile(innovation_dir, ...
    '52_stage8_k2_tangent_pipeline_cache_economics.csv'), ...
    'manifest', fullfile(innovation_dir, ...
    '52_stage8_k2_tangent_pipeline_cache_placement_manifest.json'));
writetable(static_output.rows, paths.static);
writetable(query_output.query_rows, paths.query);
writetable(runtime_output.runtime_summary, paths.runtime);
writetable(economics_output.economics, paths.economics);
write_report_local(paths.report, static_output, query_output, ...
    runtime_output, micro_output, economics_output, protocol, git_metadata);
manifest = manifest_local(static_output, query_output, runtime_output, ...
    economics_output, protocol, git_metadata, paths);
write_json_local(paths.manifest, manifest);
end

