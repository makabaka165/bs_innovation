function write_mismatch_local(fid, label, value)
fprintf(fid, '- %s mismatch: `%d`.\n', label, value);
end

function histogram = histogram_sum_local(values)
histogram = zeros(1, 21);
for index = 1:numel(values)
    histogram = histogram + reshape(jsondecode(values(index)), 1, []);
end
end

function row = overall_runtime_row_local(runtime, stage_id)
row = aggregate_runtime_row_local(runtime, 'OVERALL', ...
    'ALL_72_TRIALS', stage_id);
end

function row = aggregate_runtime_row_local(runtime, level, value, stage_id)
row = runtime(runtime.aggregation_level == string(level) & ...
    runtime.scenario_aggregate == string(value) & ...
    runtime.timing_mode == "TIMING_STAGE" & ...
    runtime.stage_id == string(stage_id), :);
if height(row) ~= 1
    error('stage8_k2_tcc_write_evidence:RuntimeAggregate', ...
        'Runtime aggregate %s/%s/%s is unavailable.', level, value, stage_id);
end
end

function runtime_stage_line_local(fid, runtime, stage_id, label)
row = overall_runtime_row_local(runtime, stage_id);
fprintf(fid, '- %s: `%.4f%%` (median inclusive `%.6f s`).\n', ...
    label, 100 * row.median_stage_share, row.median_runtime_sec);
end

