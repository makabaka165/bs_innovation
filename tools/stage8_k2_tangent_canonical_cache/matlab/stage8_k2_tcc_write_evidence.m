end

function value = short_hash_local(hash)
text = char(string(hash));
value = text(1:min(12, numel(text)));
end

function value = ternary_local(condition, yes_value, no_value)
if condition, value = yes_value; else, value = no_value; end
end

function value = sign_text_local(number)
if number > 0, value = 'POSITIVE'; ...
elseif number < 0, value = 'NEGATIVE'; else, value = 'ZERO'; end
end

function value = repo_dir_text_local(value)
value = strrep(char(string(value)), '\', '/');
end
