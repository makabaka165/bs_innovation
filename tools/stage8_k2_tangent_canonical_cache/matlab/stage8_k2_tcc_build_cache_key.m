function [cache_key, identity] = stage8_k2_tcc_build_cache_key( ...
    model, geometry, delta_grid_deg, el_grid_deg, options)
%STAGE8_K2_TCC_BUILD_CACHE_KEY Build the complete cache identity.

if nargin < 2 || isempty(geometry)
    geometry = stage8_k2_tcc_build_canonical_geometry(model);
end
if nargin < 3 || isempty(delta_grid_deg)
    delta_grid_deg = [];
end
if nargin < 4 || isempty(el_grid_deg)
    el_grid_deg = [];
end
if nargin < 5 || isempty(options)
    options = struct();
end
constants = stage8_k2_tcc_constants();
tolerance = get_option_local(options, 'grid_key_tolerance_deg', ...
    constants.grid_key_tolerance_deg);
if isempty(delta_grid_deg) || isempty(el_grid_deg)
    error('stage8_k2_tcc_build_cache_key:Grid', ...
        'Both delta and elevation grids are required.');
end
delta_grid_deg = double(delta_grid_deg(:).');
el_grid_deg = double(el_grid_deg(:).');
if any(~isfinite(delta_grid_deg)) || any(~isfinite(el_grid_deg)) || ...
        isempty(delta_grid_deg) || isempty(el_grid_deg)
    error('stage8_k2_tcc_build_cache_key:Grid', ...
        'Cache grids must be finite and non-empty.');
end
numeric_class = get_option_local(options, 'numeric_class', ...
    class(model.Wseq));
identity = struct( ...
    'cache_version', constants.cache_version, ...
    'fixed_measurement_hash', text_field_local(model, ...
        'fixed_measurement_hash', ''), ...
    'measurement_config_id', text_field_local(model, ...
        'measurement_config_id', ''), ...
    'noise_profile_id', text_field_local(model, ...
        'noise_profile_id', ''), ...
    'phase_factor', double(get_field_local(model, 'phase_factor', 1)), ...
    'steering_phase_sign', constants.steering_phase_sign, ...
    'lambda', double(get_field_local(model, 'lambda', NaN)), ...
    'numeric_class', char(string(numeric_class)), ...
    'array_geometry_hash', geometry.array_geometry_hash, ...
    'canonical_geometry_hash', geometry.canonical_geometry_hash, ...
    'canonical_element_order', geometry.canonical_element_order, ...
    'center_column', double(geometry.center_column), ...
    'requested_center_az_deg', double(geometry.requested_center_az_deg), ...
    'measurement_center_az_deg', double(geometry.measurement_center_az_deg), ...
    'W_hash', stage8_k2_tcc_stable_hash(model.Wseq), ...
    'T_hash', stage8_k2_tcc_stable_hash(model.Tseq), ...
    'delta_grid_hash', stage8_k2_tcc_stable_hash(delta_grid_deg), ...
    'el_grid_hash', stage8_k2_tcc_stable_hash(el_grid_deg), ...
    'grid_key_tolerance_deg', double(tolerance));
identity.cache_identity_hash = stage8_k2_tcc_stable_hash( ...
    'CACHE_IDENTITY', identity);
cache_key = identity.cache_identity_hash;
end

function value = get_option_local(options, name, fallback)
if isfield(options, name) && ~isempty(options.(name))
    value = options.(name);
else
    value = fallback;
end
end

function value = get_field_local(s, name, fallback)
if isfield(s, name) && ~isempty(s.(name))
    value = s.(name);
else
    value = fallback;
end
end

function value = text_field_local(s, name, fallback)
value = char(string(get_field_local(s, name, fallback)));
end
