function [stats, average_sample] = measure_operation_local(callback, repeats)
callback();
times = zeros(repeats, 1);
hit_total = 0;
miss_total = 0;
fallback_total = 0;
for index = 1:repeats
    clock = tic;
    sample = callback();
    times(index) = toc(clock);
    hit_total = hit_total + sample.cache_hit_count;
    miss_total = miss_total + sample.cache_miss_count;
    fallback_total = fallback_total + sample.direct_fallback_count;
end
ordered = sort(times);
stats = struct('repeat_count', repeats, ...
    'median', ordered(ceil(repeats / 2)), ...
    'p90', ordered(max(1, ceil(0.90 * repeats))));
average_sample = sample_template_local();
average_sample.cache_hit_count = hit_total / repeats;
average_sample.cache_miss_count = miss_total / repeats;
average_sample.direct_fallback_count = fallback_total / repeats;
end

function sample = sample_template_local()
sample = struct('cache_hit_count', 0, 'cache_miss_count', 0, ...
    'direct_fallback_count', 0);
end

