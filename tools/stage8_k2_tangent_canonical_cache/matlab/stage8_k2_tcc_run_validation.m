function output = stage8_k2_tcc_run_validation(repo_dir, runtime_dir)
%STAGE8_K2_TCC_RUN_VALIDATION Run compact equivalence and runtime evidence.

if nargin < 1 || isempty(repo_dir)
    [status, repo_dir] = system('git rev-parse --show-toplevel');
    if status ~= 0
        error('stage8_k2_tcc_run_validation:Repository', ...
            'Unable to locate the repository root.');
    end
    repo_dir = strtrim(repo_dir);
end
if nargin < 2 || isempty(runtime_dir)
    runtime_dir = 'E:\bs_innovation_runtime\stage8_k2_tangent_canonical_cache_v1';
end
repo_dir = char(java.io.File(char(string(repo_dir))).getCanonicalPath());
if ~isfolder(runtime_dir)
    mkdir(runtime_dir);
end
scope = stage8_k2_tcc_add_paths(repo_dir); %#ok<NASGU>
output_dir = fullfile(repo_dir, 'innovation-mining');
test_summary = stage8_k2_tcc_run_tests(repo_dir);

context = stage8_k2_tp_build_context(repo_dir);
registry = stage8_k2_tp_build_registry( ...
    context.plan.local_domain, context.constants);
selected = registry.noise_profile_id == "WHITE" & registry.L == 8 & ...
    registry.snr_db == 6 & ismember(registry.profile_id, ...
    ["P1", "P2", "P3", "P4"]);
specs = registry(selected, :);
if height(specs) ~= 4
    error('stage8_k2_tcc_run_validation:Registry', ...
        'The compact validation requires four registered trials.');
end

model = resolve_stage8_measurement_model( ...
    context.plan.measurement_model_registry, ...
    context.primary_measurement_config_id, 'WHITE');
cache_options = struct('domain_bounds_deg', ...
    context.plan.local_domain.domain_bounds_deg);
[cache, cache_info] = stage8_k2_tcc_build_cache(model, cache_options);
direct_provider = stage8_k2_tcc_build_provider( ...
    'DIRECT_ONLY', model, [], struct());
hybrid_provider = stage8_k2_tcc_build_provider( ...
    'EXACT_CACHE_OR_DIRECT', model, cache, struct());

equivalence_rows = repmat(equivalence_template_local(), 0, 1);
trial_records = repmat(struct('spec', [], 'trial', [], ...
    'legacy', [], 'direct', [], 'hybrid', [], ...
    'legacy_diag', [], 'direct_diag', [], 'hybrid_diag', []), ...
    height(specs), 1);
for index = 1:height(specs)
    spec = specs(index, :);
    % This call creates one deterministic element trial and evaluates legacy.
    [legacy_rows, legacy_diag_table, trial] = ...
        stage8_k2_tp_evaluate_trial(spec, context);
    legacy_row = legacy_rows(legacy_rows.method_id == ...
        "TANGENT_PROFILE_SAFE", :);
    direct_context = context;
    direct_context.manifold_provider = direct_provider;
    hybrid_context = context;
    hybrid_context.manifold_provider = hybrid_provider;
    [direct_result, direct_diag] = stage8_k2_tp_fit_safe( ...
        trial.Y_element, trial.model, direct_context);
    [hybrid_result, hybrid_diag] = stage8_k2_tp_fit_safe( ...
        trial.Y_element, trial.model, hybrid_context);
    legacy = fit_summary_local(legacy_row, legacy_diag_table, ...
        trial.element_trial_hash, 'LEGACY_DIRECT');
    direct = fit_summary_local(direct_result, direct_diag, ...
        trial.element_trial_hash, 'DIRECT_ONLY');
    hybrid = fit_summary_local(hybrid_result, hybrid_diag, ...
        trial.element_trial_hash, 'EXACT_CACHE_OR_DIRECT');
    trial_records(index) = struct('spec', spec, 'trial', trial, ...
        'legacy', legacy, 'direct', direct, 'hybrid', hybrid, ...
        'legacy_diag', legacy_diag_table, 'direct_diag', direct_diag, ...
        'hybrid_diag', hybrid_diag);
    equivalence_rows(end + 1, 1) = build_equivalence_row_local( ...
        spec, trial, legacy, direct, model, hybrid_provider, ...
        'LEGACY_DIRECT_VS_DIRECT_ONLY'); %#ok<AGROW>
    equivalence_rows(end + 1, 1) = build_equivalence_row_local( ...
        spec, trial, direct, hybrid, model, hybrid_provider, ...
        'DIRECT_ONLY_VS_EXACT_CACHE_OR_DIRECT'); %#ok<AGROW>
    fprintf('VALIDATED %s (%d/%d) hits=%d misses=%d\n', ...
        char(spec.trial_id), index, height(specs), ...
        hybrid.cache_hit_count, hybrid.cache_miss_count);
end
equivalence = struct2table(equivalence_rows);

runtime = run_benchmarks_local(model, cache, cache_info, ...
    direct_provider, hybrid_provider, trial_records(1), context);
manifest = build_manifest_local(repo_dir, model, cache, ...
    cache_info, equivalence, runtime, trial_records, test_summary);
write_validation_files_local(output_dir, equivalence, runtime, manifest, ...
    cache_info);

output = struct('equivalence', equivalence, 'runtime', runtime, ...
    'manifest', manifest, 'test_summary', test_summary, 'cache', cache, ...
    'cache_info', cache_info, 'trial_records', trial_records);
fprintf('STAGE8_K2_TCC_VALIDATION_COMPLETE rows=%d runtime_rows=%d\n', ...
    height(equivalence), height(runtime));
end

