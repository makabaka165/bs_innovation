function write_text_local(filename, text)
fid = fopen(filename, 'w', 'n', 'UTF-8');
if fid < 0
    error('stage8_k2_tcc_run_validation:Write', ...
        'Unable to write %s.', filename);
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fwrite(fid, char(text), 'char');
end
