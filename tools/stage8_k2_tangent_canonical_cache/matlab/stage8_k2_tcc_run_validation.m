    summary.cache_miss_count = diagnostics.cache_miss_count;
    summary.direct_fallback_count = diagnostics.direct_fallback_count;
    summary.identity_rejection_count = diagnostics.identity_rejection_count;
end
end

function row = build_equivalence_row_local(spec, trial, reference, ...
    candidate, model, hybrid_provider, comparison)
row = equivalence_template_local();
row.case_id = string(spec.trial_id);
row.comparison = string(comparison);
row.fixed_measurement_hash = string(model.fixed_measurement_hash);
row.element_trial_hash = string(trial.element_trial_hash);
row.provider_mode = candidate.provider_mode;
reference_angles = reference.angles_hat_deg;
if any(~isfinite(reference_angles(:)))
    row.failure_reason = "REFERENCE_ANGLES_INVALID";
    return;
end
[G_full, ~, full_info] = build_full_sequential_local_manifold( ...
    reference_angles, model, struct('rank_multiplier', 1));
G_direct = stage8_k2_tcc_build_g_direct(reference_angles, model, struct());
if strcmp(candidate.provider_mode, 'EXACT_CACHE_OR_DIRECT')
    [G_candidate, candidate_manifold_info, provider_info] = ...
        stage8_k2_tcc_get_pair_manifold(reference_angles, model, ...
        hybrid_provider, struct('rank_multiplier', 1));
else
    G_candidate = G_direct;
    [candidate_rank, candidate_singular, candidate_threshold] = ...
        stage8_k2_tcc_stable_matrix_rank(G_candidate, 1);
    candidate_manifold_info = struct('rank_Gseq', candidate_rank, ...
        'singular_values_Gseq', candidate_singular, ...
        'rank_threshold_Gseq', candidate_threshold);
    provider_info = struct('cache_hit_count', 0, 'cache_miss_count', 0, ...
        'direct_fallback_count', 0, 'identity_rejection_count', 0);
end
row.max_G_abs_error = max(abs(G_candidate(:) - G_direct(:)));
row.G_relative_error = norm(G_candidate - G_direct, 'fro') / ...
    max(norm(G_direct, 'fro'), realmin);
row.rank_reference = full_info.rank_Gseq;
row.rank_candidate = candidate_manifold_info.rank_Gseq;
row.rank_match = row.rank_reference == row.rank_candidate;
if strcmp(reference.provider_mode, 'LEGACY_DIRECT')
    row.max_G_abs_error = max(abs(G_direct(:) - G_full(:)));
    row.G_relative_error = norm(G_direct - G_full, 'fro') / ...
        max(norm(G_full, 'fro'), realmin);
end
row.max_scan_loglik_abs_error = trace_error_local(reference, candidate);
row.rho_hat_abs_error_deg = abs(reference.rho_hat_deg - ...
    candidate.rho_hat_deg);
row.max_angle_abs_error_deg = max(abs(reference.angles_hat_deg(:) - ...
    candidate.angles_hat_deg(:)));
row.RSS_abs_error = abs(reference.rss - candidate.rss);
row.loglik_abs_error = abs(reference.loglik - candidate.loglik);
row.selected_source_reference = reference.selected_source;
row.selected_source_candidate = candidate.selected_source;
row.selected_source_match = strcmp(reference.selected_source, ...
    candidate.selected_source);
row.upgrade_match = reference.upgrade_flag == candidate.upgrade_flag;
row.fallback_match = reference.fallback_flag == candidate.fallback_flag && ...
    reference.fallback_reason == candidate.fallback_reason;
row.cache_hit_count = provider_info.cache_hit_count;
row.cache_miss_count = provider_info.cache_miss_count;
row.direct_fallback_count = provider_info.direct_fallback_count;
row.identity_rejection_count = provider_info.identity_rejection_count;
scan_pass = isnan(row.max_scan_loglik_abs_error) || ...
    row.max_scan_loglik_abs_error <= 1e-8 * max(1, ...
    max(abs(reference.trace_loglik), [], 'omitnan'));
row.pass = row.rank_match && row.selected_source_match && ...
    row.upgrade_match && row.fallback_match && ...
    row.G_relative_error <= 1e-10 && scan_pass && ...
    row.rho_hat_abs_error_deg <= 2e-4 && ...
    row.max_angle_abs_error_deg <= 2e-4 && ...
    row.RSS_abs_error <= 1e-8 * max(1, abs(reference.rss)) && ...
    row.loglik_abs_error <= 1e-8 * max(1, abs(reference.loglik)) && ...
    ~reference.truth_used_in_fit_flag && ~candidate.truth_used_in_fit_flag;
if row.pass
    row.failure_reason = "NOT_APPLICABLE";
else
    reasons = strings(0, 1);
    if ~row.rank_match, reasons(end + 1) = "RANK_MISMATCH"; end %#ok<AGROW>
    if ~row.selected_source_match, reasons(end + 1) = "SOURCE_MISMATCH"; end %#ok<AGROW>
    if ~row.upgrade_match, reasons(end + 1) = "UPGRADE_MISMATCH"; end %#ok<AGROW>
    if ~row.fallback_match, reasons(end + 1) = "FALLBACK_MISMATCH"; end %#ok<AGROW>
    if row.G_relative_error > 1e-10, reasons(end + 1) = "G_NOT_EQUIVALENT"; end %#ok<AGROW>
    if ~scan_pass, reasons(end + 1) = "SCAN_NOT_EQUIVALENT"; end %#ok<AGROW>
    if row.rho_hat_abs_error_deg > 2e-4, reasons(end + 1) = "RHO_MISMATCH"; end %#ok<AGROW>
    row.failure_reason = strjoin(reasons, '|');
end
end

function value = trace_error_local(reference, candidate)
if isempty(reference.trace_rho) || isempty(candidate.trace_rho) || ...
        numel(reference.trace_rho) ~= numel(candidate.trace_rho) || ...
        any(reference.trace_rho ~= candidate.trace_rho)
    value = NaN;
    return;
end
left = reference.trace_loglik(:);
right = candidate.trace_loglik(:);
finite_pair = isfinite(left) & isfinite(right);
value = 0;
if any(finite_pair)
    value = max(abs(left(finite_pair) - right(finite_pair)));
end
if any(xor(isfinite(left), isfinite(right)))
    value = Inf;
end
end

function value = field_value_local(source, name, fallback)
if nargin < 3
    fallback = NaN;
end
if istable(source)
    if ismember(name, source.Properties.VariableNames)
        value = source.(name)(1);
    else
        value = fallback;
    end
elseif isstruct(source) && isfield(source, name)
    value = source.(name);
else
    value = fallback;
end
end

function angles = parse_angles_local(value)
if isnumeric(value)
    angles = double(value);
else
    angles = str2num(char(value)); %#ok<ST2NM>
end
end

function runtime = run_benchmarks_local(model, cache, cache_info, ...
    direct_provider, hybrid_provider, record, context)
micro_repeats = 30;
profile_repeats = 10;
end_to_end_repeats = 3;
rows = repmat(runtime_template_local(), 0, 1);
rows(end + 1, 1) = runtime_row_local('CACHE_BUILD', 'cache_build', ...
    'NOT_APPLICABLE', 1, cache_info.cache_build_time_sec, ...
    cache_info.cache_build_time_sec, sample_template_local(), ...
    cache.cache_memory_MB, NaN, NaN); %#ok<AGROW>

exact_first = [cache.global_az_grid_deg(1), cache.el_grid_deg(1)];
exact_second = [cache.global_az_grid_deg(end), cache.el_grid_deg(end)];
off_grid = [mean(cache.global_az_grid_deg) + 0.004, ...
    mean(cache.el_grid_deg) + 0.004];
direct_single_callback = @() sample_single_local( ...
    off_grid, model, direct_provider);
cache_single_callback = @() sample_single_local( ...
    exact_first, model, hybrid_provider);
[direct_single_stats, direct_single_sample] = ...
    measure_operation_local(direct_single_callback, micro_repeats);
[cache_single_stats, cache_single_sample] = ...
    measure_operation_local(cache_single_callback, micro_repeats);
rows(end + 1, 1) = runtime_row_from_stats_local( ...
    'SINGLE_DIRECT', 'single_target_direct_g_only', 'DIRECT_ONLY', ...
    direct_single_stats, direct_single_sample, cache.cache_memory_MB, 1, NaN); %#ok<AGROW>
single_speedup = direct_single_stats.median / cache_single_stats.median;
single_break_even = break_even_local(cache_info.cache_build_time_sec, ...
    direct_single_stats.median, cache_single_stats.median);
rows(end + 1, 1) = runtime_row_from_stats_local( ...
    'SINGLE_CACHE', 'single_target_exact_cache_lookup', ...
    'EXACT_CACHE_OR_DIRECT', cache_single_stats, cache_single_sample, ...
    cache.cache_memory_MB, single_speedup, single_break_even); %#ok<AGROW>

pair_exact = [exact_first; exact_second];
pair_mixed = [exact_first; off_grid];
direct_pair_callback = @() sample_pair_local( ...
    pair_exact, model, direct_provider);
cache_pair_callback = @() sample_pair_local( ...
    pair_exact, model, hybrid_provider);
mixed_pair_callback = @() sample_pair_local( ...
    pair_mixed, model, hybrid_provider);
[direct_pair_stats, direct_pair_sample] = ...
    measure_operation_local(direct_pair_callback, micro_repeats);
[cache_pair_stats, cache_pair_sample] = ...
    measure_operation_local(cache_pair_callback, micro_repeats);
[mixed_pair_stats, mixed_pair_sample] = ...
    measure_operation_local(mixed_pair_callback, micro_repeats);
rows(end + 1, 1) = runtime_row_from_stats_local( ...
    'PAIR_DIRECT', 'pair_direct_g_only', 'DIRECT_ONLY', ...
    direct_pair_stats, direct_pair_sample, cache.cache_memory_MB, 1, NaN); %#ok<AGROW>
pair_speedup = direct_pair_stats.median / cache_pair_stats.median;
pair_break_even = break_even_local(cache_info.cache_build_time_sec, ...
    direct_pair_stats.median, cache_pair_stats.median);
rows(end + 1, 1) = runtime_row_from_stats_local( ...
    'PAIR_CACHE_CACHE', 'pair_cache_cache', 'EXACT_CACHE_OR_DIRECT', ...
    cache_pair_stats, cache_pair_sample, cache.cache_memory_MB, ...
    pair_speedup, pair_break_even); %#ok<AGROW>
rows(end + 1, 1) = runtime_row_from_stats_local( ...
    'PAIR_MIXED', 'pair_cache_direct_mixed', 'EXACT_CACHE_OR_DIRECT', ...
    mixed_pair_stats, mixed_pair_sample, cache.cache_memory_MB, ...
    direct_pair_stats.median / mixed_pair_stats.median, NaN); %#ok<AGROW>

full_data = build_stage8_full_data_from_element( ...
    record.trial.Y_element, model, struct( ...
    'data_role', 'SINGLE_CPI_SINGLE_RANGE_DOPPLER_CELL'));
center = reshape(record.direct_diag.K1_center_deg, 1, 2);
direction = record.direct_diag.direction_hat;
domain = context.plan.local_domain;
constants = context.constants;
direct_profile_callback = @() sample_profile_local(full_data.Zseq_white, ...
    model, center, direction, domain, constants, direct_provider);
hybrid_profile_callback = @() sample_profile_local(full_data.Zseq_white, ...
    model, center, direction, domain, constants, hybrid_provider);
[direct_profile_stats, direct_profile_sample] = ...
    measure_operation_local(direct_profile_callback, profile_repeats);
[hybrid_profile_stats, hybrid_profile_sample] = ...
    measure_operation_local(hybrid_profile_callback, profile_repeats);
rows(end + 1, 1) = runtime_row_from_stats_local( ...
    'PROFILE_DIRECT', 'profile_direct_only', 'DIRECT_ONLY', ...
    direct_profile_stats, direct_profile_sample, cache.cache_memory_MB, 1, NaN); %#ok<AGROW>
rows(end + 1, 1) = runtime_row_from_stats_local( ...
    'PROFILE_HYBRID', 'profile_exact_cache_or_direct', ...
    'EXACT_CACHE_OR_DIRECT', hybrid_profile_stats, hybrid_profile_sample, ...
    cache.cache_memory_MB, direct_profile_stats.median / ...
    hybrid_profile_stats.median, NaN); %#ok<AGROW>

direct_context = context;
direct_context.manifold_provider = direct_provider;
hybrid_context = context;
hybrid_context.manifold_provider = hybrid_provider;
direct_fit_callback = @() sample_fit_local(record.trial.Y_element, ...
    model, direct_context);
hybrid_fit_callback = @() sample_fit_local(record.trial.Y_element, ...
    model, hybrid_context);
[direct_fit_stats, direct_fit_sample] = ...
    measure_operation_local(direct_fit_callback, end_to_end_repeats);
[hybrid_fit_stats, hybrid_fit_sample] = ...
    measure_operation_local(hybrid_fit_callback, end_to_end_repeats);
rows(end + 1, 1) = runtime_row_from_stats_local( ...
    'END_TO_END_DIRECT', 'end_to_end_tangent_direct_only', 'DIRECT_ONLY', ...
    direct_fit_stats, direct_fit_sample, cache.cache_memory_MB, 1, NaN); %#ok<AGROW>
rows(end + 1, 1) = runtime_row_from_stats_local( ...
    'END_TO_END_HYBRID', 'end_to_end_tangent_exact_cache_or_direct', ...
    'EXACT_CACHE_OR_DIRECT', hybrid_fit_stats, hybrid_fit_sample, ...
    cache.cache_memory_MB, direct_fit_stats.median / ...
    hybrid_fit_stats.median, NaN); %#ok<AGROW>
runtime = struct2table(rows);
end

