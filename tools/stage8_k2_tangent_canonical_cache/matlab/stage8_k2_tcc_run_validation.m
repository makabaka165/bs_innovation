    'fallback_reason', 'NOT_RUN'));
summary.truth_used_in_fit_flag = logical(field_value_local( ...
    result_or_row, 'truth_used_in_fit_flag', false));
if isstruct(diagnostics) && isfield(diagnostics, 'evaluated_rho_deg')
    summary.trace_rho = diagnostics.evaluated_rho_deg(:);
    summary.trace_loglik = diagnostics.evaluated_loglik(:);
    summary.trace_valid = diagnostics.evaluated_valid(:);
    summary.trace_status = diagnostics.evaluated_status(:);
