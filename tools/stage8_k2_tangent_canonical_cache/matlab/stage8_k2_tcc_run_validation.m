function manifest = build_manifest_local(repo_dir, model, cache, ...
    cache_info, equivalence, runtime, trial_records, test_summary)
pass_count = nnz(equivalence.pass);
all_pass = pass_count == height(equivalence) && ...
    all(test_summary.pass);
hybrid_hits = 0;
hybrid_misses = 0;
hybrid_fallbacks = 0;
for index = 1:numel(trial_records)
    hybrid_hits = hybrid_hits + trial_records(index).hybrid.cache_hit_count;
    hybrid_misses = hybrid_misses + trial_records(index).hybrid.cache_miss_count;
    hybrid_fallbacks = hybrid_fallbacks + ...
        trial_records(index).hybrid.direct_fallback_count;
end
query_count = hybrid_hits + hybrid_misses;
hit_rate = hybrid_hits / max(1, query_count);
direct_fallback_rate = hybrid_fallbacks / max(1, query_count);
end_to_end_direct = runtime.median_runtime_sec( ...
    runtime.operation == "end_to_end_tangent_direct_only");
end_to_end_hybrid = runtime.median_runtime_sec( ...
    runtime.operation == "end_to_end_tangent_exact_cache_or_direct");
single_break_even = runtime.break_even_query_count( ...
    runtime.operation == "single_target_exact_cache_lookup");
if hit_rate == 0
    performance_observation = 'LEVEL_A_CORRECT_EXACT_HIT_RATE_ZERO';
elseif end_to_end_hybrid >= end_to_end_direct
    performance_observation = 'LEVEL_A_CORRECT_NO_END_TO_END_SPEEDUP';
elseif hit_rate < 0.10
    performance_observation = ...
        'EXACT_CACHE_SPEEDUP_BUT_REAL_PROFILE_HIT_RATE_LOW';
else
    performance_observation = 'EXACT_CACHE_SPEEDUP_AND_USEFUL_HIT_RATE';
end
if all_pass
    correctness = 'STAGE8_K2_TANGENT_CANONICAL_CACHE_LEVEL_A_COMPLETE';
else
    correctness = 'BLOCKED_HYBRID_CHANGES_TANGENT_DECISION';
end
geometry = cache.geometry;
manifest = struct( ...
    'branch', 'experiment/stage8-k2-tangent-canonical-cache-v1', ...
    'parent_branch', 'experiment/stage8-k2-tangent', ...
    'parent_commit', '3e7153ae11f8a49633a2edd2d2f710673e5d1bad', ...
    'architecture_source_commit', ...
    '8a398f4a86345520f29925f1ca7b41b700f22cb9', ...
    'MATLAB_release', version('-release'), 'single_comp_thread', true, ...
    'measurement_config_id', model.measurement_config_id, ...
    'noise_profile_id', model.noise_profile_id, ...
    'fixed_measurement_hash', model.fixed_measurement_hash, ...
    'cache_identity_hash', cache.cache_identity_hash, ...
    'cache_key', cache.cache_key, 'phase_factor', cache.phase_factor, ...
    'steering_phase_sign', cache.steering_phase_sign, ...
    'numeric_class', cache.numeric_class, ...
    'measurement_center_az_deg', cache.measurement_center_az_deg, ...
    'requested_center_az_deg', cache.requested_center_az_deg, ...
    'center_column', cache.center_column, ...
    'element_order', char(string(geometry.canonical_element_order)), ...
    'delta_grid_spec', struct('min_deg', min(cache.delta_grid_deg), ...
    'max_deg', max(cache.delta_grid_deg), 'count', numel(cache.delta_grid_deg), ...
    'key_tolerance_deg', cache.grid_key_tolerance_deg), ...
    'el_grid_spec', struct('min_deg', min(cache.el_grid_deg), ...
    'max_deg', max(cache.el_grid_deg), 'count', numel(cache.el_grid_deg), ...
    'step_deg', 0.01), 'cache_memory_MB', cache.cache_memory_MB, ...
    'cache_build_time_sec', cache_info.cache_build_time_sec, ...
    'test_count', height(test_summary), ...
    'test_pass_count', nnz(test_summary.pass), ...
    'validation_case_count', height(equivalence), ...
    'validation_pass_count', pass_count, 'truth_leakage_count', 0, ...
    'classical_baseline_rerun', false, 'white_snr_full_rerun', false, ...
    'level_b_implemented', false, 'truth_used_in_fit_flag', false, ...
    'selection_truth_used_flag', false, 'cache_truth_used_flag', false, ...
    'actual_exact_hit_count', hybrid_hits, ...
    'actual_cache_miss_count', hybrid_misses, ...
    'actual_direct_fallback_count', hybrid_fallbacks, ...
    'actual_exact_hit_rate', hit_rate, ...
    'actual_direct_fallback_rate', direct_fallback_rate, ...
    'break_even_query_count', single_break_even, ...
    'correctness_conclusion', correctness, ...
    'performance_observation', performance_observation, ...
    'repo_dir', repo_dir);
end

