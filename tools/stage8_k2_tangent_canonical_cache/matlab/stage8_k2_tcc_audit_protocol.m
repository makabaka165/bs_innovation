protocol.protocol_id = ...
    'STAGE8_K2_TANGENT_PIPELINE_CACHE_PLACEMENT_AUDIT_V1';
protocol.level_a_closure_commit = ...
    'cf35e37a74366a8d9829de3a1f8b740a788bade1';
protocol.audit_start_commit = ...
    'aff3bb42df2b3d9b435cc57eacd3237826e7d87d';
