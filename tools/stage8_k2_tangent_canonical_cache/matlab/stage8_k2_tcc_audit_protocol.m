    'MAX_ABSOLUTE_CACHE_DELTA_CHANGE_ACROSS_IDENTITY_SPECIFIC_AND_', ...
    'SINGLE_PAIR_CLASS_SPECIFIC_P10_MEDIAN_P90_SUBSTITUTIONS'];
protocol.microbenchmark_repeat_target = 100;
protocol.microbenchmark_warmup_count = 10;
protocol.stage_schema = { ...
    'ROOT_TANGENT_PROFILE_SAFE','K1_PUBLIC','K2_PUBLIC', ...
    'TAIL_FULL_DATA','CENTER_MANIFOLD_DERIVATIVES', ...
    'PROJECTED_DIRECTION','T4_PROFILE','FINAL_SAFE_SELECTOR', ...
    'K1_CONTEXT','K1_FULL_DATA','K1_INITIALIZATION_TOTAL', ...
    'K1_INIT_CONVENTIONAL','K1_INIT_GROUP_PREPARE', ...
    'K1_INIT_GROUP_Q1','K1_INIT_GROUP_Q2','K1_CORE_LITE', ...
    'K1_FIXED_FIT','K1_FIXED_START_BUILD', ...
    'K1_FIXED_REGISTERED_REFINEMENT', ...
    'K1_FIXED_FINAL_CERTIFICATION','K1_CONTINUOUS','K1_SELECTION', ...
    'K2_CONTEXT','K2_FULL_DATA','K2_INITIALIZATION_TOTAL', ...
    'K2_INIT_CONVENTIONAL','K2_INIT_GROUP_PREPARE', ...
