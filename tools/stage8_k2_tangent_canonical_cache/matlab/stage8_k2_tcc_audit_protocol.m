    audit_code_hash_local(repo_dir);
timing_fields = rmfield(protocol, {'registry_hash','audit_code_hash', ...
    'audit_code_files','level_a_closure_commit','audit_start_commit', ...
    'protocol_id'});
protocol.timing_configuration_hash = stage8_k2_tcc_stable_hash( ...
    'PLACEMENT_AUDIT_TIMING_CONFIGURATION', timing_fields);
