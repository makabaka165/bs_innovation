    'PLACEMENT_AUDIT_PROTOCOL', protocol);
end

function [digest, relative_files] = audit_code_hash_local(repo_dir)
cache_dir = fullfile(repo_dir, 'tools', ...
    'stage8_k2_tangent_canonical_cache', 'matlab');
listing = dir(fullfile(cache_dir, '*.m'));
relative_files = cell(numel(listing), 1);
for index = 1:numel(listing)
    relative_files{index} = fullfile('tools', ...
        'stage8_k2_tangent_canonical_cache', 'matlab', listing(index).name);
end
extra = { ...
    fullfile('tools','stage8_k2_tangent_profile','matlab', ...
        'stage8_k2_tp_fit_safe.m'); ...
    fullfile('tools','stage8_k2_tangent_profile','matlab', ...
        'stage8_k2_tp_profile_scale.m'); ...
    fullfile('beamspace_ml_v18','source','stepwise_signal_model','steps', ...
        'step_12_3_grouped_conditional_dml','common', ...
        'refine_joint_sequential_dml.m'); ...
    fullfile('beamspace_ml_v18','source','stepwise_signal_model','steps', ...
        'step_12_6_k12_bootstrap_resolution','common', ...
        'build_k2_initializations.m'); ...
    fullfile('beamspace_ml_v18','source','stepwise_signal_model','steps', ...
        'step_12_6_k12_bootstrap_resolution','common', ...
        'build_stage8_initialization_context_from_data.m'); ...
    fullfile('beamspace_ml_v18','source','stepwise_signal_model','steps', ...
        'step_12_6_k12_bootstrap_resolution','common', ...
        'fit_local_model_k.m'); ...
    fullfile('beamspace_ml_v18','source','stepwise_signal_model','steps', ...
        'step_12_7_known_k_local_cell_refinement','common', ...
        'build_stage8_known_k_local_context.m'); ...
    fullfile('beamspace_ml_v18','source','stepwise_signal_model','steps', ...
        'step_12_7_known_k_local_cell_refinement','common', ...
        'estimate_stage8_known_k_local_cell.m'); ...
    fullfile('beamspace_ml_v18','source','stepwise_signal_model','steps', ...
        'step_12_7_known_k_local_cell_refinement','common', ...
        'fit_stage8_core_lite.m')};
relative_files = sort([relative_files;extra]);
contents = cell(size(relative_files));
for index = 1:numel(relative_files)
    path_now = fullfile(repo_dir, relative_files{index});
    if ~isfile(path_now)
        error('stage8_k2_tcc_audit_protocol:CodeFile', ...
            'Audit code file is missing: %s', path_now);
    end
    contents{index} = fileread(path_now);
end
digest = stage8_k2_tcc_stable_hash( ...
    'PLACEMENT_AUDIT_CODE', relative_files, contents);
end
