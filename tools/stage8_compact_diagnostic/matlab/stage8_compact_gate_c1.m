function result = stage8_compact_gate_c1(repo_dir, evidence_path, output_root)
%STAGE8_COMPACT_GATE_C1 Reuse the committed K1 evaluator smoke evidence.

repo_dir = char(string(repo_dir));
evidence_path = char(string(evidence_path));
output_root = char(string(output_root));
tool_dir = fileparts(mfilename('fullpath'));
addpath(tool_dir);
addpath(fullfile(repo_dir, 'tools', 'stage8_1b_validation_sharded', 'matlab'));
step = fullfile(repo_dir, 'beamspace_ml_v18', 'source', ...
    'stepwise_signal_model', 'steps', ...
    'step_12_6_k12_bootstrap_resolution');
addpath(step);
path_cleanup = stage8_runtime_path_scope(); %#ok<NASGU>
if ~isfolder(output_root), mkdir(output_root); end
result_path = fullfile(output_root, 'gate_c1_result.json');
expected_hash = ...
    'd78ace209ee3ac352255a77d0c7ef09ee060c8fd12be39502722076b8d96f328';
result = struct('gate_c1_pass', false, ...
    'status', 'COMPACT_GATE_C1_K1_EQUIVALENCE_FAIL_STOPPED', ...
    'checked_utc', utc_now_local(), 'last_error', '');
stage8_1b_write_json_atomic(result_path, result);
try
    if ~isfile(evidence_path)
        error('stage8_compact_gate_c1:Evidence', ...
            'The reusable scientific smoke evidence is missing.');
    end
    values = parse_evidence_local(fileread(evidence_path));
    test_relative = ['tools/stage8_1b_validation_sharded/tests/', ...
        'test_external_runner_matches_reference.m'];
    [show_status, committed_test] = system(sprintf( ...
        'git -C "%s" show HEAD:%s', repo_dir, test_relative));
    assertion_present = show_status == 0 && contains(committed_test, ...
        'assert(isequal(num2hex(double(reference_trials.lambda_12))');
    evaluator_call_present = show_status == 0 && contains(committed_test, ...
        'stage8_1b_evaluate_common_trial');
    pass = strcmp(values.SMOKE_PASS, '1') && ...
        strcmp(values.REFERENCE_HASH, expected_hash) && ...
        strcmp(values.EXTERNAL_HASH, expected_hash) && ...
        assertion_present && evaluator_call_present;
    if ~pass
        error('stage8_compact_gate_c1:Evidence', ...
            'Reusable smoke evidence or its committed assertion is invalid.');
    end
    result = struct('gate_c1_pass', true, ...
        'status', 'COMPACT_GATE_C1_K1_EQUIVALENCE_PASS', ...
        'checked_utc', utc_now_local(), ...
        'evidence_path', evidence_path, ...
        'reference_row_hash', values.REFERENCE_HASH, ...
        'external_row_hash', values.EXTERNAL_HASH, ...
        'row_hash_equality', true, ...
        'lambda_num2hex_equality', true, ...
        'lambda_assertion_source', test_relative, ...
        'state_equality_confirmed_by_smoke', true, ...
        'reused_existing_evidence', true, ...
        'fallback_six_trial_smoke_executed', false, ...
        'last_error', '');
    stage8_1b_write_json_atomic(result_path, result);
catch exception
    result.checked_utc = utc_now_local();
    result.last_error = getReport(exception, 'extended', 'hyperlinks', 'off');
    stage8_1b_write_json_atomic(result_path, result);
    rethrow(exception);
end
clear path_cleanup
end

function values = parse_evidence_local(text_value)
values = struct('SMOKE_PASS', '', 'REFERENCE_HASH', '', 'EXTERNAL_HASH', '');
lines = splitlines(string(text_value));
for index = 1:numel(lines)
    parts = split(lines(index), '=');
    if numel(parts) ~= 2, continue; end
    name = char(strtrim(parts(1)));
    if isfield(values, name), values.(name) = char(strtrim(parts(2))); end
end
end

function value = utc_now_local()
value = char(datetime('now', 'TimeZone', 'UTC', ...
    'Format', 'yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
