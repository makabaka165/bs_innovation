function [trial, contract] = stage8_compact_generate_k2_trial(spec, context)
%STAGE8_COMPACT_GENERATE_K2_TRIAL Generate one deterministic K2 element trial.

if ~(istable(spec) && height(spec) == 1 && string(spec.trial_type) == "K2")
    error('stage8_compact_generate_k2_trial:Spec', ...
        'spec must be one K2 compact-registry row.');
end
constants = stage8_compact_constants();
base_model = resolve_stage8_measurement_model( ...
    context.plan.measurement_model_registry, ...
    constants.primary_measurement_config_id, spec.noise_profile_id);
center = [8 + spec.center_offset_az_deg, 10 + spec.center_offset_el_deg];
direction = [cosd(spec.direction_deg), sind(spec.direction_deg)];
targets = [center - spec.separation_deg * direction / 2; ...
    center + spec.separation_deg * direction / 2];
bounds = context.plan.local_domain.domain_bounds_deg;
endpoints_in_domain = all(targets(:, 1) >= bounds(1) & ...
    targets(:, 1) <= bounds(2) & targets(:, 2) >= bounds(3) & ...
    targets(:, 2) <= bounds(4));
if ~endpoints_in_domain
    error('stage8_compact_generate_k2_trial:Domain', ...
        'Both K2 endpoints must remain inside the frozen local domain.');
end

rng_state = rng;
cleanup = onCleanup(@() rng(rng_state));
rng(spec.parameter_seed, 'twister');
correlation_phase_rad = 2 * pi * rand();
clear cleanup
manifold = build_stage8_element_manifold(targets, base_model);
[source, source_info] = construct_deterministic_source_matrix(2, spec.L, ...
    spec.secondary_power_db, spec.correlation_magnitude, ...
    correlation_phase_rad, sprintf('COMPACT_PROFILE_%02d', spec.profile_id));
signal_unscaled = manifold.A * source;
target_energy = 10 ^ (spec.snr_db / 10) * ...
    size(signal_unscaled, 1) * size(signal_unscaled, 2);
scale = sqrt(target_energy / max(norm(signal_unscaled, 'fro') ^ 2, realmin));
source = source * scale;
signal = manifold.A * source;
[noise, noise_debug] = generate_stage8_element_noise( ...
    base_model, spec.L, 1, spec.element_noise_seed);
Y_element = signal + noise;
element_trial_hash = stage8_stable_hash( ...
    'STAGE8_COMPACT_K2_ELEMENT_TRIAL_V2', Y_element, targets, source, ...
    spec.parameter_seed, spec.element_noise_seed, spec.profile_id, ...
    char(string(spec.noise_profile_id)));

energy_relative_error = abs(norm(signal, 'fro') ^ 2 - target_energy) / ...
    max(target_energy, realmin);
power_contract_pass = source_info.power_relative_error <= 1e-12;
correlation_contract_pass = ...
    source_info.correlation_absolute_error <= 1e-12;
seed_separation_pass = numel(unique([spec.parameter_seed, ...
    spec.element_noise_seed, spec.separation_auxiliary_seed])) == 3;
contract = struct('diagnostic_trial_id', char(spec.diagnostic_trial_id), ...
    'element_trial_hash', element_trial_hash, ...
    'source_total_energy_contract_pass', energy_relative_error <= 1e-12, ...
    'source_total_energy_relative_error', energy_relative_error, ...
    'secondary_power_contract_pass', power_contract_pass, ...
    'secondary_power_relative_error', source_info.power_relative_error, ...
    'correlation_contract_pass', correlation_contract_pass, ...
    'correlation_absolute_error', source_info.correlation_absolute_error, ...
    'endpoints_in_domain_pass', endpoints_in_domain, ...
    'seed_roles_separated_pass', seed_separation_pass, ...
    'truth_used_in_fit_flag', false, ...
    'truth_used_in_classifier_flag', false, ...
    'correlation_magnitude', double(spec.correlation_magnitude), ...
    'correlation_phase_rad', correlation_phase_rad, ...
    'noise_covariance_hash', noise_debug.element_covariance_hash);
if ~(contract.source_total_energy_contract_pass && power_contract_pass && ...
        correlation_contract_pass && endpoints_in_domain && ...
        seed_separation_pass)
    error('stage8_compact_generate_k2_trial:Contract', ...
        'One or more K2 generation contracts failed.');
end
trial = struct('Y_element', Y_element, 'targets_deg', targets, ...
    'center_deg', center, 'source_matrix', source, 'signal', signal, ...
    'noise', noise, 'base_model', base_model, ...
    'element_trial_hash', element_trial_hash, ...
    'correlation_phase_rad', correlation_phase_rad, ...
    'source_info', source_info);
end
