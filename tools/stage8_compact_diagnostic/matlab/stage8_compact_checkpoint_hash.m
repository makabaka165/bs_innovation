function digest = stage8_compact_checkpoint_hash(checkpoint)
%STAGE8_COMPACT_CHECKPOINT_HASH Hash runtime-independent trial content.

rows = sortrows(checkpoint.rows, 'diagnostic_row_index');
if ismember('row_runtime_sec', rows.Properties.VariableNames)
    rows.row_runtime_sec(:) = 0;
end
digest = stage8_stable_hash( ...
    'STAGE8_COMPACT_ELEMENT_TRIAL_CHECKPOINT_V2', ...
    char(string(checkpoint.protocol_version)), ...
    char(string(checkpoint.checkpoint_contract_version)), ...
    char(string(checkpoint.diagnostic_trial_id)), ...
    double(checkpoint.global_trial_index), ...
    char(string(checkpoint.trial_type)), ...
    char(string(checkpoint.stratum_id)), double(checkpoint.profile_id), ...
    rows, checkpoint.truth_metrics, checkpoint.seeds, ...
    char(string(checkpoint.element_trial_hash)), ...
    char(string(checkpoint.stage8_stable_code_identity_hash)), ...
    char(string(checkpoint.stage8_plan_hash)), ...
    char(string(checkpoint.stage8_calibration_plan_hash)), ...
    char(string(checkpoint.stage8_validation_plan_hash)), ...
    char(string(checkpoint.measurement_registry_hash)), ...
    char(string(checkpoint.calibration_evidence_bundle_hash)), ...
    char(string(checkpoint.threshold_set_hash)), ...
    checkpoint.threshold_artifact_hashes, ...
    char(string(checkpoint.diagnostic_protocol_source_hash)), ...
    char(string(checkpoint.completion_status)));
end
