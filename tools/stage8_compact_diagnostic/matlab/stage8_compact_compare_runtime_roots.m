function result = stage8_compact_compare_runtime_roots( ...
    repo_dir, baseline_root, candidate_root, result_path, gate_name)
%STAGE8_COMPACT_COMPARE_RUNTIME_ROOTS Compare two complete checkpoint sets.

repo_dir = char(string(repo_dir));
baseline_root = char(string(baseline_root));
candidate_root = char(string(candidate_root));
result_path = char(string(result_path));
gate_name = upper(char(string(gate_name)));
tool_dir = fileparts(mfilename('fullpath'));
addpath(tool_dir);
addpath(fullfile(repo_dir, 'tools', 'stage8_1b_validation_sharded', 'matlab'));
step = fullfile(repo_dir, 'beamspace_ml_v18', 'source', ...
    'stepwise_signal_model', 'steps', ...
    'step_12_6_k12_bootstrap_resolution');
addpath(step);
path_cleanup = stage8_runtime_path_scope(); %#ok<NASGU>
context = stage8_compact_context(repo_dir, true);
left_protocol = jsondecode(fileread(fullfile(baseline_root, 'protocol.json')));
right_protocol = jsondecode(fileread(fullfile(candidate_root, 'protocol.json')));
stage8_compact_verify_protocol(left_protocol, context);
stage8_compact_verify_protocol(right_protocol, context);
left_indices = sort(double(left_protocol.trial_indices(:)));
right_indices = sort(double(right_protocol.trial_indices(:)));
if ~isequal(left_indices, right_indices)
    error('stage8_compact_compare_runtime_roots:Registry', ...
        'Runtime roots use different compact trial selections.');
end
registry = context.compact_registry(left_indices, :);
left_rows = cell(height(registry), 1);
right_rows = cell(height(registry), 1);
left_hashes = strings(height(registry), 1);
right_hashes = strings(height(registry), 1);
left_element = strings(height(registry), 1);
right_element = strings(height(registry), 1);
for index = 1:height(registry)
    spec = registry(index, :);
    left_path = fullfile(baseline_root, 'checkpoints', ...
        [char(spec.diagnostic_trial_id), '.mat']);
    right_path = fullfile(candidate_root, 'checkpoints', ...
        [char(spec.diagnostic_trial_id), '.mat']);
    if ~isfile(left_path) || ~isfile(right_path)
        error('stage8_compact_compare_runtime_roots:Missing', ...
            'Checkpoint set is incomplete at %s.', spec.diagnostic_trial_id);
    end
    stage8_compact_validate_checkpoint(left_path, left_protocol, spec);
    stage8_compact_validate_checkpoint(right_path, right_protocol, spec);
    left = load(left_path, 'checkpoint', '-mat');
    right = load(right_path, 'checkpoint', '-mat');
    left_rows{index} = left.checkpoint.rows;
    right_rows{index} = right.checkpoint.rows;
    left_hashes(index) = string(left.checkpoint.scientific_content_hash);
    right_hashes(index) = string(right.checkpoint.scientific_content_hash);
    left_element(index) = string(left.checkpoint.element_trial_hash);
    right_element(index) = string(right.checkpoint.element_trial_hash);
end
left_trials = sortrows(vertcat(left_rows{:}), 'diagnostic_row_index');
right_trials = sortrows(vertcat(right_rows{:}), 'diagnostic_row_index');
left_scientific = zero_runtime_local(left_trials);
right_scientific = zero_runtime_local(right_trials);
left_row_hash = stage8_stable_hash( ...
    'STAGE8_COMPACT_DIAGNOSTIC_TRIAL_SET_V2', left_scientific);
right_row_hash = stage8_stable_hash( ...
    'STAGE8_COMPACT_DIAGNOSTIC_TRIAL_SET_V2', right_scientific);
checkpoint_equal = isequal(left_hashes, right_hashes);
row_equal = strcmp(left_row_hash, right_row_hash);
numeric_equal = numeric_num2hex_equal_local( ...
    left_scientific, right_scientific);
lambda_equal = isequal(num2hex(double(left_trials.lambda_12)), ...
    num2hex(double(right_trials.lambda_12)));
state_equal = isequal(string(left_trials.state), string(right_trials.state));
diagnostic_state_equal = isequal(string(left_trials.diagnostic_state), ...
    string(right_trials.diagnostic_state));
element_equal = isequal(left_element, right_element) && ...
    isequal(string(left_trials.element_trial_hash), ...
    string(right_trials.element_trial_hash));
k2 = left_trials.trial_type == "K2";
angle_names = {'azimuth_rmse_deg','elevation_rmse_deg', ...
    'joint_2d_rmse_deg','initial_joint_2d_rmse_deg', ...
    'separation_vector_error_deg','final_target1_az_deg', ...
    'final_target1_el_deg','final_target2_az_deg','final_target2_el_deg'};
k2_angle_equal = true;
for index = 1:numel(angle_names)
    name = angle_names{index};
    k2_angle_equal = k2_angle_equal && isequal( ...
        num2hex(double(left_trials.(name)(k2))), ...
        num2hex(double(right_trials.(name)(k2))));
end
expected_rows = sum(registry.expected_row_count);
no_duplicate = numel(unique(string(left_trials.diagnostic_row_index))) == ...
    expected_rows && numel(unique(string(right_trials.diagnostic_row_index))) == ...
    expected_rows;
pass = checkpoint_equal && row_equal && numeric_equal && lambda_equal && ...
    state_equal && diagnostic_state_equal && element_equal && ...
    k2_angle_equal && no_duplicate && ...
    height(left_trials) == expected_rows && ...
    height(right_trials) == expected_rows;
result = struct('gate_name', gate_name, 'pass', pass, ...
    'checkpoint_scientific_hash_equality', checkpoint_equal, ...
    'baseline_row_hash', left_row_hash, ...
    'candidate_row_hash', right_row_hash, ...
    'row_stable_hash_equality', row_equal, ...
    'row_numeric_num2hex_equality', numeric_equal, ...
    'lambda_num2hex_equality', lambda_equal, ...
    'state_equality', state_equal, ...
    'diagnostic_state_equality', diagnostic_state_equal, ...
    'element_trial_hash_equality', element_equal, ...
    'k2_angle_metric_num2hex_equality', k2_angle_equal, ...
    'no_missing_or_duplicate_trial', no_duplicate, ...
    'element_trial_count', height(registry), 'row_count', expected_rows, ...
    'baseline_separation_trigger_count', ...
    nnz(left_trials.separation_evaluated_flag), ...
    'candidate_separation_trigger_count', ...
    nnz(right_trials.separation_evaluated_flag), ...
    'last_error', '');
stage8_1b_write_json_atomic(result_path, result);
clear path_cleanup
end

function trials = zero_runtime_local(trials)
trials.row_runtime_sec(:) = 0;
end

function pass = numeric_num2hex_equal_local(left, right)
pass = isequal(left.Properties.VariableNames, right.Properties.VariableNames);
if ~pass, return; end
for index = 1:width(left)
    a = left{:, index};
    b = right{:, index};
    if isnumeric(a)
        pass = pass && isequal(num2hex(double(a)), num2hex(double(b)));
    elseif islogical(a)
        pass = pass && isequal(a, b);
    end
    if ~pass, return; end
end
end
