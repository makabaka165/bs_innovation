function audit = stage8_core_v2_validate_checkpoint(path_now, protocol, spec)
%STAGE8_CORE_V2_VALIDATE_CHECKPOINT Validate one atomic known-K checkpoint.

if ischar(protocol) || (isstring(protocol) && isscalar(protocol))
    protocol = jsondecode(fileread(char(protocol)));
end
loaded = load(char(string(path_now)), 'checkpoint', '-mat');
if ~isfield(loaded, 'checkpoint') || ...
        ~(isstruct(loaded.checkpoint) && isscalar(loaded.checkpoint))
    error('stage8_core_v2_validate_checkpoint:Payload', ...
        'Checkpoint must contain one scalar checkpoint struct.');
end
checkpoint = loaded.checkpoint;
required = {'identity','rows','scientific_content_hash', ...
    'completion_status'};
if ~isequal(sort(fieldnames(checkpoint)), sort(required(:)))
    error('stage8_core_v2_validate_checkpoint:Contract', ...
        'Checkpoint fields differ from the minimal contract.');
end
identity = checkpoint.identity;
identity_required = {'protocol_version','checkpoint_contract_version', ...
    'trial_id','global_trial_index','truth_K','element_trial_hash', ...
    'k1_solver_contract_hash','k2_solver_contract_hash', ...
    'protocol_source_tree_hash'};
if ~isequal(sort(fieldnames(identity)), sort(identity_required(:)))
    error('stage8_core_v2_validate_checkpoint:IdentityContract', ...
        'Checkpoint identity fields differ from the contract.');
end
protocol_fields = {'protocol_version','checkpoint_contract_version', ...
    'k1_solver_contract_hash','k2_solver_contract_hash', ...
    'protocol_source_tree_hash'};
for index = 1:numel(protocol_fields)
    name = protocol_fields{index};
    if ~strcmp(string(identity.(name)), string(protocol.(name)))
        error('stage8_core_v2_validate_checkpoint:ProtocolIdentity', ...
            'Checkpoint identity %s differs from protocol.', name);
    end
end
if ~(istable(spec) && height(spec) == 1) || ...
        string(identity.trial_id) ~= string(spec.trial_id) || ...
        double(identity.global_trial_index) ~= spec.global_trial_index || ...
        double(identity.truth_K) ~= spec.truth_K
    error('stage8_core_v2_validate_checkpoint:Registry', ...
        'Checkpoint identity differs from its registry row.');
end

rows = checkpoint.rows;
required_rows = fieldnames(stage8_core_v2_row_template());
methods = ["B0_FIXED_GRID_KNOWN_K"; ...
    "B1_DIRECT_CONTINUOUS_KNOWN_K"; ...
    "B2_GROUPED_CONTINUOUS_KNOWN_K"];
row_contract = istable(rows) && height(rows) == 3 && ...
    all(ismember(required_rows, rows.Properties.VariableNames)) && ...
    isequal(sort(string(rows.method_id)), sort(methods)) && ...
    all(rows.trial_id == string(spec.trial_id)) && ...
    all(rows.global_trial_index == spec.global_trial_index) && ...
    all(rows.truth_K == spec.truth_K) && ...
    all(rows.element_trial_hash == string(identity.element_trial_hash)) && ...
    ~any(rows.truth_used_in_initialization_flag) && ...
    ~any(rows.truth_used_in_fit_flag) && ...
    all(rows.shared_element_data_flag) && ...
    ~any(rows.monotonicity_violation_count ~= 0);
if ~row_contract
    error('stage8_core_v2_validate_checkpoint:Rows', ...
        'Checkpoint method rows violate the known-K contract.');
end
if ~strcmp(string(checkpoint.completion_status), "COMPLETE_PASS")
    error('stage8_core_v2_validate_checkpoint:Completion', ...
        'Checkpoint completion status is not COMPLETE_PASS.');
end
computed = stage8_core_v2_checkpoint_hash(checkpoint);
if ~strcmp(string(computed), string(checkpoint.scientific_content_hash))
    error('stage8_core_v2_validate_checkpoint:ScientificHash', ...
        'Checkpoint scientific hash is invalid.');
end
audit = struct('valid', true, 'trial_id', char(string(identity.trial_id)), ...
    'global_trial_index', double(identity.global_trial_index), ...
    'truth_K', double(identity.truth_K), 'row_count', height(rows), ...
    'scientific_content_hash', char(string(computed)));
end
