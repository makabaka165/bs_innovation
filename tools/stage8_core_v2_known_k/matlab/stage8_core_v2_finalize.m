function output = stage8_core_v2_finalize(repo_dir, runtime_root, output_root)
%STAGE8_CORE_V2_FINALIZE Merge checkpoints and write the five allowed outputs.

repo_dir = char(string(repo_dir));
runtime_root = char(string(runtime_root));
output_root = char(string(output_root));
tool_dir = fileparts(mfilename('fullpath'));
step = fullfile(repo_dir, 'beamspace_ml_v18', 'source', ...
    'stepwise_signal_model', 'steps', ...
    'step_12_6_k12_bootstrap_resolution');
addpath(tool_dir); addpath(step);
path_cleanup = stage8_runtime_path_scope(); %#ok<NASGU>
protocol = jsondecode(fileread(fullfile(runtime_root, 'protocol.json')));
constants = stage8_core_v2_constants();
if ~strcmp(string(protocol.registry_kind), "FORMAL") || ...
        double(protocol.element_trial_count) ~= 24 || ...
        double(protocol.row_count) ~= 72 || ...
        logical(protocol.stage8_2_executed_flag)
    error('stage8_core_v2_finalize:Protocol', ...
        'Finalize requires the complete formal non-Stage8.2 runtime.');
end
if ~isempty(dir(fullfile(runtime_root, 'tmp', '*.tmp'))) || ...
        ~isempty(dir(fullfile(runtime_root, 'workers', '*.current.lock')))
    error('stage8_core_v2_finalize:UnsafeRuntime', ...
        'Temporary checkpoint or active lock remains.');
end
context = stage8_core_v2_context(repo_dir, true);
registry = stage8_core_v2_registry(context, 'FORMAL');
cells = cell(height(registry), 1);
hashes = strings(height(registry), 1);
for index = 1:height(registry)
    path_now = fullfile(runtime_root, 'checkpoints', ...
        [char(registry.trial_id(index)), '.mat']);
    stage8_core_v2_validate_checkpoint(path_now, protocol, ...
        registry(index, :));
    loaded = load(path_now, 'checkpoint', '-mat');
    cells{index} = loaded.checkpoint.rows;
    hashes(index) = string(loaded.checkpoint.scientific_content_hash);
end
trials = sortrows(vertcat(cells{:}), {'global_trial_index','method_id'});
validate_trial_table_local(trials, registry, constants);
[summary, comparison, decision] = analyze_local(trials);
gate_path = fullfile(runtime_root, 'gates', 'gate_decision.json');
if ~isfile(gate_path)
    error('stage8_core_v2_finalize:Gates', ...
        'Finalization requires the recorded G0-G2 decision.');
end
gates = jsondecode(fileread(gate_path));
if ~(logical(gates.gate_g0_pass) && logical(gates.gate_g1_pass) && ...
        logical(gates.gate_g2_pass) && ...
        double(gates.selected_worker_count) == ...
        double(protocol.selected_worker_count))
    error('stage8_core_v2_finalize:Gates', ...
        'Gate decision is not compatible with the formal runtime.');
end
if ~isfolder(output_root), mkdir(output_root); end
paths = { ...
    fullfile(output_root, '26_stage8_core_v2_known_k_pruning_experiment.md'), ...
    fullfile(output_root, '26_stage8_core_v2_known_k_pruning_trials.csv'), ...
    fullfile(output_root, '26_stage8_core_v2_known_k_pruning_summary.csv'), ...
    fullfile(output_root, '26_stage8_core_v2_known_k_pruning_comparison.csv')};
for index = 1:numel(paths)
    if isfile(paths{index})
        error('stage8_core_v2_finalize:Overwrite', ...
            'Finalize refuses to overwrite %s.', paths{index});
    end
end
writetable(trials, paths{2});
writetable(summary, paths{3});
writetable(comparison, paths{4});
write_report_local(paths{1}, protocol, gates, summary, comparison, ...
    decision, hashes);
output = struct('trials', trials, 'summary', summary, ...
    'comparison', comparison, 'decision', decision, ...
    'trial_path', paths{2}, 'summary_path', paths{3}, ...
    'comparison_path', paths{4}, 'report_path', paths{1});
clear path_cleanup
end

function validate_trial_table_local(trials, registry, constants)
methods = ["B0_FIXED_GRID_KNOWN_K"; ...
    "B1_DIRECT_CONTINUOUS_KNOWN_K"; ...
    "B2_GROUPED_CONTINUOUS_KNOWN_K"];
if height(trials) ~= constants.formal_row_count || ...
        numel(unique(trials.trial_id)) ~= constants.formal_trial_count || ...
        numel(unique(trials.trial_id + "|" + trials.method_id)) ~= 72 || ...
        ~isequal(sort(unique(trials.method_id)), sort(methods)) || ...
        nnz(trials.truth_K == 1) ~= 48 || nnz(trials.truth_K == 2) ~= 24 || ...
        any(trials.truth_used_in_initialization_flag) || ...
        any(trials.truth_used_in_fit_flag) || ...
        any(trials.monotonicity_violation_count ~= 0) || ...
        any(~trials.shared_element_data_flag) || height(registry) ~= 24
    error('stage8_core_v2_finalize:Trials', ...
        'Merged trials violate completeness or truth isolation.');
end
for index = 1:height(registry)
    subset = trials(trials.trial_id == registry.trial_id(index), :);
    if height(subset) ~= 3 || numel(unique(subset.element_trial_hash)) ~= 1
        error('stage8_core_v2_finalize:Pairing', ...
            'One trial does not contain three paired method rows.');
    end
end
end

function [summary, comparison, decision] = analyze_local(trials)
method_ids = ["B0_FIXED_GRID_KNOWN_K"; ...
    "B1_DIRECT_CONTINUOUS_KNOWN_K"; ...
    "B2_GROUPED_CONTINUOUS_KNOWN_K"];
summary_cells = cell(3, 1);
metrics = repmat(struct('method_id', "", 'k1_valid', 0, ...
    'k2_valid', 0, 'k1_offgrid_median', NaN, ...
    'k2_median', NaN, 'mean_score_calls', NaN, ...
    'k2_mean_score_calls', NaN, ...
    'mean_svd_calls', NaN, 'median_runtime_sec', NaN, ...
    'operational', false), 3, 1);
for index = 1:3
    subset = trials(trials.method_id == method_ids(index), :);
    k1 = subset(subset.truth_K == 1, :);
    k2 = subset(subset.truth_K == 2, :);
    valid_k2 = k2(k2.fit_valid, :);
    offgrid = k1(k1.support_or_difficulty == ...
        "INSIDE_OFF_GRID" & k1.fit_valid, :);
    k1_median = median_or_nan_local(offgrid.known_K_joint_RMSE);
    k2_median = median_or_nan_local(valid_k2.known_K_joint_RMSE);
    valid_all = subset(subset.fit_valid, :);
    leakage = nnz(subset.truth_used_in_initialization_flag | ...
        subset.truth_used_in_fit_flag);
    operational = nnz(k1.fit_valid) >= 15 && nnz(k2.fit_valid) >= 7 && ...
        isfinite(k1_median) && k1_median <= 0.05 && ...
        isfinite(k2_median) && k2_median <= 0.20 && leakage == 0 && ...
        all(valid_all.monotonicity_violation_count == 0);
    metrics(index) = struct('method_id', method_ids(index), ...
        'k1_valid', nnz(k1.fit_valid), 'k2_valid', nnz(k2.fit_valid), ...
        'k1_offgrid_median', k1_median, 'k2_median', k2_median, ...
        'mean_score_calls', mean(subset.score_calls), ...
        'k2_mean_score_calls', mean(k2.score_calls), ...
        'mean_svd_calls', mean(subset.SVD_calls), ...
        'median_runtime_sec', median(subset.runtime_sec), ...
        'operational', operational);
    summary_cells{index} = struct('method_id', method_ids(index), ...
        'K1_valid', nnz(k1.fit_valid), 'K2_valid', nnz(k2.fit_valid), ...
        'K1_off_grid_median_joint_RMSE_deg', k1_median, ...
        'K2_overall_median_joint_RMSE_deg', k2_median, ...
        'mean_score_calls', mean(subset.score_calls), ...
        'mean_SVD_calls', mean(subset.SVD_calls), ...
        'median_runtime_sec', median(subset.runtime_sec), ...
        'monotonicity_violation_count', nnz(subset.monotonicity_violation_count), ...
        'truth_leakage_count', leakage, ...
        'operational', operational);
end
summary = struct2table(vertcat(summary_cells{:}));
comparison = compare_k2_local(trials);
b1 = metrics(2); b2 = metrics(3);
wins = nnz(comparison.outcome == "B2_WIN");
losses = nnz(comparison.outcome == "B2_LOSS");
median_b1 = b1.k2_median; median_b2 = b2.k2_median;
if ~b1.operational && ~b2.operational
    conclusion = 'STAGE8_CORE_V2_K2_SOLVER_NOT_OPERATIONAL_STOP';
elseif b2.operational && ~b1.operational
    conclusion = 'STAGE8_CORE_V2_OPERATIONAL_GROUPED_RETAIN';
elseif b1.operational && ~b2.operational
    conclusion = 'STAGE8_CORE_V2_OPERATIONAL_GROUPED_PRUNE';
elseif wins >= 5 && median_b2 <= 0.95 * median_b1
    conclusion = 'STAGE8_CORE_V2_OPERATIONAL_GROUPED_RETAIN';
elseif losses >= 5 && median_b2 >= 1.05 * median_b1
    conclusion = 'STAGE8_CORE_V2_OPERATIONAL_GROUPED_PRUNE';
elseif abs(median_b2 - median_b1) <= 0.002 && ...
        b2.k2_mean_score_calls <= 0.80 * b1.k2_mean_score_calls
    conclusion = 'STAGE8_CORE_V2_OPERATIONAL_GROUPED_RETAIN';
elseif abs(median_b2 - median_b1) <= 0.002 && ...
        b2.k2_mean_score_calls >= 1.20 * b1.k2_mean_score_calls
    conclusion = 'STAGE8_CORE_V2_OPERATIONAL_GROUPED_PRUNE';
else
    conclusion = 'STAGE8_CORE_V2_OPERATIONAL_GROUPED_OPTIONAL';
end
decision = struct('B1_operational', b1.operational, ...
    'B2_operational', b2.operational, 'B2_wins', wins, ...
    'B2_ties', nnz(comparison.outcome == "TIE"), ...
    'B2_losses', losses, 'final_conclusion', conclusion, ...
    'model_order_status', 'MODEL_ORDER_DEFERRED', ...
    'formal_6000_trial_status', 'DEFERRED_NOT_FAILED', ...
    'stage8_2_executed_flag', false, 'stage8_2_authorized_flag', false);
end

function comparison = compare_k2_local(trials)
ids = unique(trials.trial_id(trials.truth_K == 2), 'stable');
cells = cell(numel(ids), 1);
for index = 1:numel(ids)
    b1 = trials(trials.trial_id == ids(index) & ...
        trials.method_id == "B1_DIRECT_CONTINUOUS_KNOWN_K", :);
    b2 = trials(trials.trial_id == ids(index) & ...
        trials.method_id == "B2_GROUPED_CONTINUOUS_KNOWN_K", :);
    v1 = b1.fit_valid; v2 = b2.fit_valid;
    if v2 && ~v1
        outcome = "B2_WIN";
    elseif v1 && ~v2
        outcome = "B2_LOSS";
    elseif ~v1 && ~v2
        outcome = "INVALID_COMPARISON";
    elseif b2.known_K_joint_RMSE < b1.known_K_joint_RMSE - 1e-3
        outcome = "B2_WIN";
    elseif b1.known_K_joint_RMSE < b2.known_K_joint_RMSE - 1e-3
        outcome = "B2_LOSS";
    else
        outcome = "TIE";
    end
    cells{index} = struct('trial_id', ids(index), ...
        'B1_fit_valid', v1, 'B2_fit_valid', v2, ...
        'B1_known_K_joint_RMSE_deg', b1.known_K_joint_RMSE, ...
        'B2_known_K_joint_RMSE_deg', b2.known_K_joint_RMSE, ...
        'B1_score_calls', b1.score_calls, 'B2_score_calls', b2.score_calls, ...
        'B1_SVD_calls', b1.SVD_calls, 'B2_SVD_calls', b2.SVD_calls, ...
        'B1_runtime_sec', b1.runtime_sec, 'B2_runtime_sec', b2.runtime_sec, ...
        'outcome', outcome);
end
comparison = struct2table(vertcat(cells{:}));
end

function value = median_or_nan_local(values)
values = values(isfinite(values));
if isempty(values), value = NaN; else, value = median(values); end
end

function write_report_local(path_now, protocol, gates, summary, comparison, ...
    decision, hashes)
fid = fopen(path_now, 'w', 'n', 'UTF-8');
if fid < 0, error('stage8_core_v2_finalize:Report', ...
        'Cannot write final report.'); end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '# Stage8 Core-V2 Known-K Center-Difference Pruning Experiment\n\n');
fprintf(fid, 'KNOWN_K_DIAGNOSTIC_ONLY\n\nMODEL_ORDER_DEFERRED\n\n');
fprintf(fid, 'NO_FORMAL_THRESHOLD\n\nNO_STAGE8_1_VALIDATION_PASS\n\n');
fprintf(fid, 'NO_STAGE8_2_AUTHORIZATION\n\n');
fprintf(fid, 'Branch: %s\n\nStarting/runner HEAD: %s / %s\n\n', ...
    'experiment/stage8-core-v2', protocol.starting_commit, ...
    protocol.protocol_runner_commit);
fprintf(fid, 'Selected workers: %s (%d)\n\n', ...
    protocol.selected_execution_mode, protocol.selected_worker_count);
fprintf(fid, 'G0: PASS, G0_BOUNDARY_IDENTITY_PASS\n\n');
fprintf(fid, 'G1: PASS, %s\n\n', gates.gate_g1_status);
fprintf(fid, 'G2: PASS, %s\n\n', gates.gate_g2_status);
fprintf(fid, 'Trials: K1 16/16; K2 8/8; method rows 72/72.\n\n');
fprintf(fid, '| Method | K1 valid | K2 valid | K1 off-grid median RMSE | K2 median RMSE | score calls | SVD calls | runtime | operational |\n');
fprintf(fid, '|---|---:|---:|---:|---:|---:|---:|---:|---|\n');
for index = 1:height(summary)
    fprintf(fid, '| %s | %d | %d | %.9g | %.9g | %.9g | %.9g | %.9g | %d |\n', ...
        summary.method_id(index), summary.K1_valid(index), ...
        summary.K2_valid(index), ...
        summary.K1_off_grid_median_joint_RMSE_deg(index), ...
        summary.K2_overall_median_joint_RMSE_deg(index), ...
        summary.mean_score_calls(index), summary.mean_SVD_calls(index), ...
        summary.median_runtime_sec(index), summary.operational(index));
end
fprintf(fid, '\nB2 vs B1: wins=%d, ties=%d, losses=%d.\n\n', ...
    nnz(comparison.outcome == "B2_WIN"), nnz(comparison.outcome == "TIE"), ...
    nnz(comparison.outcome == "B2_LOSS"));
fprintf(fid, 'Scientific checkpoint hashes: %d valid.\n\n', ...
    numel(unique(hashes)));
fprintf(fid, 'Final conclusion: %s\n\n', decision.final_conclusion);
fprintf(fid, 'Model-order status = DEFERRED\n');
fprintf(fid, 'Formal 6000-trial status = DEFERRED_NOT_FAILED\n');
fprintf(fid, 'Stage8.2 executed = false\n');
clear cleanup
end
