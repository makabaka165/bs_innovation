function [fit, debug] = stage8_core_v2_fit_known_k( ...
    full_data, K, starts, local_domain, model, opts)
%STAGE8_CORE_V2_FIT_KNOWN_K Refine fixed starts and select by log-likelihood.

if nargin < 6, opts = struct(); end
if ~(isscalar(K) && ismember(K, [1, 2]))
    error('stage8_core_v2_fit_known_k:K', 'K must be 1 or 2.');
end
if ~(isstruct(starts) && isvector(starts) && ~isempty(starts))
    error('stage8_core_v2_fit_known_k:Starts', ...
        'starts must be a nonempty struct vector.');
end
if ~(isstruct(opts) && isscalar(opts) && isempty(fieldnames(opts)))
    error('stage8_core_v2_fit_known_k:Options', ...
        'The known-K fit budget is fixed; opts must be empty.');
end

clock = tic;
results = repmat(empty_result_local(K), numel(starts), 1);
for index = 1:numel(starts)
    results(index).initialization_id = ...
        char(string(starts(index).initialization_id));
    results(index).initial_angles_deg = starts(index).angles_deg;
    results(index).initialization_available_flag = ...
        logical(starts(index).available_flag);
    if isfield(starts, 'initialization_status')
        results(index).initialization_status = ...
            char(string(starts(index).initialization_status));
    end
    if ~results(index).initialization_available_flag || ...
            ~isequal(size(results(index).initial_angles_deg), [K, 2]) || ...
            any(~isfinite(results(index).initial_angles_deg(:)))
        continue;
    end
    if K == 1
        [estimate, history, solver_debug] = ...
            stage8_r1_refine_continuous_dml(full_data, ...
            results(index).initial_angles_deg, local_domain, model, struct());
        solver_status = char(string(estimate.status));
        solver_usable = strcmp(solver_status, ...
            'CONTINUOUS_REFINEMENT_CONVERGED');
        if strcmp(solver_status, 'CONTINUOUS_REFINEMENT_MAX_SWEEPS') && ...
                estimate.monotonicity_violation_count == 0 && ...
                isfinite(estimate.relative_score_change) && ...
                estimate.relative_score_change <= 1e-7 && ...
                isfinite(estimate.max_angle_update_deg) && ...
                estimate.max_angle_update_deg <= 2e-3
            solver_status = 'K1_CONTINUOUS_MAX_SWEEPS_USABLE';
            solver_usable = true;
        end
    else
        [estimate, history, solver_debug] = ...
            stage8_core_v2_k2_center_difference_solver(full_data, ...
            results(index).initial_angles_deg, local_domain, model, struct());
        solver_status = char(string(estimate.status));
        solver_usable = logical(estimate.usable_flag);
    end
    results(index).angles_hat_deg = estimate.angles_hat_deg;
    results(index).initial_angles_deg = estimate.initial_angles_deg;
    results(index).solver_status = solver_status;
    results(index).initial_score = estimate.initial_score;
    results(index).final_score = estimate.final_score;
    results(index).score_call_count = estimate.score_call_count;
    results(index).svd_call_count = estimate.svd_call_count;
    results(index).monotonicity_violation_count = ...
        estimate.monotonicity_violation_count;
    results(index).solver_contract_hash = estimate.solver_contract_hash;
    results(index).history = history;
    results(index).solver_debug = solver_debug;
    if ~(solver_usable && estimate.estimate_returned_flag && ...
            estimate.monotonicity_violation_count == 0)
        results(index).fit_status = 'SOLVER_NOT_OPERATIONAL';
        continue;
    end
    [results(index), valid] = rebuild_fit_local(results(index), ...
        full_data, K, model);
    results(index).valid_for_selection_flag = valid;
end

valid_indices = find([results.valid_for_selection_flag]);
fit = empty_fit_local(K, full_data, local_domain, model);
fit.all_start_results = results;
fit.num_start = numel(starts);
fit.valid_start_count = numel(valid_indices);
fit.num_score_eval = sum([results.score_call_count]);
fit.num_svd = sum([results.svd_call_count]);
fit.monotonicity_violation_count = ...
    sum([results.monotonicity_violation_count]);
fit.runtime = toc(clock);
if isempty(valid_indices)
    debug = struct('selected_start_index', 0, ...
        'selected_start_id', '', 'valid_start_count', 0, ...
        'selection_rule', ...
        'MAXIMUM_CONCENTRATED_LOG_LIKELIHOOD_AMONG_VALID_STARTS');
    return;
end
loglik = [results(valid_indices).loglik_concentrated];
maximum = max(loglik);
tolerance = 64 * eps(max(1, abs(maximum)));
selected_index = valid_indices(find(loglik >= maximum - tolerance, ...
    1, 'first'));
selected = results(selected_index);
fields = {'angles_hat_deg','G_hat','S_hat','score','rss','sigma2_hat', ...
    'loglik_concentrated','effective_rank','solver_status', ...
    'solver_contract_hash'};
for index = 1:numel(fields)
    fit.(fields{index}) = selected.(fields{index});
end
fit.fit_status = 'KNOWN_K_FIT_VALID';
fit.estimate_returned_flag = true;
fit.converged_flag = true;
fit.initialization_id = selected.initialization_id;
fit.selected_initial_angles_deg = selected.initial_angles_deg;
fit.runtime = toc(clock);
debug = struct('selected_start_index', selected_index, ...
    'selected_start_id', selected.initialization_id, ...
    'valid_start_count', numel(valid_indices), ...
    'selection_tolerance', tolerance, ...
    'selection_rule', ...
    'MAXIMUM_CONCENTRATED_LOG_LIKELIHOOD_AMONG_VALID_STARTS');
end

function [result, valid] = rebuild_fit_local(result, data, K, model)
[G, ~, manifold_info] = build_full_sequential_local_manifold( ...
    result.angles_hat_deg, model, struct('rank_multiplier', 1));
[score, rss, sigma2, loglik, rank_now] = concentrated_dml_rss( ...
    data.Zseq_white, G, struct('requested_rank', K, ...
    'rank_multiplier', 1, 'compute_projector_checks', false));
[S, solve_info] = solve_fitted_source_coefficients( ...
    G, data.Zseq_white, struct('rank_multiplier', 1));
result.score_call_count = result.score_call_count + 1;
result.svd_call_count = result.svd_call_count + ...
    manifold_info.num_svd + 1 + solve_info.num_svd;
result.G_hat = G;
result.S_hat = S;
result.score = score;
result.rss = rss;
result.sigma2_hat = sigma2;
result.loglik_concentrated = loglik;
result.effective_rank = min(rank_now, solve_info.effective_rank);
valid = result.effective_rank >= K && isfinite(score) && ...
    isfinite(rss) && rss >= 0 && isfinite(sigma2) && sigma2 >= 0 && ...
    isfinite(loglik) && all(isfinite(S(:)));
if valid, result.fit_status = 'KNOWN_K_FIT_VALID'; ...
else, result.fit_status = 'FIT_NUMERIC_INVALID'; end
end

function fit = empty_fit_local(K, data, domain, model)
r_C = size(data.Zseq_white, 1);
L = size(data.Zseq_white, 2);
fit = struct('K', K, 'angles_hat_deg', NaN(K, 2), ...
    'G_hat', complex(NaN(r_C, K)), 'S_hat', complex(NaN(K, L)), ...
    'score', NaN, 'rss', NaN, 'sigma2_hat', NaN, ...
    'loglik_concentrated', NaN, 'effective_rank', 0, ...
    'fit_status', 'NO_VALID_START', 'solver_status', 'NO_VALID_START', ...
    'estimate_returned_flag', false, 'converged_flag', false, ...
    'initialization_id', '', 'selected_initial_angles_deg', NaN(K, 2), ...
    'all_start_results', struct([]), 'num_start', 0, ...
    'valid_start_count', 0, 'num_score_eval', 0, 'num_svd', 0, ...
    'runtime', 0, 'monotonicity_violation_count', 0, ...
    'fixed_measurement_hash', model.fixed_measurement_hash, ...
    'local_domain_hash', domain.domain_hash, 'solver_contract_hash', '', ...
    'observation_hash', stage8_stable_hash(data.Zseq_white), ...
    'effective_whitening_dimension', r_C, 'snapshot_count', L, ...
    'n_complex_observations', r_C * L, 'phase_factor', 1);
end

function result = empty_result_local(K)
result = struct('initialization_id', '', ...
    'initialization_available_flag', false, ...
    'initialization_status', 'INITIALIZATION_NOT_BUILT', ...
    'initial_angles_deg', NaN(K, 2), 'angles_hat_deg', NaN(K, 2), ...
    'score', NaN, 'rss', NaN, 'sigma2_hat', NaN, ...
    'loglik_concentrated', -Inf, 'effective_rank', 0, ...
    'G_hat', complex(NaN(0, K)), 'S_hat', complex(NaN(K, 0)), ...
    'fit_status', 'INITIALIZATION_FAILED', 'solver_status', 'NOT_RUN', ...
    'initial_score', NaN, 'final_score', NaN, ...
    'valid_for_selection_flag', false, 'score_call_count', 0, ...
    'svd_call_count', 0, 'monotonicity_violation_count', 0, ...
    'solver_contract_hash', '', 'history', table(), ...
    'solver_debug', struct());
end
