function result = test_external_runner_matches_reference(repo_dir)
%TEST_EXTERNAL_RUNNER_MATCHES_REFERENCE Run one real common trial per stratum.

context = stage8_1b_frozen_context(repo_dir, false);
reference = run_stage8_1_k1_validation( ...
    context.plan.validation, context.plan.local_domain, ...
    context.plan.measurement_model_registry, context.thresholds, ...
    build_stage8_stage5_locked_config(), struct( ...
    'formal_run', false, 'max_common_trials_per_stratum', 1, ...
    'evaluation_callback', [], 'fit_options', struct(), ...
    'Bsep', 199, 'run_separation', false, ...
    'execution_authorization', '', 'frozen_plan', context.plan));
selected = context.registry( ...
    context.registry.trial_index_within_stratum <= 1, :);
pair_ids = unique(string(selected.common_trial_id), 'stable');
external = cell(numel(pair_ids), 1);
for index = 1:numel(pair_ids)
    pair = selected(selected.common_trial_id == pair_ids(index), :);
    external{index} = stage8_1b_evaluate_common_trial( ...
        pair, context.plan, context.thresholds, struct( ...
        'formal_run', false, 'fit_options', struct(), ...
        'Bsep', 199, 'run_separation', false));
end
external_trials = sortrows(vertcat(external{:}), 'evaluation_row_index');
reference_trials = sortrows(reference.trials, 'evaluation_row_index');
reference_hash = stage8_stable_hash( ...
    'STAGE8_1_VALIDATION_TRIAL_SET_V1', reference_trials);
external_hash = stage8_stable_hash( ...
    'STAGE8_1_VALIDATION_TRIAL_SET_V1', external_trials);
assert(height(reference_trials) == 12);
assert(strcmp(reference_hash, external_hash));
assert(isequal(num2hex(double(reference_trials.lambda_12)), ...
    num2hex(double(external_trials.lambda_12))));
assert(isequal(string(reference_trials.state), ...
    string(external_trials.state)));
[protocol, ~, ~] = build_checkpoint_fixture();
real_rows = external_trials(external_trials.common_trial_id == pair_ids(1), :);
checkpoint = struct( ...
    'protocol_version', protocol.protocol_version, ...
    'checkpoint_contract_version', protocol.checkpoint_contract_version, ...
    'common_trial_id', char(pair_ids(1)), ...
    'global_common_trial_index', 1, 'rows', real_rows, ...
    'stage8_stable_code_identity_hash', ...
    protocol.stage8_stable_code_identity_hash, ...
    'stage8_plan_hash', protocol.stage8_plan_hash, ...
    'stage8_validation_plan_hash', protocol.stage8_validation_plan_hash, ...
    'measurement_registry_hash', protocol.measurement_registry_hash, ...
    'calibration_evidence_bundle_hash', ...
    protocol.calibration_evidence_bundle_hash, ...
    'threshold_set_hash', protocol.threshold_set_hash, ...
    'calibration_snapshot_hash', protocol.calibration_snapshot_hash, ...
    'threshold_lookup_only_flag', true, ...
    'threshold_modification_flag', false, ...
    'completion_status', 'COMPLETE_PASS', 'content_hash', '', ...
    'runtime_sec', 0, 'worker_id', 1, 'attempt_id', 'REAL_ROW_SCHEMA', ...
    'created_utc', '2026-07-27T00:00:00.000Z');
checkpoint.content_hash = stage8_1b_checkpoint_content_hash(checkpoint);
checkpoint_path = [tempname, '.mat'];
cleanup = onCleanup(@() delete(checkpoint_path));
save(checkpoint_path, 'checkpoint', '-mat');
audit = stage8_1b_validate_checkpoint(checkpoint_path, protocol, ...
    selected(selected.common_trial_id == pair_ids(1), :));
assert(audit.valid);
result = struct('pass', true, 'reference_row_hash', reference_hash, ...
    'external_row_hash', external_hash, 'row_count', 12);
clear cleanup
end
