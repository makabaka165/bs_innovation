function stage8_1b_verify_protocol(protocol, context)
%STAGE8_1B_VERIFY_PROTOCOL Verify immutable protocol and repository state.

constants = context.constants;
required = {'protocol_version','execution_authorization','repo_dir', ...
    'protocol_runner_commit','protocol_source_tree_hash', ...
    'threshold_evidence_commit','stage8_stable_code_identity_hash', ...
    'stage8_plan_hash','stage8_calibration_plan_hash', ...
    'stage8_validation_plan_hash','measurement_registry_hash', ...
    'calibration_evidence_bundle_hash','threshold_set_hash', ...
    'calibration_snapshot_hash','matlab_release','threads_per_worker', ...
    'selected_worker_count','common_trial_count','row_count','Bsep', ...
    'checkpoint_contract_version'};
if ~(isstruct(protocol) && isscalar(protocol) && ...
        all(isfield(protocol, required)))
    error('stage8_1b_verify_protocol:Contract', ...
        'The immutable protocol is incomplete.');
end
if ~strcmp(string(protocol.protocol_version), ...
        string(constants.protocol_version)) || ...
        ~strcmp(string(protocol.execution_authorization), ...
        string(constants.execution_authorization)) || ...
        ~strcmp(string(protocol.threshold_evidence_commit), ...
        string(constants.threshold_evidence_commit)) || ...
        ~strcmp(string(protocol.checkpoint_contract_version), ...
        string(constants.checkpoint_contract_version))
    error('stage8_1b_verify_protocol:Version', ...
        'Protocol version or authorization is invalid.');
end
actual = [string(protocol.stage8_stable_code_identity_hash), ...
    string(protocol.stage8_plan_hash), ...
    string(protocol.stage8_calibration_plan_hash), ...
    string(protocol.stage8_validation_plan_hash), ...
    string(protocol.measurement_registry_hash), ...
    string(protocol.calibration_evidence_bundle_hash), ...
    string(protocol.threshold_set_hash), ...
    string(protocol.calibration_snapshot_hash)];
expected = [string(constants.stage8_stable_code_identity_hash), ...
    string(constants.stage8_plan_hash), ...
    string(constants.stage8_calibration_plan_hash), ...
    string(constants.stage8_validation_plan_hash), ...
    string(constants.measurement_registry_hash), ...
    string(constants.calibration_evidence_bundle_hash), ...
    string(constants.threshold_set_hash), ...
    string(context.calibration_snapshot_hash)];
if ~isequal(actual, expected)
    error('stage8_1b_verify_protocol:FrozenIdentity', ...
        'Protocol identities differ from committed evidence.');
end
if ~strcmpi(canonical_local(protocol.repo_dir), ...
        canonical_local(context.repo_dir)) || ...
        ~strcmp(string(protocol.matlab_release), "R2022b") || ...
        double(protocol.threads_per_worker) ~= 1 || ...
        double(protocol.Bsep) ~= constants.Bsep
    error('stage8_1b_verify_protocol:RuntimeContract', ...
        'Repository, MATLAB, thread, or Bsep protocol fields are invalid.');
end
if ~strcmp(version('-release'), '2022b') || maxNumCompThreads ~= 1
    error('stage8_1b_verify_protocol:SingleThread', ...
        'Workers require MATLAB R2022b -singleCompThread.');
end
if ~isempty(ver('parallel')) && ~isempty(gcp('nocreate'))
    error('stage8_1b_verify_protocol:ParallelPool', ...
        'A parallel pool is forbidden for this protocol.');
end

[head_status, head] = system(sprintf( ...
    'git -C "%s" rev-parse HEAD', context.repo_dir));
[git_status, worktree] = system(sprintf( ...
    'git -C "%s" status --porcelain=v1 --untracked-files=all', ...
    context.repo_dir));
if head_status ~= 0 || git_status ~= 0 || ...
        ~strcmp(strtrim(head), char(string(protocol.protocol_runner_commit))) || ...
        ~isempty(strtrim(worktree))
    error('stage8_1b_verify_protocol:RepositoryState', ...
        'HEAD or Git worktree differs from the immutable protocol.');
end
source_hash = stage8_1b_protocol_source_tree_hash(context.repo_dir);
if ~strcmp(string(source_hash), string(protocol.protocol_source_tree_hash))
    error('stage8_1b_verify_protocol:ToolSource', ...
        'Committed sharded-runner source tree changed.');
end
[ancestor_status, ~] = system(sprintf( ...
    'git -C "%s" merge-base --is-ancestor %s HEAD', ...
    context.repo_dir, constants.threshold_evidence_commit));
step_relative = ['beamspace_ml_v18/source/stepwise_signal_model/steps/', ...
    'step_12_6_k12_bootstrap_resolution'];
[diff_status, step_diff] = system(sprintf( ...
    'git -C "%s" diff --name-only %s..HEAD -- "%s"', ...
    context.repo_dir, constants.threshold_evidence_commit, step_relative));
if ancestor_status ~= 0 || diff_status ~= 0 || ~isempty(strtrim(step_diff))
    error('stage8_1b_verify_protocol:FrozenStep', ...
        'Threshold commit ancestry or frozen Stage8 step diff is invalid.');
end
verify_results_clean_local(context.step);
end

function verify_results_clean_local(step)
root = fullfile(step, 'results');
items = dir(root);
names = string({items(~[items.isdir]).name});
if numel(names) ~= 1 || names ~= ".gitkeep"
    error('stage8_1b_verify_protocol:ResultsNotClean', ...
        'results/ must contain only .gitkeep before finalization.');
end
end

function value = canonical_local(value)
value = char(java.io.File(char(string(value))).getCanonicalPath());
end
