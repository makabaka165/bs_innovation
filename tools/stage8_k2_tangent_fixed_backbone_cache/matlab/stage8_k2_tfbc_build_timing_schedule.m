function [schedule, schedule_hash] = ...
    stage8_k2_tfbc_build_timing_schedule(registry)
%STAGE8_K2_TFBC_BUILD_TIMING_SCHEDULE Freeze two paired comparisons.

comparisons = struct( ...
    'comparison_id',{'CACHE_VS_LEGACY','CACHE_VS_DIRECT_G'}, ...
    'baseline_mode',{'LEGACY_FULL','DIRECT_G_ONLY'});
row_count = height(registry) * 20 * numel(comparisons);
rows = repmat(struct('global_pair_index',0, 'comparison_id',"", ...
    'trial_index',0, 'trial_id',"", 'repeat_index',0, ...
    'pair_order',"", 'baseline_mode',"", ...
    'treatment_mode',"REGISTERED_CACHE"), row_count, 1);
row_index = 0;
for comparison_index = 1:numel(comparisons)
    for trial_index = 1:height(registry)
        for repeat_index = 1:20
            row_index = row_index + 1;
            order = "AB";
            if repeat_index > 10, order = "BA"; end
            rows(row_index) = struct('global_pair_index',row_index, ...
                'comparison_id',string( ...
                comparisons(comparison_index).comparison_id), ...
                'trial_index',trial_index, ...
                'trial_id',string(registry.trial_id(trial_index)), ...
                'repeat_index',repeat_index, 'pair_order',order, ...
                'baseline_mode',string( ...
                comparisons(comparison_index).baseline_mode), ...
                'treatment_mode',"REGISTERED_CACHE");
        end
    end
end
schedule = struct2table(rows);
schedule_hash = stage8_k2_tcc_stable_hash( ...
    'STAGE8_K2_TFBC_TIMING_SCHEDULE_V1', schedule);
end
