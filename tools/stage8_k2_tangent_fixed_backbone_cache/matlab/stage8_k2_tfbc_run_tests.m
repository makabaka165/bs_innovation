function summary = stage8_k2_tfbc_run_tests(repo_dir, runtime_root, options)
%STAGE8_K2_TFBC_RUN_TESTS Run TFBC and frozen regression tests.

if nargin < 2, runtime_root = ''; end
if nargin < 3 || isempty(options), options = struct(); end
if ~isfield(options, 'include_formal_72')
    options.include_formal_72 = ~isempty(runtime_root) && isfile(fullfile( ...
        runtime_root, 'correctness', 'correctness_output.mat'));
end
fixture = stage8_k2_tfbc_test_fixture(repo_dir);
tests = { ...
    'test_stage8_k2_tfbc_registered_index', @() ...
        test_stage8_k2_tfbc_registered_index(fixture); ...
    'test_stage8_k2_tfbc_identity', @() ...
        test_stage8_k2_tfbc_identity(fixture); ...
    'test_stage8_k2_tfbc_static_domain', @() ...
        test_stage8_k2_tfbc_static_domain(fixture); ...
    'test_stage8_k2_tfbc_k1_refinement', @() ...
        test_stage8_k2_tfbc_k1_refinement(fixture); ...
    'test_stage8_k2_tfbc_k2_refinement', @() ...
        test_stage8_k2_tfbc_k2_refinement(fixture); ...
    'test_stage8_k2_tfbc_nested_anchor', @() ...
        test_stage8_k2_tfbc_nested_anchor(fixture); ...
    'test_stage8_k2_tfbc_final_certification', @() ...
        test_stage8_k2_tfbc_final_certification(fixture); ...
    'test_stage8_k2_tfbc_t4_bypass', @() ...
        test_stage8_k2_tfbc_t4_bypass(fixture); ...
    'test_stage8_k2_tfbc_runtime_protocol', @() ...
        test_stage8_k2_tfbc_runtime_protocol(fixture)};
if logical(options.include_formal_72)
    tests(end + 1, :) = {'test_stage8_k2_tfbc_72_trial_semantics', ...
        @() test_stage8_k2_tfbc_72_trial_semantics(runtime_root)};
end
rows = repmat(struct('test_name',"", 'pass',false, ...
    'runtime_sec',0, 'message',""), size(tests, 1), 1);
for index = 1:size(tests, 1)
    rows(index).test_name = string(tests{index, 1});
    clock = tic;
    try
        value = tests{index, 2}();
        rows(index).pass = isstruct(value) && logical(value.pass);
    catch exception
        rows(index).message = string(exception.identifier) + ": " + ...
            string(exception.message);
    end
    rows(index).runtime_sec = toc(clock);
end
summary = struct2table(rows);
disp(summary);
assert(all(summary.pass), 'stage8_k2_tfbc_run_tests:Failed', ...
    '%d of %d TFBC tests failed.', nnz(~summary.pass), height(summary));
end
