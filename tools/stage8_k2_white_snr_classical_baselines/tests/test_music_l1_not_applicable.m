function result = test_music_l1_not_applicable(fixture)
%TEST_MUSIC_L1_NOT_APPLICABLE Verify L=1 skips EVD and peak search.

entry = struct('G_beamspace', complex(zeros(3, 1)), ...
    'standalone_precompute_runtime_sec', 0);
resources = struct('grid_size', [1, 1], 'grid_point_count', 1, ...
    'az_grid_deg', 0, 'el_grid_deg', 0);
fit = stage8_k2_cb_music(complex(zeros(3, 1)), entry, ...
    resources, 'BEAMSPACE', 1, fixture.context.constants);
assert(~fit.applicable && ~fit.fit_valid && ...
    fit.applicability_status == ...
    "NOT_APPLICABLE_INSUFFICIENT_SAMPLE_SUBSPACE_RANK" && ...
    fit.eig_call_count == 0 && fit.score_call_count == 0, ...
    'test_music_l1_not_applicable:Status', ...
    'L=1 MUSIC must be N/A without EVD or peak search.');
result = struct('pass', true, 'status', fit.applicability_status, ...
    'eig_call_count', fit.eig_call_count);
end
