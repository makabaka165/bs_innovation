function result = test_checkpoint_roundtrip_resume(fixture)
%TEST_CHECKPOINT_ROUNDTRIP_RESUME Verify atomic write, skip, hash, hard stop.

runtime_root = tempname;
mkdir(runtime_root);
mkdir(fullfile(runtime_root, 'checkpoints'));
cleanup = onCleanup(@() cleanup_local(runtime_root));
spec = fixture.registry(1, :);
[trial, ~, identity] = stage8_k2_wcb_reconstruct_trial( ...
    spec, fixture.context);
rows = fixture_rows_local(spec, trial, fixture.context.constants);
registry_hash = stage8_k2_wcb_stable_hash( ...
    'CHECKPOINT_TEST_REGISTRY', spec);
[original_checkpoint, path_now] = stage8_k2_wcb_checkpoint_write( ...
    runtime_root, spec, identity, rows, fixture.context, ...
    registry_hash, 1.25);
audit = stage8_k2_wcb_checkpoint_validate( ...
    path_now, spec, fixture.context, registry_hash);
scan = stage8_k2_wcb_scan_checkpoints( ...
    runtime_root, spec, fixture.context, registry_hash);
exists_rejected = false;
try
    stage8_k2_wcb_checkpoint_write(runtime_root, spec, identity, rows, ...
        fixture.context, registry_hash, 1.25);
catch exception
    exists_rejected = strcmp(exception.identifier, ...
        'stage8_k2_wcb_checkpoint_write:Exists');
end

loaded = load(path_now, 'checkpoint', '-mat');
loaded.checkpoint.scientific_hash = 'tampered';
tampered_path = [path_now, '.tampered'];
checkpoint = loaded.checkpoint; %#ok<NASGU>
save(tampered_path, 'checkpoint', '-mat');
tamper_rejected = false;
try
    stage8_k2_wcb_checkpoint_validate( ...
        tampered_path, spec, fixture.context, registry_hash);
catch exception
    tamper_rejected = strcmp(exception.identifier, ...
        'stage8_k2_wcb_checkpoint_validate:ScientificHash');
end
assert(audit.pass && scan.completed_count == 1 && exists_rejected && ...
    tamper_rejected && strcmp(checkpoint.scientific_hash, 'tampered'), ...
    'test_checkpoint_roundtrip_resume:Contract', ...
    'Checkpoint roundtrip, resume skip, or hard-stop contract failed.');
result = struct('pass', true, 'scientific_hash', ...
    string(original_checkpoint.scientific_hash), ...
    'resume_completed_count', scan.completed_count, ...
    'existing_final_rejected', exists_rejected, ...
    'tamper_rejected', tamper_rejected);
clear cleanup
end

function rows = fixture_rows_local(spec, trial, constants)
beam = result_local("FULL4D_BEAMSPACE_CML_MULTISTART", ...
    "BEAMSPACE", true, "FULL4D_CML_NO_VALID_COARSE_PAIR");
music = result_local("BEAMSPACE_MUSIC_K2", "BEAMSPACE", false, ...
    "NOT_APPLICABLE_INSUFFICIENT_SAMPLE_SUBSPACE_RANK");
element = result_local("FULL4D_ELEMENT_CML_MULTISTART", "ELEMENT", ...
    false, "NOT_IN_REGISTERED_ELEMENT_REFERENCE_SUBSET");
rows = struct2table([ ...
    stage8_k2_wcb_result_row(spec, trial, beam, constants); ...
    stage8_k2_wcb_result_row(spec, trial, music, constants); ...
    stage8_k2_wcb_result_row(spec, trial, element, constants)]);
end

function value = result_local(method, domain, applicable, status)
value = struct('method_id', method, 'observation_domain', domain, ...
    'applicable', applicable, ...
    'applicability_status', string(status), 'fit_valid', false, ...
    'fit_status', string(status), 'optimizer_status', "NOT_APPLICABLE", ...
    'angles_hat_deg', NaN(2, 2), 'rss', NaN, ...
    'loglik_concentrated', NaN, 'effective_rank', 0, ...
    'score_call_count', 0, 'svd_call_count', 0, ...
    'eig_call_count', 0, 'runtime_sec', 0, ...
    'truth_used_in_fit_flag', false, ...
    'profile_used_in_fit_flag', false, ...
    'tangent_used_in_start_flag', false, ...
    'core_used_in_start_flag', false);
end

function cleanup_local(path_now)
if isfolder(path_now)
    rmdir(path_now, 's');
end
end
