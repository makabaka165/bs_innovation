function relative = relative_path_local(path_now, repo_dir)
canonical = char(java.io.File(char(path_now)).getCanonicalPath());
prefix = [char(java.io.File(repo_dir).getCanonicalPath()), filesep];
if ~startsWith(canonical, prefix, 'IgnoreCase', true)
    error('stage8_k2_wcb_summarize:ArtifactScope', ...
        'Output artifact is outside the repository.');
end
relative = strrep(canonical(numel(prefix) + 1:end), filesep, '/');
end

function write_json_atomic_local(path_now, value)
temporary = [path_now, '.tmp'];
encoded = jsonencode(value, 'PrettyPrint', true);
fid = fopen(temporary, 'w');
if fid < 0
    error('stage8_k2_wcb_summarize:ManifestOpen', ...
        'Unable to write the runtime manifest.');
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '%s\n', encoded);
clear cleanup
[ok, message] = movefile(temporary, path_now, 'f');
if ~ok
    error('stage8_k2_wcb_summarize:ManifestMove', '%s', message);
end
end

function value = finite_median_local(values)
values = double(values(isfinite(values)));
if isempty(values)
    value = NaN;
else
    value = median(values);
end
end

function value = percentile_local(values, percentile)
value = stage8_k2_mc_percentile(values, percentile);
end

function value = ratio_local(numerator, denominator)
if denominator == 0
    value = NaN;
else
    value = numerator / denominator;
end
end
