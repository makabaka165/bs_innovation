function audit = numerical_audit_local(data, constants)
beam = sortrows(data(data.method_id == ...
    "FULL4D_BEAMSPACE_CML_MULTISTART", :), 'trial_id');
tangent = sortrows(data(data.method_id == "TANGENT_PROFILE_SAFE", :), ...
    'trial_id');
if height(beam) ~= constants.trial_count || ...
        ~isequal(beam.trial_id, tangent.trial_id)
    error('stage8_k2_wcb_summarize:NumericalPair', ...
        'Full4D and Tangent numerical audit rows do not align.');
end
delta = tangent.joint_RMSE_deg - beam.joint_RMSE_deg;
outcome = repmat("EXCLUDED_INVALID", height(beam), 1);
paired = beam.fit_valid & tangent.fit_valid;
outcome(paired & delta < -constants.paired_tie_tolerance_deg) = ...
    "TANGENT_WIN";
outcome(paired & abs(delta) <= constants.paired_tie_tolerance_deg) = ...
    "TIE";
outcome(paired & delta > constants.paired_tie_tolerance_deg) = ...
    "TANGENT_LOSS";
likelihood_tolerance = 64 * eps('double') * ...
    max(1, abs(tangent.loglik));
audit = table(beam.trial_id, beam.snr_db, beam.profile_id, ...
    beam.noise_profile_id, beam.L, beam.replicate_id, ...
    tangent.fit_valid, beam.fit_valid, tangent.loglik, beam.loglik, ...
    likelihood_tolerance, ...
    beam.numerical_optimization_incomplete_flag, ...
    beam.complete_likelihood_subset_flag, ...
    tangent.joint_RMSE_deg, beam.joint_RMSE_deg, delta, outcome, ...
    beam.optimizer_status, beam.score_call_count, ...
    beam.SVD_call_count, beam.runtime_sec, ...
    'VariableNames', {'trial_id','white_snr_db','profile_id', ...
    'noise_profile_id','L','replicate_id','tangent_valid', ...
    'full4d_valid','tangent_loglik','full4d_loglik', ...
    'likelihood_tolerance','numerical_optimization_incomplete_flag', ...
    'complete_likelihood_subset_flag','tangent_joint_RMSE_deg', ...
    'full4d_joint_RMSE_deg','paired_delta_deg','paired_outcome', ...
    'optimizer_status','score_call_count','SVD_call_count','runtime_sec'});
end

