    "FULL4D_CML_MAX_SWEEPS_VALID");
row.numerical_incomplete_count = nnz( ...
    method_rows.numerical_optimization_incomplete_flag);
valid = method_rows.fit_valid;
row.median_joint_RMSE_deg = finite_median_local( ...
    method_rows.joint_RMSE_deg(valid));
row.p90_joint_RMSE_deg = percentile_local( ...
    method_rows.joint_RMSE_deg(valid), 90);
row.median_center_error_deg = finite_median_local( ...
    method_rows.center_error_deg(valid));
row.p90_center_error_deg = percentile_local( ...
    method_rows.center_error_deg(valid), 90);
row.median_axis_error_deg = finite_median_local( ...
    method_rows.axis_error_deg(valid));
row.p90_axis_error_deg = percentile_local( ...
    method_rows.axis_error_deg(valid), 90);
row.median_rho_error_deg = finite_median_local( ...
    method_rows.rho_error_deg(valid));
row.p90_rho_error_deg = percentile_local( ...
    method_rows.rho_error_deg(valid), 90);
row.median_rho_relative_error = finite_median_local( ...
    method_rows.rho_relative_error(valid));
