    pair = pair_stats_local(tangent, music, constants);
    applicable = music.applicable;
    valid_rate = ratio_local(nnz(music.fit_valid), nnz(applicable));
    state = "MUSIC_TWO_PEAK_REGION_NOT_IDENTIFIED";
    if valid_rate >= 0.5
        state = "MUSIC_TWO_PEAK_REGION_IDENTIFIED";
    end
    rows(index) = struct('white_snr_db', snr, ...
        'total_count', height(music), ...
        'applicable_count', nnz(applicable), ...
        'sample_rank_valid_count', nnz(applicable & music.sample_rank >= 2), ...
        'single_peak_count', nnz(music.fit_status == ...
        "MUSIC_FEWER_THAN_TWO_PEAKS"), ...
        'two_or_more_local_peak_count', nnz(applicable & ...
        music.local_peak_count >= 2), ...
        'valid_k2_output_count', nnz(music.fit_valid), ...
        'valid_two_peak_rate', valid_rate, ...
        'median_valid_joint_RMSE_deg', finite_median_local( ...
        music.joint_RMSE_deg(music.fit_valid)), ...
        'p90_valid_joint_RMSE_deg', percentile_local( ...
        music.joint_RMSE_deg(music.fit_valid), 90), ...
        'median_runtime_sec', finite_median_local( ...
        music.runtime_sec(applicable)), ...
        'paired_count', pair.count, 'tangent_wins', pair.wins, ...
        'ties', pair.ties, 'tangent_losses', pair.losses, ...
        'median_paired_delta_deg', pair.median_delta, ...
        'two_peak_region_state', state);
end
output = struct2table(rows);
end

function output = element_summary_local(data, constants)
rows = repmat(element_template_local(), 0, 1);
methods = ["TANGENT_PROFILE_SAFE"; ...
    "FULL4D_BEAMSPACE_CML_MULTISTART"; ...
    "FULL4D_ELEMENT_CML_MULTISTART"];
registered = ismember(data.snr_db, constants.element_snr_targets_db) & ...
    data.L == constants.element_snapshot_count & ...
    ismember(data.replicate_id, constants.element_replicates);
element_data = data(registered, :);
rows = add_element_scope_local(rows, element_data, ...
    "ELEMENT_SUBSET_OVERALL", "ALL", methods, constants);
for snr = constants.element_snr_targets_db
    rows = add_element_scope_local(rows, ...
        element_data(element_data.snr_db == snr, :), ...
        "SNR", string(snr), methods, constants);
end
for profile = constants.profile_ids.'
    rows = add_element_scope_local(rows, ...
        element_data(element_data.profile_id == profile, :), ...
        "PROFILE", profile, methods, constants);
end
for noise = constants.noise_profile_ids.'
    rows = add_element_scope_local(rows, ...
        element_data(element_data.noise_profile_id == noise, :), ...
        "NOISE", noise, methods, constants);
end
output = struct2table(rows);
end

function rows = add_element_scope_local( ...
    rows, subset, scope_type, scope_value, methods, constants)
tangent = subset(subset.method_id == "TANGENT_PROFILE_SAFE", :);
for method = methods.'
    selected = subset(subset.method_id == method, :);
    pair = pair_stats_local(tangent, selected, constants);
    valid = selected.fit_valid;
    row = element_template_local();
    row.scope_type = scope_type;
    row.scope_value = scope_value;
    row.method_id = method;
    row.total_count = height(selected);
    row.applicable_count = nnz(selected.applicable);
    row.fit_valid_count = nnz(valid);
    row.median_joint_RMSE_deg = finite_median_local( ...
        selected.joint_RMSE_deg(valid));
    row.p90_joint_RMSE_deg = percentile_local( ...
        selected.joint_RMSE_deg(valid), 90);
    row.median_runtime_sec = finite_median_local( ...
        selected.runtime_sec(selected.applicable));
    if method ~= "TANGENT_PROFILE_SAFE"
        row.paired_count = pair.count;
        row.tangent_wins = pair.wins;
        row.ties = pair.ties;
        row.tangent_losses = pair.losses;
        row.median_paired_delta_deg = pair.median_delta;
    end
    row.reference_status = "ELEMENT_REFERENCE_DESCRIPTIVE";
    rows(end + 1, 1) = row; %#ok<AGROW>
end
end

function row = element_template_local()
row = struct('scope_type', "", 'scope_value', "", 'method_id', "", ...
    'total_count', 0, 'applicable_count', 0, 'fit_valid_count', 0, ...
    'median_joint_RMSE_deg', NaN, 'p90_joint_RMSE_deg', NaN, ...
    'median_runtime_sec', NaN, 'paired_count', 0, ...
    'tangent_wins', 0, 'ties', 0, 'tangent_losses', 0, ...
    'median_paired_delta_deg', NaN, 'reference_status', "");
end

function interpretation = interpretation_local( ...
    data, summary, music, constants)
working = constants.element_snr_targets_db;
qualifies = false(numel(working), 1);
for index = 1:numel(working)
    row = summary(summary.white_snr_db == working(index) & ...
        summary.method_id == "FULL4D_BEAMSPACE_CML_MULTISTART", :);
    if height(row) ~= 1
        error('stage8_k2_wcb_summarize:InterpretationRows', ...
            'A working-region Full4D summary row is missing.');
    end
    qualifies(index) = row.paired_tangent_median_RMSE_deg <= ...
        row.paired_baseline_median_RMSE_deg && ...
        row.paired_tangent_p90_RMSE_deg <= ...
        row.paired_baseline_p90_RMSE_deg && ...
        row.tangent_wins > row.tangent_losses;
end
work_mask = ismember(data.snr_db, working);
tangent = data(data.method_id == "TANGENT_PROFILE_SAFE" & work_mask, :);
complete = data(data.method_id == ...
    "FULL4D_BEAMSPACE_CML_MULTISTART" & work_mask & ...
    data.complete_likelihood_subset_flag, :);
pair = pair_stats_local(tangent, complete, constants);
complete_tangent = pair.count > 0 && ...
    pair.tangent_median <= pair.baseline_median && ...
    pair.tangent_p90 <= pair.baseline_p90 && pair.wins > pair.losses;
complete_full_dominates = pair.count == 0 || ...
    (pair.baseline_median < pair.tangent_median && ...
    pair.baseline_p90 < pair.tangent_p90 && pair.losses > pair.wins);
if all(qualifies) && complete_tangent
    full4d_state = ...
        'STAGE8_K2_TANGENT_ADVANTAGE_OVER_NUMERICAL_BEAMSPACE_CML_SUPPORTED';
elseif nnz(qualifies) >= 2 && ~complete_full_dominates
    full4d_state = ...
        'STAGE8_K2_TANGENT_ADVANTAGE_OVER_NUMERICAL_BEAMSPACE_CML_PARTIAL';
else
    full4d_state = ...
        'STAGE8_K2_TANGENT_ADVANTAGE_OVER_NUMERICAL_BEAMSPACE_CML_NOT_SUPPORTED';
end
identified = music.valid_two_peak_rate >= 0.5;
if any(identified)
    music_state = 'MUSIC_TWO_PEAK_REGION_IDENTIFIED';
    first_music = min(music.white_snr_db(identified));
else
    music_state = 'MUSIC_TWO_PEAK_REGION_NOT_IDENTIFIED';
    first_music = NaN;
end
interpretation = struct('full4d_state', full4d_state, ...
    'working_snr_db', working, 'qualifying_snr_mask', qualifies, ...
    'qualifying_snr_count', nnz(qualifies), ...
    'complete_likelihood_paired_count', pair.count, ...
    'complete_tangent_condition', complete_tangent, ...
    'complete_full4d_dominates', complete_full_dominates, ...
    'music_state', music_state, ...
    'first_music_snr_db', first_music, ...
    'element_state', 'ELEMENT_REFERENCE_DESCRIPTIVE');
end

