function output = build_summary_local(data, constants, mode)
rows = repmat(summary_template_local(), 0, 1);
methods = ["TANGENT_PROFILE_SAFE"; constants.baseline_method_ids];
for snr = constants.white_snr_targets_db
    if mode == "SNR_OVERALL"
        rows = add_scope_local(rows, data(data.snr_db == snr, :), ...
            mode, snr, "ALL", "ALL", NaN, methods, constants);
    elseif mode == "SNR_PROFILE"
        for profile = constants.profile_ids.'
            subset = data(data.snr_db == snr & ...
                data.profile_id == profile, :);
            rows = add_scope_local(rows, subset, mode, snr, profile, ...
                "ALL", NaN, methods, constants);
        end
    elseif mode == "EXACT_CELL"
        for noise = constants.noise_profile_ids.'
            for L = constants.snapshot_counts
                for profile = constants.profile_ids.'
                    subset = data(data.snr_db == snr & ...
                        data.profile_id == profile & ...
                        data.noise_profile_id == noise & data.L == L, :);
                    rows = add_scope_local(rows, subset, mode, snr, ...
                        profile, noise, L, methods, constants);
                end
            end
        end
    else
        error('stage8_k2_wcb_summarize:SummaryMode', ...
            'Unknown summary mode.');
    end
end
output = struct2table(rows);
end

function rows = add_scope_local(rows, subset, scope_type, snr, ...
    profile, noise, L, methods, constants)
for method = methods.'
    method_rows = subset(subset.method_id == method, :);
    tangent_rows = subset(subset.method_id == "TANGENT_PROFILE_SAFE", :);
    row = method_summary_local(method_rows, tangent_rows, constants);
    row.scope_type = scope_type;
    row.white_snr_db = snr;
    row.profile_id = profile;
    row.noise_profile_id = noise;
    row.L = L;
    rows(end + 1, 1) = row; %#ok<AGROW>
end
end

function row = method_summary_local(method_rows, tangent_rows, constants)
row = summary_template_local();
if isempty(method_rows)
    return;
end
row.method_id = method_rows.method_id(1);
