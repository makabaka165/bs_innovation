    method_rows.SVD_call_count(applicable));
row.median_eig_call_count = finite_median_local( ...
    method_rows.eig_call_count(applicable));
row.median_runtime_sec = finite_median_local( ...
    method_rows.runtime_sec(applicable));
row.p90_runtime_sec = percentile_local( ...
    method_rows.runtime_sec(applicable), 90);
if row.method_id ~= "TANGENT_PROFILE_SAFE"
    pair = pair_stats_local(tangent_rows, method_rows, constants);
    row = assign_pair_local(row, pair, 'paired_');
end
if row.method_id == "FULL4D_BEAMSPACE_CML_MULTISTART"
    complete = method_rows( ...
        method_rows.complete_likelihood_subset_flag, :);
    pair = pair_stats_local(tangent_rows, complete, constants);
    row.complete_likelihood_count = height(complete);
    row.complete_tangent_median_RMSE_deg = pair.tangent_median;
    row.complete_tangent_p90_RMSE_deg = pair.tangent_p90;
    row.complete_baseline_median_RMSE_deg = pair.baseline_median;
    row.complete_baseline_p90_RMSE_deg = pair.baseline_p90;
    row.complete_wins = pair.wins;
    row.complete_ties = pair.ties;
    row.complete_losses = pair.losses;
    row.complete_median_delta_deg = pair.median_delta;
    row.complete_p90_delta_deg = pair.p90_delta;
end
end

function row = assign_pair_local(row, pair, ~)
row.paired_count = pair.count;
row.tangent_wins = pair.wins;
row.ties = pair.ties;
row.tangent_losses = pair.losses;
row.non_tie_tangent_win_rate = pair.non_tie_win_rate;
row.median_paired_delta_deg = pair.median_delta;
row.p90_paired_delta_deg = pair.p90_delta;
row.paired_tangent_median_RMSE_deg = pair.tangent_median;
row.paired_tangent_p90_RMSE_deg = pair.tangent_p90;
row.paired_baseline_median_RMSE_deg = pair.baseline_median;
row.paired_baseline_p90_RMSE_deg = pair.baseline_p90;
end

function pair = pair_stats_local(tangent, baseline, constants)
pair = struct('count', 0, 'wins', 0, 'ties', 0, 'losses', 0, ...
    'non_tie_win_rate', NaN, 'median_delta', NaN, 'p90_delta', NaN, ...
    'tangent_median', NaN, 'tangent_p90', NaN, ...
    'baseline_median', NaN, 'baseline_p90', NaN);
tangent = tangent(tangent.fit_valid, :);
baseline = baseline(baseline.fit_valid, :);
ids = intersect(tangent.trial_id, baseline.trial_id);
if isempty(ids)
    return;
end
tangent = sortrows(tangent(ismember(tangent.trial_id, ids), :), 'trial_id');
baseline = sortrows(baseline(ismember(baseline.trial_id, ids), :), 'trial_id');
if ~isequal(tangent.trial_id, baseline.trial_id)
    error('stage8_k2_wcb_summarize:PairIdentity', ...
        'Paired method rows do not align by trial.');
end
delta = tangent.joint_RMSE_deg - baseline.joint_RMSE_deg;
tolerance = constants.paired_tie_tolerance_deg;
pair.count = numel(delta);
pair.wins = nnz(delta < -tolerance);
pair.ties = nnz(abs(delta) <= tolerance);
pair.losses = nnz(delta > tolerance);
pair.non_tie_win_rate = ratio_local(pair.wins, pair.wins + pair.losses);
pair.median_delta = finite_median_local(delta);
pair.p90_delta = percentile_local(delta, 90);
pair.tangent_median = finite_median_local(tangent.joint_RMSE_deg);
pair.tangent_p90 = percentile_local(tangent.joint_RMSE_deg, 90);
pair.baseline_median = finite_median_local(baseline.joint_RMSE_deg);
pair.baseline_p90 = percentile_local(baseline.joint_RMSE_deg, 90);
end

