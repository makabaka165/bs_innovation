function row = stage8_k2_wcb_result_row(spec, trial, result, constants)
%STAGE8_K2_WCB_RESULT_ROW Add evaluation-only metrics to one fit result.

row = template_local();
row.trial_id = string(spec.trial_id);
row.global_trial_index = double(spec.global_trial_index);
row.element_trial_hash = string(trial.element_trial_hash);
row.measurement_hash = string(trial.measurement_hash);
row.method_id = string(result.method_id);
row.observation_domain = string(result.observation_domain);
row.white_beamspace_snr_target_db = ...
    double(spec.white_beamspace_snr_target_db);
row.noise_profile_id = string(spec.noise_profile_id);
row.L = double(spec.L);
row.profile_id = string(spec.profile_id);
row.replicate_id = double(spec.replicate_id);
row.base_realization_index = double(spec.base_realization_index);
row.applicable = logical(result.applicable);
row.applicability_status = string(result.applicability_status);
row.fit_valid = logical(result.fit_valid);
row.fit_status = string(result.fit_status);
row.optimizer_status = string(get_local(result, ...
    'optimizer_status', 'NOT_APPLICABLE'));
row.selected_source = string(get_local(result, ...
    'selected_source', result.method_id));
row.selected_start_id = string(get_local(result, ...
    'selected_start_id', ''));
row.angles_hat_deg = string(mat2str(result.angles_hat_deg, 17));
row.RSS = double(get_local(result, 'rss', NaN));
row.loglik = double(get_local(result, 'loglik_concentrated', NaN));
row.effective_rank = double(get_local(result, 'effective_rank', 0));
row.score_call_count = double(get_local(result, 'score_call_count', 0));
row.SVD_call_count = double(get_local(result, 'svd_call_count', 0));
row.eig_call_count = double(get_local(result, 'eig_call_count', 0));
row.runtime_sec = double(get_local(result, 'runtime_sec', 0));
row.online_runtime_sec = double(get_local(result, ...
    'online_runtime_sec', row.runtime_sec));
row.precompute_runtime_sec_amortized = double(get_local(result, ...
    'precompute_runtime_sec_amortized', 0));
row.coarse_candidate_count = double(get_local(result, ...
    'coarse_candidate_count', 0));
row.continuous_start_count = double(get_local(result, ...
    'continuous_start_count', 0));
row.sweep_count = double(get_local(result, 'sweep_count', 0));
row.local_peak_count = double(get_local(result, 'local_peak_count', 0));
row.peak_values = string(mat2str(get_local(result, ...
    'peak_values', [NaN, NaN]), 17));
if row.method_id == "BEAMSPACE_MUSIC_K2"
    row.sample_rank = row.effective_rank;
end
row.truth_used_in_fit_flag = logical(get_local(result, ...
    'truth_used_in_fit_flag', false));
row.profile_used_in_fit_flag = logical(get_local(result, ...
    'profile_used_in_fit_flag', false));
row.tangent_used_in_start_flag = logical(get_local(result, ...
    'tangent_used_in_start_flag', false));
row.core_used_in_start_flag = logical(get_local(result, ...
    'core_used_in_start_flag', false));
row.full_manifold_used_flag = logical(get_local(result, ...
    'full_manifold_used_flag', false));
row.more_informative_element_reference_flag = ...
    row.observation_domain == "ELEMENT";
row.same_hardware_interface_flag = row.observation_domain == "BEAMSPACE";
if row.fit_valid
    metrics = stage8_k2_cb_metrics(result.angles_hat_deg, ...
        trial.truth_angles_deg, constants);
    row.joint_RMSE_deg = metrics.joint_RMSE_deg;
    row.azimuth_RMSE_deg = metrics.azimuth_RMSE_deg;
    row.elevation_RMSE_deg = metrics.elevation_RMSE_deg;
    row.center_error_deg = metrics.center_error_deg;
    row.axis_error_deg = metrics.axis_error_deg;
    row.rho_error_deg = metrics.separation_error_deg;
    row.rho_relative_error = metrics.separation_error_deg / ...
        max(metrics.separation_true_deg, realmin('double'));
    row.separation_vector_error_deg = ...
        metrics.separation_vector_error_deg;
end
end

function row = template_local()
row = struct('trial_id', "", 'global_trial_index', 0, ...
    'element_trial_hash', "", 'measurement_hash', "", ...
    'method_id', "", 'observation_domain', "", ...
    'white_beamspace_snr_target_db', NaN, ...
    'noise_profile_id', "", 'L', 0, 'profile_id', "", ...
    'replicate_id', 0, 'base_realization_index', 0, ...
    'applicable', false, 'applicability_status', "NOT_RUN", ...
    'fit_valid', false, 'fit_status', "NOT_RUN", ...
    'optimizer_status', "NOT_RUN", 'selected_source', "", ...
    'selected_start_id', "", 'angles_hat_deg', "", ...
    'RSS', NaN, 'loglik', NaN, 'effective_rank', 0, ...
    'joint_RMSE_deg', NaN, 'azimuth_RMSE_deg', NaN, ...
    'elevation_RMSE_deg', NaN, 'center_error_deg', NaN, ...
    'axis_error_deg', NaN, 'rho_error_deg', NaN, ...
    'rho_relative_error', NaN, 'separation_vector_error_deg', NaN, ...
    'score_call_count', 0, 'SVD_call_count', 0, ...
    'eig_call_count', 0, 'runtime_sec', 0, ...
    'online_runtime_sec', 0, 'precompute_runtime_sec_amortized', 0, ...
    'coarse_candidate_count', 0, 'continuous_start_count', 0, ...
    'sweep_count', 0, 'local_peak_count', 0, 'sample_rank', 0, ...
    'peak_values', "[NaN NaN]", ...
    'numerical_optimization_incomplete_flag', false, ...
    'numerical_optimization_status', "NOT_APPLICABLE", ...
    'complete_likelihood_subset_flag', false, ...
    'raw_tangent_loglik_reference', NaN, ...
    'likelihood_tolerance', NaN, ...
    'truth_used_in_fit_flag', false, ...
    'profile_used_in_fit_flag', false, ...
    'tangent_used_in_start_flag', false, ...
    'core_used_in_start_flag', false, ...
    'full_manifold_used_flag', false, ...
    'more_informative_element_reference_flag', false, ...
    'same_hardware_interface_flag', true);
end

function value = get_local(input, field, default)
if isfield(input, field)
    value = input.(field);
else
    value = default;
end
end
