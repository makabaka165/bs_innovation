function state = stage8_k2_wcb_registry_prepare( ...
    runtime_root, registry, context, test_output, preflight)
%STAGE8_K2_WCB_REGISTRY_PREPARE Create or validate one resumable runtime.

registry_hash = stage8_k2_wcb_stable_hash( ...
    'BASELINE_REGISTRY', registry, context.evidence44.identity, ...
    context.constants.protocol);
registry_dir = fullfile(runtime_root, 'registry');
state_path = fullfile(runtime_root, 'run_state.mat');
formal_path = fullfile(runtime_root, 'formal_execution_state.mat');
if ~isfolder(runtime_root)
    if isfile(runtime_root) || ~mkdir(runtime_root)
        error('stage8_k2_wcb_registry_prepare:RuntimeCreate', ...
            'Unable to create the formal runtime root.');
    end
    directories = {'registry','checkpoints','status','merged','audit'};
    for index = 1:numel(directories)
        if ~mkdir(fullfile(runtime_root, directories{index}))
            error('stage8_k2_wcb_registry_prepare:Directory', ...
                'Unable to create runtime directory: %s', directories{index});
        end
    end
    registry_path = fullfile(registry_dir, 'registry.mat');
    temporary = [registry_path, '.tmp'];
    save(temporary, 'registry', 'registry_hash', '-mat');
    [ok, message] = movefile(temporary, registry_path);
    if ~ok
        error('stage8_k2_wcb_registry_prepare:RegistryMove', '%s', message);
    end
    writetable(registry, fullfile(registry_dir, 'registry.csv'));
    write_text_local(fullfile(registry_dir, 'registry_hash.txt'), ...
        [registry_hash, newline]);
    write_text_local(fullfile(registry_dir, 'code_identity.txt'), ...
        [context.code_identity.tree_hash, newline]);
    formal_state = struct('protocol', context.constants.protocol, ...
        'formal_head', preflight.head, ...
        'context_hash', context.context_hash, ...
        'code_identity', context.code_identity.tree_hash, ...
        'registry_hash', registry_hash, ...
        'evidence44_identity', context.evidence44.identity, ...
        'test_output', test_output, ...
        'tests_completed_utc', stage8_k2_mc_utc_now());
    temporary = [formal_path, '.tmp'];
    save(temporary, 'formal_state', '-mat');
    [ok, message] = movefile(temporary, formal_path);
    if ~ok
        error('stage8_k2_wcb_registry_prepare:FormalMove', '%s', message);
    end
    run_state = struct('launch_count', 1, 'resume_count', 0, ...
        'created_utc', stage8_k2_mc_utc_now(), ...
        'last_launch_utc', stage8_k2_mc_utc_now());
    mode = "NEW";
else
    required = {registry_dir, fullfile(runtime_root, 'checkpoints'), ...
        fullfile(runtime_root, 'status'), ...
        fullfile(runtime_root, 'merged'), ...
        fullfile(runtime_root, 'audit'), ...
        fullfile(registry_dir, 'registry.mat'), state_path, formal_path};
    if ~all(cellfun(@(path_now) isfolder(path_now) || isfile(path_now), ...
            required))
        error('stage8_k2_wcb_registry_prepare:ResumeSchema', ...
            'Existing runtime is missing a required file or directory.');
    end
    loaded = load(fullfile(registry_dir, 'registry.mat'), ...
        'registry', 'registry_hash', '-mat');
    if ~strcmp(loaded.registry_hash, registry_hash) || ...
            ~strcmp(stage8_k2_wcb_stable_hash( ...
            'BASELINE_REGISTRY', loaded.registry, ...
            context.evidence44.identity, context.constants.protocol), ...
            registry_hash)
        error('stage8_k2_wcb_registry_prepare:RegistryIdentity', ...
            'Existing runtime registry differs from the current registry.');
    end
    stored_code = strtrim(fileread(fullfile(registry_dir, ...
        'code_identity.txt')));
    if ~strcmp(stored_code, context.code_identity.tree_hash)
        error('stage8_k2_wcb_registry_prepare:CodeIdentity', ...
            'Existing runtime was created by a different source tree.');
    end
    formal_loaded = load(formal_path, 'formal_state', '-mat');
    formal_state = formal_loaded.formal_state;
    if ~strcmp(formal_state.protocol, context.constants.protocol) || ...
            ~strcmp(formal_state.formal_head, preflight.head) || ...
            ~strcmp(formal_state.context_hash, context.context_hash) || ...
            ~strcmp(formal_state.code_identity, ...
            context.code_identity.tree_hash) || ...
            ~strcmp(formal_state.registry_hash, registry_hash) || ...
            string(formal_state.evidence44_identity) ~= ...
            context.evidence44.identity || ...
            ~isstruct(formal_state.test_output) || ...
            ~formal_state.test_output.pass || ...
            formal_state.test_output.test_count ~= 10
        error('stage8_k2_wcb_registry_prepare:FormalIdentity', ...
            'Stored tests or formal execution identity changed.');
    end
    test_output = formal_state.test_output;
    loaded_state = load(state_path, 'run_state', '-mat');
    run_state = loaded_state.run_state;
    run_state.launch_count = run_state.launch_count + 1;
    run_state.resume_count = run_state.resume_count + 1;
    run_state.last_launch_utc = stage8_k2_mc_utc_now();
    mode = "RESUME";
end
temporary_state = [state_path, '.tmp'];
if isfile(temporary_state)
    delete(temporary_state);
end
save(temporary_state, 'run_state', '-mat');
[ok, message] = movefile(temporary_state, state_path, 'f');
if ~ok
    error('stage8_k2_wcb_registry_prepare:StateMove', '%s', message);
end
state = struct('mode', mode, 'registry_hash', registry_hash, ...
    'run_state', run_state, 'test_output', test_output);
end

function write_text_local(path_now, content)
temporary = [path_now, '.tmp'];
fid = fopen(temporary, 'w');
if fid < 0
    error('stage8_k2_wcb_registry_prepare:TextOpen', ...
        'Unable to write %s.', temporary);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '%s', content);
clear cleanup
[ok, message] = movefile(temporary, path_now, 'f');
if ~ok
    error('stage8_k2_wcb_registry_prepare:TextMove', '%s', message);
end
end
