function publish_local(stage_paths, relative_paths, repo_dir)
for index = 1:numel(stage_paths)
    destination = fullfile(repo_dir, ...
        strrep(relative_paths{index}, '/', filesep));
    folder = fileparts(destination);
    if ~isfolder(folder) && ~mkdir(folder)
        error('stage8_k2_mc_summarize:PublishDirectory', ...
            'Unable to create evidence destination directory.');
    end
    [ok, message] = copyfile(stage_paths{index}, destination, 'f');
    if ~ok
        error('stage8_k2_mc_summarize:Publish', '%s', message);
    end
end
end

function validate_published_local(stage_paths, relative_paths, ...
    manifest_path, manifest_relative, repo_dir, artifacts)
for index = 1:numel(stage_paths)
    destination = fullfile(repo_dir, ...
        strrep(relative_paths{index}, '/', filesep));
    left = stage8_k2_mc_file_sha256(stage_paths{index});
    right = stage8_k2_mc_file_sha256(destination);
    if ~strcmp(left, right) || ~strcmp(left, artifacts(index).sha256)
        error('stage8_k2_mc_summarize:PublishedIdentity', ...
            'Runtime/Git artifact identity failed: %s', relative_paths{index});
    end
end
manifest_destination = fullfile(repo_dir, ...
    strrep(manifest_relative, '/', filesep));
if ~strcmp(stage8_k2_mc_file_sha256(manifest_path), ...
        stage8_k2_mc_file_sha256(manifest_destination))
    error('stage8_k2_mc_summarize:ManifestIdentity', ...
        'Runtime/Git manifest identity failed.');
end
end

