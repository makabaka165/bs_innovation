function label = bin_label_local(lower, upper)
if isinf(lower)
    label = "(-Inf,-10)";
elseif isinf(upper)
    label = "[10,+Inf)";
else
    label = "[" + string(lower) + "," + string(upper) + ")";
end
end

function value = finite_median_local(values)
values = double(values(isfinite(values)));
if isempty(values)
    value = NaN;
else
    value = median(values);
end
end

function value = mean_or_nan_local(values)
if isempty(values)
    value = NaN;
else
    value = mean(values);
end
end

