function consistency = consistency42_local(methods, context)
path_now = fullfile(context.repo_dir, 'innovation-mining', ...
    '42_stage8_k2_white_beamspace_control_method_results.csv');
reference = readtable(path_now, 'TextType', 'string');
rows = repmat(consistency_template_local(), height(reference), 1);
for index = 1:height(reference)
    ref = reference(index, :);
    subset = methods( ...
        methods.white_beamspace_snr_target_db == ...
        ref.white_beamspace_snr_target_db & ...
        methods.profile_id == ref.profile_id & ...
        methods.noise_profile_id == ref.noise_profile_id & ...
        methods.L == ref.L & methods.method_id == ref.method_id & ...
        methods.fit_valid, :);
    values = subset.joint_RMSE_deg;
    if height(subset) ~= context.constants.replicate_count
        error('stage8_k2_mc_summarize:Consistency42Join', ...
            'A 42 reference row did not join to ten MC replicates.');
    end
    row = consistency_template_local();
    row.reference_trial_id = ref.trial_id;
    row.method_id = ref.method_id;
    row.noise_profile_id = ref.noise_profile_id;
    row.L = ref.L;
    row.profile_id = ref.profile_id;
    row.white_beamspace_snr_target_db = ...
        ref.white_beamspace_snr_target_db;
    row.reference_joint_RMSE_deg = ref.joint_RMSE_deg;
    row.mc_N = height(subset);
    row.mc_min_joint_RMSE_deg = min(values);
    row.mc_p10_joint_RMSE_deg = stage8_k2_mc_percentile(values, 10);
    row.mc_median_joint_RMSE_deg = median(values);
    row.mc_p90_joint_RMSE_deg = stage8_k2_mc_percentile(values, 90);
    row.mc_max_joint_RMSE_deg = max(values);
    row.reference_empirical_percentile = ...
        100 * mean(values <= ref.joint_RMSE_deg);
    row.within_mc_min_max = ref.joint_RMSE_deg >= min(values) && ...
        ref.joint_RMSE_deg <= max(values);
    row.within_mc_p10_p90 = ref.joint_RMSE_deg >= ...
        row.mc_p10_joint_RMSE_deg && ref.joint_RMSE_deg <= ...
        row.mc_p90_joint_RMSE_deg;
    if row.within_mc_min_max
        row.descriptive_position = "WITHIN_MC_MIN_MAX";
    else
        row.descriptive_position = "OUTSIDE_MC_MIN_MAX_DESCRIPTIVE_ONLY";
    end
    rows(index) = row;
end
consistency = struct2table(rows);
end

