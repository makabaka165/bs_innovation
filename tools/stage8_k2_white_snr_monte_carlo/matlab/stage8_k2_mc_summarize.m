function output = stage8_k2_mc_summarize( ...
    merged, context, runtime_root, test_output, run_info, preflight)
%STAGE8_K2_MC_SUMMARIZE Build, validate, and publish the evidence bundle.

constants = context.constants;
registry = merged.registry;
snr_rows = merged.snr_rows;
method_rows = merged.method_rows;
validate_inputs_local(registry, snr_rows, method_rows, constants);

summary = general_summary_local(method_rows, constants);
profile_summary = profile_summary_local(method_rows, constants);
exact_summary = exact_summary_local(method_rows, constants);
transition_summary = transition_summary_local( ...
    summary, profile_summary, constants);
projected_analysis = projected_analysis_local(method_rows, constants);
consistency42 = consistency42_local(method_rows, context);
identified = any(transition_summary.classification == ...
    "STABLE_RELATIVE_GAIN");
if identified
    working_state = "IDENTIFIED";
    terminal_status = ...
        "STAGE8_K2_TANGENT_WHITE_SNR_WORKING_REGION_IDENTIFIED";
else
    working_state = "NOT_IDENTIFIED";
    terminal_status = ...
        "STAGE8_K2_TANGENT_WHITE_SNR_NO_STABLE_REGION_IDENTIFIED";
end

stage_root = fullfile(runtime_root, 'evidence', 'innovation-mining');
figure_root = fullfile(stage_root, 'figures');
if ~isfolder(stage_root) && ~mkdir(stage_root)
    error('stage8_k2_mc_summarize:StageDirectory', ...
        'Unable to create runtime evidence staging directory.');
end
if ~isfolder(figure_root) && ~mkdir(figure_root)
    error('stage8_k2_mc_summarize:FigureDirectory', ...
        'Unable to create runtime figure staging directory.');
end
paths = output_paths_local(stage_root);
writetable(registry, paths.registry);
writetable(snr_rows, paths.snr_trials);
writetable(method_rows, paths.method_results);
writetable(summary, paths.summary);
writetable(profile_summary, paths.profile_summary);
writetable(exact_summary, paths.exact_summary);
writetable(transition_summary, paths.transition_summary);
writetable(projected_analysis, paths.projected_analysis);
writetable(consistency42, paths.consistency42);
figure_paths = stage8_k2_mc_plot( ...
    summary, profile_summary, snr_rows, figure_root, constants);
write_report_local(paths.report, summary, transition_summary, ...
    consistency42, working_state, terminal_status, run_info, constants);

[artifact_ids, artifact_paths, relative_paths] = artifact_lists_local( ...
    paths, figure_paths);
artifacts = repmat(struct('artifact_id', '', 'path', '', ...
    'runtime_relative_path', '', 'sha256', ''), ...
    numel(artifact_ids), 1);
for index = 1:numel(artifact_ids)
    artifacts(index) = struct('artifact_id', artifact_ids{index}, ...
        'path', relative_paths{index}, ...
        'runtime_relative_path', runtime_relative_local( ...
        artifact_paths{index}, runtime_root), ...
        'sha256', stage8_k2_mc_file_sha256(artifact_paths{index}));
end
target_error = max(abs(snr_rows.white_beam_snr_expected_db - ...
    snr_rows.white_beamspace_snr_target_db));
prompt_commit = git_output_local(context.repo_dir, ...
    'log -1 --format=%H --grep="docs(stage8-k2): define white-SNR Monte Carlo closure"');
tool_commit = git_output_local(context.repo_dir, ...
    'log -1 --format=%H --grep="analysis(stage8-k2): add resumable white-SNR Monte Carlo"');
manifest = struct( ...
    'status', 'STAGE8_K2_TANGENT_WHITE_SNR_MONTE_CARLO_COMPLETE', ...
    'terminal_status', char(terminal_status), ...
    'final_working_region_state', char(working_state), ...
    'protocol', constants.protocol, ...
    'authorization', constants.authorization, ...
    'branch', constants.branch, ...
    'starting_head', constants.starting_commit, ...
    'prompt_commit', prompt_commit, 'tool_commit', tool_commit, ...
    'formal_run_head', preflight.head, ...
    'matlab_release', version('-release'), ...
    'max_computational_threads', maxNumCompThreads, ...
    'runtime_root', runtime_root, 'test_count', test_output.test_count, ...
    'registry_count', height(registry), ...
    'snr_row_count', height(snr_rows), ...
    'method_row_count', height(method_rows), ...
    'checkpoint_count', merged.scan.completed_count, ...
    'unique_trial_hash_count', numel(unique(registry.element_trial_hash)), ...
    'base_realization_count', ...
    numel(unique(registry.base_realization_index)), ...
    'unique_source_seed_count', numel(unique(registry.source_seed)), ...
    'unique_noise_seed_count', numel(unique(registry.noise_seed)), ...
    'white_snr_targets_db', constants.white_snr_targets_db, ...
    'replicates_per_exact_cell', constants.replicate_count, ...
    'truth_leakage_count', nnz(method_rows.truth_used_in_fit_flag), ...
    'max_white_target_error_db', target_error, ...
    'max_raw_covariance_residual', max(snr_rows.raw_covariance_residual), ...
    'max_whitening_residual', max(snr_rows.whitening_residual), ...
    'registry_hash', run_info.runtime_state.registry_hash, ...
    'code_identity', context.code_identity.tree_hash, ...
    'evidence42_identity', context.evidence42_identity, ...
    'launch_count', run_info.runtime_state.run_state.launch_count, ...
    'resume_count', run_info.runtime_state.run_state.resume_count, ...
    'total_active_runtime_sec', run_info.total_active_runtime_sec, ...
    'median_trial_runtime_sec', run_info.median_trial_runtime_sec, ...
    'shutdown_anomaly', run_info.shutdown_anomaly, ...
    'consistency42_row_count', height(consistency42), ...
    'tangent_algorithm_modified', false, ...
    'production_interface_modified', false, ...
    'online_snr_threshold_created', false, ...
    'automatic_selector_created', false, ...
    'further_stage8_k2_algorithm_work_authorized', false, ...
    'next', 'THESIS_DOCUMENTATION_ONLY', ...
    'artifacts', artifacts);
encoded = jsonencode(manifest, 'PrettyPrint', true);
stage8_k2_mc_write_text_atomic(paths.manifest, [encoded, newline]);

publish_local(artifact_paths, relative_paths, context.repo_dir);
manifest_relative = ...
    'innovation-mining/44_stage8_k2_white_snr_monte_carlo_runtime_manifest.json';
publish_local({paths.manifest}, {manifest_relative}, context.repo_dir);
validate_published_local(artifact_paths, relative_paths, ...
    paths.manifest, manifest_relative, context.repo_dir, artifacts);

output = struct('status', manifest.status, ...
    'terminal_status', char(terminal_status), ...
    'working_region_state', char(working_state), ...
    'manifest', manifest, 'summary', summary, ...
    'profile_summary', profile_summary, ...
    'transition_summary', transition_summary, ...
    'projected_analysis', projected_analysis, ...
    'consistency42', consistency42, 'stage_paths', paths, ...
    'figure_paths', figure_paths);
end

function validate_inputs_local(registry, snr_rows, methods, constants)
if height(registry) ~= constants.trial_count || ...
        height(snr_rows) ~= constants.trial_count || ...
        height(methods) ~= constants.method_row_count || ...
        numel(unique(registry.trial_id)) ~= constants.trial_count || ...
        numel(unique(registry.element_trial_hash)) ~= ...
        constants.trial_count || ...
        numel(unique(methods.trial_id + "|" + methods.method_id)) ~= ...
        constants.method_row_count || ...
        any(methods.truth_used_in_fit_flag) || ...
        any(abs(snr_rows.white_beam_snr_expected_db - ...
        snr_rows.white_beamspace_snr_target_db) > ...
        constants.snr_db_tolerance)
    error('stage8_k2_mc_summarize:Integrity', ...
        'Final rows violate cardinality, hash, SNR, or truth isolation.');
end
end

function summary = general_summary_local(methods, constants)
blocks = cell(0, 1);
for target = constants.white_snr_targets_db
    target_rows = methods(methods.white_beamspace_snr_target_db == target, :);
    blocks{end + 1, 1} = stage8_k2_mc_build_scope_summary( ...
        target_rows, "SNR", string(target), constants, true); %#ok<AGROW>
    for noise = reshape(constants.noise_profile_ids, 1, [])
        subset = target_rows(target_rows.noise_profile_id == noise, :);
        value = string(target) + "|" + noise;
        blocks{end + 1, 1} = stage8_k2_mc_build_scope_summary( ...
            subset, "SNR_X_NOISE", value, constants, true); %#ok<AGROW>
    end
    for L = constants.snapshot_counts
        subset = target_rows(target_rows.L == L, :);
        value = string(target) + "|L=" + string(L);
        blocks{end + 1, 1} = stage8_k2_mc_build_scope_summary( ...
            subset, "SNR_X_L", value, constants, true); %#ok<AGROW>
    end
end
summary = vertcat(blocks{:});
end

function summary = profile_summary_local(methods, constants)
blocks = cell(0, 1);
for target = constants.white_snr_targets_db
    for profile = reshape(constants.profile_ids, 1, [])
        subset = methods(methods.white_beamspace_snr_target_db == target & ...
            methods.profile_id == profile, :);
        value = string(target) + "|" + profile;
        blocks{end + 1, 1} = stage8_k2_mc_build_scope_summary( ...
            subset, "SNR_X_PROFILE", value, constants, true); %#ok<AGROW>
    end
end
summary = vertcat(blocks{:});
end

function summary = exact_summary_local(methods, constants)
blocks = cell(0, 1);
for target = constants.white_snr_targets_db
    for profile = reshape(constants.profile_ids, 1, [])
        for noise = reshape(constants.noise_profile_ids, 1, [])
            for L = constants.snapshot_counts
                subset = methods( ...
                    methods.white_beamspace_snr_target_db == target & ...
                    methods.profile_id == profile & ...
                    methods.noise_profile_id == noise & methods.L == L, :);
                value = string(target) + "|" + profile + "|" + ...
                    noise + "|L=" + string(L);
                blocks{end + 1, 1} = stage8_k2_mc_build_scope_summary( ...
                    subset, "EXACT_CELL", value, constants, false); %#ok<AGROW>
            end
        end
    end
end
summary = vertcat(blocks{:});
end

function transition = transition_summary_local(summary, profiles, constants)
scope_values = ["ALL"; constants.profile_ids];
scope_types = ["SNR_OVERALL"; repmat("SNR_X_PROFILE", 4, 1)];
blocks = cell(numel(scope_values), 1);
for scope_index = 1:numel(scope_values)
    rows = repmat(transition_template_local(), ...
        numel(constants.white_snr_targets_db), 1);
    classes = strings(numel(constants.white_snr_targets_db), 1);
    for target_index = 1:numel(constants.white_snr_targets_db)
        target = constants.white_snr_targets_db(target_index);
        if scope_values(scope_index) == "ALL"
            block = summary(summary.scope_type == "SNR" & ...
                summary.white_beamspace_snr_target_db == target, :);
        else
            value = string(target) + "|" + scope_values(scope_index);
            block = profiles(profiles.scope_value == value, :);
        end
        classes(target_index) = stage8_k2_mc_classify_scope(block, constants);
        tangent = block(block.row_type == "METHOD" & ...
            block.method_id == "TANGENT_PROFILE_SAFE", :);
        pair_lite = block(block.row_type == "PAIRWISE" & ...
            block.reference_method_id == "CORE_LITE", :);
        pair_plus = block(block.row_type == "PAIRWISE" & ...
            block.reference_method_id == "CORE_PLUS", :);
        row = transition_template_local();
        row.scope_type = scope_types(scope_index);
        row.scope_value = scope_values(scope_index);
        row.white_beamspace_snr_target_db = target;
        row.classification = classes(target_index);
        row.tangent_valid_rate = tangent.valid_rate;
        row.tangent_fallback_rate = tangent.fallback_rate;
        row.tangent_median_joint_RMSE_deg = tangent.median_joint_RMSE_deg;
        row.tangent_p90_joint_RMSE_deg = tangent.p90_joint_RMSE_deg;
        row.vs_core_lite_wins = pair_lite.wins;
        row.vs_core_lite_ties = pair_lite.ties;
        row.vs_core_lite_losses = pair_lite.losses;
        row.vs_core_plus_wins = pair_plus.wins;
        row.vs_core_plus_ties = pair_plus.ties;
        row.vs_core_plus_losses = pair_plus.losses;
        rows(target_index) = row;
    end
    stable = find(classes == "STABLE_RELATIVE_GAIN");
    if isempty(stable)
        first_stable = NaN;
        region_state = "NO_STABLE_REGION";
    else
        first_stable = constants.white_snr_targets_db(stable(1));
        if all(classes(stable(1):end) == "STABLE_RELATIVE_GAIN")
            region_state = "MONOTONIC_FROM_FIRST_OBSERVED_POINT";
        else
            region_state = "NON_MONOTONIC_EMPIRICAL_REGION";
        end
    end
    for row_index = 1:numel(rows)
        rows(row_index).first_stable_snr_db = first_stable;
        rows(row_index).empirical_region_state = region_state;
    end
    blocks{scope_index} = struct2table(rows);
end
transition = vertcat(blocks{:});
end

function row = transition_template_local()
row = struct('scope_type', "", 'scope_value', "", ...
    'white_beamspace_snr_target_db', NaN, 'classification', "", ...
    'tangent_valid_rate', NaN, 'tangent_fallback_rate', NaN, ...
    'tangent_median_joint_RMSE_deg', NaN, ...
    'tangent_p90_joint_RMSE_deg', NaN, ...
    'vs_core_lite_wins', 0, 'vs_core_lite_ties', 0, ...
    'vs_core_lite_losses', 0, 'vs_core_plus_wins', 0, ...
    'vs_core_plus_ties', 0, 'vs_core_plus_losses', 0, ...
    'first_stable_snr_db', NaN, 'empirical_region_state', "");
end

function analysis = projected_analysis_local(methods, constants)
edges = constants.projected_snr_bin_edges_db;
tangent_all = methods(methods.method_id == "TANGENT_PROFILE_SAFE", :);
rows = repmat(projected_template_local(), numel(edges) - 1, 1);
for index = 1:(numel(edges) - 1)
    lower = edges(index);
    upper = edges(index + 1);
    mask = tangent_all.k2_projected_snr_expected_db >= lower & ...
        tangent_all.k2_projected_snr_expected_db < upper;
    tangent = tangent_all(mask, :);
    if isinf(upper)
        mask = tangent_all.k2_projected_snr_expected_db >= lower;
        tangent = tangent_all(mask, :);
    end
    row = projected_template_local();
    row.bin_id = string(sprintf('BIN_%d', index));
    row.bin_label = bin_label_local(lower, upper);
    row.lower_db = lower;
    row.upper_db = upper;
    row.N = height(tangent);
    row.profile_composition = composition_string_local( ...
        tangent.profile_id, constants.profile_ids);
    row.white_snr_composition = snr_composition_local( ...
        tangent.white_beamspace_snr_target_db, ...
        constants.white_snr_targets_db);
    row.tangent_fallback_rate = mean_or_nan_local( ...
        double(tangent.fallback_flag));
    valid = tangent.fit_valid;
    row.tangent_median_joint_RMSE_deg = finite_median_local( ...
        tangent.joint_RMSE_deg(valid));
    row.tangent_p90_joint_RMSE_deg = stage8_k2_mc_percentile( ...
        tangent.joint_RMSE_deg(valid), 90);
    for reference_index = 1:2
        reference = constants.method_ids(reference_index);
        baseline = methods(methods.method_id == reference & ...
            ismember(methods.trial_id, tangent.trial_id), :);
        left = sortrows(tangent, 'trial_id');
        right = sortrows(baseline, 'trial_id');
        if height(left) ~= height(right) || any(left.trial_id ~= right.trial_id)
            error('stage8_k2_mc_summarize:ProjectedPairing', ...
                'Projected-bin paired rows lost trial identity.');
        end
        common = left.fit_valid & right.fit_valid;
        delta = left.joint_RMSE_deg(common) - right.joint_RMSE_deg(common);
        wins = nnz(delta < -constants.paired_tie_tolerance_deg);
        ties = nnz(abs(delta) <= constants.paired_tie_tolerance_deg);
        losses = nnz(delta > constants.paired_tie_tolerance_deg);
        if reference_index == 1
            row.vs_core_lite_wins = wins;
            row.vs_core_lite_ties = ties;
            row.vs_core_lite_losses = losses;
        else
            row.vs_core_plus_wins = wins;
            row.vs_core_plus_ties = ties;
            row.vs_core_plus_losses = losses;
        end
    end
    rows(index) = row;
end
analysis = struct2table(rows);
if sum(analysis.N) ~= constants.trial_count
    error('stage8_k2_mc_summarize:ProjectedBins', ...
        'Projected-SNR bins do not partition all trials.');
end
end

