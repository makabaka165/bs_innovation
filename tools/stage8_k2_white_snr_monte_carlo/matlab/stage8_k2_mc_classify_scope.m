function classification = stage8_k2_mc_classify_scope(summary, constants)
%STAGE8_K2_MC_CLASSIFY_SCOPE Apply the registered descriptive gates.

tangent = summary(summary.row_type == "METHOD" & ...
    summary.method_id == "TANGENT_PROFILE_SAFE", :);
lite = summary(summary.row_type == "METHOD" & ...
    summary.method_id == "CORE_LITE", :);
plus = summary(summary.row_type == "METHOD" & ...
    summary.method_id == "CORE_PLUS", :);
pair_lite = summary(summary.row_type == "PAIRWISE" & ...
    summary.reference_method_id == "CORE_LITE", :);
pair_plus = summary(summary.row_type == "PAIRWISE" & ...
    summary.reference_method_id == "CORE_PLUS", :);
if any([height(tangent), height(lite), height(plus), ...
        height(pair_lite), height(pair_plus)] ~= 1)
    error('stage8_k2_mc_classify_scope:Rows', ...
        'Classification requires three method and two pairwise rows.');
end
if tangent.fallback_rate >= 0.50
    classification = "FALLBACK_DOMINATED";
    return;
end
stable = tangent.valid_rate == 1 && ...
    tangent.median_joint_RMSE_deg <= lite.median_joint_RMSE_deg && ...
    tangent.median_joint_RMSE_deg <= plus.median_joint_RMSE_deg && ...
    tangent.p90_joint_RMSE_deg <= lite.p90_joint_RMSE_deg && ...
    tangent.p90_joint_RMSE_deg <= plus.p90_joint_RMSE_deg && ...
    pair_lite.wins > pair_lite.losses && ...
    pair_plus.wins > pair_plus.losses;
if stable
    classification = "STABLE_RELATIVE_GAIN";
elseif tangent.median_joint_RMSE_deg < lite.median_joint_RMSE_deg || ...
        tangent.median_joint_RMSE_deg < plus.median_joint_RMSE_deg
    classification = "RELATIVE_GAIN_UNSTABLE";
else
    classification = "NO_RELATIVE_GAIN";
end
if constants.paired_tie_tolerance_deg ~= 1e-6
    error('stage8_k2_mc_classify_scope:TieContract', ...
        'The registered paired tie tolerance changed.');
end
end
