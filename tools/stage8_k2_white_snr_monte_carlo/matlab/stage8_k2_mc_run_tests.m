function output = stage8_k2_mc_run_tests(repo_dir)
%STAGE8_K2_MC_RUN_TESTS Run the ten registered pre-formal tests.

if nargin < 1 || isempty(repo_dir)
    [status, repo_dir] = system('git rev-parse --show-toplevel');
    if status ~= 0
        error('stage8_k2_mc_run_tests:Repository', ...
            'Unable to locate the repository root.');
    end
    repo_dir = strtrim(repo_dir);
end
scope = stage8_k2_mc_add_paths(repo_dir); %#ok<NASGU>
context = stage8_k2_mc_build_context(repo_dir);
fixture = stage8_k2_mc_test_fixture(context);
tests = { ...
    @() test_42_formula_equivalence(fixture), ...
    @() test_white_target_contract(fixture), ...
    @() test_common_random_numbers(fixture), ...
    @() test_seed_uniqueness(fixture), ...
    @() test_trial_hash_uniqueness(fixture), ...
    @() test_truth_isolation(fixture), ...
    @() test_checkpoint_roundtrip(fixture), ...
    @() test_interrupted_checkpoint_resume(fixture), ...
    @() test_four_trial_smoke(fixture), ...
    @() test_summary_fixture(fixture)};
names = ["T1_42_FORMULA_EQUIVALENCE"; "T2_WHITE_TARGET"; ...
    "T3_COMMON_RANDOM_NUMBERS"; "T4_SEED_UNIQUENESS"; ...
    "T5_TRIAL_HASH"; "T6_TRUTH_ISOLATION"; ...
    "T7_CHECKPOINT_ROUNDTRIP"; "T8_INTERRUPTED_CHECKPOINT"; ...
    "T9_FOUR_TRIAL_SMOKE"; "T10_SUMMARY_FIXTURE"];
results = cell(numel(tests), 1);
for index = 1:numel(tests)
    results{index} = tests{index}();
    if ~isstruct(results{index}) || ~isfield(results{index}, 'pass') || ...
            ~results{index}.pass
        error('stage8_k2_mc_run_tests:Failure', ...
            'Registered test failed: %s', names(index));
    end
    fprintf('%s PASS\n', names(index));
end
output = struct('pass', true, 'test_count', numel(tests), ...
    'test_names', names, 'results', {results}, ...
    'context_hash', context.context_hash, ...
    'registry_hash', fixture.registry_hash);
fprintf('STAGE8_K2_WHITE_SNR_MONTE_CARLO_TESTS_PASS 10/10\n');
end
