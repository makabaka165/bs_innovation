function write_runtime_row_local(fid, path_now, digest)
info = dir(path_now);
fprintf(fid, '| `%s` | %d | `%s` |\n', ...
    strrep(path_now, '\\', '/'), info.bytes, digest);
end

function validate_runtime_tables_local(diagnostics, runtime_methods, ...
    registry, committed_methods, constants)
if height(diagnostics) ~= constants.trial_count || ...
        height(runtime_methods) ~= constants.method_row_count || ...
        height(committed_methods) ~= constants.method_row_count || ...
        height(registry) ~= constants.trial_count || ...
        numel(unique(diagnostics.trial_id)) ~= constants.trial_count || ...
        numel(unique(registry.trial_id)) ~= constants.trial_count || ...
        numel(unique(runtime_methods.trial_id + "|" + ...
        runtime_methods.method_id)) ~= constants.method_row_count
    error('stage8_k2_tp_correct_diagnostics:Cardinality', ...
        'Runtime or committed evidence violates the fixed row contract.');
end
for index = 1:height(diagnostics)
    rows = runtime_methods(runtime_methods.trial_id == ...
        diagnostics.trial_id(index), :);
    if height(rows) ~= 3 || numel(unique(rows.element_trial_hash)) ~= 1 || ...
            unique(rows.element_trial_hash) ~= ...
            diagnostics.element_trial_hash(index)
        error('stage8_k2_tp_correct_diagnostics:RuntimePairing', ...
            'Runtime element hashes are not shared by three method rows.');
    end
end
end

function values = parse_vector_local(value, count)
values = parse_decimal_values_local(value, count);
values = reshape(values, 1, count);
end

function matrix = parse_matrix_local(value, rows, columns)
values = parse_decimal_values_local(value, rows * columns);
matrix = reshape(values, columns, rows).';
end

function values = parse_decimal_values_local(value, expected_count)
text = char(string(value));
pattern = '[-+]?(?:(?:\d+\.?\d*)|(?:\.\d+))(?:[eE][-+]?\d+)?';
tokens = regexp(text, pattern, 'match');
residual = regexprep(text, pattern, '');
residual = regexprep(residual, '[\[\]\s,;]', '');
if ~isempty(residual) || numel(tokens) ~= expected_count
    error('stage8_k2_tp_correct_diagnostics:DecimalFormat', ...
        'A committed numeric vector or matrix has an invalid format.');
end
values = str2double(tokens);
if any(~isfinite(values))
    error('stage8_k2_tp_correct_diagnostics:DecimalFinite', ...
        'Committed numeric text must be finite.');
end
end

function value = median_finite_local(values)
values = values(isfinite(values));
if isempty(values), value = NaN; else, value = median(values); end
end

function value = percentile_finite_local(values, percentage)
values = sort(values(isfinite(values)));
if isempty(values)
    value = NaN;
    return;
end
position = 1 + (numel(values) - 1) * percentage / 100;
lower = floor(position);
upper = ceil(position);
if lower == upper
    value = values(lower);
else
    weight = position - lower;
    value = (1 - weight) * values(lower) + weight * values(upper);
end
end

function digest = sha256_file_local(path_now)
fid = fopen(path_now, 'rb');
if fid < 0
    error('stage8_k2_tp_correct_diagnostics:HashOpen', ...
        'Unable to open file for SHA-256: %s', path_now);
end
cleanup = onCleanup(@() fclose(fid));
bytes = fread(fid, Inf, '*uint8');
engine = java.security.MessageDigest.getInstance('SHA-256');
engine.update(typecast(bytes(:), 'int8'));
digest_bytes = typecast(engine.digest(), 'uint8');
digest = lower(reshape(dec2hex(digest_bytes, 2).', 1, []));
end

function write_json_local(path_now, value)
text = jsonencode(value, 'PrettyPrint', true);
fid = fopen(path_now, 'w');
if fid < 0
    error('stage8_k2_tp_correct_diagnostics:JsonOpen', ...
        'Unable to create the runtime manifest.');
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '%s\n', text);
end

function assert_files_exist_local(paths)
for index = 1:numel(paths)
    if ~isfile(paths{index})
        error('stage8_k2_tp_correct_diagnostics:MissingInput', ...
            'Required read-only input is missing: %s', paths{index});
    end
end
end

function path_out = canonical_path_local(path_in)
path_out = char(java.io.File(char(string(path_in))).getCanonicalPath());
end
