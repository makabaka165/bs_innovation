function output = stage8_k2_tp_correct_diagnostics(repo_dir, runtime_root)
%STAGE8_K2_TP_CORRECT_DIAGNOSTICS Correct diagnostics without refitting.

if nargin < 1 || isempty(repo_dir)
    [status, repo_dir] = system('git rev-parse --show-toplevel');
    if status ~= 0
        error('stage8_k2_tp_correct_diagnostics:Repository', ...
            'Unable to locate the repository root.');
    end
    repo_dir = strtrim(repo_dir);
end
constants = stage8_k2_tp_constants();
if nargin < 2 || isempty(runtime_root)
    runtime_root = constants.runtime_root;
end
repo_dir = canonical_path_local(repo_dir);
runtime_root = canonical_path_local(runtime_root);
expected_runtime = canonical_path_local(constants.runtime_root);
if ~strcmp(runtime_root, expected_runtime)
    error('stage8_k2_tp_correct_diagnostics:RuntimeRoot', ...
        'The correction must use the registered formal runtime root.');
end

runtime_paths = struct( ...
    'diagnostics', fullfile(runtime_root, 'tangent_diagnostics.csv'), ...
    'methods', fullfile(runtime_root, 'method_rows.csv'), ...
    'registry', fullfile(runtime_root, 'registry.csv'), ...
    'complete_run', fullfile(runtime_root, 'complete_run.mat'));
evidence_dir = fullfile(repo_dir, 'innovation-mining');
trial_path = fullfile(evidence_dir, ...
    '31_stage8_k2_tangent_profile_trials.csv');
output_paths = struct( ...
    'diagnostics', fullfile(evidence_dir, ...
    '32_stage8_k2_tangent_profile_corrected_diagnostics.csv'), ...
    'geometry', fullfile(evidence_dir, ...
    '32_stage8_k2_tangent_profile_corrected_geometry_analysis.csv'), ...
    'report', fullfile(evidence_dir, ...
    '32_stage8_k2_tangent_profile_diagnostic_correction.md'), ...
    'manifest', fullfile(evidence_dir, ...
    '32_stage8_k2_tangent_profile_runtime_manifest.json'));
assert_files_exist_local([struct2cell(runtime_paths); {trial_path}]);
names = fieldnames(output_paths);
for index = 1:numel(names)
    if isfile(output_paths.(names{index}))
        error('stage8_k2_tp_correct_diagnostics:ExistingEvidence', ...
            'Refusing to overwrite correction evidence: %s', ...
            output_paths.(names{index}));
    end
end

diagnostics = readtable(runtime_paths.diagnostics, 'TextType', 'string');
runtime_methods = readtable(runtime_paths.methods, 'TextType', 'string');
registry = readtable(runtime_paths.registry, 'TextType', 'string');
method_rows = readtable(trial_path, 'TextType', 'string');
validate_runtime_tables_local( ...
    diagnostics, runtime_methods, registry, method_rows, constants);
if ~strcmp(sha256_file_local(trial_path), ...
        sha256_file_local(runtime_paths.methods))
    error('stage8_k2_tp_correct_diagnostics:MethodIdentity', ...
        'Committed 31 trials differ from the formal runtime method rows.');
end

m2 = method_rows(method_rows.method_id == "TANGENT_PROFILE_SAFE", :);
[matched, location] = ismember(diagnostics.trial_id, m2.trial_id);
if ~all(matched) || numel(unique(location)) ~= constants.trial_count
    error('stage8_k2_tp_correct_diagnostics:Pairing', ...
        'Diagnostics and committed M2 rows are not one-to-one.');
end
m2 = m2(location, :);
if any(diagnostics.element_trial_hash ~= m2.element_trial_hash) || ...
        any(diagnostics.selected_source ~= m2.selected_source)
    error('stage8_k2_tp_correct_diagnostics:ElementIdentity', ...
        'A diagnostic row differs from its selected M2 result.');
end

corrected = diagnostics;
oriented = double(diagnostics.direction_error_deg);
axis_error = NaN(height(diagnostics), 1);
selected_separation = NaN(height(diagnostics), 1);
for index = 1:height(diagnostics)
    direction_hat = parse_vector_local(diagnostics.direction_hat(index), 2);
    direction_true = parse_vector_local(diagnostics.direction_true(index), 2);
    axis_error(index) = stage8_k2_tp_axis_error_deg( ...
        direction_hat, direction_true);
    angles = parse_matrix_local(m2.angles_hat_deg(index), 2, 2);
    selected_separation(index) = norm(angles(2, :) - angles(1, :));
end
rho_error = abs(double(diagnostics.rho_hat_deg) - ...
    double(diagnostics.rho_true_deg));
rho_relative_error = rho_error ./ double(diagnostics.rho_true_deg);
selected_separation_error = abs(selected_separation - ...
    double(diagnostics.rho_true_deg));
rho_hat = double(diagnostics.rho_hat_deg);
lower_tolerance = 64 * eps(max(1, abs(rho_hat)));
lower_bound_hit = isfinite(rho_hat) & ...
    abs(rho_hat - constants.rho_min_deg) <= lower_tolerance;
corrected.direction_oriented_error_deg_original = oriented;
corrected.direction_axis_error_deg = axis_error;
corrected.rho_relative_error = rho_relative_error;
corrected.selected_separation_deg = selected_separation;
corrected.selected_separation_error_deg = selected_separation_error;
corrected.joint_RMSE_deg = double(m2.joint_RMSE_deg);
corrected.separation_vector_error_deg = ...
    double(m2.separation_vector_error_deg);
corrected.rho_at_registered_lower_bound_flag = lower_bound_hit;
corrected.selected_source = m2.selected_source;
if any(~isfinite(axis_error)) || any(axis_error < 0 | axis_error > 90)
    error('stage8_k2_tp_correct_diagnostics:AxisRange', ...
        'Corrected axis errors must all be finite and inside [0,90].');
end

analysis = build_analysis_local(corrected, m2);
manifest = build_manifest_local( ...
    runtime_root, runtime_paths, evidence_dir, constants);
write_report_local(output_paths.report, corrected, analysis, manifest, ...
    runtime_paths, constants);
writetable(corrected, output_paths.diagnostics);
writetable(analysis, output_paths.geometry);
write_json_local(output_paths.manifest, manifest);

overall = analysis(analysis.scope_type == "OVERALL", :);
output = struct('status', ...
    'STAGE8_K2_TP1_DIAGNOSTIC_CORRECTION_PASS', ...
    'corrected_diagnostic_count', height(corrected), ...
    'analysis_row_count', height(analysis), ...
    'oriented_median_deg', overall.oriented_direction_median_deg, ...
    'oriented_p90_deg', overall.oriented_direction_p90_deg, ...
    'axis_median_deg', overall.axis_direction_median_deg, ...
    'axis_p90_deg', overall.axis_direction_p90_deg, ...
    'sign_equivalent_tail_count', overall.sign_equivalent_tail_count, ...
    'output_paths', output_paths, 'manifest', manifest);
fprintf(['DIAGNOSTIC_CORRECTION_COMPLETE rows=%d ', ...
    'axis_median=%.17g axis_p90=%.17g\n'], ...
    height(corrected), output.axis_median_deg, output.axis_p90_deg);
end

function analysis = build_analysis_local(diagnostics, m2)
gamma = double(diagnostics.Gamma_K2_proxy);
[~, order] = sort(gamma, 'ascend');
quartile_id = zeros(height(diagnostics), 1);
for rank_index = 1:height(diagnostics)
    quartile_id(order(rank_index)) = ceil(4 * rank_index / ...
        height(diagnostics));
end
rows = cell(9, 1);
rows{1} = analysis_row_local('OVERALL', 'ALL', ...
    true(height(diagnostics), 1), diagnostics, m2);
for quartile = 1:4
    rows{1 + quartile} = analysis_row_local('GAMMA_QUARTILE', ...
        sprintf('Q%d', quartile), quartile_id == quartile, ...
        diagnostics, m2);
end
profiles = ["P1", "P2", "P3", "P4"];
for index = 1:numel(profiles)
    rows{5 + index} = analysis_row_local('PROFILE', profiles(index), ...
        diagnostics.profile_id == profiles(index), diagnostics, m2);
end
analysis = struct2table(vertcat(rows{:}));
end

function row = analysis_row_local(scope_type, scope_value, selected, d, m2)
oriented = double(d.direction_oriented_error_deg_original(selected));
axis_error = double(d.direction_axis_error_deg(selected));
rho_error = double(d.rho_error_deg(selected));
rho_relative = double(d.rho_relative_error(selected));
selected_separation = double(d.selected_separation_deg(selected));
selected_error = double(d.selected_separation_error_deg(selected));
rmse = double(m2.joint_RMSE_deg(selected));
separation_vector_error = double(m2.separation_vector_error_deg(selected));
row = struct('scope_type', string(scope_type), ...
    'scope_value', string(scope_value), 'trial_count', nnz(selected), ...
    'Gamma_median', median_finite_local(double(d.Gamma_K2_proxy(selected))), ...
    'oriented_direction_median_deg', median_finite_local(oriented), ...
    'oriented_direction_p90_deg', percentile_finite_local(oriented, 90), ...
    'axis_direction_median_deg', median_finite_local(axis_error), ...
    'axis_direction_p90_deg', percentile_finite_local(axis_error, 90), ...
    'rho_error_median_deg', median_finite_local(rho_error), ...
    'rho_error_p90_deg', percentile_finite_local(rho_error, 90), ...
    'rho_relative_error_median', median_finite_local(rho_relative), ...
    'rho_relative_error_p90', percentile_finite_local(rho_relative, 90), ...
    'selected_separation_median_deg', ...
    median_finite_local(selected_separation), ...
    'selected_separation_error_median_deg', ...
    median_finite_local(selected_error), ...
    'selected_separation_error_p90_deg', ...
    percentile_finite_local(selected_error, 90), ...
    'separation_vector_error_median_deg', ...
    median_finite_local(separation_vector_error), ...
    'separation_vector_error_p90_deg', ...
    percentile_finite_local(separation_vector_error, 90), ...
    'joint_RMSE_median_deg', median_finite_local(rmse), ...
    'raw_candidate_valid_rate', ...
    mean(double(d.raw_tangent_candidate_valid(selected))), ...
    'fallback_rate', mean(double(d.fallback_flag(selected))), ...
    'rho_lower_bound_hit_count', ...
    nnz(d.rho_at_registered_lower_bound_flag(selected)), ...
    'upgrade_count', nnz(d.upgrade_flag(selected)), ...
    'fallback_count', nnz(d.fallback_flag(selected)), ...
    'sign_equivalent_tail_count', nnz(oriented > 90), ...
    'oriented_166_to_180_count', nnz(oriented >= 166 & oriented <= 180));
end

