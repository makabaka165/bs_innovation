function [method_rows, diagnostic_row, trial] = ...
    stage8_k2_tp_evaluate_trial(spec, context)
%STAGE8_K2_TP_EVALUATE_TRIAL Generate once and evaluate three methods.

if ~(istable(spec) && height(spec) == 1)
    error('stage8_k2_tp_evaluate_trial:Spec', ...
        'spec must be exactly one registered trial row.');
end
trial = generate_trial_local(spec, context);
domain = context.plan.local_domain;
noise_model = trial.model.noise_factorization;
lite = estimate_stage8_known_k_local_cell( ...
    trial.Y_element, trial.model, domain, context.stage5_locked, ...
    noise_model, 2, struct('mode', 'CORE_LITE', ...
    'return_diagnostics', true));
plus = estimate_stage8_known_k_local_cell( ...
    trial.Y_element, trial.model, domain, context.stage5_locked, ...
    noise_model, 2, struct('mode', 'CORE_PLUS', ...
    'return_diagnostics', true));
[tangent, tangent_diagnostics] = stage8_k2_tp_fit_safe( ...
    trial.Y_element, trial.model, context);

rows = repmat(method_row_template_local(), 3, 1);
rows(1) = method_row_local(spec, trial, 'CORE_LITE', lite);
rows(2) = method_row_local(spec, trial, 'CORE_PLUS', plus);
rows(3) = method_row_local(spec, trial, ...
    'TANGENT_PROFILE_SAFE', tangent);
method_rows = struct2table(rows);
diagnostic_row = struct2table(diagnostic_row_local( ...
    spec, trial, tangent_diagnostics, tangent));
end

function trial = generate_trial_local(spec, context)
model = resolve_stage8_measurement_model( ...
    context.plan.measurement_model_registry, ...
    context.primary_measurement_config_id, spec.noise_profile_id);
direction = [cosd(spec.direction_deg), sind(spec.direction_deg)];
center = [spec.center_az_deg, spec.center_el_deg];
truth = [center - spec.separation_deg * direction / 2; ...
    center + spec.separation_deg * direction / 2];
bounds = context.plan.local_domain.domain_bounds_deg;
if any(truth(:, 1) < bounds(1) | truth(:, 1) > bounds(2) | ...
        truth(:, 2) < bounds(3) | truth(:, 2) > bounds(4))
    error('stage8_k2_tp_evaluate_trial:TruthDomain', ...
        'Both K2 truth endpoints must remain inside the frozen domain.');
end
rng_state = rng;
rng_cleanup = onCleanup(@() rng(rng_state));
rng(spec.source_seed, 'twister');
source_phase_rad = 2 * pi * rand();
clear rng_cleanup
manifold = build_stage8_element_manifold(truth, model);
[source, source_info] = construct_deterministic_source_matrix( ...
    2, spec.L, spec.secondary_power_db, spec.correlation_magnitude, ...
    source_phase_rad, char(spec.trial_id));
unscaled = manifold.A * source;
target_energy = 10 ^ (spec.snr_db / 10) * numel(unscaled);
source = source * sqrt(target_energy / ...
    max(norm(unscaled, 'fro') ^ 2, realmin));
signal = manifold.A * source;
[noise, noise_debug] = generate_stage8_element_noise( ...
    model, spec.L, 1, spec.noise_seed);
Y_element = signal + noise;
element_trial_hash = stage8_k2_tp_stable_hash( ...
    'ELEMENT_TRIAL', char(spec.trial_id), Y_element, truth, ...
    double(spec.L), double(spec.snr_db), double(spec.source_seed), ...
    double(spec.noise_seed), char(spec.noise_profile_id));
trial = struct('Y_element', Y_element, 'truth_angles_deg', truth, ...
    'model', model, 'source_matrix', source, ...
    'signal_element', signal, 'noise_element', noise, ...
    'source_phase_rad', source_phase_rad, 'source_info', source_info, ...
    'noise_debug', noise_debug, 'element_trial_hash', element_trial_hash, ...
    'single_cpi_flag', true, 'same_range_doppler_cell_flag', true, ...
    'cross_cpi_data_used_flag', false, ...
    'tracking_input_used_flag', false, ...
    'truth_used_in_fit_flag', false);
end

function row = method_row_local(spec, trial, method_id, result)
row = method_row_template_local();
row.trial_id = string(spec.trial_id);
row.method_id = string(method_id);
row.noise_profile_id = string(spec.noise_profile_id);
row.L = double(spec.L);
row.SNR = double(spec.snr_db);
row.snr_db = double(spec.snr_db);
row.profile_id = string(spec.profile_id);
row.source_seed = double(spec.source_seed);
row.noise_seed = double(spec.noise_seed);
row.element_trial_hash = string(trial.element_trial_hash);
row.fit_valid = logical(result.fit_valid);
row.fit_status = string(result.fit_status);
row.selected_source = string(result.selected_source);
row.angles_hat_deg = string(mat2str(result.angles_hat_deg, 17));
row.RSS = double(result.rss);
row.loglik = double(result.loglik_concentrated);
row.effective_rank = double(result.effective_rank);
row.score_call_count = double(result.score_call_count);
row.SVD_call_count = double(result.svd_call_count);
row.runtime_sec = double(result.runtime_sec);
row.truth_used_in_fit_flag = logical(result.truth_used_in_fit_flag);
row.single_cpi_flag = logical(result.single_cpi_flag);
row.same_range_doppler_cell_flag = ...
    logical(result.same_range_doppler_cell_flag);
row.cross_cpi_data_used_flag = logical(result.cross_cpi_data_used_flag);
row.tracking_input_used_flag = logical(result.tracking_input_used_flag);
row.K_estimated_inside_module_flag = ...
    logical(result.K_estimated_inside_module_flag);
if ~result.fit_valid || any(~isfinite(result.angles_hat_deg(:)))
    return;
end
matched = match_targets_local(result.angles_hat_deg, ...
    trial.truth_angles_deg);
error_now = matched - trial.truth_angles_deg;
row.joint_RMSE_deg = sqrt(mean(sum(error_now .^ 2, 2)));
row.azimuth_RMSE_deg = sqrt(mean(error_now(:, 1) .^ 2));
row.elevation_RMSE_deg = sqrt(mean(error_now(:, 2) .^ 2));
row.separation_vector_error_deg = norm( ...
    (matched(2, :) - matched(1, :)) - ...
    (trial.truth_angles_deg(2, :) - trial.truth_angles_deg(1, :)));
end

function row = method_row_template_local()
row = struct('trial_id', "", 'method_id', "", ...
    'noise_profile_id', "", 'L', 0, 'SNR', NaN, 'snr_db', NaN, ...
    'profile_id', "", 'source_seed', 0, 'noise_seed', 0, ...
    'element_trial_hash', "", 'fit_valid', false, ...
    'fit_status', "NOT_RUN", 'selected_source', "NOT_RUN", ...
    'angles_hat_deg', "", 'RSS', NaN, 'loglik', NaN, ...
    'effective_rank', 0, 'joint_RMSE_deg', NaN, ...
    'azimuth_RMSE_deg', NaN, 'elevation_RMSE_deg', NaN, ...
    'separation_vector_error_deg', NaN, 'score_call_count', 0, ...
    'SVD_call_count', 0, 'runtime_sec', 0, ...
    'truth_used_in_fit_flag', false, 'single_cpi_flag', true, ...
    'same_range_doppler_cell_flag', true, ...
    'cross_cpi_data_used_flag', false, ...
    'tracking_input_used_flag', false, ...
    'K_estimated_inside_module_flag', false);
end

function row = diagnostic_row_local(spec, trial, diagnostics, tangent)
truth = trial.truth_angles_deg;
center_true = mean(truth, 1);
direction_true = (truth(2, :) - truth(1, :));
direction_true = direction_true / norm(direction_true);
if direction_true(2) < -1e-12 || ...
        (abs(direction_true(2)) <= 1e-12 && direction_true(1) < 0)
    direction_true = -direction_true;
end
direction_error = NaN;
if all(isfinite(diagnostics.direction_hat))
    cosine = dot(diagnostics.direction_hat, direction_true);
    cosine = min(1, max(-1, cosine));
    direction_error = acosd(cosine);
end
k1_center_error = NaN;
if all(isfinite(diagnostics.K1_center_deg(:)))
    k1_center_error = norm(reshape(diagnostics.K1_center_deg, 1, 2) - ...
        center_true);
end
geometry = compute_stage8_projected_separation_geometry(truth, trial.model);
p_minus = norm(trial.source_matrix(2, :) - ...
    trial.source_matrix(1, :)) ^ 2 / spec.L;
gamma_proxy = 0.5 * norm(trial.source_matrix(2, :) - ...
    trial.source_matrix(1, :)) ^ 2 * geometry.q;
row = struct('trial_id', string(spec.trial_id), ...
    'noise_profile_id', string(spec.noise_profile_id), ...
    'L', double(spec.L), 'SNR', double(spec.snr_db), ...
    'snr_db', double(spec.snr_db), 'profile_id', string(spec.profile_id), ...
    'element_trial_hash', string(trial.element_trial_hash), ...
    'K1_center_deg', string(mat2str(diagnostics.K1_center_deg, 17)), ...
    'K1_center_error_deg', double(k1_center_error), ...
    'metric_rank', double(diagnostics.metric_rank), ...
    'metric_condition', double(diagnostics.metric_condition), ...
    'metric_eigenvalues', ...
    string(mat2str(diagnostics.metric_eigenvalues(:).', 17)), ...
    'direction_hat', string(mat2str(diagnostics.direction_hat, 17)), ...
    'direction_true', string(mat2str(direction_true, 17)), ...
    'direction_error_deg', double(direction_error), ...
    'rho_hat_deg', double(diagnostics.rho_hat_deg), ...
    'rho_true_deg', double(spec.separation_deg), ...
    'rho_error_deg', abs(double(diagnostics.rho_hat_deg) - ...
    double(spec.separation_deg)), ...
    'rho_max_deg', double(diagnostics.rho_max_deg), ...
    'raw_tangent_candidate_valid', ...
    logical(diagnostics.raw_tangent_candidate_valid), ...
    'raw_tangent_loglik', double(diagnostics.raw_tangent_loglik), ...
    'upgrade_flag', logical(diagnostics.upgrade_flag), ...
    'fallback_flag', logical(diagnostics.fallback_flag), ...
    'fallback_reason', string(diagnostics.fallback_reason), ...
    'endpoint_in_domain_flag', ...
    logical(diagnostics.endpoint_in_domain_flag), ...
    'full_manifold_profile_used_flag', ...
    logical(diagnostics.full_manifold_profile_used_flag), ...
    'q', double(geometry.q), 'p_minus', double(p_minus), ...
    'Gamma_K2_proxy', double(gamma_proxy), ...
    'selected_source', string(tangent.selected_source), ...
    'truth_used_in_fit_flag', false);
end

function matched = match_targets_local(estimate, truth)
identity_cost = sum((estimate - truth) .^ 2, 'all');
swap_cost = sum((estimate([2, 1], :) - truth) .^ 2, 'all');
if swap_cost < identity_cost
    matched = estimate([2, 1], :);
else
    matched = estimate;
end
end
