function fixture = build_stage8_synthetic_fixture(kind)
%BUILD_STAGE8_SYNTHETIC_FIXTURE Build a tiny factor-1 physical test problem.

if nargin < 1
    kind = 'K2_SAME_ELEVATION';
end
phi = deg2rad([-12;-4;4;12]);
z = [0,0.45];
X = cos(phi) * ones(1, 2);
Y = sin(phi) * ones(1, 2);
Z = ones(4, 1) * z;
array_meta = struct('XAct', X, 'YAct', Y, 'ZAct', Z, ...
    'xActVec', X(:), 'yActVec', Y(:), 'zActVec', Z(:));
model = struct('Wseq', eye(8), 'Tseq', eye(8), ...
    'array_meta', array_meta, 'lambda', 1, 'phase_factor', 1, ...
    'element_order', 'elevation_fastest_azimuth_slowest', ...
    'fixed_measurement_hash', 'SYNTHETIC_FIXED_MEASUREMENT');
[domain, ~] = build_common_registered_local_domain([8,10], struct( ...
    'azimuth_offsets_deg', -0.6:0.2:0.6, ...
    'elevation_offsets_deg', -0.2:0.2:0.2, ...
    'domain_id', 'STAGE8_SYNTHETIC_LOCAL_DOMAIN', ...
    'domain_source', 'DETERMINISTIC_UNIT_TEST_FIXTURE', ...
    'configuration_hash', 'SYNTHETIC_CONFIGURATION', ...
    'phase_factor', 1));
switch char(kind)
    case 'K1'
        angles = [8.0,10.0];
        S = [1,0.7+0.2j,-0.4+0.5j,0.3-0.6j];
    case 'K1_NOISY'
        angles = [8.0,10.0];
        S = [1,0.7+0.2j,-0.4+0.5j,0.3-0.6j];
    case 'K2_SAME_ELEVATION'
        angles = [7.8,10.0;8.2,10.0];
        S = [1,0.5+0.2j,-0.2+0.7j,0.8-0.1j; ...
            0.3j,0.9-0.2j,0.6+0.1j,-0.4+0.5j];
    case 'K2_TWO_ELEVATION_GROUPS'
        angles = [7.8,9.8;8.2,10.2];
        S = [1,0.5+0.2j,-0.2+0.7j,0.8-0.1j; ...
            0.3j,0.9-0.2j,0.6+0.1j,-0.4+0.5j];
    otherwise
        error('build_stage8_synthetic_fixture:Kind', ...
            'Unknown synthetic fixture kind: %s.', char(kind));
end
[G, ~] = build_full_sequential_local_manifold(angles, model, struct());
Z_white = G * S;
if strcmp(kind, 'K1_NOISY')
    deterministic_noise = 0.015 * [ ...
        1+1j,-1+0.5j,0.2-0.7j,-0.4+0.1j; ...
        -0.3+0.8j,0.6-0.2j,-0.7+0.4j,0.5+0.9j; ...
        0.4-0.6j,-0.2+0.3j,0.8+0.2j,-0.9-0.1j; ...
        -0.5+0.2j,0.7+0.6j,-0.1-0.4j,0.3-0.8j; ...
        0.9-0.3j,-0.6+0.7j,0.5-0.5j,-0.2+0.4j; ...
        -0.8+0.1j,0.4-0.9j,0.6+0.3j,-0.5+0.2j; ...
        0.2+0.5j,-0.7-0.3j,0.9+0.1j,-0.1-0.6j; ...
        -0.4-0.7j,0.3+0.8j,-0.5+0.6j,0.7-0.2j];
    Z_white = Z_white + deterministic_noise;
end
full_data = struct('Zseq_white', Z_white, ...
    'fixed_measurement_hash', model.fixed_measurement_hash, ...
    'phase_factor', 1);
context = stage8_synthetic_initialization_factory(full_data);
fixture = struct('model', model, 'domain', domain, ...
    'full_data', full_data, 'target_angles_deg', angles, ...
    'source_coefficients', S, 'G', G, 'init_context', context, ...
    'initialization_factory', @stage8_synthetic_initialization_factory);
end
