function result = verify_step11_frozen_results(package_dir)
%VERIFY_STEP11_FROZEN_RESULTS Recheck the official Step11 hash registry.

manifest = readtable(fullfile(package_dir, 'FILE_SHA256.csv'), ...
    'TextType', 'string');
selected = startsWith(manifest.RelativePath, ...
    "source/stepwise_signal_model/steps/step_11_") & ...
    contains(manifest.RelativePath, "/results_step11_");
frozen = manifest(selected, :);
result = verify_stage8_manifest_rows(package_dir, frozen.RelativePath, ...
    frozen.Bytes, frozen.SHA256);
assert(height(result) == 351 && all(result.pass_flag), ...
    'verify_step11_frozen_results:Failed', ...
    'A frozen Step11 result changed.');
end
