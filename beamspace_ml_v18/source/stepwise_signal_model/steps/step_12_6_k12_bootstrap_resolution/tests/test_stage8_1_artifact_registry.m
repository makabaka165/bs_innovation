function result = test_stage8_1_artifact_registry()
%TEST_STAGE8_1_ARTIFACT_REGISTRY Check every required evidence path.

calibration = stage8_1_calibration_artifact_registry();
validation = stage8_1_validation_artifact_registry();
required_calibration = [ ...
    "calibration/stage8_1_plan_registry.csv"; ...
    "calibration/stage8_1_measurement_registry.csv"; ...
    "calibration/stage8_1_calibration_cells.csv"; ...
    "calibration/stage8_1_seed_registry.csv"; ...
    "calibration/stage8_1_cell_results.csv"; ...
    "calibration/stage8_1_lambda_samples.csv"; ...
    "calibration/stage8_1_cell_quantiles.csv"; ...
    "calibration/stage8_1_locked_thresholds.csv"; ...
    "calibration/stage8_1_complexity.csv"; ...
    "calibration/stage8_1_provenance.csv"; ...
    "calibration/stage8_1_source_manifest.csv"; ...
    "calibration/stage8_1_calibration_evidence_manifest.csv"];
required_validation = [ ...
    "results/stage8_1_k1_validation_trials.csv"; ...
    "results/stage8_1_k1_validation_summary.csv"; ...
    "results/stage8_1_k1_paired_sensitivity.csv"; ...
    "results/stage8_1_validation_provenance.csv"; ...
    "results/stage8_1_keypoints.csv"; ...
    "results/stage8_1_report.md"];
pass = all(ismember(required_calibration, ...
    calibration.table.relative_path)) && ...
    all(ismember(required_validation, validation.table.relative_path)) && ...
    nnz(calibration.table.manifest_self_excluded_flag) == 1 && ...
    nnz(validation.table.manifest_self_excluded_flag) == 1 && ...
    nnz(calibration.table.runtime_excluded_flag) == 1 && ...
    nnz(validation.table.runtime_excluded_flag) == 1 && ...
    strcmp(calibration.lifecycle, 'CALIBRATION') && ...
    strcmp(validation.lifecycle, 'VALIDATION');
assert(pass, 'test_stage8_1_artifact_registry:Failed', ...
    'The Stage8.1 artifact registry is incomplete.');
result = table(pass, height(calibration.table), height(validation.table), ...
    'VariableNames', {'pass_flag','calibration_artifact_count', ...
    'validation_artifact_count'});
end
