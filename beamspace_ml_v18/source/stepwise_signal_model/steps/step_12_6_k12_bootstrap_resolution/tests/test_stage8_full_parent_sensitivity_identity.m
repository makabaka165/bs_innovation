function result = test_stage8_full_parent_sensitivity_identity(cfg)
%TEST_STAGE8_FULL_PARENT_SENSITIVITY_IDENTITY Verify RECT_E31_A31.

[model, debug] = build_stage8_measurement_model( ...
    'SENSITIVITY_FULL_PARENT_5X5', 'WHITE', cfg, struct());
pool = build_stage7_candidate_pool(cfg);
pass = strcmp(model.subset_id, 'RECT_E31_A31') && ...
    isequal(model.channels, 1:25) && debug.B_el == 5 && ...
    debug.B_az == 5 && debug.B_out == 25 && ...
    norm(model.W_I - pool.W0, 'fro') == 0;
assert(pass, 'test_stage8_full_parent_sensitivity_identity:Failed', ...
    'The Stage8 sensitivity model does not match the full parent.');
result = table(pass, debug.B_out, ...
    'VariableNames', {'pass_flag','B_out'});
end
