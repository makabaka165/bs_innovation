function result = test_separation_confidence_zero_inside()
%TEST_SEPARATION_CONFIDENCE_ZERO_INSIDE Verify the strict exclusion rule.

fixture = build_stage8_synthetic_fixture('K2_SAME_ELEVATION');
[fit1, ~] = fit_local_model_k(fixture.full_data, 1, fixture.domain, ...
    fixture.model, fixture.init_context, struct());
context = fixture.init_context;
context.k1_fit = fit1;
[fit2, ~] = fit_local_model_k(fixture.full_data, 2, fixture.domain, ...
    fixture.model, context, struct());
center = mean(fit2.angles_hat_deg, 1);
samples = repmat(reshape([center;center], 2, 2, 1), 1, 1, 3);
callback = build_stage8_refit_callback(fit2, samples);
[confidence, ~] = bootstrap_separation_confidence(fit2, ...
    fixture.domain, fixture.model, struct('Bsep', 3, ...
    'refit_callback', callback, 'seed', 6101));
pass = strcmp(confidence.confidence_status, 'OK') && ...
    ~confidence.zero_excluded_flag;
assert(pass, 'test_separation_confidence_zero_inside:Failed', ...
    'Zero must remain inside when the radius reaches its metric distance.');
result = table(pass, confidence.zero_distance_squared, ...
    confidence.r_conf_squared, 'VariableNames', ...
    {'pass_flag','zero_distance_squared','r_conf_squared'});
end
