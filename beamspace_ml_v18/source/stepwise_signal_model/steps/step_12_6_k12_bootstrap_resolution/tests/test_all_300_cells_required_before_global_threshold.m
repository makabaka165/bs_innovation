function result = test_all_300_cells_required_before_global_threshold(plan)
%TEST_ALL_300_CELLS_REQUIRED_BEFORE_GLOBAL_THRESHOLD Reject 299 cells.

if nargin < 1, plan = build_stage8_calibration_plan(); end
base = struct('measurement_config_id', 'X', 'noise_profile_id', 'WHITE', ...
    'calibration_cell_id', 'X', 'global_cell_index', 1, ...
    'bootstrap_seed_start', 1, 'bootstrap_seed_end', 1, ...
    'lambda_samples', 1, 'q_cell_0p95', 1, ...
    'source_identity', 'X', 'plan_hash', plan.calibration_plan_hash, ...
    'model_key', 'X', 'model_hash', 'X', 'cell_input_hash', 'X', ...
    'data_seed', 1, 'cell_artifact_hash', 'X', ...
    'status', 'CALIBRATION_CELL_PASS');
artifacts = repmat(base, 299, 1);
stage8_assert_error(@() aggregate_stage8_1_calibration( ...
    artifacts, plan, struct('formal_run', true)), ...
    'aggregate_stage8_1_calibration:IncompleteCells');
pass = true;
result = table(pass, 'VariableNames', {'pass_flag'});
end
