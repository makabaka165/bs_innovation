function result = test_low_norm_fitted_mean_does_not_false_fail(fixture)
%TEST_LOW_NORM_FITTED_MEAN_DOES_NOT_FALSE_FAIL Avoid norm-division gates.

fit = fixture.fit;
fit.S_hat = fit.S_hat * 1e-140;
evaluation = evaluate_stage8_bootstrap_mean_identity(fit, fixture.mini.model);
pass = evaluation.fitted_mean_norm > 0 && ...
    evaluation.fitted_mean_norm < 1e-100 && evaluation.overall_pass && ...
    isfinite(evaluation.mean_max_bound_ratio);
assert(pass, 'test_low_norm_fitted_mean_does_not_false_fail:Failed', ...
    'A finite low-norm fitted mean falsely failed the backward-error gate.');
result = table(pass, evaluation.fitted_mean_norm, ...
    evaluation.mean_max_bound_ratio, ...
    'VariableNames', {'pass_flag','fitted_mean_norm','mean_max_bound_ratio'});
end
