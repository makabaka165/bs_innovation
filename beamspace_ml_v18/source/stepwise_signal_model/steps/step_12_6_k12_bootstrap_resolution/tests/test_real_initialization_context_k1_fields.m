function result = test_real_initialization_context_k1_fields()
%TEST_REAL_INITIALIZATION_CONTEXT_K1_FIELDS Check data-driven K1 starts.

fixture = build_stage8_1a_mini_fixture();
[context, debug] = build_stage8_initialization_context_from_data( ...
    fixture.full_k1, fixture.model, fixture.domain, ...
    fixture.stage5_locked, fixture.model.noise_factorization, struct());
mini_plan = calibration_plan_local(fixture.model);
[materialized, ~] = materialize_stage8_calibration_cells( ...
    mini_plan, fixture.domain, fixture.registry, fixture.stage5_locked, ...
    struct('source_identity', 'MINI_MATERIALIZATION_SOURCE'));
required = {'grouped_q1_kq1_angles_deg', ...
    'conventional_singleton_peak_deg','grouped_q1_kq1_status', ...
    'conventional_singleton_status','num_score_eval','num_svd', ...
    'runtime','status_counters','factory_invocation_hash'};
pass = all(isfield(context, required)) && ...
    all(isfinite(context.conventional_singleton_peak_deg)) && ...
    context.num_score_eval == debug.num_score_eval && ...
    context.num_svd == debug.num_svd && numel(materialized) == 1 && ...
    materialized.full_data.element_data_retained_flag && ...
    strcmp(materialized.initialization_factory_contract, ...
    'BUILD_STAGE8_INITIALIZATION_CONTEXT_FROM_DATA_V1');
assert(pass, 'test_real_initialization_context_k1_fields:Failed', ...
    'The real initialization context is missing K1 audit fields.');
result = table(pass, context.num_score_eval, context.num_svd, ...
    'VariableNames', {'pass_flag','score_calls','svd_calls'});
end

function plan = calibration_plan_local(model)
row = struct('measurement_config_id', string(model.measurement_config_id), ...
    'calibration_cell_id', "MINI_MATERIALIZED_CELL", ...
    'center_az_deg', 8, 'center_el_deg', 10, 'snr_db', 6, 'L', 4, ...
    'noise_profile_id', string(model.noise_profile_id), ...
    'model_key', string(model.model_key), ...
    'fixed_measurement_hash', string(model.fixed_measurement_hash), ...
    'Bboot_per_cell', 2, 'global_cell_index', 1, ...
    'calibration_data_seed', 901, 'bootstrap_seed_start', 1901, ...
    'bootstrap_seed_end', 1902, 'seed_block_stride', 1000, ...
    'bootstrap_seed_formula', ...
    "bootstrap_seed_start + bootstrap_index - 1");
cells = struct2table(row);
plan = struct('cells', cells, 'calibration_plan_hash', ...
    stage8_stable_hash(cells), 'Bboot_per_cell', 2);
end
