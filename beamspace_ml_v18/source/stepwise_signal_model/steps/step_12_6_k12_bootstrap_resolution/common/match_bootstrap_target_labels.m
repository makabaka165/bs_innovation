function [matched_angles_deg, assignment, info] = ...
    match_bootstrap_target_labels(bootstrap_angles_deg, reference_angles_deg)
%MATCH_BOOTSTRAP_TARGET_LABELS Minimize total two-dimensional angular cost.

if ~(isnumeric(bootstrap_angles_deg) && ...
        isequal(size(bootstrap_angles_deg), [2, 2]) && ...
        all(isfinite(bootstrap_angles_deg(:))) && ...
        isnumeric(reference_angles_deg) && ...
        isequal(size(reference_angles_deg), [2, 2]) && ...
        all(isfinite(reference_angles_deg(:))))
    error('match_bootstrap_target_labels:Angles', ...
        'Both angle sets must be finite 2-by-2 [azimuth,elevation] matrices.');
end
permutations = [1,2;2,1];
cost = zeros(2, 1);
for index = 1:2
    error_now = bootstrap_angles_deg(permutations(index, :), :) - ...
        reference_angles_deg;
    cost(index) = sum(error_now(:) .^ 2);
end
[minimum_cost, best] = min(cost);
assignment = permutations(best, :);
matched_angles_deg = bootstrap_angles_deg(assignment, :);
info = struct('total_squared_angular_cost', minimum_cost, ...
    'all_assignment_costs', cost, ...
    'matching_rule', 'MINIMUM_TWO_DIMENSIONAL_ANGULAR_COST', ...
    'truth_used_flag', false);
end
