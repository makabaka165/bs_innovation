function [thresholds, threshold_set_hash] = ...
    validate_stage8_locked_threshold_set( ...
    measurement_config_ids, locked_artifacts, expected_contract)
%VALIDATE_STAGE8_LOCKED_THRESHOLD_SET Require one threshold per config.

config_ids = string(measurement_config_ids(:));
if isempty(config_ids) || numel(unique(config_ids)) ~= numel(config_ids)
    error('validate_stage8_locked_threshold_set:ConfigurationRegistry', ...
        'Expected measurement configuration IDs must be unique.');
end
if ~(isstruct(locked_artifacts) && ...
        numel(locked_artifacts) == numel(config_ids))
    error('validate_stage8_locked_threshold_set:ThresholdCount', ...
        'The locked threshold count must equal the configuration count.');
end
threshold_cells = cell(numel(config_ids), 1);
for config_index = 1:numel(config_ids)
    threshold_cells{config_index} = lookup_locked_lrt_threshold( ...
        config_ids(config_index), locked_artifacts, expected_contract);
end
thresholds = vertcat(threshold_cells{:});
artifact_ids = string({locked_artifacts.measurement_config_id}).';
if numel(unique(artifact_ids)) ~= numel(config_ids) || ...
        ~isempty(setxor(artifact_ids, config_ids))
    error('validate_stage8_locked_threshold_set:ConfigurationCoverage', ...
        'Locked thresholds must cover every expected configuration exactly once.');
end
registry = table(string({thresholds.measurement_config_id}).', ...
    string({thresholds.calibration_hash}).', ...
    string({thresholds.threshold_artifact_hash}).', ...
    'VariableNames', {'measurement_config_id','calibration_hash', ...
    'threshold_artifact_hash'});
threshold_set_hash = stage8_stable_hash( ...
    'STAGE8_LOCKED_THRESHOLD_SET_V3', registry, expected_contract);
end
