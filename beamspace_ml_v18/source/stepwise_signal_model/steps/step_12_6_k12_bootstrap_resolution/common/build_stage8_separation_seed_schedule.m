function schedule = build_stage8_separation_seed_schedule( ...
    separation_auxiliary_seed, Bsep)
%BUILD_STAGE8_SEPARATION_SEED_SCHEDULE Freeze auxiliary seed and substreams.

if ~(isscalar(separation_auxiliary_seed) && ...
        isfinite(separation_auxiliary_seed) && ...
        separation_auxiliary_seed >= 0 && ...
        separation_auxiliary_seed == fix(separation_auxiliary_seed)) || ...
        ~(isscalar(Bsep) && isfinite(Bsep) && Bsep >= 1 && Bsep == fix(Bsep))
    error('build_stage8_separation_seed_schedule:Input', ...
        'The auxiliary seed and Bsep must be nonnegative/positive integers.');
end
bootstrap_index = (1:Bsep).';
seed = repmat(separation_auxiliary_seed, Bsep, 1);
substream = bootstrap_index;
schedule = table(bootstrap_index, seed, substream, ...
    'VariableNames', {'bootstrap_index','separation_auxiliary_seed', ...
    'substream'});
end
