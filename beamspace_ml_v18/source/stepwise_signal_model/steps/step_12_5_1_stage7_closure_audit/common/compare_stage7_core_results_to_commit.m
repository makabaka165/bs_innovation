function [comparison, summary] = compare_stage7_core_results_to_commit( ...
    repo_dir, current_result_dir, opts)
%COMPARE_STAGE7_CORE_RESULTS_TO_COMMIT Compare core CSVs to Git history.

if nargin < 3 || isempty(opts), opts = struct(); end
opts = normalize_options_local(opts);
repo_dir = existing_dir_local(repo_dir, 'repo_dir');
current_result_dir = existing_dir_local(current_result_dir, ...
    'current_result_dir');
historical_commit = ...
    "85615e0f5027e7d6dee840dcb71aa1a2c07e85c3";
contract = comparison_contract_local();
rows = cell(0, 1);
current_tables = struct();
historical_tables = struct();
for file_index = 1:height(contract)
    artifact_id = contract.artifact_id(file_index);
    current = read_current_local(current_result_dir, contract, ...
        file_index, opts);
    historical = read_historical_local(repo_dir, historical_commit, ...
        contract, file_index, opts);
    current_tables.(char(artifact_id)) = current;
    historical_tables.(char(artifact_id)) = historical;
    keys = split(contract.primary_key_columns(file_index), ';').';
    [file_rows, current, historical] = compare_table_local( ...
        artifact_id, contract.file_name(file_index), keys, ...
        current, historical);
    current_tables.(char(artifact_id)) = current;
    historical_tables.(char(artifact_id)) = historical;
    rows = [rows; file_rows]; %#ok<AGROW>
    if startsWith(artifact_id, "finite_sample_")
        rows{end + 1, 1} = finite_success_count_row_local( ...
            artifact_id, contract.file_name(file_index), keys, ...
            current, historical); %#ok<AGROW>
    end
end

comparison = struct2table(vertcat(rows{:}));
enumeration = current_tables.fim_subset_enumeration;
historical_enumeration = historical_tables.fim_subset_enumeration;
operating = current_tables.fim_operating_points;
historical_operating = historical_tables.fim_operating_points;
keypoints = current_tables.stage7_keypoints;
historical_keypoints = historical_tables.stage7_keypoints;
selected = operating(abs(operating.eta0 - 0.80) <= eps(0.80) & ...
    operating.fim_gate_pass, :);
historical_selected = historical_operating( ...
    abs(historical_operating.eta0 - 0.80) <= eps(0.80) & ...
    historical_operating.fim_gate_pass, :);
status_value = keypoints.value(keypoints.metric == "stage7_status");
historical_status_value = historical_keypoints.value( ...
    historical_keypoints.metric == "stage7_status");
subset_contract_pass = height(enumeration) == 961 && ...
    height(historical_enumeration) == 961 && ...
    isequal(sort(enumeration.subset_id), ...
    sort(historical_enumeration.subset_id));
selection_contract_pass = height(selected) == 1 && ...
    height(historical_selected) == 1 && ...
    selected.subset_id == "RECT_E14_A31" && ...
    selected.subset_id == historical_selected.subset_id;
status_contract_pass = isscalar(status_value) && ...
    isscalar(historical_status_value) && ...
    status_value == "PASS_SYSTEM_ANALYSIS_ONLY" && ...
    status_value == historical_status_value;
failed_comparison_count = nnz(~comparison.pass_flag);
pass_flag = failed_comparison_count == 0 && subset_contract_pass && ...
    selection_contract_pass && status_contract_pass;
comparison_status = string(ternary_local(pass_flag, ...
    "PASS_STAGE7_CORE_MATCHES_HISTORICAL_COMMIT", ...
    "FAIL_STAGE7_CORE_HISTORICAL_COMPARISON"));
summary = table(historical_commit, height(contract), height(comparison), ...
    failed_comparison_count, height(enumeration), subset_contract_pass, ...
    string(selected.subset_id), selection_contract_pass, ...
    string(status_value), status_contract_pass, 1e-12, 1e-10, ...
    comparison_status, pass_flag, 'VariableNames', { ...
    'historical_commit','compared_file_count','comparison_row_count', ...
    'failed_comparison_count','current_subset_count', ...
    'subset_contract_pass','selected_exact_subset_id', ...
    'selected_exact_subset_pass','stage7_status', ...
    'stage7_status_pass','absolute_tolerance','relative_tolerance', ...
    'comparison_status','pass_flag'});
end

function contract = comparison_contract_local()
artifact_id = [ ...
    "fim_subset_enumeration";"fim_operating_points"; ...
    "fim_greedy_exact_gap";"fim_subset_validation"; ...
    "fim_subset_holdout";"finite_sample_normal_holdout"; ...
    "finite_sample_threshold_holdout"; ...
    "finite_sample_mismatch_holdout"; ...
    "finite_sample_stress_holdout";"fim_vs_finite_sample_risk"; ...
    "stage7_keypoints"];
file_name = artifact_id + ".csv";
primary_key_columns = [ ...
    "subset_id";"eta0";"eta0";"scenario_id;method_id"; ...
    "scenario_id;method_id";"scenario_id;method_id"; ...
    "scenario_id;method_id";"scenario_id;method_id"; ...
    "scenario_id;method_id";"method_id";"metric"];
contract = table(artifact_id, file_name, primary_key_columns);
end

function [rows, current, historical] = compare_table_local( ...
    artifact_id, file_name, keys, current, historical)
rows = cell(0, 1);
current = normalize_expected_variation_local(artifact_id, current);
historical = normalize_expected_variation_local(artifact_id, historical);
if ~all(ismember(keys, current.Properties.VariableNames)) || ...
        ~all(ismember(keys, historical.Properties.VariableNames))
    rows{1, 1} = comparison_row_local(artifact_id, file_name, ...
        strjoin(keys, ';'), "__PRIMARY_KEY_SCHEMA__", ...
        "EXACT", height(current), height(historical), 1, NaN, NaN, false);
    return;
end
current = sortrows(current, cellstr(keys));
historical = sortrows(historical, cellstr(keys));
keys_unique = height(unique(current(:, cellstr(keys)), 'rows')) == ...
    height(current) && height(unique(historical(:, cellstr(keys)), 'rows')) == ...
    height(historical);
keys_match = keys_unique && height(current) == height(historical) && ...
    isequaln(current(:, cellstr(keys)), historical(:, cellstr(keys)));
rows{end + 1, 1} = comparison_row_local(artifact_id, file_name, ...
    strjoin(keys, ';'), "__PRIMARY_KEY__", "EXACT", ...
    height(current), height(historical), double(~keys_match), ...
    NaN, NaN, keys_match);
if ~keys_match, return; end

historical_columns = string(historical.Properties.VariableNames);
ignored = ignored_column_local(historical_columns);
required_columns = historical_columns(~ignored);
current_columns = string(current.Properties.VariableNames);
unexpected = current_columns(~ismember(current_columns, historical_columns) & ...
    ~ignored_column_local(current_columns));
for index = 1:numel(unexpected)
    rows{end + 1, 1} = comparison_row_local(artifact_id, file_name, ...
        strjoin(keys, ';'), unexpected(index), ...
        "UNEXPECTED_CURRENT_COLUMN", height(current), ...
        height(historical), height(current), NaN, NaN, false); %#ok<AGROW>
end
missing = required_columns(~ismember(required_columns, ...
    string(current.Properties.VariableNames)));
for index = 1:numel(missing)
    rows{end + 1, 1} = comparison_row_local(artifact_id, file_name, ...
        strjoin(keys, ';'), missing(index), "MISSING_CURRENT_COLUMN", ...
        height(current), height(historical), height(historical), ...
        NaN, NaN, false); %#ok<AGROW>
end

for index = 1:numel(required_columns)
    name = required_columns(index);
    if ~ismember(name, string(current.Properties.VariableNames)), continue; end
    current_value = current.(name);
    historical_value = historical.(name);
    if (isnumeric(current_value) || islogical(current_value)) && ...
            (isnumeric(historical_value) || islogical(historical_value))
        exact_numeric = contains(lower(name), 'flag') || ...
            name == "n_trials" || contains(lower(name), 'count') || ...
            contains(lower(name), 'rank') || contains(lower(name), 'mask');
        [mismatch_count, max_absolute, max_relative, pass] = ...
            numeric_compare_local(double(current_value), ...
            double(historical_value), exact_numeric);
        comparison_type = string(ternary_local(exact_numeric, ...
            "EXACT_NUMERIC", "NUMERIC_ABS_OR_REL"));
    else
        current_text = string(current_value);
        historical_text = string(historical_value);
        equal = (current_text == historical_text) | ...
            (ismissing(current_text) & ismissing(historical_text));
        mismatch_count = nnz(~equal);
        max_absolute = NaN;
        max_relative = NaN;
        pass = mismatch_count == 0;
        comparison_type = "EXACT_TEXT";
    end
    rows{end + 1, 1} = comparison_row_local(artifact_id, file_name, ...
        strjoin(keys, ';'), name, comparison_type, height(current), ...
        height(historical), mismatch_count, max_absolute, ...
        max_relative, pass); %#ok<AGROW>
end
end

function table_out = normalize_expected_variation_local(artifact_id, table_out)
if artifact_id ~= "stage7_keypoints" || ...
        ~all(ismember({'metric','value'}, table_out.Properties.VariableNames))
    return;
end
metric = lower(string(table_out.metric));
expected_variation = contains(metric, 'runtime') | ...
    contains(metric, 'wall_clock') | ...
    contains(metric, 'source_tree_hash') | ...
    contains(metric, 'dependency_tree_hash') | ...
    contains(metric, 'provenance_hash') | ...
    contains(metric, 'plan_hash') | ...
    contains(metric, 'runtime_head') | ...
    contains(metric, 'file_size') | ...
    contains(metric, 'byte_count') | ...
    metric == "result_data_volume";
value = string(table_out.value);
value(expected_variation) = "EXPECTED_VARIATION_EXCLUDED";
table_out.value = value;
end

function row = finite_success_count_row_local( ...
    artifact_id, file_name, keys, current, historical)
required = {'oracle_k_success_rate','n_trials'};
pass = height(current) == height(historical) && ...
    all(ismember(required, current.Properties.VariableNames)) && ...
    all(ismember(required, historical.Properties.VariableNames));
if pass
    current_count = round(current.oracle_k_success_rate .* current.n_trials);
    historical_count = round( ...
        historical.oracle_k_success_rate .* historical.n_trials);
    mismatch_count = nnz(current_count ~= historical_count);
    max_absolute = max(abs(current_count - historical_count), [], 'all');
    pass = mismatch_count == 0;
else
    mismatch_count = max(height(current), height(historical));
    max_absolute = NaN;
end
row = comparison_row_local(artifact_id, file_name, strjoin(keys, ';'), ...
    "__FINITE_SAMPLE_SUCCESS_COUNT__", "EXACT_DERIVED_COUNT", ...
    height(current), height(historical), mismatch_count, ...
    max_absolute, 0, pass);
end

function [mismatch_count, max_absolute, max_relative, pass] = ...
    numeric_compare_local(current, historical, exact_numeric)
same_special = (isnan(current) & isnan(historical)) | ...
    (isinf(current) & isinf(historical) & sign(current) == sign(historical));
finite_pair = isfinite(current) & isfinite(historical);
absolute = zeros(size(current));
relative = zeros(size(current));
absolute(finite_pair) = abs(current(finite_pair) - historical(finite_pair));
scale = max(abs(current(finite_pair)), abs(historical(finite_pair)));
relative(finite_pair) = absolute(finite_pair) ./ max(scale, realmin);
if exact_numeric
    equal = same_special | (finite_pair & absolute == 0);
else
    equal = same_special | (finite_pair & ...
        (absolute <= 1e-12 | relative <= 1e-10));
end
mismatch_count = nnz(~equal);
if any(finite_pair, 'all')
    max_absolute = max(absolute(finite_pair));
    max_relative = max(relative(finite_pair));
else
    max_absolute = 0;
    max_relative = 0;
end
pass = mismatch_count == 0;
end

function ignored = ignored_column_local(names)
lower_names = lower(names);
ignored = contains(lower_names, 'runtime') | ...
    contains(lower_names, 'wall_clock') | ...
    contains(lower_names, 'source_tree_hash') | ...
    contains(lower_names, 'dependency_tree_hash') | ...
    contains(lower_names, 'provenance_hash') | ...
    contains(lower_names, 'plan_hash') | ...
    contains(lower_names, 'runtime_head') | ...
    contains(lower_names, 'byte_count') | ...
    contains(lower_names, 'file_size');
end

function row = comparison_row_local(artifact_id, file_name, primary_key, ...
    column_name, comparison_type, current_count, historical_count, ...
    mismatch_count, max_absolute, max_relative, pass)
row = struct('artifact_id', string(artifact_id), ...
    'file_name', string(file_name), ...
    'primary_key_columns', string(primary_key), ...
    'column_name', string(column_name), ...
    'comparison_type', string(comparison_type), ...
    'current_row_count', current_count, ...
    'historical_row_count', historical_count, ...
    'mismatch_count', mismatch_count, ...
    'maximum_absolute_difference', max_absolute, ...
    'maximum_relative_difference', max_relative, ...
    'absolute_tolerance', 1e-12, 'relative_tolerance', 1e-10, ...
    'pass_flag', logical(pass));
end

function table_out = read_current_local(result_dir, contract, index, opts)
id = char(contract.artifact_id(index));
if isfield(opts.current_tables_override, id)
    table_out = opts.current_tables_override.(id);
else
    table_out = read_result_table_local(fullfile(result_dir, ...
        char(contract.file_name(index))), contract.artifact_id(index));
end
end

function table_out = read_historical_local(repo_dir, commit, ...
    contract, index, opts)
id = char(contract.artifact_id(index));
if isfield(opts.historical_tables_override, id)
    table_out = opts.historical_tables_override.(id);
    return;
end
prefix = ['beamspace_ml_v18/source/stepwise_signal_model/steps/', ...
    'step_12_5_exact_subset_fim_beam_design/results/'];
git_path = prefix + contract.file_name(index);
command = sprintf('git -C "%s" show "%s:%s"', ...
    repo_dir, commit, git_path);
[status, output] = system(command);
if status ~= 0
    error('compare_stage7_core_results_to_commit:GitObject', ...
        'Unable to read historical Git object %s.', git_path);
end
temporary_path = [tempname, '.csv'];
cleanup = onCleanup(@() delete_if_exists_local(temporary_path));
fid = fopen(temporary_path, 'wb');
if fid < 0
    error('compare_stage7_core_results_to_commit:TemporaryFile', ...
        'Unable to create a temporary historical CSV.');
end
file_cleanup = onCleanup(@() fclose(fid));
fwrite(fid, unicode2native(output, 'UTF-8'), 'uint8');
clear file_cleanup
table_out = read_result_table_local(temporary_path, ...
    contract.artifact_id(index));
clear cleanup
end

function table_out = read_result_table_local(path_now, artifact_id)
if artifact_id == "stage7_keypoints"
    import_options = detectImportOptions(path_now, 'TextType', 'string');
    text_columns = intersect(["metric","value","unit","status"], ...
        string(import_options.VariableNames), 'stable');
    import_options = setvartype(import_options, cellstr(text_columns), ...
        'string');
    table_out = readtable(path_now, import_options);
else
    table_out = readtable(path_now, 'TextType', 'string');
end
end

function opts = normalize_options_local(opts)
if ~(isstruct(opts) && isscalar(opts))
    error('compare_stage7_core_results_to_commit:Options', ...
        'opts must be a scalar struct.');
end
allowed = {'unit_test_mode','current_tables_override', ...
    'historical_tables_override'};
unknown = setdiff(fieldnames(opts), allowed);
if ~isempty(unknown)
    error('compare_stage7_core_results_to_commit:UnknownOption', ...
        'Unknown option: %s.', unknown{1});
end
if ~isfield(opts, 'unit_test_mode'), opts.unit_test_mode = false; end
if ~isfield(opts, 'current_tables_override')
    opts.current_tables_override = struct();
end
if ~isfield(opts, 'historical_tables_override')
    opts.historical_tables_override = struct();
end
if ~(islogical(opts.unit_test_mode) && isscalar(opts.unit_test_mode) && ...
        isstruct(opts.current_tables_override) && ...
        isscalar(opts.current_tables_override) && ...
        isstruct(opts.historical_tables_override) && ...
        isscalar(opts.historical_tables_override))
    error('compare_stage7_core_results_to_commit:OptionValue', ...
        'Invalid historical comparison options.');
end
if ~opts.unit_test_mode && ...
        (~isempty(fieldnames(opts.current_tables_override)) || ...
        ~isempty(fieldnames(opts.historical_tables_override)))
    error('compare_stage7_core_results_to_commit:TestOverride', ...
        'Table overrides are restricted to explicit unit-test mode.');
end
end

function value = existing_dir_local(value, name)
if isstring(value), value = char(value); end
if ~(ischar(value) && isrow(value) && exist(value, 'dir') == 7)
    error('compare_stage7_core_results_to_commit:Directory', ...
        '%s must identify an existing directory.', name);
end
value = char(java.io.File(value).getCanonicalPath());
end

function delete_if_exists_local(path_now)
if exist(path_now, 'file') == 2, delete(path_now); end
end

function value = ternary_local(condition, yes_value, no_value)
if condition, value = yes_value; else, value = no_value; end
end
