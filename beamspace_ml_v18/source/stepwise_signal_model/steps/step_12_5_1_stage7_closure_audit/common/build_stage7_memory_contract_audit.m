function audit = build_stage7_memory_contract_audit( ...
    stage7_result_dir, stage7_plan, historical_summary, ...
    corrected_complexity)
%BUILD_STAGE7_MEMORY_CONTRACT_AUDIT Audit deterministic and legacy memory.

stage7_result_dir = existing_dir_local(stage7_result_dir);
validate_plan_local(stage7_plan);
historical = historical_row_local(historical_summary);
complexity = scalar_struct_local(corrected_complexity, ...
    'corrected_complexity');

keypoints = read_keypoints_local(stage7_result_dir);
enumeration = readtable(fullfile(stage7_result_dir, ...
    'fim_subset_enumeration.csv'), 'TextType', 'string');
operating = readtable(fullfile(stage7_result_dir, ...
    'fim_operating_points.csv'), 'TextType', 'string');

candidate_pool_size = height(stage7_plan.pool.table);
admissible_subset_count = height(stage7_plan.subset_family);
evaluated_subset_count = height(enumeration);
selected = operating(abs(operating.eta0 - 0.80) <= eps(0.80) & ...
    logical(operating.fim_gate_pass), :);
if height(selected) ~= 1
    error('build_stage7_memory_contract_audit:OperatingPoint', ...
        'Expected one passing eta0=0.80 Stage 7 operating point.');
end
selected_subset_id = string(selected.subset_id);
selected_family = stage7_plan.subset_family( ...
    string(stage7_plan.subset_family.subset_id) == selected_subset_id, :);
if height(selected_family) ~= 1
    error('build_stage7_memory_contract_audit:SelectedSubset', ...
        'The selected operating subset is absent from the frozen family.');
end
selected_B_el = selected_family.B_e;
selected_B_az = selected_family.B_a;
selected_B_out = selected_family.B_out;

N_el = stage7_plan.cost.N_el;
N_az = stage7_plan.cost.N_az;
complex_bytes = stage7_plan.cost.complex_double_bytes;
workspace_contract_bytes = 8 * (N_el * N_az) ^ 2;
materialized_equivalent_W_bytes = complex_bytes * N_el * N_az * ...
    selected_B_el * selected_B_az;
factorized_elevation_weight_bytes = complex_bytes * N_el * selected_B_el;
factorized_azimuth_weight_bytes = complex_bytes * N_az * ...
    selected_B_az * selected_B_el;
factorized_total_weight_bytes = factorized_elevation_weight_bytes + ...
    factorized_azimuth_weight_bytes;
[actual_unique_subset_score_calls, charged_method_score_calls] = ...
    score_call_counts_local(stage7_result_dir);
duplicate_method_charge = charged_method_score_calls - ...
    actual_unique_subset_score_calls;

keypoint_candidate_count = keypoint_integer_local( ...
    keypoints, 'candidate_pool_size');
keypoint_admissible_count = keypoint_integer_local( ...
    keypoints, 'admissible_subset_count');
keypoint_evaluated_count = keypoint_integer_local( ...
    keypoints, 'evaluated_subset_count');
family_ids = sort(string(stage7_plan.subset_family.subset_id));
enumerated_ids = sort(string(enumeration.subset_id));
complexity_required = {'actual_unique_subset_score_calls', ...
    'charged_method_score_calls','duplicate_method_charge', ...
    'materialized_equivalent_W_bytes', ...
    'factorized_elevation_weight_bytes', ...
    'factorized_azimuth_weight_bytes','factorized_total_weight_bytes', ...
    'dimension_source'};
complexity_complete = all(isfield(complexity, complexity_required));
if ~complexity_complete
    error('build_stage7_memory_contract_audit:Complexity', ...
        'Corrected complexity is missing a required deterministic field.');
end

derived_contract_pass = candidate_pool_size == keypoint_candidate_count && ...
    admissible_subset_count == keypoint_admissible_count && ...
    evaluated_subset_count == keypoint_evaluated_count && ...
    numel(unique(family_ids)) == admissible_subset_count && ...
    numel(unique(enumerated_ids)) == evaluated_subset_count && ...
    isequal(family_ids, enumerated_ids) && ...
    selected.subset_id == selected_family.subset_id && ...
    selected.B_e == selected_B_el && selected.B_a == selected_B_az && ...
    selected.B_out == selected_B_out && ...
    selected_B_out == selected_B_el * selected_B_az && ...
    strcmp(complexity.dimension_source, ...
    'FROZEN_STAGE7_PLAN_EXPLICIT_DIMENSIONS') && ...
    complexity.actual_unique_subset_score_calls == ...
    actual_unique_subset_score_calls && ...
    complexity.charged_method_score_calls == charged_method_score_calls && ...
    complexity.duplicate_method_charge == duplicate_method_charge && ...
    complexity.materialized_equivalent_W_bytes == ...
    materialized_equivalent_W_bytes && ...
    complexity.factorized_elevation_weight_bytes == ...
    factorized_elevation_weight_bytes && ...
    complexity.factorized_azimuth_weight_bytes == ...
    factorized_azimuth_weight_bytes && ...
    complexity.factorized_total_weight_bytes == factorized_total_weight_bytes;

frozen_value_pass = workspace_contract_bytes == 34611200 && ...
    candidate_pool_size == 25 && admissible_subset_count == 961 && ...
    evaluated_subset_count == 961 && ...
    selected_subset_id == "RECT_E14_A31" && ...
    selected_B_el == 3 && selected_B_az == 5 && selected_B_out == 15 && ...
    materialized_equivalent_W_bytes == 499200 && ...
    factorized_elevation_weight_bytes == 1536 && ...
    factorized_azimuth_weight_bytes == 15600 && ...
    factorized_total_weight_bytes == 17136 && ...
    actual_unique_subset_score_calls == 9152562 && ...
    charged_method_score_calls == 11734516 && ...
    duplicate_method_charge == 2581954;
deterministic_contract_pass = derived_contract_pass && frozen_value_pass;

historical_peak_memory_estimate_bytes = ...
    historical.peak_memory_historical_bytes;
current_peak_memory_estimate_bytes = ...
    historical.peak_memory_current_bytes;
peak_memory_delta_bytes = current_peak_memory_estimate_bytes - ...
    historical_peak_memory_estimate_bytes;
peak_memory_relative_delta = abs(peak_memory_delta_bytes) / ...
    historical_peak_memory_estimate_bytes;
peak_memory_comparison_status = string( ...
    historical.peak_memory_comparison_status);
schema_dependent_estimate_diagnostic_pass = ...
    historical.pass_flag && ...
    peak_memory_comparison_status == ...
    "EXPECTED_PROVENANCE_SCHEMA_DEPENDENT_VARIATION" && ...
    positive_integer_local(historical_peak_memory_estimate_bytes) && ...
    positive_integer_local(current_peak_memory_estimate_bytes) && ...
    historical.peak_memory_delta_bytes == peak_memory_delta_bytes && ...
    abs(historical.peak_memory_relative_delta - ...
    peak_memory_relative_delta) <= eps(max(1, peak_memory_relative_delta));
overall_memory_audit_pass = deterministic_contract_pass && ...
    schema_dependent_estimate_diagnostic_pass;

audit = struct();
audit.historical_peak_memory_estimate_bytes = ...
    historical_peak_memory_estimate_bytes;
audit.current_peak_memory_estimate_bytes = ...
    current_peak_memory_estimate_bytes;
audit.peak_memory_delta_bytes = peak_memory_delta_bytes;
audit.peak_memory_relative_delta = peak_memory_relative_delta;
audit.peak_memory_estimate_semantics = ...
    'LEGACY_SCHEMA_DEPENDENT_WORKSPACE_ESTIMATE';
audit.peak_memory_comparison_status = char(peak_memory_comparison_status);
audit.peak_memory_diagnostic_reason = ...
    'PROVENANCE_SCHEMA_CHANGED_CONTEXT_WHOS_BYTES';
audit.workspace_contract_bytes = workspace_contract_bytes;
audit.candidate_pool_size = candidate_pool_size;
audit.admissible_subset_count = admissible_subset_count;
audit.evaluated_subset_count = evaluated_subset_count;
audit.selected_subset_id = char(selected_subset_id);
audit.selected_B_el = selected_B_el;
audit.selected_B_az = selected_B_az;
audit.selected_B_out = selected_B_out;
audit.materialized_equivalent_W_bytes = ...
    materialized_equivalent_W_bytes;
audit.factorized_elevation_weight_bytes = ...
    factorized_elevation_weight_bytes;
audit.factorized_azimuth_weight_bytes = ...
    factorized_azimuth_weight_bytes;
audit.factorized_total_weight_bytes = factorized_total_weight_bytes;
audit.actual_unique_subset_score_calls = ...
    actual_unique_subset_score_calls;
audit.charged_method_score_calls = charged_method_score_calls;
audit.duplicate_method_charge = duplicate_method_charge;
audit.deterministic_contract_pass = deterministic_contract_pass;
audit.deterministic_memory_contract_pass = deterministic_contract_pass;
audit.schema_dependent_estimate_diagnostic_pass = ...
    schema_dependent_estimate_diagnostic_pass;
audit.overall_memory_audit_pass = overall_memory_audit_pass;
end

function validate_plan_local(plan)
required = {'pool','subset_family','cost','phase_factor', ...
    'plan_freeze_status'};
required_cost = {'N_el','N_az','complex_double_bytes'};
if ~(isstruct(plan) && isscalar(plan) && all(isfield(plan, required)) && ...
        isstruct(plan.pool) && isscalar(plan.pool) && ...
        isfield(plan.pool, 'table') && istable(plan.pool.table) && ...
        istable(plan.subset_family) && ...
        all(ismember({'subset_id','B_e','B_a','B_out'}, ...
        plan.subset_family.Properties.VariableNames)) && ...
        isstruct(plan.cost) && isscalar(plan.cost) && ...
        all(isfield(plan.cost, required_cost)))
    error('build_stage7_memory_contract_audit:FrozenPlan', ...
        'A complete frozen Stage 7 plan is required.');
end
dimensions = [plan.cost.N_el, plan.cost.N_az, ...
    plan.cost.complex_double_bytes];
if any(~isfinite(dimensions) | dimensions <= 0 | ...
        dimensions ~= fix(dimensions)) || plan.phase_factor ~= 1 || ...
        ~strcmp(plan.plan_freeze_status, ...
        'FROZEN_BEFORE_ANY_STAGE7_FIM_RESULT')
    error('build_stage7_memory_contract_audit:FrozenPlanContract', ...
        'The Stage 7 plan does not satisfy its frozen dimension contract.');
end
end

function row = historical_row_local(summary)
required = {'peak_memory_historical_bytes', ...
    'peak_memory_current_bytes','peak_memory_delta_bytes', ...
    'peak_memory_relative_delta','peak_memory_comparison_status', ...
    'pass_flag'};
if ~(istable(summary) && height(summary) == 1 && ...
        all(ismember(required, summary.Properties.VariableNames)))
    error('build_stage7_memory_contract_audit:HistoricalSummary', ...
        'Historical comparison summary is incomplete.');
end
row = table2struct(summary);
end

function value = scalar_struct_local(value, name)
if istable(value) && height(value) == 1
    value = table2struct(value);
end
if ~(isstruct(value) && isscalar(value))
    error('build_stage7_memory_contract_audit:ScalarStruct', ...
        '%s must be a scalar struct or one-row table.', name);
end
end

function keypoints = read_keypoints_local(result_dir)
path_now = fullfile(result_dir, 'stage7_keypoints.csv');
options = detectImportOptions(path_now, 'TextType', 'string');
text_columns = intersect({'metric','value','unit','status'}, ...
    options.VariableNames, 'stable');
options = setvartype(options, text_columns, 'string');
keypoints = readtable(path_now, options);
end

function value = keypoint_integer_local(keypoints, metric)
selected = keypoints(string(keypoints.metric) == string(metric), :);
if height(selected) ~= 1
    error('build_stage7_memory_contract_audit:Keypoint', ...
        'Expected one Stage 7 keypoint for %s.', metric);
end
value = str2double(string(selected.value));
if ~positive_integer_local(value) || ~true_flag_local(selected.pass_flag)
    error('build_stage7_memory_contract_audit:KeypointValue', ...
        'Stage 7 keypoint %s is not a passing positive integer.', metric);
end
end

function [actual_calls, charged_calls] = score_call_counts_local(result_dir)
names = ["finite_sample_normal_holdout.csv"; ...
    "finite_sample_threshold_holdout.csv"; ...
    "finite_sample_mismatch_holdout.csv"; ...
    "finite_sample_stress_holdout.csv"];
tables = cell(numel(names), 1);
for index = 1:numel(names)
    tables{index} = readtable(fullfile(result_dir, names(index)), ...
        'TextType', 'string');
end
summary = vertcat(tables{:});
required = {'scenario_id','subset_id','score_calls'};
if ~all(ismember(required, summary.Properties.VariableNames)) || ...
        any(~isfinite(summary.score_calls) | summary.score_calls < 0 | ...
        summary.score_calls ~= fix(summary.score_calls))
    error('build_stage7_memory_contract_audit:ScoreCalls', ...
        'Finite-sample score-call evidence is invalid.');
end
charged_calls = sum(summary.score_calls);
keys = string(summary.scenario_id) + "|" + string(summary.subset_id);
[~, first_index] = unique(keys, 'stable');
actual_calls = sum(summary.score_calls(first_index));
end

function flag = positive_integer_local(value)
flag = isscalar(value) && isfinite(value) && value > 0 && value == fix(value);
end

function flag = true_flag_local(value)
if islogical(value) || isnumeric(value)
    flag = isscalar(value) && isfinite(double(value)) && double(value) == 1;
else
    text_value = lower(string(value));
    flag = isscalar(text_value) && ~ismissing(text_value) && ...
        any(text_value == ["1","true"]);
end
end

function value = existing_dir_local(value)
if isstring(value), value = char(value); end
if ~(ischar(value) && isrow(value) && exist(value, 'dir') == 7)
    error('build_stage7_memory_contract_audit:ResultDir', ...
        'stage7_result_dir must identify an existing directory.');
end
value = char(java.io.File(value).getCanonicalPath());
end
