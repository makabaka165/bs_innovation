        numel(unique(registry.relative_path)) ~= height(registry)
    error('stage7_1_artifact_registry:Duplicate', ...
        'Artifact ids and relative paths must be unique.');
end
if any(registry.self_referential_exclusion_flag & ...
        registry.included_in_deterministic_bundle) || ...
        any(registry.contains_runtime_metadata & ...
        registry.included_in_deterministic_bundle)
    error('stage7_1_artifact_registry:BundleScope', ...
        'Runtime and self-referential artifacts cannot enter the bundle.');
end
