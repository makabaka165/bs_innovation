function row = row_local(id, path_now, type, evidence_class, ...
    bundle_included, self_excluded, runtime_metadata)
row = struct('artifact_id', string(id), ...
    'relative_path', string(path_now), ...
    'artifact_type', string(type), ...
    'evidence_class', string(evidence_class), ...
    'required_by_closure_runner', true, ...
    'included_in_deterministic_bundle', logical(bundle_included), ...
    'self_referential_exclusion_flag', logical(self_excluded), ...
    'contains_runtime_metadata', logical(runtime_metadata));
end
