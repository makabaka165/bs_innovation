metric = ["stage7_1_closure_status";"stage7_status"; ...
    "stage8_technical_permission";"historical_comparison_status"; ...
    "historical_comparison_failed_count"; ...
    "stage7_core_scientific_comparison_status"; ...
    "stage7_diagnostic_variation_count"; ...
    "peak_memory_comparison_status";"peak_memory_delta_bytes"; ...
    "peak_memory_relative_delta"; ...
    "deterministic_memory_contract_status"; ...
    "edge_common_trial_generation_count"; ...
    "edge_method_evaluation_count";"stage7_selection_changed_flag"; ...
    "stage7_1_source_tree_hash";"stage7_1_stable_code_identity_hash"];
value = ["PASS_STAGE7_1_CLOSURE_AUDIT"; ...
    "PASS_SYSTEM_ANALYSIS_ONLY";"false"; ...
    string(historical.comparison_status); ...
    string(historical.failed_comparison_count); ...
    "PASS_STAGE7_CORE_SCIENTIFIC_MATCHES_HISTORICAL_COMMIT"; ...
    string(historical.diagnostic_variation_count); ...
    string(historical.peak_memory_comparison_status); ...
    string(memory.peak_memory_delta_bytes); ...
    string(memory.peak_memory_relative_delta); ...
    "PASS_DETERMINISTIC_MEMORY_CONTRACT"; ...
    string(edge.common_trial_generation_count); ...
    string(edge.method_evaluation_count);"false"; ...
    string(identity.stage7_1_source_tree_hash); ...
    string(identity.stage7_1_stable_code_identity_hash)];
unit = ["status";"status";"boolean";"status";"count"; ...
    "status";"count";"status";"byte";"ratio";"status"; ...
    "count";"count";"boolean";"sha256";"sha256"];
status = ["PASS";"PASS";"NOT_PERMITTED";"PASS";"PASS"; ...
    "PASS";"PASS";"PASS";"PASS";"PASS";"PASS"; ...
    "PASS";"PASS";"PASS";"PASS";"PASS"];
pass_flag = true(numel(metric), 1);
keypoints = table(metric, value, unit, status, pass_flag);
end

