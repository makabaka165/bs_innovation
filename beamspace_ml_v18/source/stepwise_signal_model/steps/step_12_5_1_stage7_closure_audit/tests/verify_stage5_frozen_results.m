function [result_table, context] = verify_list_local(root, names, bytes, hashes)
missing = false(numel(names), 1);
size_mismatch = false(numel(names), 1);
hash_mismatch = false(numel(names), 1);
for index = 1:numel(names)
    path_now = fullfile(root, names(index));
    if exist(path_now, 'file') ~= 2
        missing(index) = true;
        continue;
    end
    info = dir(path_now);
    size_mismatch(index) = info.bytes ~= bytes(index);
    hash_mismatch(index) = ~strcmpi( ...
        stage7_1_sha256_file(path_now), hashes(index));
end
pass_flag = ~(missing | size_mismatch | hash_mismatch);
result_table = table(names, missing, size_mismatch, hash_mismatch, pass_flag);
context = struct('file_count', numel(names), ...
    'hash_mismatch_count', nnz(hash_mismatch), 'pass_flag', all(pass_flag));
end
