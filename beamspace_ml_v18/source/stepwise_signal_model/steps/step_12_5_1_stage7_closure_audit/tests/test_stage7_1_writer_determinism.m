function table_out = test_stage7_1_writer_determinism(repo_dir)
%TEST_STAGE7_1_WRITER_DETERMINISM Exclude runtime HEAD from stable files.

first_root = tempname;
second_root = tempname;
stale_root = tempname;
mkdir(first_root);
mkdir(second_root);
mkdir(stale_root);
first_result_dir = fullfile(first_root, 'results');
second_result_dir = fullfile(second_root, 'results');
stale_result_dir = fullfile(stale_root, 'results');
mkdir(first_result_dir);
mkdir(second_result_dir);
mkdir(stale_result_dir);
write_placeholder_local(fullfile(first_result_dir, '.gitkeep'));
write_placeholder_local(fullfile(second_result_dir, '.gitkeep'));
write_placeholder_local(fullfile(stale_result_dir, 'stale.csv'));
cleanup = onCleanup(@() ...
    remove_temp_local(first_root, second_root, stale_root));
first_bundle = build_stage7_1_writer_fixture(repo_dir);
second_bundle = first_bundle;
second_bundle.identity.runtime_head_commit = repmat('f', 1, 40);
[~, first_manifest, first_evidence] = write_stage7_1_results_bundle( ...
    first_result_dir, first_bundle, ...
    struct('unit_test_mode', true));
[~, second_manifest, second_evidence] = write_stage7_1_results_bundle( ...
    second_result_dir, second_bundle, ...
    struct('unit_test_mode', true));
stale_rejected = throws_local(@() write_stage7_1_results_bundle( ...
    stale_result_dir, first_bundle, struct('unit_test_mode', true)), ...
    'write_stage7_1_results_bundle:ExistingResults');
first_stable = sortrows(first_manifest( ...
    first_manifest.included_in_deterministic_bundle, ...
    {'relative_path','sha256'}), 'relative_path');
second_stable = sortrows(second_manifest( ...
    second_manifest.included_in_deterministic_bundle, ...
    {'relative_path','sha256'}), 'relative_path');
first_provenance = readtable(fullfile(first_root, 'results', ...
    'stage7_1_provenance.csv'), 'TextType', 'string');
second_provenance = readtable(fullfile(second_root, 'results', ...
    'stage7_1_provenance.csv'), 'TextType', 'string');

case_id = ["FAKE_RUNTIME_HEADS_DIFFER"; ...
    "DETERMINISTIC_FILE_HASHES_IDENTICAL"; ...
    "EVIDENCE_BUNDLE_HASH_IDENTICAL"; ...
    "STABLE_IDENTITY_IDENTICAL";"PROVENANCE_RUNTIME_DIFFERS"; ...
    "GITKEEP_PLACEHOLDER_ACCEPTED";"STALE_RESULT_REJECTED"];
pass_flag = [~strcmp(first_bundle.identity.runtime_head_commit, ...
    second_bundle.identity.runtime_head_commit); ...
    isequal(first_stable, second_stable); ...
    first_evidence.stage7_1_evidence_bundle_hash == ...
    second_evidence.stage7_1_evidence_bundle_hash; ...
    first_evidence.stage7_1_stable_code_identity_hash == ...
    second_evidence.stage7_1_stable_code_identity_hash; ...
    first_provenance.runtime_head_commit ~= ...
    second_provenance.runtime_head_commit; ...
    exist(fullfile(first_result_dir, '.gitkeep'), 'file') == 2 && ...
    exist(fullfile(first_result_dir, 'stage7_1_keypoints.csv'), 'file') == 2; ...
    stale_rejected];
table_out = table(case_id, pass_flag);
assert(all(pass_flag), 'test_stage7_1_writer_determinism:Failed', ...
    'Runtime metadata changed deterministic Stage7.1 artifacts.');
clear cleanup
end

function write_placeholder_local(path_now)
fid = fopen(path_now, 'wt');
if fid < 0
    error('test_stage7_1_writer_determinism:Fixture', ...
        'Unable to create a writer fixture file.');
end
fclose(fid);
end

function flag = throws_local(action, expected_identifier)
flag = false;
try
    action();
catch exception
    flag = strcmp(exception.identifier, expected_identifier);
end
end

function remove_temp_local(first, second, stale)
if exist(first, 'dir') == 7, rmdir(first, 's'); end
if exist(second, 'dir') == 7, rmdir(second, 's'); end
if exist(stale, 'dir') == 7, rmdir(stale, 's'); end
end
