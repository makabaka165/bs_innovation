function table_out = test_method_subset_alias_detection(result_dir)
%TEST_METHOD_SUBSET_ALIAS_DETECTION Verify duplicate physical labels.

aliases = build_stage7_method_subset_alias_table(result_dir);
stage6 = aliases(aliases.method_id == "STAGE6_CENTER_3X3", :);
fixed3 = aliases(aliases.method_id == "FIXED_RECT_3X3", :);
fixed35 = aliases(aliases.method_id == "FIXED_RECT_3X5", :);
exact = aliases(aliases.method_id == "EXACT_ETA_080", :);
required_status = "IDENTICAL_PHYSICAL_SUBSET_NOT_INDEPENDENT_METHOD";

case_id = ["METHOD_COUNT";"UNIQUE_SUBSET_COUNT"; ...
    "STAGE6_FIXED3_SUBSET";"STAGE6_FIXED3_HASH"; ...
    "STAGE6_FIXED3_STATUS";"FIXED35_EXACT_SUBSET"; ...
    "FIXED35_EXACT_HASH";"FIXED35_EXACT_STATUS"; ...
    "PRIMARY_LABELS"];
pass_flag = [height(aliases) == 9; ...
    numel(unique(aliases.physical_subset_hash)) == 7; ...
    stage6.subset_id == fixed3.subset_id; ...
    stage6.physical_subset_hash == fixed3.physical_subset_hash; ...
    stage6.comparison_independence_status == required_status && ...
    fixed3.comparison_independence_status == required_status; ...
    fixed35.subset_id == exact.subset_id; ...
    fixed35.physical_subset_hash == exact.physical_subset_hash; ...
    fixed35.comparison_independence_status == required_status && ...
    exact.comparison_independence_status == required_status; ...
    stage6.primary_label == "FIXED_RECT_3X3" && ...
    fixed3.primary_label == "FIXED_RECT_3X3" && ...
    fixed35.primary_label == "FIXED_RECT_3X5" && ...
    exact.primary_label == "FIXED_RECT_3X5"];
table_out = table(case_id, pass_flag);
assert(all(pass_flag), 'test_method_subset_alias_detection:Failed', ...
    'Method-to-physical-subset alias detection failed.');
end
