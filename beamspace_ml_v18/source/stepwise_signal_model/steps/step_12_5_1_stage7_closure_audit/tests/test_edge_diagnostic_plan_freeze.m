function table_out = test_edge_diagnostic_plan_freeze(result_dir)
%TEST_EDGE_DIAGNOSTIC_PLAN_FREEZE Verify fixed IDs, methods, seeds, and hash.

[plan, plan_hash] = build_stage7_1_edge_diagnostic_plan(result_dir);
[plan_again, hash_again] = build_stage7_1_edge_diagnostic_plan(result_dir);
expected_scenarios = ["D0318";"V0014";"H0057"; ...
    "D0286";"V0050";"H0230"];
expected_methods = ["FIXED_RECT_3X5";"GREEDY_ETA_080"; ...
    "FULL_PARENT_5X5"];
expected_subsets = ["RECT_E14_A31";"RECT_E28_A31";"RECT_E31_A31"];
expected_hash = ...
    "c4f333cf74dcb2a0b2f2f4b07e01e6a7bec687d408527c3d2e357acd1201b307";
fprintf('Stage7.1 edge diagnostic plan hash: %s\n', plan_hash);

case_id = ["ROW_COUNT";"SCENARIO_IDS";"METHOD_IDS";"SUBSET_IDS"; ...
    "SNR_GRID";"NMC";"SEED_BASE";"PAIRED_GROUP_COUNT"; ...
    "PAIRED_SEED_COUNT";"COMMON_TRIAL_STATUS";"STATUS"; ...
    "D0286_PARAMETERS_PRESERVED";"D0286_TOLERANT_GATE"; ...
    "DETERMINISTIC";"FROZEN_HASH"];
d0286 = plan(plan.scenario_id == "D0286", :);
pass_flag = [height(plan) == 54; ...
    isequal(unique(plan.scenario_id, 'stable'), expected_scenarios); ...
    all(ismember(expected_methods, unique(plan.method_id))); ...
    all(ismember(expected_subsets, unique(plan.subset_id))); ...
    isequal(unique(plan.element_snr_db).', [0,5,10]); ...
    all(plan.Nmc == 200);all(plan.seed_base == 20260719); ...
    numel(unique(plan.paired_group_id)) == 18; ...
    numel(unique(plan.seed)) == 18; ...
    all(plan.common_trial_generation_status == ...
    "GENERATE_ELEMENT_DOMAIN_TRIAL_ONCE_THEN_APPLY_THREE_PHYSICAL_SUBSETS"); ...
    all(plan.diagnostic_status == ...
    "POST_HOC_EDGE_SENSITIVITY_NOT_USED_FOR_SELECTION"); ...
    height(d0286) == 9 && all(d0286.registered_domain_pass == 0) && ...
    all(d0286.center_az_deg == 7.6) && all(d0286.separation_deg == 0.4); ...
    all(~d0286.historical_registered_domain_pass) && ...
    all(d0286.tolerant_registered_domain_pass) && ...
    all(d0286.boundary_numeric_disagreement_flag) && ...
    all(d0286.edge_diagnostic_domain_pass); ...
    isequaln(plan, plan_again) && strcmp(plan_hash, hash_again); ...
    string(plan_hash) == expected_hash];
table_out = table(case_id, pass_flag);
assert(all(pass_flag), 'test_edge_diagnostic_plan_freeze:Failed', ...
    'Frozen Stage7.1 edge diagnostic plan failed.');
end
