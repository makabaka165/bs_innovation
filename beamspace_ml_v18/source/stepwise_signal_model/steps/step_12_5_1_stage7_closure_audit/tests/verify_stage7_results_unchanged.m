function table_out = verify_stage7_results_unchanged(repo_dir)
%VERIFY_STAGE7_RESULTS_UNCHANGED Confirm frozen results and figures are clean.

stage7_root = ['beamspace_ml_v18/source/stepwise_signal_model/steps/', ...
    'step_12_5_exact_subset_fim_beam_design'];
result_scope = [stage7_root, '/results'];
figure_scope = [stage7_root, '/figures'];
[result_status, result_text] = git_status_local(repo_dir, result_scope);
[figure_status, figure_text] = git_status_local(repo_dir, figure_scope);
result_count = tracked_count_local(repo_dir, [result_scope, '/*']);
figure_count = tracked_count_local(repo_dir, [figure_scope, '/*']);

registry = readtable(fullfile(repo_dir, strrep(result_scope, '/', filesep), ...
    'stage7_plan_registry.csv'), 'TextType', 'string');
plan_hash = registry.registry_value( ...
    registry.registry_key == "stage7_plan_hash");
source_hash = registry.registry_value( ...
    registry.registry_key == "stage7_source_tree_hash");

case_id = ["RESULT_STATUS_COMMAND";"FIGURE_STATUS_COMMAND"; ...
    "RESULT_MODIFICATION_COUNT_ZERO";"FIGURE_MODIFICATION_COUNT_ZERO"; ...
    "RESULT_FILE_COUNT";"FIGURE_FILE_COUNT";"FROZEN_PLAN_HASH"; ...
    "FROZEN_SOURCE_HASH"];
pass_flag = [result_status == 0;figure_status == 0; ...
    isempty(strtrim(result_text));isempty(strtrim(figure_text)); ...
    result_count == 28;figure_count == 8; ...
    plan_hash == ...
    "e630a084e68108a1604527afe7a81db7150b045454b3f54b05e6cfd389259a3b"; ...
    source_hash == ...
    "2b3f71fcb63d2393cf0f49ab4e3583628c564a9d8d72525b74a05e83bbe30482"];
table_out = table(case_id, pass_flag);
assert(all(pass_flag), 'verify_stage7_results_unchanged:Failed', ...
    'Frozen Stage 7 results or figures changed.');
end

function [status, output] = git_status_local(repo_dir, scope)
command = sprintf(['git -C "%s" status --porcelain=v1 ', ...
    '--untracked-files=all -- "%s"'], repo_dir, scope);
[status, output] = system(command);
end

function count = tracked_count_local(repo_dir, scope)
[status, output] = system(sprintf( ...
    'git -C "%s" ls-files -- "%s"', repo_dir, scope));
if status ~= 0
    error('verify_stage7_results_unchanged:Git', ...
        'Unable to enumerate tracked Stage 7 evidence.');
end
lines = splitlines(string(regexprep(output, '[\r\n]+$', '')));
lines(lines == "") = [];
count = numel(lines);
end
