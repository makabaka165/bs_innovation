function table_out = test_stage7_1_artifact_registry()
%TEST_STAGE7_1_ARTIFACT_REGISTRY Freeze formal output paths and classes.

registry = stage7_1_artifact_registry();
required_paths = [ ...
    "results/stage7_1_provenance.csv"; ...
    "results/stage7_1_source_manifest.csv"; ...
    "results/stage7_core_historical_comparison.csv"; ...
    "results/sequential_3by5_semantics.md"; ...
    "results/method_subset_aliases.csv"; ...
    "results/minimum_cost_feasible_3by5.csv"; ...
    "results/same_cost_dominance.csv"; ...
    "results/existing_method_pareto_sensitivity.csv"; ...
    "results/complexity_accounting_correction.csv"; ...
    "results/edge_diagnostic_plan.csv"; ...
    "results/edge_diagnostic_trials.csv"; ...
    "results/edge_diagnostic_summary.csv"; ...
    "results/stage7_1_evidence_manifest.csv"; ...
    "results/stage7_1_keypoints.csv"; ...
    "results/stage7_1_closure_report.md"];
manifest = registry.artifact_id == "stage7_1_evidence_manifest";
runtime = registry.contains_runtime_metadata;

case_id = ["REGISTRY_ROW_COUNT_16";"FORMAL_PATHS_PRESENT"; ...
    "PATHS_UNIQUE";"DETERMINISTIC_ARTIFACT_COUNT_13"; ...
    "MANIFEST_EXCLUDES_SELF";"RUNTIME_EXCLUDED"; ...
    "NO_FIGURES"];
pass_flag = [height(registry) == 16; ...
    all(ismember(required_paths, registry.relative_path)); ...
    numel(unique(registry.relative_path)) == height(registry); ...
    nnz(registry.included_in_deterministic_bundle) == 13; ...
    nnz(manifest) == 1 && ...
    registry.self_referential_exclusion_flag(manifest) && ...
    ~registry.included_in_deterministic_bundle(manifest); ...
    all(~registry.included_in_deterministic_bundle(runtime)); ...
    ~any(endsWith(lower(registry.relative_path), '.png'))];
table_out = table(case_id, pass_flag);
assert(all(pass_flag), 'test_stage7_1_artifact_registry:Failed', ...
    'The fixed Stage7.1 artifact registry changed.');
end
