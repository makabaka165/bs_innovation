function output = run_stage7_1_edge_diagnostics(repo_dir, opts)
%RUN_STAGE7_1_EDGE_DIAGNOSTICS Execute paired post-hoc edge diagnostics.

if nargin < 2 || isempty(opts), opts = struct(); end
opts = normalize_options_local(opts);
repo_dir = existing_dir_local(repo_dir, 'repo_dir');
step_dir = fileparts(mfilename('fullpath'));
steps_dir = fileparts(step_dir);
stage7_dir = fullfile(steps_dir, 'step_12_5_exact_subset_fim_beam_design');
stage7_result_dir = fullfile(stage7_dir, 'results');
old_path = path;
addpath(fullfile(step_dir, 'common'));
addpath(fullfile(stage7_dir, 'common'));
path_cleanup = onCleanup(@() path(old_path));

identity = build_stage7_1_code_identity(repo_dir, ...
    struct('formal_mode', ~opts.unit_test_mode));
if isempty(opts.edge_plan)
    [edge_plan, edge_plan_hash] = ...
        build_stage7_1_edge_diagnostic_plan(stage7_result_dir);
else
    edge_plan = opts.edge_plan;
    edge_plan_hash = stage7_stable_hash(edge_plan, ...
        'UNIT_TEST_EDGE_PLAN_OVERRIDE');
end
if isempty(opts.execution_context)
    execution = build_stage7_1_execution_context( ...
        repo_dir, stage7_dir, stage7_result_dir);
else
    execution = opts.execution_context;
end
groups = validate_plan_local(edge_plan, opts.unit_test_mode);

trial_cells = cell(sum(groups.paired_trial_count) * 3, 1);
runtime_cells = cell(size(trial_cells));
row_index = 0;
common_trial_generation_count = 0;
for group_index = 1:height(groups)
    selected = edge_plan(string(edge_plan.paired_group_id) == ...
        string(groups.paired_group_id(group_index)), :);
    for trial_index = 1:groups.paired_trial_count(group_index)
        if isempty(opts.common_trial_generator)
            trial = generate_stage7_1_common_edge_trial( ...
                selected(1, :), trial_index, execution, struct());
        else
            trial = opts.common_trial_generator( ...
                selected(1, :), trial_index, execution);
        end
        common_trial_generation_count = common_trial_generation_count + 1;
        expected_seed = groups.group_seed_start(group_index) + ...
            trial_index - 1;
        if trial.trial_seed ~= expected_seed || ...
                string(trial.paired_group_id) ~= ...
                string(groups.paired_group_id(group_index))
            error('run_stage7_1_edge_diagnostics:TrialIdentity', ...
                'A common trial did not preserve its frozen seed identity.');
        end
        if isempty(opts.method_evaluator)
            models = method_models_local(execution.finite, selected);
            [rows, runtime_rows] = evaluate_stage7_1_edge_methods( ...
                trial, models, execution.finite, selected, struct());
        else
            [rows, runtime_rows] = opts.method_evaluator( ...
                trial, selected, execution);
        end
        validate_method_rows_local(rows, trial);
        for method_index = 1:3
            row_index = row_index + 1;
            trial_cells{row_index} = table2struct(rows(method_index, :));
            runtime_cells{row_index} = ...
                table2struct(runtime_rows(method_index, :));
        end
    end
end
trials = struct2table(vertcat(trial_cells{:}));
runtime_diagnostics = struct2table(vertcat(runtime_cells{:}));
summary = summarize_edge_trials_local(trials);
common_seeds = unique(trials(:, ...
    {'paired_group_id','trial_index','trial_seed'}), 'rows');
method_evaluation_count = height(trials);
if common_trial_generation_count ~= height(common_seeds) || ...
        method_evaluation_count ~= 3 * height(common_seeds)
    error('run_stage7_1_edge_diagnostics:ExecutionCount', ...
        'Common trial and method evaluation counts are inconsistent.');
end
if ~opts.unit_test_mode && ...
        (common_trial_generation_count ~= 3600 || ...
        method_evaluation_count ~= 10800)
    error('run_stage7_1_edge_diagnostics:FormalCount', ...
        'Formal edge diagnostics require 3600 common trials and 10800 rows.');
end

output = struct();
output.identity = identity;
output.edge_plan = edge_plan;
output.edge_plan_hash = char(edge_plan_hash);
output.trials = trials;
output.summary = summary;
output.runtime_diagnostics = runtime_diagnostics;
output.common_trial_generation_count = common_trial_generation_count;
output.method_evaluation_count = method_evaluation_count;
output.execution_status = ...
    'POST_HOC_EDGE_SENSITIVITY_NOT_USED_FOR_SELECTION';
output.stage7_selection_changed_flag = false;
clear path_cleanup
end

function groups = validate_plan_local(plan, unit_test_mode)
required = {'paired_group_id','paired_group_index','group_seed_start', ...
    'paired_trial_count','method_id','subset_id','element_snr_db'};
if ~(istable(plan) && all(ismember(required, plan.Properties.VariableNames)))
    error('run_stage7_1_edge_diagnostics:PlanSchema', ...
        'The frozen edge plan schema is incomplete.');
end
groups = unique(plan(:, {'paired_group_id','paired_group_index', ...
    'group_seed_start','paired_trial_count'}), 'rows', 'stable');
expected_methods = sort(["FIXED_RECT_3X5";"GREEDY_ETA_080"; ...
    "FULL_PARENT_5X5"]);
for index = 1:height(groups)
    selected = plan(string(plan.paired_group_id) == ...
        string(groups.paired_group_id(index)), :);
    if height(selected) ~= 3 || ...
            ~isequal(sort(selected.method_id), expected_methods) || ...
            numel(unique(selected.group_seed_start)) ~= 1
        error('run_stage7_1_edge_diagnostics:PairedGroup', ...
            'Each paired group must contain the three fixed methods.');
    end
end
if numel(unique(groups.paired_group_index)) ~= height(groups) || ...
        numel(unique(groups.group_seed_start)) ~= height(groups)
    error('run_stage7_1_edge_diagnostics:GroupIdentity', ...
        'Paired group indices and seed starts must be unique.');
end
if ~unit_test_mode && (height(plan) ~= 54 || height(groups) ~= 18 || ...
        any(groups.paired_trial_count ~= 200))
    error('run_stage7_1_edge_diagnostics:FormalPlan', ...
        'Formal edge execution requires the frozen 54-row plan.');
end
end

function models = method_models_local(finite, plan_group)
noise_id = string(plan_group.noise_covariance_id(1));
if noise_id == "WHITE", noise_index = 1; else, noise_index = 2; end
available = finite.method_models{noise_index};
models = repmat(struct('method_id', "", 'subset_id', "", ...
    'channels', [], 'model', struct(), 'G_bank', []), 3, 1);
for index = 1:3
    match = find([available.subset_id] == plan_group.subset_id(index));
    if numel(match) ~= 1
        error('run_stage7_1_edge_diagnostics:MethodModel', ...
            'A frozen edge subset model is missing.');
    end
    models(index) = struct('method_id', plan_group.method_id(index), ...
        'subset_id', plan_group.subset_id(index), ...
        'channels', available(match).channels, ...
        'model', available(match).model, ...
        'G_bank', available(match).G_bank);
end
end

function validate_method_rows_local(rows, trial)
required = {'paired_group_id','trial_index','trial_seed','method_id', ...
    'realized_element_snr_db','target1_az_deg','target1_el_deg', ...
    'target2_az_deg','target2_el_deg'};
if ~(istable(rows) && height(rows) == 3 && ...
        all(ismember(required, rows.Properties.VariableNames)))
    error('run_stage7_1_edge_diagnostics:MethodRows', ...
        'Each common trial must produce exactly three method rows.');
end
shared = {'paired_group_id','trial_index','trial_seed', ...
    'realized_element_snr_db','target1_az_deg','target1_el_deg', ...
    'target2_az_deg','target2_el_deg'};
pass = numel(unique(rows.method_id)) == 3;
for index = 1:numel(shared)
    pass = pass && numel(unique(rows.(shared{index}))) == 1;
end
pass = pass && all(rows.trial_seed == trial.trial_seed);
if ~pass
    error('run_stage7_1_edge_diagnostics:SharedTrial', ...
        'The three method rows do not share one trial realization.');
end
end

function summary = summarize_edge_trials_local(trials)
keys = unique(trials(:, ...
    {'scenario_id','element_snr_db','method_id','subset_id'}), ...
    'rows', 'stable');
rows = cell(height(keys), 1);
for index = 1:height(keys)
    selected = trials(trials.scenario_id == keys.scenario_id(index) & ...
        trials.element_snr_db == keys.element_snr_db(index) & ...
        trials.method_id == keys.method_id(index), :);
    reference = trials(trials.scenario_id == keys.scenario_id(index) & ...
        trials.element_snr_db == keys.element_snr_db(index) & ...
        trials.method_id == "FIXED_RECT_3X5", :);
    selected = sortrows(selected, 'trial_index');
    reference = sortrows(reference, 'trial_index');
    if ~isequal(selected.trial_seed, reference.trial_seed)
        error('run_stage7_1_edge_diagnostics:PairedSummary', ...
            'Edge summary inputs are not paired by trial seed.');
    end
    [success_mean, success_low, success_high] = paired_interval_local( ...
        double(selected.oracle_k_success) - ...
        double(reference.oracle_k_success));
    [error_mean, error_low, error_high] = paired_interval_local( ...
        selected.unconditional_penalized_error - ...
        reference.unconditional_penalized_error);
    [wilson_low, wilson_high] = wilson_local( ...
        nnz(selected.oracle_k_success), height(selected));
    rows{index} = struct('scenario_id', keys.scenario_id(index), ...
        'element_snr_db', keys.element_snr_db(index), ...
        'method_id', keys.method_id(index), ...
        'subset_id', keys.subset_id(index), ...
        'n_trials', height(selected), ...
        'oracle_k_success_rate', mean(selected.oracle_k_success), ...
        'Wilson_95_low', wilson_low, 'Wilson_95_high', wilson_high, ...
        'azimuth_rmse_all_trials', ...
        sqrt(mean(selected.azimuth_error_deg .^ 2)), ...
        'elevation_rmse_all_trials', ...
        sqrt(mean(selected.elevation_error_deg .^ 2)), ...
        'pair_rmse_all_trials', sqrt(mean(selected.pair_error_deg .^ 2)), ...
        'unconditional_penalized_error', ...
        mean(selected.unconditional_penalized_error), ...
        'wrong_local_peak_rate', mean(selected.wrong_local_peak), ...
        'paired_success_difference', success_mean, ...
        'paired_success_difference_95_low', success_low, ...
        'paired_success_difference_95_high', success_high, ...
        'paired_error_difference', error_mean, ...
        'paired_error_difference_95_low', error_low, ...
        'paired_error_difference_95_high', error_high, ...
        'diagnostic_status', ...
        "POST_HOC_EDGE_SENSITIVITY_NOT_USED_FOR_SELECTION");
end
summary = struct2table(vertcat(rows{:}));
end

function [mean_value, low, high] = paired_interval_local(values)
mean_value = mean(values);
if numel(values) <= 1
    low = mean_value;
    high = mean_value;
else
    half_width = 1.95996398454005 * std(values, 0) / sqrt(numel(values));
    low = mean_value - half_width;
    high = mean_value + half_width;
end
end

function [low, high] = wilson_local(success_count, n)
z = 1.95996398454005;
p = success_count / n;
denominator = 1 + z ^ 2 / n;
center = (p + z ^ 2 / (2 * n)) / denominator;
half_width = z * sqrt(p * (1 - p) / n + ...
    z ^ 2 / (4 * n ^ 2)) / denominator;
low = max(0, center - half_width);
high = min(1, center + half_width);
end

function opts = normalize_options_local(opts)
if ~(isstruct(opts) && isscalar(opts))
    error('run_stage7_1_edge_diagnostics:Options', ...
        'opts must be a scalar struct.');
end
allowed = {'unit_test_mode','edge_plan','execution_context', ...
    'common_trial_generator','method_evaluator'};
unknown = setdiff(fieldnames(opts), allowed);
if ~isempty(unknown)
    error('run_stage7_1_edge_diagnostics:UnknownOption', ...
        'Unknown option: %s.', unknown{1});
end
if ~isfield(opts, 'unit_test_mode'), opts.unit_test_mode = false; end
defaults = {'edge_plan','execution_context','common_trial_generator', ...
    'method_evaluator'};
for index = 1:numel(defaults)
    if ~isfield(opts, defaults{index}), opts.(defaults{index}) = []; end
end
if ~(islogical(opts.unit_test_mode) && isscalar(opts.unit_test_mode))
    error('run_stage7_1_edge_diagnostics:OptionValue', ...
        'unit_test_mode must be a logical scalar.');
end
if ~opts.unit_test_mode && (~isempty(opts.edge_plan) || ...
        ~isempty(opts.common_trial_generator) || ...
        ~isempty(opts.method_evaluator))
    error('run_stage7_1_edge_diagnostics:TestOverride', ...
        'Plan and callback overrides are restricted to unit-test mode.');
end
if ~isempty(opts.common_trial_generator) && ...
        ~isa(opts.common_trial_generator, 'function_handle') || ...
        ~isempty(opts.method_evaluator) && ...
        ~isa(opts.method_evaluator, 'function_handle')
    error('run_stage7_1_edge_diagnostics:Callback', ...
        'Edge fixture callbacks must be function handles.');
end
end

function value = existing_dir_local(value, name)
if isstring(value), value = char(value); end
if ~(ischar(value) && isrow(value) && exist(value, 'dir') == 7)
    error('run_stage7_1_edge_diagnostics:Directory', ...
        '%s must identify an existing directory.', name);
end
value = char(java.io.File(value).getCanonicalPath());
end
