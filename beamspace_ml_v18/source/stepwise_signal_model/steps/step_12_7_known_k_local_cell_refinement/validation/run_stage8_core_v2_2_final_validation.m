    result.anchor_is_ancestor = is_ancestor_local(repo_dir, anchor_local());
    result.frozen_paths_clean = frozen_paths_clean_local(repo_dir);
    result.old_runtime_audit = old_runtime_audit_local();
    result.new_evidence_absent = new_evidence_absent_local(repo_dir);
    result.lock_count = numel(dir(fullfile(runtime_root, '**', '*.lock')));
    result.matlab_external_count = external_matlab_count_local();
    result.coordinator_count = coordinator_count_local();
    result.pass = strcmp(result.branch, 'experiment/stage8-core-v2') && ...
        strcmp(result.head, result.origin_head) && ...
        strcmp(result.origin_main, ...
        '247fad2208e77b04f7062e22b0fd3fd8a81bfc1f') && ...
        result.worktree_clean && result.anchor_is_ancestor && ...
        result.frozen_paths_clean && result.old_runtime_audit.pass && ...
        result.new_evidence_absent && result.lock_count == 0 && ...
        result.matlab_external_count == 0 && result.coordinator_count == 0;
    if result.pass
        result.status = 'F0_BOUNDARY_AND_ENVIRONMENT_PASS';
    else
        result.last_error = ['Branch, remote, frozen-path, runtime, process, ' ...
            'or clean-tree check failed.'];
    end
catch exception
    result.last_error = getReport(exception, 'extended', 'hyperlinks', 'off');
end
end

