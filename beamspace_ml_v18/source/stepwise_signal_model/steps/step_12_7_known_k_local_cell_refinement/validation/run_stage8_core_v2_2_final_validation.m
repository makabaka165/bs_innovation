        error('run_stage8_core_v2_2_final_validation:GateAuditPayload', ...
            'Gate audit payload is missing: %s.', specs{index, 1});
    end
    audit = loaded.(specs{index, 2});
    if ~isfield(audit, 'pass') || ~audit.pass || ...
            ~isfield(audit, 'status') || ...
            ~strcmp(audit.status, specs{index, 3})
        error('run_stage8_core_v2_2_final_validation:GateAuditStatus', ...
            'Gate audit is not passing: %s.', specs{index, 1});
