    'f1b_production_regression_audit.mat', 'f1b', ...
    'F1B_PRODUCTION_24_TRIAL_REGRESSION_PASS'};
for index = 1:size(specs, 1)
    path_now = fullfile(runtime_root, specs{index, 1});
    if ~isfile(path_now)
        error('run_stage8_core_v2_2_final_validation:GateAudit', ...
            'Required gate audit is missing: %s.', specs{index, 1});
