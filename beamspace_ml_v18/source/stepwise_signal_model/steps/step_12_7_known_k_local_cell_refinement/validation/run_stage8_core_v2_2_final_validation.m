function hash = file_sha256_local(path_now)
[status, output] = system(sprintf('certutil -hashfile "%s" SHA256', path_now));
tokens = regexp(output, '[0-9A-Fa-f]{64}', 'match');
if status ~= 0 || numel(tokens) ~= 1
    error('run_stage8_core_v2_2_final_validation:FileHash', ...
        'Unable to compute SHA-256 for %s.', path_now);
end
hash = upper(tokens{1});
end

