function output = run_stage8_core_v2_2_final_validation(repo_dir, runtime_root, action)
%RUN_STAGE8_CORE_V2_2_FINAL_VALIDATION Single-process corrected final run.

if nargin < 1 || isempty(repo_dir)
    repo_dir = fileparts(fileparts(fileparts(fileparts(fileparts( ...
        fileparts(fileparts(mfilename('fullpath'))))))));
end
if nargin < 2 || isempty(runtime_root)
    runtime_root = fullfile('E:\bs_innovation_runtime', ...
        'stage8_core_v2_2_single_cpi_known_k_final_f1_oracle_correction_v1');
end
if nargin < 3 || isempty(action), action = 'Status'; end
action = upper(char(string(action)));
repo_dir = canonical_path_local(repo_dir);
runtime_root = canonical_path_local(runtime_root);
reject_old_runtime_local(runtime_root);

switch action
    case 'PREFLIGHT'
        output = f0_local(repo_dir, runtime_root);
    case 'START'
        output = start_local(repo_dir, runtime_root);
    case 'STATUS'
        output = status_local(runtime_root);
    case 'PAUSE'
        validate_protocol_local(runtime_root);
        write_text_local(fullfile(runtime_root, 'pause.request'), 'PAUSE\n');
        output = status_local(runtime_root);
    case 'RESUME'
        protocol = validate_protocol_local(runtime_root);
        pause_path = fullfile(runtime_root, 'pause.request');
        if isfile(pause_path), delete(pause_path); end
        output = resume_local(repo_dir, runtime_root, protocol);
    case 'FINALIZE'
        validate_protocol_local(runtime_root);
        output = finalize_stage8_core_v2_2_final_validation( ...
            repo_dir, runtime_root);
    otherwise
        error('run_stage8_core_v2_2_final_validation:Action', ...
            ['Action must be Preflight, Start, Status, Pause, Resume, ' ...
            'or Finalize.']);
end
end

function output = start_local(repo_dir, runtime_root)
f0 = f0_local(repo_dir, runtime_root);
if ~f0.pass
    save_preflight_failure_audit_local(runtime_root, f0);
    error('run_stage8_core_v2_2_final_validation:F0', ...
        'F0_FAIL_STOPPED: %s', f0.last_error);
end
prepare_new_runtime_local(runtime_root);
save(fullfile(runtime_root, 'f0_audit.mat'), 'f0', '-mat');
try
    f1a = test_f1_canonical_oracle_contract(repo_dir);
catch exception
    f1a = failed_audit_local('F1A_FAIL_STOPPED', exception);
    save(fullfile(runtime_root, 'f1a_oracle_audit.mat'), 'f1a', '-mat');
    rethrow(exception);
end
save(fullfile(runtime_root, 'f1a_oracle_audit.mat'), 'f1a', '-mat');
try
    f1b = test_historical_24_trial_regression(repo_dir);
catch exception
    f1b = failed_audit_local('F1B_FAIL_STOPPED', exception);
    save(fullfile(runtime_root, ...
        'f1b_production_regression_audit.mat'), 'f1b', '-mat');
    rethrow(exception);
end
save(fullfile(runtime_root, ...
    'f1b_production_regression_audit.mat'), 'f1b', '-mat');

context = build_stage8_core_v2_2_validation_context(repo_dir, true);
registry = build_stage8_core_v2_2_final_registry(context.plan.local_domain);
assert_registry_local(registry);
initialize_protocol_local(runtime_root, repo_dir, registry, f0, f1a, f1b);
output = execute_pending_local(context, registry, runtime_root);
end

function output = resume_local(repo_dir, runtime_root, protocol)
current_head = git_local(repo_dir, 'rev-parse HEAD');
if ~strcmp(current_head, protocol.git_head)
    error('run_stage8_core_v2_2_final_validation:ResumeHead', ...
        'Resume requires the exact Start commit.');
end
context = build_stage8_core_v2_2_validation_context(repo_dir, true);
registry = build_stage8_core_v2_2_final_registry(context.plan.local_domain);
assert_registry_local(registry);
actual_hash = registry_hash_local(registry);
if ~strcmp(actual_hash, protocol.registry_contract_hash)
    error('run_stage8_core_v2_2_final_validation:RegistryIdentity', ...
        'The corrected protocol registry identity changed.');
end
output = execute_pending_local(context, registry, runtime_root);
end

function output = execute_pending_local(context, registry, runtime_root)
completed = false(height(registry), 1);
for index = 1:height(registry)
    checkpoint_path = checkpoint_path_local( ...
        runtime_root, registry.trial_id(index));
    if isfile(checkpoint_path)
        validate_checkpoint_local(checkpoint_path, registry(index, :));
        completed(index) = true;
    end
end
for index = 1:height(registry)
    if completed(index), continue; end
    if isfile(fullfile(runtime_root, 'pause.request'))
        break;
    end
    spec = registry(index, :);
    trial = generate_stage8_core_v2_2_trial(spec, context);
    lite = estimate_stage8_known_k_local_cell( ...
        trial.Y_element, trial.model, context.plan.local_domain, ...
        context.stage5_locked, trial.model.noise_factorization, spec.K, ...
        struct('mode', 'CORE_LITE'));
    plus = estimate_stage8_known_k_local_cell( ...
        trial.Y_element, trial.model, context.plan.local_domain, ...
        context.stage5_locked, trial.model.noise_factorization, spec.K, ...
        struct('mode', 'CORE_PLUS'));
    if spec.K == 1
        assert_same_k1_local(lite, plus);
    end
    checkpoint = struct('trial_id', char(spec.trial_id), ...
        'global_trial_index', double(spec.global_trial_index), ...
        'K', double(spec.K), 'element_trial_hash', trial.element_trial_hash, ...
        'spec', spec, 'trial', trial, 'core_lite', lite, ...
        'core_plus', plus, 'completion_status', 'COMPLETE_PASS');
    checkpoint_path = checkpoint_path_local(runtime_root, spec.trial_id);
    tmp_path = fullfile(runtime_root, 'tmp', ...
        [char(string(spec.trial_id)), '.mat.tmp']);
    if isfile(tmp_path)
        error('run_stage8_core_v2_2_final_validation:StaleTmp', ...
            'A stale temporary checkpoint exists for %s.', spec.trial_id);
    end
    save(tmp_path, 'checkpoint', '-mat');
    validate_checkpoint_local(tmp_path, spec);
    if isfile(checkpoint_path)
        error('run_stage8_core_v2_2_final_validation:Collision', ...
            'A completed checkpoint appeared while processing %s.', ...
            spec.trial_id);
    end
    [moved, message] = movefile(tmp_path, checkpoint_path);
    if ~moved
        error('run_stage8_core_v2_2_final_validation:AtomicMove', '%s', message);
    end
    validate_checkpoint_local(checkpoint_path, spec);
    completed(index) = true;
end
output = status_local(runtime_root);
output.completed_trial_count = nnz(completed);
output.remaining_trial_count = height(registry) - nnz(completed);
end

