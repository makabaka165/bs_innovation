function count = external_matlab_count_local()
pid = feature('getpid');
command = sprintf(['powershell -NoProfile -Command "$all = @(' ...
    'Get-CimInstance Win32_Process); $excluded = @(%d); ' ...
    '$cursor = $all | Where-Object { $_.ProcessId -eq %d }; ' ...
    'while ($null -ne $cursor -and $cursor.ParentProcessId -gt 0) { ' ...
    '$parentId = $cursor.ParentProcessId; $excluded += $parentId; ' ...
    '$cursor = $all | Where-Object { $_.ProcessId -eq $parentId } }; ' ...
    '$items = @($all | Where-Object { $_.Name -match ''^MATLAB'' -and ' ...
    '$_.ProcessId -notin $excluded }); $items.Count"'], pid, pid);
[status, output] = system(command);
if status ~= 0 || ~isfinite(str2double(strtrim(output)))
    error('run_stage8_core_v2_2_final_validation:MatlabProcessAudit', ...
        'Unable to audit external MATLAB processes.');
end
count = str2double(strtrim(output));
end

