function protocol = validate_protocol_local(runtime_root)
path_now = fullfile(runtime_root, 'protocol.mat');
if ~isfile(path_now)
    error('run_stage8_core_v2_2_final_validation:ProtocolMissing', ...
        'The corrected Start-created protocol is required.');
end
loaded = load(path_now, 'protocol', '-mat');
required = {'protocol_version','runtime_root','f0_status','f1a_status', ...
    'f1b_status','trial_count','k1_trial_count','k2_trial_count', ...
    'result_row_count','registry_contract_hash','git_head'};
if ~isfield(loaded, 'protocol') || ...
        ~all(isfield(loaded.protocol, required))
    error('run_stage8_core_v2_2_final_validation:ProtocolPayload', ...
        'The corrected protocol payload is incomplete.');
end
protocol = loaded.protocol;
valid = strcmp(protocol.protocol_version, protocol_version_local()) && ...
    strcmp(canonical_path_local(protocol.runtime_root), runtime_root) && ...
    strcmp(protocol.f0_status, 'F0_BOUNDARY_AND_ENVIRONMENT_PASS') && ...
    strcmp(protocol.f1a_status, 'F1A_CANONICAL_ORACLE_CONTRACT_PASS') && ...
    strcmp(protocol.f1b_status, ...
    'F1B_PRODUCTION_24_TRIAL_REGRESSION_PASS') && ...
    protocol.trial_count == 144 && protocol.k1_trial_count == 72 && ...
    protocol.k2_trial_count == 72 && protocol.result_row_count == 288;
if ~valid
    error('run_stage8_core_v2_2_final_validation:ProtocolIdentity', ...
        'Runtime protocol is not the corrected V1 identity.');
end
validate_gate_audits_local(runtime_root);
end

