fprintf(fid, '- Noncanonical H2 K1 difference trials: `%d`\n', ...
    f1a.h1_h2_k1_difference_count);
fprintf(fid, '- Scientific H1/H2 K1 difference trials: `%d`\n\n', ...
    f1a.h1_h2_k1_scientific_difference_count);
