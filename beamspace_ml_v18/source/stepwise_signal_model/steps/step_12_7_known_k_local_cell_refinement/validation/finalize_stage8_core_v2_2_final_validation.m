lite_complexity = output.complexity(output.complexity.mode == "CORE_LITE", :);
plus_complexity = output.complexity(output.complexity.mode == "CORE_PLUS", :);
trials = output.trials;
k2_plus = trials(trials.K == 2 & trials.mode == "CORE_PLUS", :);
