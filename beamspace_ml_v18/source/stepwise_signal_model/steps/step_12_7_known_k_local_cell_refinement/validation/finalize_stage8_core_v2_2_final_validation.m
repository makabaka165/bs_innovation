    subset = k2_plus(k2_plus.profile_id == profile_ids(index), :);
    fprintf(fid, '- K2 profile `%s` median RMSE: `%.17g deg`\n', ...
        char(profile_ids(index)), median(subset.joint_rmse_deg));
