    f1b.k1_mode_identity_match_count, ...
    f1b.k1_mode_identity_expected_count);
fprintf(fid, '- K1 H1 canonical: `%d/%d`\n', ...
    f1b.k1_h1_canonical_match_count, ...
    f1b.k1_h1_canonical_expected_count);
