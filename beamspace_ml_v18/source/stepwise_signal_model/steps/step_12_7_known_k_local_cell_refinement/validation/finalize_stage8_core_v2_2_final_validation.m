    row.k1_off_grid_median_rmse_deg, row.k1_off_grid_p90_rmse_deg);
fprintf(fid, '- K1 paired wins/ties/losses: `%d/%d/%d`\n', ...
    row.k1_wins, row.k1_ties, row.k1_losses);
