fprintf(fid, 'KNOWN_K_CONDITIONAL_ESTIMATION\nNO_TRACKING_INPUT\n');
fprintf(fid, 'NO_CROSS_CPI_INPUT\nNO_MODEL_ORDER_CLAIM\n');
fprintf(fid, 'NO_FORMAL_STAGE8_1_PASS\nNO_STAGE8_2_AUTHORIZATION\n\n');
