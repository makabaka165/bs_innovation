    audit.k1_checkpoint_count, audit.k2_checkpoint_count, ...
    audit.result_row_count);

fprintf(fid, '## CORE_LITE\n\n');
fprintf(fid, '- Valid: K1 `%d/72`, K2 `%d/72`\n', ...
    row.k1_core_lite_valid, row.k2_core_lite_valid);
fprintf(fid, '- K1 overall median/p90 RMSE: `%.17g / %.17g deg`\n', ...
    row.k1_median_rmse_deg, row.k1_p90_rmse_deg);
