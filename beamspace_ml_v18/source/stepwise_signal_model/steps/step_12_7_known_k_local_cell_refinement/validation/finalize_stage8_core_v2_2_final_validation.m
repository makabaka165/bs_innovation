function output = finalize_stage8_core_v2_2_final_validation(repo_dir, runtime_root)
%FINALIZE_STAGE8_CORE_V2_2_FINAL_VALIDATION Write corrected final evidence.

if isfile(fullfile(runtime_root, 'pause.request'))
    error('finalize_stage8_core_v2_2_final_validation:Pause', ...
        'Finalize is unavailable while a pause is requested.');
end
protocol = validate_protocol_local(runtime_root);
[f0, f1a, f1b] = load_gate_audits_local(runtime_root);
context = build_stage8_core_v2_2_validation_context(repo_dir, true);
registry = build_stage8_core_v2_2_final_registry(context.plan.local_domain);
validate_registry_local(registry, protocol);
checkpoint_audit = validate_checkpoints_local(runtime_root, registry);
targets = target_paths_local(repo_dir);
for index = 1:numel(targets)
    if isfile(targets{index})
        error('finalize_stage8_core_v2_2_final_validation:Overwrite', ...
            'Finalize refuses to overwrite %s.', targets{index});
    end
end

summary = summarize_stage8_core_v2_2_final_validation(runtime_root);
if height(summary.trials) ~= 288 || ...
        ~ismember(summary.decision.final_state, allowed_states_local())
    error('finalize_stage8_core_v2_2_final_validation:Summary', ...
        'The corrected final summary contract failed.');
end
writetable(summary.trials, targets{2});
writetable(summary.summary, targets{3});
writetable(summary.q_analysis, targets{4});
writetable(summary.complexity, targets{5});
write_report_local(targets{1}, summary, protocol, f0, f1a, f1b, ...
    checkpoint_audit);
finalized = struct('protocol', protocol, 'f0', f0, 'f1a', f1a, ...
    'f1b', f1b, 'checkpoint_audit', checkpoint_audit, ...
    'summary', summary, 'target_paths', {targets}, ...
    'finalized_utc', char(datetime('now', 'TimeZone', 'UTC')));
save(fullfile(runtime_root, 'finalized.mat'), 'finalized', '-mat');
output = struct('report_path', targets{1}, 'trials_path', targets{2}, ...
    'summary_path', targets{3}, 'q_analysis_path', targets{4}, ...
    'complexity_path', targets{5}, 'decision', summary.decision, ...
    'checkpoint_audit', checkpoint_audit);
end

function targets = target_paths_local(repo_dir)
root = fullfile(repo_dir, 'innovation-mining');
targets = { ...
    fullfile(root, ...
    '29_stage8_core_v2_2_corrected_final_single_cpi_known_k_validation.md'), ...
    fullfile(root, ...
    '29_stage8_core_v2_2_corrected_final_single_cpi_known_k_trials.csv'), ...
    fullfile(root, ...
    '29_stage8_core_v2_2_corrected_final_single_cpi_known_k_summary.csv'), ...
    fullfile(root, ...
    '29_stage8_core_v2_2_corrected_final_single_cpi_known_k_q_analysis.csv'), ...
    fullfile(root, ...
    '29_stage8_core_v2_2_corrected_final_single_cpi_known_k_complexity.csv')};
end

function protocol = validate_protocol_local(runtime_root)
path_now = fullfile(runtime_root, 'protocol.mat');
if ~isfile(path_now)
    error('finalize_stage8_core_v2_2_final_validation:ProtocolMissing', ...
        'The corrected protocol is missing.');
end
loaded = load(path_now, 'protocol', '-mat');
required = {'protocol_version','trial_count','k1_trial_count', ...
    'k2_trial_count','result_row_count','f0_status','f1a_status', ...
    'f1b_status','registry_contract_hash','runtime_root'};
if ~isfield(loaded, 'protocol') || ...
        ~all(isfield(loaded.protocol, required))
    error('finalize_stage8_core_v2_2_final_validation:ProtocolPayload', ...
        'The corrected protocol payload is incomplete.');
end
protocol = loaded.protocol;
expected_version = ['STAGE8_CORE_V2_2_SINGLE_CPI_KNOWN_K_FINAL_FREEZE_' ...
    'F1_ORACLE_CORRECTION_V1'];
valid = strcmp(protocol.protocol_version, expected_version) && ...
    strcmp(canonical_path_local(protocol.runtime_root), ...
    canonical_path_local(runtime_root)) && ...
    protocol.trial_count == 144 && protocol.k1_trial_count == 72 && ...
    protocol.k2_trial_count == 72 && protocol.result_row_count == 288 && ...
    strcmp(protocol.f0_status, 'F0_BOUNDARY_AND_ENVIRONMENT_PASS') && ...
    strcmp(protocol.f1a_status, 'F1A_CANONICAL_ORACLE_CONTRACT_PASS') && ...
    strcmp(protocol.f1b_status, ...
    'F1B_PRODUCTION_24_TRIAL_REGRESSION_PASS');
if ~valid
    error('finalize_stage8_core_v2_2_final_validation:ProtocolIdentity', ...
        'The runtime is not the corrected final-freeze protocol.');
end
end

function validate_registry_local(registry, protocol)
valid = istable(registry) && height(registry) == 144 && ...
    nnz(registry.K == 1) == 72 && nnz(registry.K == 2) == 72 && ...
    numel(unique(registry.trial_id)) == 144 && ...
    all(registry.single_cpi_flag) && ...
    all(registry.same_range_doppler_cell_flag) && ...
    ~any(registry.cross_cpi_data_used_flag) && ...
    ~any(registry.tracking_input_used_flag) && ...
    ~any(registry.K_estimated_inside_module_flag);
hash = stage8_core_v2_2_stable_hash( ...
    'STAGE8_CORE_V2_2_FINAL_REGISTRY_V1', table2struct(registry));
if ~valid || ~strcmp(hash, protocol.registry_contract_hash)
    error('finalize_stage8_core_v2_2_final_validation:RegistryIdentity', ...
        'The unchanged final registry identity failed.');
end
end

function [f0, f1a, f1b] = load_gate_audits_local(runtime_root)
f0 = load_audit_local(runtime_root, 'f0_audit.mat', 'f0', ...
    'F0_BOUNDARY_AND_ENVIRONMENT_PASS');
f1a = load_audit_local(runtime_root, 'f1a_oracle_audit.mat', 'f1a', ...
    'F1A_CANONICAL_ORACLE_CONTRACT_PASS');
f1b = load_audit_local(runtime_root, ...
    'f1b_production_regression_audit.mat', 'f1b', ...
    'F1B_PRODUCTION_24_TRIAL_REGRESSION_PASS');
end

function audit = load_audit_local(runtime_root, filename, variable, status)
path_now = fullfile(runtime_root, filename);
if ~isfile(path_now)
    error('finalize_stage8_core_v2_2_final_validation:AuditMissing', ...
        'Required gate audit is missing: %s.', filename);
end
loaded = load(path_now, variable, '-mat');
if ~isfield(loaded, variable)
    error('finalize_stage8_core_v2_2_final_validation:AuditPayload', ...
        'Required gate audit payload is missing: %s.', filename);
end
audit = loaded.(variable);
if ~isfield(audit, 'pass') || ~audit.pass || ...
        ~isfield(audit, 'status') || ~strcmp(audit.status, status)
    error('finalize_stage8_core_v2_2_final_validation:AuditStatus', ...
        'Required gate audit is not passing: %s.', filename);
end
end

function audit = validate_checkpoints_local(runtime_root, registry)
paths = dir(fullfile(runtime_root, 'checkpoints', '*.mat'));
temporary = dir(fullfile(runtime_root, 'tmp', '*'));
temporary = temporary(~[temporary.isdir]);
if numel(paths) ~= 144 || ~isempty(temporary)
    error('finalize_stage8_core_v2_2_final_validation:Completeness', ...
        'Finalize requires 144 checkpoints and zero temporary files.');
end
k1_count = 0;
k2_count = 0;
trial_ids = strings(numel(paths), 1);
element_hashes = strings(numel(paths), 1);
for index = 1:numel(paths)
    loaded = load(fullfile(paths(index).folder, paths(index).name), ...
        'checkpoint', '-mat');
    if ~isfield(loaded, 'checkpoint')
        error('finalize_stage8_core_v2_2_final_validation:CheckpointPayload', ...
            'A checkpoint payload is missing.');
    end
    checkpoint = loaded.checkpoint;
    required = {'trial_id','global_trial_index','K','element_trial_hash', ...
        'spec','trial','core_lite','core_plus','completion_status'};
    spec = registry(registry.trial_id == string(checkpoint.trial_id), :);
    if ~all(isfield(checkpoint, required)) || ...
            height(spec) ~= 1 || ~isequaln(checkpoint.spec, spec) || ...
            checkpoint.global_trial_index ~= spec.global_trial_index || ...
            checkpoint.K ~= spec.K || ...
            ~strcmp(checkpoint.completion_status, 'COMPLETE_PASS') || ...
            ~strcmp(checkpoint.element_trial_hash, ...
            checkpoint.trial.element_trial_hash) || ...
            ~ismember(checkpoint.K, [1, 2])
        error('finalize_stage8_core_v2_2_final_validation:CheckpointContract', ...
            'A checkpoint violates the corrected final contract.');
    end
    validate_result_local(checkpoint.core_lite, checkpoint.K, 'CORE_LITE');
    validate_result_local(checkpoint.core_plus, checkpoint.K, 'CORE_PLUS');
    if checkpoint.K == 1
        assert_same_k1_local(checkpoint.core_lite, checkpoint.core_plus);
    end
    trial_ids(index) = string(checkpoint.trial_id);
    element_hashes(index) = string(checkpoint.element_trial_hash);
    k1_count = k1_count + double(checkpoint.K == 1);
    k2_count = k2_count + double(checkpoint.K == 2);
end
if k1_count ~= 72 || k2_count ~= 72 || ...
        numel(unique(trial_ids)) ~= 144 || ...
        numel(unique(element_hashes)) ~= 144
    error('finalize_stage8_core_v2_2_final_validation:CheckpointShape', ...
        'Checkpoint K blocks or identities are incomplete.');
end
audit = struct('pass', true, 'checkpoint_count', numel(paths), ...
    'k1_checkpoint_count', k1_count, 'k2_checkpoint_count', k2_count, ...
    'result_row_count', 2 * numel(paths), 'tmp_checkpoint_count', 0, ...
    'pause_request_absent', true);
end

function validate_result_local(result, K, mode)
valid = result.K == K && strcmp(result.mode, mode) && ...
    result.single_cpi_flag && ...
    result.same_range_doppler_cell_flag && ...
    ~result.cross_cpi_data_used_flag && ...
    ~result.tracking_input_used_flag && ...
    ~result.K_estimated_inside_module_flag && ...
    ~result.truth_used_in_fit_flag;
if ~valid
    error('finalize_stage8_core_v2_2_final_validation:ResultFlags', ...
        'A final result violates the single-CPI known-K boundary.');
end
end

function value = canonical_path_local(value)
value = char(java.io.File(char(string(value))).getCanonicalPath());
end

function assert_same_k1_local(lite, plus)
same = isequal(num2hex(lite.angles_hat_deg), ...
    num2hex(plus.angles_hat_deg)) && ...
    isequal(num2hex(lite.rss), num2hex(plus.rss)) && ...
    isequal(num2hex(lite.loglik_concentrated), ...
    num2hex(plus.loglik_concentrated)) && ...
    lite.fit_valid == plus.fit_valid && ...
    strcmp(lite.fit_status, plus.fit_status) && ...
    strcmp(lite.selected_source, plus.selected_source) && ...
    strcmp(lite.selected_start_id, plus.selected_start_id) && ...
    strcmp(selected_solver_status_local(lite), ...
    selected_solver_status_local(plus));
if ~same
    error('finalize_stage8_core_v2_2_final_validation:K1ModeIdentity', ...
        'A K1 checkpoint violates CORE_LITE/CORE_PLUS identity.');
end
end

function status = selected_solver_status_local(result)
if strcmp(result.selected_source, 'CONTINUOUS_UPGRADE')
    candidate = result.continuous_candidate;
else
    candidate = result.fixed_grid_candidate;
end
status = char(string(candidate.solver_status));
end

