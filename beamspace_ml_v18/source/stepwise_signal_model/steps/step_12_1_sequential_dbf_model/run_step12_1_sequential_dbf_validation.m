function value = metric_for_scenario_local(T, scenario, variable_name)
row = T.scenario == scenario;
if nnz(row) ~= 1
    error('run_step12_1:ScenarioLookup', 'Expected one row for scenario %s.', scenario);
end
value = T.(variable_name)(row);
end

function write_report_local(path_out, cfg, el_beam_deg, az_beam_deg, ...
    el_condition_deg, array_order_table, equivalence_table, factorized_table, ...
    conditional_table, snapshot_table, dependency_table, noise_table, ...
    noise_info, runtime_sec, overall_pass)
fid = fopen(path_out, 'w');
if fid < 0
    error('run_step12_1:ReportOpen', 'Cannot open report file: %s', path_out);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '---\nphase_factor: 1\nvalidation_status: %s\n', pass_fail_local(overall_pass));
fprintf(fid, 'element_order: elevation_fastest_azimuth_slowest\n---\n\n');
fprintf(fid, '# Step12.1 Strict Sequential DBF Validation\n\n');
fprintf(fid, '## Scope\n\n');
fprintf(fid, ['This report validates only array ordering, elevation-then-azimuth DBF, ', ...
    'equivalent Kronecker weights, the factor-1 full receive manifold, and ', ...
    'white-noise covariance. No DML, grouping, FIM, bootstrap, or model-order ', ...
    'implementation is present.\n\n']);
fprintf(fid, 'The active snapshot generator calls `build_receive_cyl_steering_vec` and does not call legacy echo generators.\n\n');
fprintf(fid, '## Configuration\n\n');
fprintf(fid, '- Array: %d x %d full, %d x %d work subarray.\n', ...
    cfg.arr.Naz, cfg.arr.Nel, cfg.beam.subNaz, cfg.arr.Nel);
fprintf(fid, '- Elevation beams: `%s` deg.\n', vector_text_local(el_beam_deg));
fprintf(fid, '- Azimuth beams: `%s` deg.\n', vector_text_local(az_beam_deg));
fprintf(fid, '- Elevation conditions: `%s` deg.\n', vector_text_local(el_condition_deg));
fprintf(fid, '- Sequential output order: elevation channel fastest, azimuth beam next.\n\n');
fprintf(fid, '## Array-order validation\n\n');
write_table_header_local(fid, {'case','roundtrip error','permutation error','coordinate error','pass'});
for i = 1:height(array_order_table)
    fprintf(fid, '| %s | %.6e | %.6e | %.6e | %d |\n', ...
        char(array_order_table.case_name(i)), array_order_table.relative_roundtrip_error(i), ...
        array_order_table.permutation_relative_error(i), ...
        array_order_table.coordinate_mapping_error(i), array_order_table.pass_flag(i));
end
fprintf(fid, '\n## Staged versus equivalent beam matrix\n\n');
write_table_header_local(fid, {'scenario','staged/direct error','physical manifold error','pass'});
for i = 1:height(equivalence_table)
    fprintf(fid, '| %s | %.6e | %.6e | %d |\n', char(equivalence_table.scenario(i)), ...
        equivalence_table.sequential_direct_relative_error(i), ...
        equivalence_table.physical_manifold_relative_error(i), equivalence_table.pass_flag(i));
end
fprintf(fid, '\nMaximum full/factorized manifold error over %d angles: %.6e.\n\n', ...
    height(factorized_table), max(factorized_table.full_factorized_relative_error));
fprintf(fid, '## Conditional azimuth dependence\n\n');
write_table_header_local(fid, {'el condition (deg)','formula error','change from el=0','independent-model error','pass'});
for i = 1:height(conditional_table)
    fprintf(fid, '| %.6g | %.6e | %.6e | %.6e | %d |\n', ...
        conditional_table.el_condition_deg(i), conditional_table.formula_relative_error(i), ...
        conditional_table.change_from_el0(i), ...
        conditional_table.elevation_independent_model_error(i), conditional_table.pass_flag(i));
end
fprintf(fid, '\n## Active snapshot model and legacy dependency\n\n');
fprintf(fid, '- Factor-1 orthogonal residual: %.6e.\n', snapshot_table.factor1_orthogonal_residual(1));
fprintf(fid, '- Isolated legacy factor-2 orthogonal residual: %.6e.\n', ...
    snapshot_table.legacy_factor2_orthogonal_residual(1));
fprintf(fid, '- Active-source dependency rules passed: %d/%d.\n\n', ...
    nnz(dependency_table.pass_flag), height(dependency_table));
fprintf(fid, '## White-noise covariance\n\n');
write_table_header_local(fid, {'samples','relative covariance error','trace ratio','threshold','pass'});
for i = 1:height(noise_table)
    fprintf(fid, '| %d | %.6e | %.9f | %.6g | %d |\n', noise_table.n_samples(i), ...
        noise_table.relative_covariance_error(i), noise_table.trace_ratio(i), ...
        noise_table.registered_threshold(i), noise_table.pass_flag(i));
end
fprintf(fid, '\n- Maximum sequential/direct white-noise error: %.6e.\n', ...
    noise_info.max_sequential_direct_relative_error);
fprintf(fid, '- Covariance convergence flag: %d.\n\n', noise_info.convergence_flag);
fprintf(fid, '## Result\n\n');
fprintf(fid, '**%s.** Runtime %.6f s. This deterministic/Monte Carlo engineering validation reports no confidence interval.\n', ...
    pass_fail_local(overall_pass), runtime_sec);
clear cleanup;
end

function write_table_header_local(fid, headings)
fprintf(fid, '| %s |\n', strjoin(headings, ' | '));
separators = repmat({'---'}, 1, numel(headings));
fprintf(fid, '| %s |\n', strjoin(separators, ' | '));
end

function text = vector_text_local(values)
text = strtrim(sprintf('%.6g ', values));
end

function text = pass_fail_local(flag)
if flag
    text = 'PASS';
else
    text = 'FAIL';
end
end
