    "factor1_single_target_snapshot", 'sequential_direct_relative_error');
double_error = metric_for_scenario_local(equivalence_table, ...
    "factor1_two_target_snapshot", 'sequential_direct_relative_error');
single_model_error = metric_for_scenario_local(equivalence_table, ...
    "factor1_single_target_snapshot", 'physical_manifold_relative_error');
double_model_error = metric_for_scenario_local(equivalence_table, ...
    "factor1_two_target_snapshot", 'physical_manifold_relative_error');
dependency_violation_count = sum(~dependency_table.pass_flag);
min_conditional_change = min(conditional_table.change_from_el0(2:end));
overall_pass = all(array_order_table.pass_flag) && all(equivalence_table.pass_flag) && ...
    all(factorized_table.pass_flag) && all(conditional_table.pass_flag) && ...
    all(snapshot_table.pass_flag) && all(dependency_table.pass_flag) && ...
    all(noise_table.pass_flag);

metric = ["active_phase_factor"; "array_roundtrip_max_relative_error"; ...
    "array_permutation_max_relative_error"; "coordinate_mapping_max_error"; ...
    "random_complex_sequential_direct_error"; ...
    "single_target_sequential_direct_error"; ...
    "two_target_sequential_direct_error"; ...
    "single_target_physical_manifold_error"; ...
    "two_target_physical_manifold_error"; ...
    "factorized_full_manifold_max_error"; ...
    "factorized_projected_manifold_max_error"; ...
    "conditional_azimuth_formula_max_error"; ...
    "conditional_azimuth_min_nonzero_change"; ...
    "receive_snapshot_factor1_residual"; ...
    "receive_snapshot_legacy_factor2_residual"; ...
    "legacy_dependency_violation_count"; ...
    "noise_sequential_direct_max_error"; ...
    "noise_covariance_final_relative_error"; ...
    "noise_covariance_convergence_flag"; "noise_monte_carlo_samples"; ...
    "dml_score_calls"; "svd_calls"; "multi_start_runs"; ...
    "validation_runtime_sec"; "overall_pass_flag"];
value = [1; max(array_order_table.relative_roundtrip_error); ...
    max(array_order_table.permutation_relative_error); ...
    max(array_order_table.coordinate_mapping_error); random_error; ...
    single_error; double_error; single_model_error; double_model_error; ...
    max(factorized_table.full_factorized_relative_error); ...
    max(factorized_table.projected_relative_error); ...
    max(conditional_table.formula_relative_error); min_conditional_change; ...
    snapshot_table.factor1_orthogonal_residual(1); ...
    snapshot_table.legacy_factor2_orthogonal_residual(1); ...
