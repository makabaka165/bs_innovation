outputs.stress = fullfile(result_dir, 'finite_sample_stress_holdout.csv');
outputs.risk = fullfile(result_dir, 'fim_vs_finite_sample_risk.csv');
outputs.baselines = fullfile(result_dir, 'fim_baseline_reproduction_status.csv');
outputs.online_runtime = fullfile(result_dir, 'online_dbf_runtime.csv');
