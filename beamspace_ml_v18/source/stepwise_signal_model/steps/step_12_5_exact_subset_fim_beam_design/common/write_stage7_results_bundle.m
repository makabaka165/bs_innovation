    'count', ternary_local(data.validation.code_analyzer_count == 0, ...
    'PASS', 'FAIL'), data.validation.code_analyzer_count == 0);
add('scope_violation_count', data.validation.scope_violation_count, ...
    'count', ternary_local(data.validation.scope_violation_count == 0, ...
    'PASS', 'FAIL'), data.validation.scope_violation_count == 0);
add('data_processing_violation_count', ...
    sum(data.enumeration.data_processing_violation_count), 'count', ...
