    'count', 'PASS', true);
add('generalized_eigenvalue_evaluations', ...
    data.complexity.generalized_eigenvalue_evaluations, 'count', 'PASS', true);
add('greedy_add_drop_swap_evaluations', ...
    data.complexity.greedy_candidate_evaluations, 'count', 'PASS', true);
add('finite_sample_DML_score_calls', ...
    data.complexity.finite_sample_DML_score_calls, 'count', 'PASS', true);
add('finite_sample_SVD_calls', data.complexity.finite_sample_SVD_calls, ...
    'count', 'PASS', true);
add('runtime', data.complexity.runtime_sec, 'second', 'PASS', true);
add('peak_memory_estimate', data.complexity.peak_memory_estimate_bytes, ...
    'byte', 'ESTIMATE', true);
