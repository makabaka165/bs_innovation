outputs = struct();
outputs.covariance = fullfile(result_dir, 'subset_covariance_validation.csv');
outputs.formula = fullfile(result_dir, 'fim_formula_validation.csv');
outputs.processing = fullfile(result_dir, 'fim_data_processing_validation.csv');
outputs.tangent = fullfile(result_dir, 'stage6_subset_tangent_consistency.csv');
outputs.enumeration = fullfile(result_dir, 'fim_subset_enumeration.csv');
outputs.pareto = fullfile(result_dir, 'fim_subset_pareto.csv');
outputs.operating = fullfile(result_dir, 'fim_operating_points.csv');
outputs.greedy = fullfile(result_dir, 'fim_greedy_exact_gap.csv');
outputs.validation = fullfile(result_dir, 'fim_subset_validation.csv');
