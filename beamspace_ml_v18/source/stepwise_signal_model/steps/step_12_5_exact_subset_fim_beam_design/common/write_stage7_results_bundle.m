outputs.prior_art = fullfile(result_dir, 'stage7_prior_art_difference.md');
outputs.report = fullfile(result_dir, 'stage7_fim_beam_design_report.md');

covariance = concatenate_tests_local(data.tests, ...
    {'covariance_exact','covariance_mc'});
formula = concatenate_tests_local(data.tests, ...
    {'derivatives','sources','schur','vectorized','permutation', ...
    'coordinates','output_basis','source_scale','retention','no_additive'});
processing = concatenate_tests_local(data.tests, ...
    {'data_processing','nested','parent_ceiling'});
writetable(covariance, outputs.covariance);
writetable(formula, outputs.formula);
writetable(processing, outputs.processing);
writetable(data.tangent, outputs.tangent);
writetable(data.enumeration, outputs.enumeration);
writetable(data.pareto, outputs.pareto);
writetable(data.operating, outputs.operating);
writetable(data.greedy_gap, outputs.greedy);
writetable(data.fim_validation, outputs.validation);
writetable(data.fim_holdout, outputs.holdout);
writetable(data.finite_summary(data.finite_summary.data_split == ...
    "NORMAL_HOLDOUT", :), outputs.normal);
writetable(data.finite_summary(data.finite_summary.data_split == ...
    "THRESHOLD_HOLDOUT", :), outputs.threshold);
writetable(data.finite_summary(data.finite_summary.data_split == ...
    "MISMATCH_HOLDOUT", :), outputs.mismatch);
writetable(data.finite_summary(data.finite_summary.data_split == ...
    "STRESS_HOLDOUT", :), outputs.stress);
writetable(data.risk, outputs.risk);
writetable(data.baseline_status, outputs.baselines);
writetable(data.online_benchmark, outputs.online_runtime);

write_prior_art_local(outputs.prior_art, data);
data.complexity.result_data_volume_bytes = directory_bytes_local(result_dir);
keypoints = keypoints_local(data);
writetable(keypoints, outputs.keypoints);
write_report_local(outputs.report, data, keypoints);
data.complexity.result_data_volume_bytes = directory_bytes_local(result_dir);
keypoints = keypoints_local(data);
writetable(keypoints, outputs.keypoints);
write_report_local(outputs.report, data, keypoints);
end

function combined = concatenate_tests_local(tests, names)
rows = cell(numel(names), 1);
for index = 1:numel(names)
    table_now = tests.(names{index});
    table_now.test_id = repmat(string(names{index}), height(table_now), 1);
    rows{index} = table_now(:, {'test_id','case_id','metric','tolerance','pass_flag'});
end
combined = vertcat(rows{:});
end

function table_out = keypoints_local(data)
metric = strings(0, 1);
value = strings(0, 1);
unit = strings(0, 1);
status = strings(0, 1);
pass_flag = false(0, 1);
    function add(name, item, item_unit, item_status, item_pass)
        metric(end + 1, 1) = string(name);
        value(end + 1, 1) = string(item);
        unit(end + 1, 1) = string(item_unit);
        status(end + 1, 1) = string(item_status);
        pass_flag(end + 1, 1) = logical(item_pass);
    end
add('stage7_status', data.decision.stage_status, 'status', ...
    data.decision.stage_status, true);
add('stage7_plan_hash', data.plan.hashes.stage7_plan_hash, 'sha256', 'PASS', true);
add('stage7_source_tree_hash', data.plan.hashes.stage7_source_tree_hash, ...
    'sha256', 'PASS', true);
