    'count', 'PASS', true);
add('whitener_eigendecompositions', ...
    data.complexity.whitener_eigendecompositions, 'count', 'PASS', true);
add('manifold_evaluations', data.complexity.manifold_evaluations, ...
    'count', 'PASS', true);
