    selected = data.enumeration( ...
        data.enumeration.subset_id == qualified.subset_id(1), :);
    add('selected_output_bytes_complex_double', ...
        selected.output_bytes_complex_double, 'byte', 'PASS', true);
    add('selected_weight_memory_bytes', selected.weight_memory_bytes, ...
        'byte', 'PASS', true);
