    data.plan.hashes.stage6_evidence_bundle_hash, 'sha256', 'PASS', true);
add('candidate_pool_size', 25, 'count', 'PASS', true);
add('admissible_subset_count', 961, 'count', 'PASS', true);
add('evaluated_subset_count', height(data.enumeration), 'count', ...
    ternary_local(height(data.enumeration) == 961, 'PASS', 'FAIL'), ...
    height(data.enumeration) == 961);
add('design_scenario_count', height(data.plan.design_scenarios), 'count', ...
    'PASS', height(data.plan.design_scenarios) == 640);
