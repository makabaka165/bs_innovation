        selected.estimated_data_movement_bytes, 'byte', 'PASS', true);
    add('selected_measured_online_dbf_runtime', ...
        selected.measured_online_dbf_runtime, 'second_per_sample', ...
        'POST_FREEZE_DIAGNOSTIC_NOT_USED_FOR_SELECTION', true);
