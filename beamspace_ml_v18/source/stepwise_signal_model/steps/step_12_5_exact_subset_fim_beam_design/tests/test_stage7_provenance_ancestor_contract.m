function table_out = test_stage7_provenance_ancestor_contract(repo_dir)
%TEST_STAGE7_PROVENANCE_ANCESTOR_CONTRACT Verify ancestry and stable hashes.

baseline = repmat('a', 1, 40);
head_a = repmat('b', 1, 40);
head_b = repmat('c', 1, 40);
origin = repmat('d', 1, 40);
base = struct('origin_main_commit_override', origin, ...
    'git_status_porcelain_override', '', 'enforce_guards', false, ...
    'phase_factor', 1);

equal_opts = base;
equal_opts.runtime_head_commit_override = baseline;
equal_opts.baseline_ancestor_flag_override = true;
equal_case = read_stage7_git_provenance(repo_dir, baseline, equal_opts);

ancestor_opts = base;
ancestor_opts.runtime_head_commit_override = head_a;
ancestor_opts.baseline_ancestor_flag_override = true;
ancestor_case = read_stage7_git_provenance( ...
    repo_dir, baseline, ancestor_opts);

nonancestor_opts = ancestor_opts;
nonancestor_opts.baseline_ancestor_flag_override = false;
nonancestor_case = read_stage7_git_provenance( ...
    repo_dir, baseline, nonancestor_opts);
enforced_opts = nonancestor_opts;
enforced_opts.enforce_guards = true;
guard_failed = false;
try
    read_stage7_git_provenance(repo_dir, baseline, enforced_opts);
catch exception
    guard_failed = strcmp(exception.identifier, ...
        'read_stage7_git_provenance:STAGE7_BASELINE_NOT_ANCESTOR');
end

real_baseline = 'ea1c0320b7ba9639d6d955a1a45037cdc6cfdb31';
real_case = read_stage7_git_provenance(repo_dir, real_baseline, struct( ...
    'git_status_porcelain_override', '', 'enforce_guards', true, ...
    'phase_factor', 1));

inputs = plan_inputs_local(real_baseline);
contract_a = contract_local(repo_dir, inputs, head_a, origin);
contract_b = contract_local(repo_dir, inputs, head_b, origin);
plan_hash_a = plan_hash_local(inputs, contract_a);
plan_hash_b = plan_hash_local(inputs, contract_b);

case_id = ["BASELINE_EQUALS_HEAD";"BASELINE_IS_ANCESTOR"; ...
    "BASELINE_NOT_ANCESTOR";"NONANCESTOR_GUARD"; ...
    "REAL_BASELINE_ANCESTOR";"RUNTIME_HEAD_CHANGED"; ...
    "SOURCE_HASH_STABLE";"DEPENDENCY_HASH_STABLE"; ...
    "PROVENANCE_HASH_EXCLUDES_RUNTIME_HEAD"; ...
    "PLAN_HASH_EXCLUDES_RUNTIME_HEAD"];
pass_flag = [equal_case.baseline_ancestor_flag && ...
    strcmp(equal_case.provenance_status, 'PASS'); ...
    ancestor_case.baseline_ancestor_flag && ...
    ~strcmp(ancestor_case.runtime_head_commit, baseline) && ...
    strcmp(ancestor_case.provenance_status, 'PASS'); ...
    ~nonancestor_case.baseline_ancestor_flag && ...
    strcmp(nonancestor_case.provenance_status, ...
    'STAGE7_BASELINE_NOT_ANCESTOR'); guard_failed; ...
    real_case.baseline_ancestor_flag && ...
    ~strcmp(real_case.runtime_head_commit, real_baseline); ...
    ~strcmp(contract_a.runtime_head_commit, contract_b.runtime_head_commit); ...
    strcmp(contract_a.stage7_source_tree_hash, ...
    contract_b.stage7_source_tree_hash); ...
    strcmp(contract_a.stage7_dependency_tree_hash, ...
    contract_b.stage7_dependency_tree_hash); ...
    strcmp(contract_a.stage7_provenance_hash, ...
    contract_b.stage7_provenance_hash);strcmp(plan_hash_a, plan_hash_b)];
table_out = table(case_id, pass_flag);
assert(all(pass_flag), 'test_stage7_provenance_ancestor_contract:Failed', ...
    'Stage 7 provenance ancestry contract failed.');
end

function digest = plan_hash_local(inputs, contract)
digest = stage7_stable_hash(inputs.baseline_commit, ...
    inputs.stable_plan_hashes, contract.stage7_source_tree_hash, ...
    contract.stage7_dependency_tree_hash, contract.stage7_provenance_hash, ...
    repmat('4', 1, 64), 0.03, 'MATLAB_R2022b');
end

function contract = contract_local(repo_dir, inputs, runtime_head, origin)
git_options = struct('runtime_head_commit_override', runtime_head, ...
    'origin_main_commit_override', origin, ...
    'baseline_ancestor_flag_override', true, ...
    'git_status_porcelain_override', '', 'enforce_guards', true, ...
    'phase_factor', 1);
contract = build_stage7_provenance_contract(repo_dir, inputs, ...
    struct('git_provenance_options', git_options));
end

function inputs = plan_inputs_local(baseline)
stable_plan_hashes = struct( ...
    'stage7_controls_hash', repmat('1', 1, 64), ...
    'stage7_candidate_pool_hash', repmat('2', 1, 64), ...
    'stage7_subset_family_hash', repmat('3', 1, 64));
inputs = struct('baseline_commit', baseline, ...
    'stable_plan_hashes', stable_plan_hashes, ...
    'stage6_evidence_bundle_hash', ...
    '0c1f444603398e03865043af4e4c6e4a414dd15a3cc90e0539b19c56e990c839', ...
    'phase_factor', 1, 'matlab_release_contract', 'MATLAB_R2022b');
end
