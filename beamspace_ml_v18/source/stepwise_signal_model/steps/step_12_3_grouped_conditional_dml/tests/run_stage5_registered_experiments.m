function evidence = run_stage5_registered_experiments(cfg)
%RUN_STAGE5_REGISTERED_EXPERIMENTS Execute locked paired stage-5 experiments.

locked = build_stage5_locked_config();
plan = build_stage5_scenario_plan(cfg);
method_tables = cell(sum([plan.nmc]), 1);
history_tables = cell(sum([plan.nmc]), 1);
conditional_tables = cell(sum([plan.nmc]), 1);
fixture_rows = cell(sum([plan.nmc]), 1);
cursor = 0;
experiment_tic = tic;
for scenario_index = 1:numel(plan)
    fprintf('Stage5 scenario %d/%d: %s, Nmc=%d\n', ...
        scenario_index, numel(plan), plan(scenario_index).name, ...
        plan(scenario_index).nmc);
    for trial_id = 1:plan(scenario_index).nmc
        cursor = cursor + 1;
        spec = plan(scenario_index);
        spec.seed = spec.seed + trial_id - 1;
        fixture_tic = tic;
        fixture = build_stage5_physical_fixture(spec, cfg, locked);
        fixture.fixture_runtime_sec = toc(fixture_tic);
        suite = run_stage5_method_suite(fixture, trial_id);
        method_table = addvars(suite.method_table, ...
            repmat(string(spec.feature_tags), height(suite.method_table), 1), ...
            repmat(spec.noise_sigma, height(suite.method_table), 1), ...
            repmat(size(spec.source_snapshots, 2), height(suite.method_table), 1), ...
            repmat(numel(spec.aperture_index), height(suite.method_table), 1), ...
            'After', 'data_split', 'NewVariableNames', ...
            {'feature_tags','noise_sigma','L','aperture_column_count'});
        method_tables{cursor} = method_table;
        history_tables{cursor} = suite.history_table;
        conditional_tables{cursor} = suite.conditional_table;
        fixture_rows{cursor} = fixture_row_local(fixture, trial_id);
        if mod(trial_id, 25) == 0 || trial_id == spec.nmc
            fprintf('  completed %d/%d trials\n', trial_id, spec.nmc);
        end
    end
end
experiment_runtime_sec = toc(experiment_tic);

trial_table = vertcat(method_tables{:});
history_table = vertcat(history_tables{:});
conditional_table = vertcat(conditional_tables{:});
fixture_table = struct2table(vertcat(fixture_rows{:}));
budget_table = aggregate_budget_local(trial_table);
score_gap_table = trial_table(:, {'scenario','data_split','trial_id', ...
    'method','score','rss','normalized_score_gap_to_local_full', ...
    'success_flag','wrong_local_peak_flag','num_score_eval_total', ...
    'statistical_calibration_status','domain_hash','phase_factor'});
wrong_peak_table = aggregate_wrong_peak_local(trial_table);
holdout = trial_table.data_split == "NORMAL_HOLDOUT" | ...
    trial_table.data_split == "STRESS_HOLDOUT";
offgrid_table = trial_table(holdout & ...
    ~trial_table.truth_on_search_grid_flag, :);
normal_summary = aggregate_split_local(trial_table, 'NORMAL_HOLDOUT');
stress_summary = aggregate_split_local(trial_table, 'STRESS_HOLDOUT');
core_nmc_table = core_nmc_local(trial_table, plan);
pareto = pareto_local(trial_table);

evidence = struct();
evidence.locked = locked;
evidence.plan = plan;
evidence.conditional_table = conditional_table;
evidence.history_table = history_table;
evidence.trial_table = trial_table;
evidence.fixture_table = fixture_table;
evidence.budget_table = budget_table;
evidence.score_gap_table = score_gap_table;
evidence.wrong_peak_table = wrong_peak_table;
evidence.offgrid_table = offgrid_table;
evidence.normal_summary = normal_summary;
evidence.stress_summary = stress_summary;
evidence.core_nmc_table = core_nmc_table;
evidence.pareto = pareto;
evidence.experiment_runtime_sec = experiment_runtime_sec;
end

function row = fixture_row_local(fixture, trial_id)
row = struct('scenario', string(fixture.spec.name), ...
    'data_split', string(fixture.spec.data_split), 'trial_id', trial_id, ...
    'feature_tags', string(fixture.spec.feature_tags), ...
    'K', fixture.K, 'oracle_Q', fixture.Q, ...
    'oracle_Kq', string(vector_text_local(fixture.oracle_Kq)), ...
    'noise_kind', string(fixture.spec.noise_kind), ...
    'noise_sigma', fixture.spec.noise_sigma, ...
    'L', size(fixture.spec.source_snapshots, 2), ...
    'aperture_column_count', numel(fixture.aperture_index), ...
    'stage4_estimate_status', string(fixture.stage4_est.estimate_status), ...
    'stage4_support_status', string(fixture.stage4_est.support_status), ...
    'stage4_estimate_returned_flag', ...
    fixture.stage4_est.estimate_returned_flag, ...
    'stage4_structural_gate_pass_flag', ...
    fixture.stage4_est.structural_gate_pass_flag, ...
    'group_noise_status', string(fixture.noise_model.status), ...
    'group_noise_scale', ...
    string(vector_text_local(fixture.noise_model.group_noise_scale)), ...
    'cross_group_noise_correlation_max', ...
    cross_group_correlation_local(fixture.noise_model), ...
    'row_whitening_error', fixture.whitening_info.row_whitening_error, ...
    'column_whitening_error', fixture.whitening_info.column_whitening_error, ...
    'full_whitening_error', fixture.full_debug.whitening_error, ...
    'fixed_measurement_hash', ...
    string(fixture.full_model.fixed_measurement_hash), ...
    'domain_hash', string(fixture.domain.domain_hash), ...
    'configuration_hash', string(fixture.locked.configuration_hash), ...
    'fixture_runtime_sec', fixture.fixture_runtime_sec, ...
    'statistical_calibration_status', "NOT_CALIBRATED_STAGE5", ...
    'phase_factor', 1);
end

function summary = aggregate_split_local(trial, split)
subset = trial(trial.data_split == string(split), :);
methods = unique(subset.method, 'stable');
rows = cell(numel(methods), 1);
[main_success, direct_success, main_penalty, direct_penalty] = ...
    paired_vectors_local(subset);
[success_difference, success_low, success_high] = ...
    paired_resampling_interval_local( ...
    double(main_success) - double(direct_success), 128001 + sum(double(split)));
[penalty_difference, penalty_low, penalty_high] = ...
    paired_resampling_interval_local( ...
    main_penalty - direct_penalty, 128101 + sum(double(split)));
for idx = 1:numel(methods)
    rows_now = subset.method == methods(idx);
    T = subset(rows_now, :);
    [wilson_low, wilson_high] = wilson_interval_local( ...
        nnz(T.success_flag), height(T));
    rows{idx} = struct('data_split', string(split), ...
        'method', methods(idx), 'n_trials', height(T), ...
        'n_scenarios', numel(unique(T.scenario)), ...
        'joint_success_rate', mean(T.success_flag), ...
        'success_wilson_95_low', wilson_low, ...
        'success_wilson_95_high', wilson_high, ...
        'az_rmse_all_returned', root_mean_square_local(T.az_rmse), ...
        'el_rmse_all_returned', root_mean_square_local(T.el_rmse), ...
        'pair_rmse_all_returned', root_mean_square_local(T.pair_rmse), ...
        'unconditional_penalized_error_mean', ...
        mean(T.unconditional_penalized_pair_error), ...
        'wrong_local_peak_rate', mean(T.wrong_local_peak_flag), ...
        'convergence_rate', mean(T.convergence_flag), ...
        'mean_normalized_score_gap', ...
        mean(T.normalized_score_gap_to_local_full, 'omitnan'), ...
        'mean_runtime_sec', mean(T.runtime_total), ...
        'mean_score_calls', mean(T.num_score_eval_total), ...
        'paired_success_difference_vs_direct', ...
        conditional_value_local(methods(idx), ...
        'MAIN_GROUPED_CONDITIONAL_JOINT', success_difference), ...
        'paired_success_difference_95_low', ...
        conditional_value_local(methods(idx), ...
        'MAIN_GROUPED_CONDITIONAL_JOINT', success_low), ...
        'paired_success_difference_95_high', ...
        conditional_value_local(methods(idx), ...
        'MAIN_GROUPED_CONDITIONAL_JOINT', success_high), ...
        'paired_penalty_difference_vs_direct', ...
        conditional_value_local(methods(idx), ...
        'MAIN_GROUPED_CONDITIONAL_JOINT', penalty_difference), ...
        'paired_penalty_difference_95_low', ...
        conditional_value_local(methods(idx), ...
        'MAIN_GROUPED_CONDITIONAL_JOINT', penalty_low), ...
        'paired_penalty_difference_95_high', ...
        conditional_value_local(methods(idx), ...
        'MAIN_GROUPED_CONDITIONAL_JOINT', penalty_high), ...
        'interval_method', ...
        "Wilson_success_and_paired_performance_resampling", ...
        'statistical_calibration_status', "NOT_CALIBRATED_STAGE5", ...
        'phase_factor', 1);
end
summary = struct2table(vertcat(rows{:}));
end

function budget = aggregate_budget_local(trial)
[group, split, method] = findgroups(trial.data_split, trial.method);
num_trials = splitapply(@numel, trial.num_score_eval_total, group);
mean_score_calls = splitapply(@mean, trial.num_score_eval_total, group);
mean_svd_calls = splitapply(@mean, trial.num_svd_total, group);
mean_eig_calls = splitapply(@mean, trial.num_eig_total, group);
mean_manifold_builds = splitapply(@mean, ...
    trial.num_candidate_manifold_build, group);
mean_iterations = splitapply(@mean, trial.num_iterations, group);
mean_multi_start = splitapply(@mean, trial.num_multi_start, group);
mean_runtime_sec = splitapply(@mean, trial.runtime_total, group);
mean_precompute_sec = splitapply(@mean, trial.precompute_time_sec, group);
mean_online_sec = splitapply(@mean, trial.online_time_sec, group);
max_primary_array_bytes = splitapply(@max, ...
    trial.max_primary_array_bytes, group);
statistical_calibration_status = repmat("NOT_CALIBRATED_STAGE5", ...
    numel(split), 1);
phase_factor = ones(numel(split), 1);
budget = table(split, method, num_trials, mean_score_calls, ...
    mean_svd_calls, mean_eig_calls, mean_manifold_builds, ...
    mean_iterations, mean_multi_start, mean_runtime_sec, ...
    mean_precompute_sec, mean_online_sec, max_primary_array_bytes, ...
    statistical_calibration_status, phase_factor, 'VariableNames', ...
    {'data_split','method','num_trials','mean_score_calls', ...
    'mean_svd_calls','mean_eig_calls','mean_candidate_manifold_builds', ...
    'mean_iterations','mean_multi_start','mean_runtime_sec', ...
    'mean_precompute_sec','mean_online_sec','max_primary_array_bytes', ...
    'statistical_calibration_status','phase_factor'});
end

function summary = aggregate_wrong_peak_local(trial)
[group, split, method] = findgroups(trial.data_split, trial.method);
n_trials = splitapply(@numel, trial.wrong_local_peak_flag, group);
wrong_local_peak_count = splitapply(@nnz, ...
    trial.wrong_local_peak_flag, group);
wrong_local_peak_rate = wrong_local_peak_count ./ n_trials;
unconditional_failure_rate = splitapply( ...
    @(x) mean(~x), trial.success_flag, group);
mean_score_gap = splitapply(@(x) mean(x, 'omitnan'), ...
    trial.normalized_score_gap_to_local_full, group);
statistical_calibration_status = repmat("NOT_CALIBRATED_STAGE5", ...
    numel(split), 1);
phase_factor = ones(numel(split), 1);
summary = table(split, method, n_trials, wrong_local_peak_count, ...
    wrong_local_peak_rate, unconditional_failure_rate, mean_score_gap, ...
    statistical_calibration_status, phase_factor, 'VariableNames', ...
    {'data_split','method','n_trials','wrong_local_peak_count', ...
    'wrong_local_peak_rate','unconditional_failure_rate', ...
    'mean_normalized_score_gap','statistical_calibration_status','phase_factor'});
end

function table_out = core_nmc_local(trial, plan)
core_names = string({plan([plan.nmc] >= 200).name}).';
rows = cell(0, 1);
methods = unique(trial.method, 'stable');
for scenario_index = 1:numel(core_names)
    for method_index = 1:numel(methods)
        selected = trial.scenario == core_names(scenario_index) & ...
            trial.method == methods(method_index);
        rows{end + 1, 1} = struct( ...
            'scenario', core_names(scenario_index), ...
            'method', methods(method_index), ...
            'nmc', nnz(selected), ...
            'paired_noise_realization_flag', true, ...
            'pass_flag', nnz(selected) >= 200, ...
            'statistical_calibration_status', "NOT_CALIBRATED_STAGE5", ...
            'phase_factor', 1); %#ok<AGROW>
    end
end
table_out = struct2table(vertcat(rows{:}));
end

function result = pareto_local(trial)
holdout = trial(trial.data_split == "NORMAL_HOLDOUT" | ...
    trial.data_split == "STRESS_HOLDOUT", :);
[main_success, direct_success, main_penalty, direct_penalty, ...
    main_calls, direct_calls] = paired_vectors_local(holdout);
[difference, low, high] = paired_resampling_interval_local( ...
    double(main_success) - double(direct_success), 128501);
[penalty_difference, penalty_low, penalty_high] = ...
    paired_resampling_interval_local(main_penalty - direct_penalty, 128502);
score_call_reduction = 1 - mean(main_calls) / mean(direct_calls);
scheme1 = low >= -0.02 && score_call_reduction >= 0.20;
scheme2 = mean(main_calls) <= mean(direct_calls) && ...
    (low > 0 || penalty_high < 0);
main = holdout(holdout.method == "MAIN_GROUPED_CONDITIONAL_JOINT", :);
reference = holdout(holdout.method == "LOCAL_FULL_DML_REFERENCE", :);
[main, reference] = align_method_rows_local(main, reference);
reference_call_reduction = 1 - mean(main.num_score_eval_total) / ...
    mean(reference.num_score_eval_total);
result = struct('holdout_trial_count', numel(main_success), ...
    'main_success_rate', mean(main_success), ...
    'direct_success_rate', mean(direct_success), ...
    'paired_success_difference', difference, ...
    'paired_success_difference_95_low', low, ...
    'paired_success_difference_95_high', high, ...
    'paired_penalty_difference', penalty_difference, ...
    'paired_penalty_difference_95_low', penalty_low, ...
    'paired_penalty_difference_95_high', penalty_high, ...
    'score_call_reduction_vs_direct', score_call_reduction, ...
    'score_call_reduction_vs_local_full', reference_call_reduction, ...
    'mean_main_score_gap_to_local_full', ...
    mean(main.normalized_score_gap_to_local_full, 'omitnan'), ...
    'scheme1_complexity_benefit_pass', scheme1, ...
    'scheme2_performance_benefit_pass', scheme2, ...
    'pareto_pass', scheme1 || scheme2, ...
    'interval_method', ...
    'paired_performance_resampling_not_model_order_calibration', ...
    'statistical_calibration_status', 'NOT_CALIBRATED_STAGE5', ...
    'phase_factor', 1);
end

function [main_success, direct_success, main_penalty, direct_penalty, ...
    main_calls, direct_calls] = paired_vectors_local(subset)
main = subset(subset.method == "MAIN_GROUPED_CONDITIONAL_JOINT", :);
direct = subset(subset.method == ...
    "DIRECT_AP_COORDINATE_ASCENT_FIXED_CENTER", :);
[main, direct] = align_method_rows_local(main, direct);
main_success = main.success_flag;
direct_success = direct.success_flag;
main_penalty = main.unconditional_penalized_pair_error;
direct_penalty = direct.unconditional_penalized_pair_error;
main_calls = main.num_score_eval_total;
direct_calls = direct.num_score_eval_total;
end

function [left, right] = align_method_rows_local(left, right)
left = sortrows(left, {'scenario','trial_id'});
right = sortrows(right, {'scenario','trial_id'});
if height(left) ~= height(right) || ...
        any(left.scenario ~= right.scenario) || ...
        any(left.trial_id ~= right.trial_id)
    error('run_stage5_registered_experiments:Pairing', ...
        'Paired method rows are not aligned by scenario and trial.');
end
end

function [estimate, low, high] = paired_resampling_interval_local(values, seed)
values = values(:);
estimate = mean(values);
if numel(values) < 2
    low = NaN;
    high = NaN;
    return;
end
rng(seed, 'twister');
resample_count = 2000;
means = zeros(resample_count, 1);
for idx = 1:resample_count
    selection = randi(numel(values), numel(values), 1);
    means(idx) = mean(values(selection));
end
means = sort(means);
low = percentile_order_local(means, 0.025);
high = percentile_order_local(means, 0.975);
end

function value = percentile_order_local(sorted_values, probability)
index = 1 + (numel(sorted_values) - 1) * probability;
lower_index = floor(index);
upper_index = ceil(index);
fraction = index - lower_index;
value = (1 - fraction) * sorted_values(lower_index) + ...
    fraction * sorted_values(upper_index);
end

function [low, high] = wilson_interval_local(success_count, total_count)
z = 1.959963984540054;
p = success_count / total_count;
denominator = 1 + z ^ 2 / total_count;
center = (p + z ^ 2 / (2 * total_count)) / denominator;
radius = z / denominator * sqrt(p * (1 - p) / total_count + ...
    z ^ 2 / (4 * total_count ^ 2));
low = max(0, center - radius);
high = min(1, center + radius);
end

function value = root_mean_square_local(values)
values = values(isfinite(values));
if isempty(values)
    value = NaN;
else
    value = sqrt(mean(values .^ 2));
end
end

function value = conditional_value_local(method, target, value_if_target)
if method == string(target)
    value = value_if_target;
else
    value = NaN;
end
end

function value = cross_group_correlation_local(model)
if size(model.cross_group_noise_correlation, 1) < 2
    value = 0;
    return;
end
matrix = model.cross_group_noise_correlation;
matrix(1:size(matrix, 1) + 1:end) = 0;
value = max(abs(matrix(:)));
end

function text = vector_text_local(values)
text = strtrim(sprintf('%.12g ', values));
end
