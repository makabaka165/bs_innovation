function [result_table, context] = verify_step11_frozen_results(package_dir)
%VERIFY_STEP11_FROZEN_RESULTS Recheck official hashes for Step11 result files.

manifest_path = fullfile(package_dir, 'FILE_SHA256.csv');
manifest = readtable(manifest_path, 'TextType', 'string');
selected = startsWith(manifest.RelativePath, ...
    "source/stepwise_signal_model/steps/step_11_") & ...
    contains(manifest.RelativePath, "/results_step11_");
frozen = manifest(selected, :);
missing_flag = false(height(frozen), 1);
size_mismatch_flag = false(height(frozen), 1);
hash_mismatch_flag = false(height(frozen), 1);
for idx = 1:height(frozen)
    path_now = fullfile(package_dir, ...
        strrep(char(frozen.RelativePath(idx)), '/', filesep));
    if exist(path_now, 'file') ~= 2
        missing_flag(idx) = true;
        continue;
    end
    file_info = dir(path_now);
    size_mismatch_flag(idx) = file_info.bytes ~= frozen.Bytes(idx);
    actual_hash = sha256_file_local(path_now);
    hash_mismatch_flag(idx) = ...
        ~strcmpi(actual_hash, char(frozen.SHA256(idx)));
end
pass_flag = ~(missing_flag | size_mismatch_flag | hash_mismatch_flag);
phase_factor = ones(height(frozen), 1);
result_table = table(frozen.RelativePath, frozen.Bytes, missing_flag, ...
    size_mismatch_flag, hash_mismatch_flag, pass_flag, phase_factor, ...
    'VariableNames', {'relative_path','expected_bytes','missing_flag', ...
    'size_mismatch_flag','hash_mismatch_flag','pass_flag','phase_factor'});
assert(height(frozen) == 351 && all(pass_flag), ...
    'verify_step11_frozen_results:Failed', ...
    'A frozen Step11 result is missing or differs from its official hash.');
context = struct('manifest_path', manifest_path, ...
    'file_count', height(frozen), ...
    'byte_count', sum(frozen.Bytes), ...
    'missing_count', nnz(missing_flag), ...
    'size_mismatch_count', nnz(size_mismatch_flag), ...
    'hash_mismatch_count', nnz(hash_mismatch_flag), ...
    'pass_flag', all(pass_flag));
end

function digest = sha256_file_local(path_now)
bytes = java.nio.file.Files.readAllBytes( ...
    java.nio.file.Paths.get(path_now, javaArray('java.lang.String', 0)));
md = java.security.MessageDigest.getInstance('SHA-256');
md.update(bytes);
digest_bytes = typecast(md.digest(), 'uint8');
digest = lower(reshape(dec2hex(digest_bytes, 2).', 1, []));
end
