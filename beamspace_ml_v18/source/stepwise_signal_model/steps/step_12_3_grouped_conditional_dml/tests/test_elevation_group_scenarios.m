    data = fixture.element_data;
    row_error = fixture.element_whitening_info.whitening_error;
else
    data = fixture.data;
    row_error = fixture.row_whitening_error;
end
row = struct();
row.scenario = string(fixture.scenario);
row.fixture_kind = string(fixture.fixture_kind);
row.method = string(method);
row.search_reference = string(search_reference);
row.K = fixture.K;
row.oracle_Q = fixture.Q;
row.Nphi = fixture.Nphi;
row.L = fixture.L;
row.aperture_columns = numel(fixture.aperture_index);
row.noise_model = string(fixture.noise_kind);
row.observation_regime = string(data.observation_regime);
row.coefficient_rank_evidence_kind = ...
    string(est.coefficient_rank_evidence_kind);
row.row_whitening_rank = data.row_whitening_rank;
row.column_whitening_rank = data.column_whitening_rank;
row.column_whitening_applied = data.column_whitening_applied;
row.column_covariance_model = string(data.column_covariance_model);
