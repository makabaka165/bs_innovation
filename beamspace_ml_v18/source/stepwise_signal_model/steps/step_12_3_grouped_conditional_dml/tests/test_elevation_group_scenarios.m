    'source_snapshots', source_snapshots, 'group_index', group_index, ...
    'aperture_index', aperture_index, 'noise_kind', noise_kind, ...
    'noise_sigma', noise_sigma, 'seed', seed, ...
    'search_grid_deg', search_grid_deg, 'angle_gate_deg', angle_gate_deg, ...
    'recovery_gate', recovery_gate);
end

