row.evaluation_scope = string(metrics.evaluation_scope);
row.relative_fro_error = metrics.relative_fro_error_by_group(q);
row.registered_fro_gate = fixture.recovery_gate;
row.subspace_chordal_distance = ...
    metrics.subspace_chordal_distance_by_group(q);
row.registered_subspace_gate = subspace_gate;
row.subspace_rank_estimate = metrics.subspace_rank_estimate(q);
row.subspace_rank_truth = metrics.subspace_rank_truth(q);
