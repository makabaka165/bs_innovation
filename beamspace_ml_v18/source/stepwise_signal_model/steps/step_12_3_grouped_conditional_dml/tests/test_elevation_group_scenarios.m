function [trial_table, identifiability_table, recovery_table, context] = ...
    test_elevation_group_scenarios(cfg, el_beam_deg)
%TEST_ELEVATION_GROUP_SCENARIOS Exercise all registered phase-4 scenarios.

specs = scenario_specs_local(cfg);
fixtures = cell(numel(specs) + 1, 1);
for idx = 1:numel(specs)
    fixtures{idx} = build_stage4_physical_fixture( ...
        specs(idx), cfg, el_beam_deg);
end
fixtures{end} = build_stage4_structural_fixture(cfg, el_beam_deg);

trial_rows = cell(0, 1);
ident_rows = cell(0, 1);
recovery_rows = cell(0, 1);
total_score_calls = 0;
total_svd_calls = 0;
total_runtime_sec = 0;
common_group_sum_relative_error = NaN;
max_structurally_supported_truth_residual = 0;

for idx = 1:numel(fixtures)
    fixture = fixtures{idx};
    [bank, candidate_parameters_deg] = build_registered_candidate_bank( ...
        fixture.search_grid_deg, fixture.Q, fixture.group_model);

    estimate_tic = tic;
    [est, est_debug] = estimate_elevation_groups_dml( ...
        fixture.data, fixture.Q, fixture.search_grid_deg, ...
        fixture.group_model, struct());
    estimate_runtime_sec = toc(estimate_tic);
    main_error_deg = ordered_angle_error_local( ...
        est.eta_hat_deg, fixture.eta_true_deg);
    main_pass = estimate_pass_local(est, main_error_deg, fixture);
    trial_rows{end + 1, 1} = make_trial_row_local( ...
        fixture, 'grouped_svd_dml', 'registered_local_full_reference', ...
        est, main_error_deg, estimate_runtime_sec, main_pass, ...
        'group_row_whitener'); %#ok<AGROW>
    total_score_calls = total_score_calls + est.num_score_eval;
    total_svd_calls = total_svd_calls + est.num_svd;
    total_runtime_sec = total_runtime_sec + estimate_runtime_sec;

    element_tic = tic;
    [element_est, ~] = estimate_elevation_groups_dml( ...
        fixture.element_data, fixture.Q, fixture.search_grid_deg, ...
        fixture.element_model, struct());
    element_runtime_sec = toc(element_tic);
    element_error_deg = ordered_angle_error_local( ...
        element_est.eta_hat_deg, fixture.eta_true_deg);
    element_pass = estimate_pass_local( ...
        element_est, element_error_deg, fixture);
    trial_rows{end + 1, 1} = make_trial_row_local( ...
        fixture, 'vertical_element_domain_dml', ...
        'registered_local_full_reference', element_est, ...
        element_error_deg, element_runtime_sec, element_pass, ...
        'element_row_whitener'); %#ok<AGROW>
    total_score_calls = total_score_calls + element_est.num_score_eval;
    total_svd_calls = total_svd_calls + element_est.num_svd;
    total_runtime_sec = total_runtime_sec + element_runtime_sec;

    truth_diag_opts = struct('evidence_kind', 'TRUTH_STRUCTURAL', ...
        'row_whitening_rank', fixture.data.row_whitening_rank, ...
        'column_whitening_rank', fixture.data.column_whitening_rank, ...
        'physical_beam_count', fixture.data.physical_beam_count, ...
        'observation_regime', fixture.observation_regime, ...
        'estimate_status', est.estimate_status, ...
        'local_manifold_bank', {bank}, ...
        'local_parameter_deg', candidate_parameters_deg, ...
        'reference_parameter_deg', fixture.eta_true_deg, ...
        'rank_multiplier', 1);
    truth_diag = diagnose_elevation_group_identifiability( ...
        fixture.Ge_true, fixture.Ce_true_recovery, truth_diag_opts);
    score_opts = struct('requested_rank', fixture.Q, ...
        'rank_multiplier', 1, 'compute_projector_checks', false);
    [~, truth_rss] = beamspace_dml_score_svd( ...
        fixture.signal_data.Z_score_mmv, fixture.Ge_true, score_opts);
    total_score_calls = total_score_calls + 1;
    total_svd_calls = total_svd_calls + truth_diag.num_svd + 1;
    truth_rss_relative = truth_rss / max( ...
        norm(fixture.signal_data.Z_score_mmv, 'fro') ^ 2, ...
        realmin(class(fixture.signal_data.Z_score_mmv)));
    truth_residual = max( ...
        fixture.truth_recovery_model_relative_residual, ...
        fixture.truth_score_model_relative_residual);
    if ~strcmp(fixture.expected_support_status, ...
            'GROUP_MMV_RANK_UNCERTIFIED')
        max_structurally_supported_truth_residual = max( ...
            max_structurally_supported_truth_residual, ...
            max(truth_residual, truth_rss_relative));
    end
    ident_pass = identifiability_pass_local( ...
        fixture, truth_diag, est, truth_rss_relative);
    ident_rows{end + 1, 1} = make_ident_row_local( ...
        fixture, truth_diag, est, truth_rss_relative, ...
        ident_pass); %#ok<AGROW>

    if fixture.Q == 1
        peak_tic = tic;
        peak_est = beam_peak_baseline_local(fixture);
        peak_runtime_sec = toc(peak_tic);
        peak_error_deg = ordered_angle_error_local( ...
            peak_est.eta_hat_deg, fixture.eta_true_deg);
        peak_pass = isfinite(peak_error_deg) && ...
            peak_error_deg <= max(diff(fixture.el_beam_deg));
        trial_rows{end + 1, 1} = make_trial_row_local( ...
            fixture, 'elevation_beam_peak', 'single_peak_q1_only', ...
            peak_est, peak_error_deg, peak_runtime_sec, peak_pass, ...
            'group_row_whitener'); %#ok<AGROW>
        total_runtime_sec = total_runtime_sec + peak_runtime_sec;
    end

    if est.estimate_returned_flag && est.structural_gate_pass_flag
        [Xphi_hat, Ce_hat, recovery_debug] = ...
            recover_group_azimuth_data( ...
            fixture.data, est.Ge_hat, struct('rank_multiplier', 1));
        truth = struct('Xphi', {fixture.Xphi_true}, ...
            'Ce_recovery', fixture.Ce_true_recovery, ...
            'Ge', fixture.Ge_true);
        recovery_metrics = evaluate_group_recovery_against_truth( ...
            Xphi_hat, Ce_hat, est.Ge_hat, truth, struct());
        total_svd_calls = total_svd_calls + recovery_debug.num_svd + ...
            recovery_metrics.num_svd;
        recovery_subspace_gate = recovery_subspace_gate_local( ...
            fixture.noise_kind);
        for q = 1:fixture.Q
            recovery_pass = recovery_debug.recovery_returned_flag && ...
                recovery_metrics.relative_fro_error_by_group(q) <= ...
                fixture.recovery_gate && ...
                recovery_metrics.subspace_chordal_distance_by_group(q) <= ...
                recovery_subspace_gate && ...
                recovery_metrics.max_offdiagonal_crosstalk <= 5e-9 && ...
                recovery_metrics.diagonal_mixing_error <= 5e-9;
            recovery_rows{end + 1, 1} = make_recovery_row_local( ...
                fixture, q, est, recovery_debug, recovery_metrics, ...
                recovery_subspace_gate, recovery_pass); %#ok<AGROW>
        end
        if strcmp(fixture.scenario, 'k2_q1_common_elevation_l3')
            common_group_sum_relative_error = ...
                recovery_metrics.relative_fro_error_by_group(1);
        end
    else
        rejection_pass = strcmp(fixture.expected_estimate_status, ...
            'ESTIMATE_NOT_RUN_STRUCTURAL_RANK_FAILURE') && ...
            strcmp(est.estimate_status, fixture.expected_estimate_status) && ...
            strcmp(est.support_status, fixture.expected_support_status) && ...
            ~est.estimate_returned_flag;
        recovery_rows{end + 1, 1} = make_rejection_recovery_row_local( ...
            fixture, est, rejection_pass); %#ok<AGROW>
    end

    if ~main_pass || ~element_pass || ~ident_pass
        fprintf('Scenario gate failed: %s\n', fixture.scenario);
        disp(est_debug);
    end
end

trial_table = struct2table(vertcat(trial_rows{:}));
identifiability_table = struct2table(vertcat(ident_rows{:}));
recovery_table = struct2table(vertcat(recovery_rows{:}));
peak_rows = trial_table.method == "elevation_beam_peak";
baseline_scope_pass = all(trial_table.upstream_group_support_status(peak_rows) == ...
    trial_table.expected_upstream_group_support_status(peak_rows)) && ...
    all(trial_table.method_status_scope(peak_rows) == "UPSTREAM_FIXTURE_ONLY") && ...
    all(trial_table.method_certification_status(peak_rows) == ...
    "NOT_APPLICABLE_BASELINE") && ...
    all(trial_table.support_status(peak_rows) == "NOT_APPLICABLE_BASELINE") && ...
    all(~trial_table.registered_model_certified_flag(peak_rows)) && ...
    all(~trial_table.structural_gate_pass_flag(peak_rows));
if any(~trial_table.pass_flag)
    disp(trial_table(~trial_table.pass_flag, :));
end
if any(~identifiability_table.pass_flag)
    disp(identifiability_table(~identifiability_table.pass_flag, :));
end
if any(~recovery_table.pass_flag)
    disp(recovery_table(~recovery_table.pass_flag, :));
end
assert(all(trial_table.pass_flag), ...
    'test_elevation_group_scenarios:TrialFailed', ...
    'An elevation-group estimator or baseline gate failed.');
assert(all(identifiability_table.pass_flag), ...
    'test_elevation_group_scenarios:IdentifiabilityFailed', ...
    'An elevation-group registered-support gate failed.');
assert(all(recovery_table.pass_flag), ...
    'test_elevation_group_scenarios:RecoveryFailed', ...
    'An elevation-group recovery gate failed.');
assert(baseline_scope_pass, ...
    'test_elevation_group_scenarios:BaselineStatusScope', ...
    'The elevation-beam baseline inherited registered-model certification.');
assert(common_group_sum_relative_error < 5e-10, ...
    'test_elevation_group_scenarios:CommonGroupSum', ...
    'The common-elevation Q1 recovery did not equal the within-group sum.');

context = struct();
context.fixtures = fixtures;
context.total_score_calls = total_score_calls;
context.total_svd_calls = total_svd_calls;
context.total_multi_start = 0;
context.total_estimator_runtime_sec = total_runtime_sec;
context.common_group_sum_relative_error = common_group_sum_relative_error;
context.max_structurally_supported_truth_residual = ...
    max_structurally_supported_truth_residual;
context.baseline_status_scope_pass = baseline_scope_pass;
context.num_physical_scenarios = numel(specs);
context.num_structural_counterexamples = 1;
context.ap_pr_baseline_status = ...
    'not_run_no_audited_exact_reproduction_available';
end

