function est = beam_peak_baseline_local(fixture)
energy = sum(abs(reshape(fixture.Zel_raw, ...
    size(fixture.Zel_raw, 1), [])) .^ 2, 2);
[score, index] = max(energy);
est = struct();
est.eta_hat_deg = fixture.el_beam_deg(index);
est.score = score;
est.rss = sum(energy) - score;
est.rank_Ge = NaN;
est.rank_Ce_hat_diagnostic = NaN;
est.rank_Z_score_diagnostic = NaN;
est.rank_Z_recovery_diagnostic = NaN;
est.num_score_eval = numel(fixture.el_beam_deg);
est.num_svd = 0;
est.estimate_status = 'ESTIMATE_RETURNED';
est.support_status = 'NOT_APPLICABLE_BASELINE';
est.statistical_calibration_status = 'NOT_CALIBRATED_STAGE4';
est.registered_model_certified_flag = false;
est.structural_gate_pass_flag = false;
est.estimate_returned_flag = true;
est.coefficient_rank_evidence_kind = ...
    fixture.coefficient_rank_evidence_kind;
end

function pass_flag = estimate_pass_local(est, angle_error_deg, fixture)
pass_flag = strcmp(est.estimate_status, fixture.expected_estimate_status) && ...
    strcmp(est.support_status, fixture.expected_support_status) && ...
    strcmp(est.statistical_calibration_status, 'NOT_CALIBRATED_STAGE4');
if strcmp(fixture.expected_estimate_status, ...
        'ESTIMATE_NOT_RUN_STRUCTURAL_RANK_FAILURE')
    pass_flag = pass_flag && ~est.estimate_returned_flag && ...
        ~est.structural_gate_pass_flag && ...
        (est.rank_Ce_hat_diagnostic < fixture.Q || ...
        est.rank_Z_score_diagnostic < fixture.Q || ...
        est.rank_Z_recovery_diagnostic < fixture.Q);
else
    pass_flag = pass_flag && est.estimate_returned_flag && ...
        est.structural_gate_pass_flag && est.rank_Ge == fixture.Q && ...
        est.rank_Ce_hat_diagnostic == fixture.Q && ...
        angle_error_deg <= fixture.angle_gate_deg;
    if strcmp(fixture.observation_regime, 'NOISY_UNCALIBRATED')
        pass_flag = pass_flag && ~est.registered_model_certified_flag;
    else
        pass_flag = pass_flag && est.registered_model_certified_flag;
    end
end
end

function pass_flag = identifiability_pass_local( ...
    fixture, truth_diag, est, truth_rss_relative)
pass_flag = strcmp(truth_diag.support_status, ...
    fixture.expected_support_status) && ...
    strcmp(est.support_status, fixture.expected_support_status) && ...
    ~truth_diag.registered_bank_exact_alias_flag && ...
    fixture.truth_recovery_model_relative_residual < 5e-12 && ...
    fixture.truth_score_model_relative_residual < 5e-12 && ...
    truth_rss_relative < 5e-12 && ...
    strcmp(truth_diag.statistical_calibration_status, ...
    'NOT_CALIBRATED_STAGE4');
if strcmp(fixture.expected_support_status, ...
        'GROUP_MMV_RANK_UNCERTIFIED')
    pass_flag = pass_flag && truth_diag.rank_Ce_evidence < fixture.Q && ...
        fixture.Nphi > fixture.Q && ~truth_diag.structural_gate_pass_flag;
else
    pass_flag = pass_flag && truth_diag.rank_Ge == fixture.Q && ...
        truth_diag.rank_Ce_evidence == fixture.Q && ...
        truth_diag.structural_gate_pass_flag;
end
end

function error_deg = ordered_angle_error_local(estimate_deg, truth_deg)
if numel(estimate_deg) ~= numel(truth_deg) || any(~isfinite(estimate_deg))
    error_deg = NaN;
else
    error_deg = max(abs(sort(estimate_deg(:)) - sort(truth_deg(:))));
end
end

