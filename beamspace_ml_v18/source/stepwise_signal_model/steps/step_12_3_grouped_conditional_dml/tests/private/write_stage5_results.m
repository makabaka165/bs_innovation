function outputs = write_stage5_results(result_dir, cfg, evidence, tests, ...
    analyzer_count, frozen_context, overall_pass)
%WRITE_STAGE5_RESULTS Write the registered stage-5 evidence bundle.

if exist(result_dir, 'dir') ~= 7
    mkdir(result_dir);
end
baseline_table = baseline_status_local();
keypoints_table = keypoints_local(cfg, evidence, tests, analyzer_count, ...
    frozen_context, overall_pass);

outputs = struct();
outputs.conditional_trial = fullfile(result_dir, ...
    'conditional_azimuth_trial.csv');
outputs.elevation_propagation = fullfile(result_dir, ...
    'conditional_azimuth_elevation_error_propagation.csv');
outputs.group_noise = fullfile(result_dir, 'group_noise_propagation.csv');
outputs.joint_history = fullfile(result_dir, 'joint_refinement_history.csv');
outputs.joint_trial = fullfile(result_dir, 'joint_refinement_trial.csv');
outputs.budget = fullfile(result_dir, 'method_budget_comparison.csv');
outputs.score_gap = fullfile(result_dir, 'method_score_gap.csv');
outputs.wrong_peak = fullfile(result_dir, 'wrong_local_peak_summary.csv');
outputs.offgrid = fullfile(result_dir, 'offgrid_holdout.csv');
outputs.normal = fullfile(result_dir, 'normal_holdout_summary.csv');
outputs.stress = fullfile(result_dir, 'stress_holdout_summary.csv');
outputs.baseline = fullfile(result_dir, 'baseline_reproduction_status.csv');
outputs.keypoints = fullfile(result_dir, 'stage5_keypoints.csv');
outputs.report = fullfile(result_dir, 'stage5_report.md');

writetable(evidence.conditional_table, outputs.conditional_trial);
writetable(tests.propagation_table, outputs.elevation_propagation);
writetable(tests.group_noise_table, outputs.group_noise);
writetable(evidence.history_table, outputs.joint_history);
writetable(evidence.trial_table, outputs.joint_trial);
writetable(evidence.budget_table, outputs.budget);
writetable(evidence.score_gap_table, outputs.score_gap);
writetable(evidence.wrong_peak_table, outputs.wrong_peak);
writetable(evidence.offgrid_table, outputs.offgrid);
writetable(evidence.normal_summary, outputs.normal);
writetable(evidence.stress_summary, outputs.stress);
writetable(baseline_table, outputs.baseline);
writetable(keypoints_table, outputs.keypoints);
write_report_local(outputs.report, evidence, tests, analyzer_count, ...
    frozen_context, baseline_table, overall_pass);
end

