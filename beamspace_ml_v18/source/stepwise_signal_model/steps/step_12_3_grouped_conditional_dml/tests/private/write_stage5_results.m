    "LOCAL_FULL_DML_REFERENCE"; "CONVENTIONAL_DBF"; ...
    "FACTOR1_COMMON_EL_OR_CONTROLLED_PAIR2D"; "PR_DML"; "KIM_2012"];
reproduction_status = ["EXECUTED_FACTOR1"; "EXECUTED_FACTOR1"; ...
    "EXECUTED_LOCAL_REFERENCE_ONLY"; "EXECUTED_FACTOR1"; ...
    "NOT_SELECTED_AS_SEPARATE_BASELINE"; ...
    "EXACT_REPRODUCTION_UNAVAILABLE"; ...
    "EXACT_REPRODUCTION_UNAVAILABLE"];
reason = [ ...
    "registered_stage4_grouping_conditional_azimuth_and_full_correction"; ...
    "classical_AP_coordinate_ascent_two_pre_registered_starts_all_costed"; ...
    "all_unordered_candidates_in_the_same_small_registered_domain"; ...
    "fixed_sequential_beam_peak_centers_snapped_to_the_common_domain"; ...
