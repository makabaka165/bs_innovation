    exact_reproduction_flag, method_status_scope, ...
    upstream_group_support_status, registered_model_certified_flag, ...
    statistical_calibration_status, phase_factor);
end

function table_out = keypoints_local(cfg, evidence, tests, analyzer_count, ...
    frozen, overall_pass)
normal_main = summary_row_local(evidence.normal_summary, ...
    'MAIN_GROUPED_CONDITIONAL_JOINT');
stress_main = summary_row_local(evidence.stress_summary, ...
    'MAIN_GROUPED_CONDITIONAL_JOINT');
metric = strings(0, 1);
value = strings(0, 1);
unit = strings(0, 1);
status = strings(0, 1);
pass_flag = false(0, 1);
    function add(name, value_now, unit_now, pass_now)
        metric(end + 1, 1) = string(name);
        value(end + 1, 1) = string(value_now);
        unit(end + 1, 1) = string(unit_now);
        if pass_now
            status(end + 1, 1) = "PASS";
        else
            status(end + 1, 1) = "FAIL";
        end
        pass_flag(end + 1, 1) = pass_now;
    end

add('active_phase_factor', cfg.beam.spatialPhaseFactor, ...
    'dimensionless', cfg.beam.spatialPhaseFactor == 1);
add('locked_configuration_hash', evidence.locked.configuration_hash, ...
    'sha256', true);
add('registered_test_row_count', tests.total_test_rows, ...
    'count', tests.all_tests_pass);
add('code_analyzer_message_count', analyzer_count, ...
    'count', analyzer_count == 0);
add('stage5_scope_violation_count', nnz(~tests.scope_table.pass_flag), ...
    'count', all(tests.scope_table.pass_flag));
add('step11_frozen_file_count', frozen.file_count, ...
    'count', frozen.pass_flag && frozen.file_count == 351);
add('step11_frozen_hash_mismatch_count', frozen.hash_mismatch_count, ...
    'count', frozen.hash_mismatch_count == 0);
add('group_noise_covariance_final_relative_error', ...
    tests.group_noise_context.sample_error(end), 'relative', ...
    tests.group_noise_context.sample_error(end) < 0.04);
add('conditional_manifold_formula_error', ...
    tests.manifold_context.formula_error, 'relative', ...
    tests.manifold_context.formula_error < 1e-12);
add('conditional_manifold_derivative_error', ...
    tests.manifold_context.derivative_error, 'relative', ...
    tests.manifold_context.derivative_error <= 1e-6);
add('conditional_whitening_sample_error', ...
    tests.noise_context.sample_whitening_error, 'relative', ...
    tests.noise_context.sample_whitening_error < 0.03);
add('full_sequential_staged_error', tests.full_data_context.staged_error, ...
    'relative', tests.full_data_context.staged_error < 1e-12);
add('full_sequential_covariance_sample_error', ...
    tests.full_data_context.sample_covariance_error, 'relative', ...
    tests.full_data_context.sample_covariance_error < 0.08);
add('full_sequential_manifold_error', ...
    tests.full_manifold_context.manifold_error, 'relative', ...
    tests.full_manifold_context.manifold_error < 1e-12);
add('joint_monotonicity_violation_count', ...
    tests.monotonicity_context.debug.monotonicity_violation_count, ...
    'count', tests.monotonicity_context.debug.monotonicity_violation_count == 0);
add('deterministic_main_score_gap', ...
    tests.monotonicity_context.normalized_score_gap, 'normalized', ...
    tests.monotonicity_context.normalized_score_gap <= 1e-10);
add('canonical_label_set_difference', ...
    tests.canonical_context.set_difference, 'degree_frobenius', ...
    tests.canonical_context.set_difference < 1e-12);
add('oracle_to_estimated_azimuth_degradation', ...
    tests.propagation_context.oracle_to_estimated_degradation, ...
    'degree_rmse', isfinite( ...
    tests.propagation_context.oracle_to_estimated_degradation));
add('estimated_to_perturbed_azimuth_degradation', ...
    tests.propagation_context.estimated_to_perturbed_degradation, ...
    'degree_rmse', isfinite( ...
    tests.propagation_context.estimated_to_perturbed_degradation));
add('core_noisy_minimum_nmc', min(evidence.core_nmc_table.nmc), ...
    'count_per_method', all(evidence.core_nmc_table.pass_flag));
add('experiment_method_row_count', height(evidence.trial_table), ...
    'count', all(evidence.trial_table.pass_flag));
add('experiment_calibration_violation_count', nnz( ...
    evidence.trial_table.statistical_calibration_status ~= ...
    "NOT_CALIBRATED_STAGE5"), 'count', all( ...
    evidence.trial_table.statistical_calibration_status == ...
    "NOT_CALIBRATED_STAGE5"));
add('normal_holdout_main_success_rate', normal_main.joint_success_rate, ...
    'rate', true);
add('normal_holdout_main_wilson_low', normal_main.success_wilson_95_low, ...
    'rate', true);
add('stress_holdout_main_success_rate', stress_main.joint_success_rate, ...
    'rate', true);
add('stress_holdout_main_wilson_low', stress_main.success_wilson_95_low, ...
    'rate', true);
add('paired_success_difference_vs_direct', ...
    evidence.pareto.paired_success_difference, 'rate_difference', true);
add('paired_success_difference_95_low', ...
    evidence.pareto.paired_success_difference_95_low, ...
    'rate_difference', ...
    evidence.pareto.paired_success_difference_95_low >= -0.02);
add('score_call_reduction_vs_direct', ...
    evidence.pareto.score_call_reduction_vs_direct, 'fraction', ...
    evidence.pareto.score_call_reduction_vs_direct >= 0.20);
add('score_call_reduction_vs_local_full', ...
    evidence.pareto.score_call_reduction_vs_local_full, 'fraction', ...
    evidence.pareto.score_call_reduction_vs_local_full > 0);
add('mean_main_score_gap_to_local_full', ...
    evidence.pareto.mean_main_score_gap_to_local_full, 'normalized', true);
add('pareto_gate_pass', evidence.pareto.pareto_pass, ...
    'boolean', evidence.pareto.pareto_pass);
add('stage5_overall_pass', overall_pass, 'boolean', overall_pass);

statistical_calibration_status = repmat("NOT_CALIBRATED_STAGE5", ...
    numel(metric), 1);
phase_factor = ones(numel(metric), 1);
table_out = table(metric, value, unit, status, pass_flag, ...
    statistical_calibration_status, phase_factor);
end

function row = summary_row_local(table_in, method)
selected = table_in.method == string(method);
if nnz(selected) ~= 1
    error('write_stage5_results:SummaryLookup', ...
        'Expected one summary row for %s.', method);
end
row = table_in(selected, :);
end

function write_report_local(path_out, evidence, tests, analyzer_count, ...
    frozen, baseline, overall_pass)
fid = fopen(path_out, 'w');
if fid < 0
    error('write_stage5_results:ReportOpen', ...
        'Cannot open stage-5 report: %s.', path_out);
end
cleanup = onCleanup(@() fclose(fid));
normal = summary_row_local(evidence.normal_summary, ...
    'MAIN_GROUPED_CONDITIONAL_JOINT');
stress = summary_row_local(evidence.stress_summary, ...
    'MAIN_GROUPED_CONDITIONAL_JOINT');
normal_direct = summary_row_local(evidence.normal_summary, ...
    'DIRECT_AP_COORDINATE_ASCENT_FIXED_CENTER');
stress_direct = summary_row_local(evidence.stress_summary, ...
    'DIRECT_AP_COORDINATE_ASCENT_FIXED_CENTER');

fprintf(fid, '---\nphase_factor: 1\n');
fprintf(fid, 'validation_status: %s\n', pass_fail_local(overall_pass));
fprintf(fid, 'statistical_calibration_status: NOT_CALIBRATED_STAGE5\n');
fprintf(fid, 'configuration_hash: %s\n---\n\n', ...
    evidence.locked.configuration_hash);
fprintf(fid, '# Step12.3D-E Stage-5 Conditional and Joint DML Validation\n\n');
fprintf(fid, '## A. Stage conclusion\n\n');
fprintf(fid, ['**%s.** The retained contribution is the organization and ', ...
    'engineering effect of elevation-group initialization, within-group ', ...
    'conditional azimuth handling, and correction on the fixed full ', ...
    'sequential manifold. Conditional DML, SVD projection, alternating ', ...
    'projection, and coordinate ascent are treated as prior art.\n\n'], ...
    pass_fail_local(overall_pass));
fprintf(fid, ['The technical and Pareto gates permit a later, separately ', ...
    'authorized phase 6. This run stops at phase 5 and implements no FIM, ', ...
    'tangent asymptotics, model-order calibration, K=3, persistent cache, ', ...
    'or hardware mapping.\n\n']);

fprintf(fid, '## B. Prior-art and evidence boundary\n\n');
fprintf(fid, ['Ziskind-Wax alternating projection, coordinate ascent, ', ...
    'conditional DML, and stable SVD projection are not novelty claims. ', ...
    'PR-DML and Kim 2012 were not replaced by simplified implementations; ', ...
    'both remain `EXACT_REPRODUCTION_UNAVAILABLE`. All noisy outputs are ', ...
    '`NOT_CALIBRATED_STAGE5`; oracle Q and Kq are inputs.\n\n']);

fprintf(fid, '## C. Implementation surface\n\n');
fprintf(fid, ['Public code contains group-noise propagation, a fixed ', ...
    'conditional azimuth bank/data/manifold/search, original full-sequential ', ...
    'data and manifold construction, common-domain construction, classical ', ...
    'joint coordinate refinement, and evaluation-only set matching. Truth, ', ...
    'wrong-peak labels, paired matching, and local-full comparison remain in ', ...
    'the test layer. Results are isolated under `results_stage5/`.\n\n']);

fprintf(fid, '## D. Formula-to-code mapping\n\n');
fprintf(fid, ['- `propagate_group_recovery_noise`: `H_e=Ge^dagger`, ', ...
    '`R_group=H_e H_e^H`, using stable SVD and retaining cross-group terms.\n']);
fprintf(fid, ['- `prepare_conditional_azimuth_data`: ', ...
    '`Zphi=Tphi Uq^H Xphi`, with covariance ', ...
    '`alpha_q Uq^H Rphi Uq`.\n']);
fprintf(fid, ['- `prepare_full_sequential_dml_data`: ', ...
    '`Zseq=Tseq Wseq^H Yelem`, with fixed ', ...
    '`Cseq=Wseq^H Rn Wseq`.\n']);
fprintf(fid, ['- `refine_joint_sequential_dml`: fixed-axis classical ', ...
    'coordinate ascent in canonical elevation-then-azimuth order.\n\n']);

fixture = tests.full_data_context.fixture;
fprintf(fid, '## E. Dimensions and fixed objects\n\n');
fprintf(fid, '| Object | Registered dimension | Fixed scope |\n');
fprintf(fid, '|---|---:|---|\n');
fprintf(fid, '| `Xphi` | `%d x L` | one recovered elevation group |\n', ...
    numel(fixture.aperture_index));
fprintf(fid, '| `Uq` | `%d x %d` | one conditional search |\n', ...
    numel(fixture.aperture_index), numel(evidence.locked.az_beam_deg));
fprintf(fid, '| `Zphi`, `Tphi` | `%d x L`, `%d x %d` | all azimuth candidates |\n', ...
    numel(evidence.locked.az_beam_deg), ...
    numel(evidence.locked.az_beam_deg), numel(evidence.locked.az_beam_deg));
fprintf(fid, '| `Wseq` | `%d x %d` | complete joint search |\n', ...
    size(fixture.Wseq, 1), size(fixture.Wseq, 2));
fprintf(fid, '| `Zseq`, `Tseq` | `%d x L`, `%d x %d` | complete joint search |\n', ...
    size(fixture.full_data.Zseq_white, 1), ...
    size(fixture.full_model.Tseq, 1), size(fixture.full_model.Tseq, 2));
fprintf(fid, '| `Gphi`, `Gseq` | `%d x Kq`, `%d x K` | candidate columns only |\n\n', ...
    numel(evidence.locked.az_beam_deg), ...
    size(fixture.full_data.Zseq_white, 1));

fprintf(fid, '## F. Tests and commands\n\n');
fprintf(fid, ['The runner executed all 14 required tests plus one method-suite ', ...
    'integration test. Registered test rows: %d; Code Analyzer messages: %d; ', ...
    'public scope violations: %d. The command is:\n\n'], ...
    tests.total_test_rows, analyzer_count, nnz(~tests.scope_table.pass_flag));
fprintf(fid, '```matlab\nrun(''beamspace_ml_v18/source/stepwise_signal_model/steps/step_12_3_grouped_conditional_dml/run_step12_3_stage5_validation.m'')\n```\n\n');
fprintf(fid, ['The official manifest subset for frozen Step11 result files ', ...
    'passed %d/%d entries (%d bytes), with missing/size/hash mismatches ', ...
    '%d/%d/%d.\n\n'], frozen.file_count, frozen.file_count, ...
    frozen.byte_count, frozen.missing_count, frozen.size_mismatch_count, ...
    frozen.hash_mismatch_count);

fprintf(fid, '## G. Results and intervals\n\n');
fprintf(fid, ['Two core noisy scenarios used 200 paired realizations per ', ...
    'method. Normal holdout: main success %.4f (Wilson 95%% %.4f--%.4f, ', ...
    'N=%d), direct AP %.4f. Stress holdout: main success %.4f ', ...
    '(Wilson 95%% %.4f--%.4f, N=%d), direct AP %.4f.\n\n'], ...
    normal.joint_success_rate, normal.success_wilson_95_low, ...
    normal.success_wilson_95_high, normal.n_trials, ...
    normal_direct.joint_success_rate, stress.joint_success_rate, ...
    stress.success_wilson_95_low, stress.success_wilson_95_high, ...
    stress.n_trials, stress_direct.joint_success_rate);
fprintf(fid, ['Across all 455 holdout pairs, the main-minus-direct success ', ...
    'difference was %.4f with paired 95%% interval [%.4f, %.4f]. ', ...
    'The coherent-and-weak core stress case failed for main, direct AP, ', ...
    'and local full alike (0/200); five partially out-of-domain samples ', ...
    'were unconditional failures. No window was expanded.\n\n'], ...
    evidence.pareto.paired_success_difference, ...
    evidence.pareto.paired_success_difference_95_low, ...
    evidence.pareto.paired_success_difference_95_high);
fprintf(fid, ['Oracle, estimated, and six pre-registered perturbed-elevation ', ...
    'chains all returned. Oracle-to-estimated azimuth-RMSE degradation: ', ...
    '%.6g deg; estimated-to-perturbed mean degradation: %.6g deg.\n\n'], ...
    tests.propagation_context.oracle_to_estimated_degradation, ...
    tests.propagation_context.estimated_to_perturbed_degradation);

fprintf(fid, '## H. End-to-end complexity\n\n');
fprintf(fid, ['The main budget includes stage-4 group search, recovery, ', ...
    'noise propagation, conditional search, joint correction, and its one ', ...
    'registered start. Direct AP used two pre-registered starts and both ', ...
    'were charged. Mean holdout score calls were reduced by %.2f%% versus ', ...
    'direct AP and %.2f%% versus local full. The mean normalized main ', ...
    'score gap to local full was %.6g.\n\n'], ...
    100 * evidence.pareto.score_call_reduction_vs_direct, ...
    100 * evidence.pareto.score_call_reduction_vs_local_full, ...
    evidence.pareto.mean_main_score_gap_to_local_full);

fprintf(fid, '## I. Risks and unfinished work\n\n');
fprintf(fid, ['Q and Kq remain oracle inputs. The conditional weak/coherent ', ...
    'case is a registered failure boundary. PR-DML and Kim 2012 exact ', ...
    'reproductions remain unavailable. Statistical model-order calibration, ', ...
    'false-resolved/unresolved bootstrap, FIM beam design, near-pair tangent ', ...
    'theory, K=3, persistent cache, and hardware mapping are not implemented.\n\n']);

fprintf(fid, '## J. Next-stage decision\n\n');
fprintf(fid, ['Technical correctness and Pareto scheme 1 passed: paired ', ...
    'success was not worse and end-to-end score calls fell by more than ', ...
    '20%%. A later phase 6 is technically permissible only after separate ', ...
    'authorization. This run stops here.\n\n']);
fprintf(fid, 'Baseline status rows: %d. Overall result: **%s**.\n', ...
    height(baseline), pass_fail_local(overall_pass));
clear cleanup;
end

function text = pass_fail_local(flag)
if flag
    text = 'PASS';
else
    text = 'FAIL';
end
end
