function g = manifold_offset_local(center_deg, direction, offset_rad, model)
point_deg = center_deg + rad2deg(offset_rad * direction(:)).';
[g, ~] = build_fixed_whitened_sequential_derivatives(point_deg, model, struct());
end

function g2 = second_difference_local(center, v, h, model, g0)
g2 = (manifold_offset_local(center, v, h, model) - 2 * g0 + ...
    manifold_offset_local(center, v, -h, model)) / h ^ 2;
end

function g3 = third_difference_local(center, v, h, model)
g3 = (manifold_offset_local(center, v, 2 * h, model) - ...
    2 * manifold_offset_local(center, v, h, model) + ...
    2 * manifold_offset_local(center, v, -h, model) - ...
    manifold_offset_local(center, v, -2 * h, model)) / (2 * h ^ 3);
end

function error = relative_error_local(actual, reference)
error = norm(actual - reference, 'fro') / ...
    max(norm(reference, 'fro'), realmin(class(reference)));
end

function error = relative_scalar_error_local(actual, reference)
error = abs(actual - reference) / max(abs(reference), realmin(class(reference)));
end

function slope = error_slope_local(r, error_value)
valid = isfinite(r) & isfinite(error_value) & r > 0 & error_value > 0;
if nnz(valid) < 2
    slope = NaN;
else
    coefficients = polyfit(log(r(valid)), log(error_value(valid)), 1);
    slope = coefficients(1);
end
end

function flag = taylor_decrease_local(values_sorted_by_r_ascending)
values = values_sorted_by_r_ascending(:);
if numel(values) < 6
    flag = false;
else
    flag = max(values(1:3)) <= max(values(end-2:end));
end
end

