function evidence = run_stage6_registered_experiments(context)
%RUN_STAGE6_REGISTERED_EXPERIMENTS Evaluate the complete locked stage-6 plan.

runtime_tic = tic;
[configuration_table, measurement_hash_table] = registry_tables_local(context);
[first_table, metric_table, eigenvalue_table] = ...
    first_derivative_and_metric_tables_local(context);
higher_table = higher_derivative_table_local(context);
secant_all = secant_table_local(context);
tail_table = tail_summary_local(secant_all, context);
identity_table = exact_identity_table_local(secant_all, context);
asymmetry_table = column_asymmetry_table_local(secant_all, context);
synthetic_table = synthetic_null_table_local(context);
invariance_table = invariance_table_local(context);
[exact_null_table, near_null_table, physical_null_status] = ...
    physical_null_tables_local(context, eigenvalue_table);

primary_nondegenerate = secant_all( ...
    secant_all.direction_class == "NONDEGENERATE_TANGENT", :);
mathematical_pass = all(first_table.pass_flag) && all(higher_table.pass_flag) && ...
    all(metric_table.pass_flag) && all(tail_table.pass_flag) && ...
    all(identity_table.pass_flag) && all(synthetic_table.pass_flag) && ...
    all(invariance_table.pass_flag) && all(asymmetry_table.pass_flag);
if mathematical_pass
    theory_status = "THEORY_SUPPORTED_AS_SCENARIO_SPECIFIC_COROLLARY";
else
    theory_status = "THEORY_PARTIALLY_SUPPORTED";
end

tables = {configuration_table, measurement_hash_table, first_table, ...
    higher_table, metric_table, eigenvalue_table, primary_nondegenerate, ...
    tail_table, exact_null_table, near_null_table, synthetic_table, ...
    identity_table, invariance_table, asymmetry_table};
for index = 1:numel(tables)
    tables{index} = finalize_theory_status_local(tables{index}, theory_status);
end
[configuration_table, measurement_hash_table, first_table, higher_table, ...
    metric_table, eigenvalue_table, primary_nondegenerate, tail_table, ...
    exact_null_table, near_null_table, synthetic_table, identity_table, ...
    invariance_table, asymmetry_table] = tables{:};

runtime_sec = toc(runtime_tic);
complexity = complexity_local(context, height(secant_all), ...
    height(first_table), height(higher_table), height(metric_table), runtime_sec);
keypoints = keypoints_local(context, mathematical_pass, theory_status, ...
    first_table, higher_table, metric_table, tail_table, identity_table, ...
    invariance_table, synthetic_table, eigenvalue_table, physical_null_status, ...
    complexity);

evidence = struct();
evidence.configuration_table = configuration_table;
evidence.measurement_hash_table = measurement_hash_table;
evidence.first_derivative_table = first_table;
evidence.higher_derivative_table = higher_table;
evidence.metric_table = metric_table;
evidence.eigenvalue_table = eigenvalue_table;
evidence.secant_table = primary_nondegenerate;
evidence.secant_all_table = secant_all;
evidence.tail_table = tail_table;
evidence.exact_null_table = exact_null_table;
evidence.near_null_table = near_null_table;
evidence.synthetic_table = synthetic_table;
evidence.identity_table = identity_table;
evidence.invariance_table = invariance_table;
evidence.asymmetry_table = asymmetry_table;
evidence.keypoints_table = keypoints;
evidence.physical_null_status = physical_null_status;
evidence.mathematical_pass = mathematical_pass;
evidence.theory_status = char(theory_status);
evidence.complexity = complexity;
end

function [config_table, hash_table] = registry_tables_local(context)
rows = cell(numel(context.models), 1);
hash_rows = cell(numel(context.models), 1);
for index = 1:numel(context.models)
    model = context.models{index};
    debug = context.model_debug{index};
    rows{index} = struct( ...
        'config_id', string(model.config_id), ...
        'is_primary_configuration', model.is_primary_configuration, ...
        'az_beam_count', numel(model.az_beam_deg), ...
        'el_beam_count', numel(model.el_beam_deg), ...
        'sequential_channel_count', size(model.Wseq, 2), ...
        'whitening_rank', model.whitening_rank, ...
        'noise_covariance_id', string(model.noise_covariance_id), ...
        'az_beam_deg', string(mat2str(model.az_beam_deg, 12)), ...
        'el_beam_deg', string(mat2str(model.el_beam_deg, 12)), ...
        'beam_indices', string(sprintf('az=%s;el=%s', ...
        mat2str(model.beam_indices.azimuth_local), ...
        mat2str(model.beam_indices.elevation_local))), ...
        'global_beam_indices', string(sprintf('az=%s;el=%s', ...
        mat2str(model.beam_indices.azimuth_global), ...
        mat2str(model.beam_indices.elevation_global))), ...
        'whitening_identity_error', debug.whitening_identity_error, ...
        'fixed_objects_candidate_independent_flag', ...
        debug.fixed_objects_candidate_independent_flag, ...
        'fixed_measurement_hash', string(model.fixed_measurement_hash), ...
        'pass_flag', model.phase_factor == 1 && ...
        debug.whitening_identity_error <= 1e-10);
    hash_rows{index} = struct( ...
        'config_id', string(model.config_id), ...
        'Wseq_hash', string(model.Wseq_hash), ...
        'Cseq_hash', string(model.Cseq_hash), ...
        'Tseq_hash', string(model.Tseq_hash), ...
        'array_geometry_hash', string(model.array_geometry_hash), ...
        'fixed_measurement_hash', string(model.fixed_measurement_hash), ...
        'hash_length', strlength(string(model.fixed_measurement_hash)), ...
        'pass_flag', strlength(string(model.fixed_measurement_hash)) == 64);
end
config_table = add_metadata_local(struct2table(vertcat(rows{:})), context, "");
hash_table = add_metadata_local(struct2table(vertcat(hash_rows{:})), context, "");
end

function [first_table, metric_table, eigenvalue_table] = ...
    first_derivative_and_metric_tables_local(context)
plan = context.plan;
h = plan.controls.first_derivative_step_rad;
first_rows = cell(numel(context.models) * size(plan.centers_deg, 1), 1);
metric_rows = cell(size(first_rows));
eigen_rows = cell(size(first_rows));
row_index = 0;
for model_index = 1:numel(context.models)
    model = context.models{model_index};
    for center_index = 1:size(plan.centers_deg, 1)
        row_index = row_index + 1;
        center = plan.centers_deg(center_index, :);
        [g, Jg, info] = build_fixed_whitened_sequential_derivatives( ...
            center, model, struct());
        g_az_plus = manifold_offset_local(center, [1; 0], h, model);
        g_az_minus = manifold_offset_local(center, [1; 0], -h, model);
        g_el_plus = manifold_offset_local(center, [0; 1], h, model);
        g_el_minus = manifold_offset_local(center, [0; 1], -h, model);
        J_fd = [(g_az_plus - g_az_minus) / (2 * h), ...
            (g_el_plus - g_el_minus) / (2 * h)];
        az_error = relative_error_local(J_fd(:, 1), Jg(:, 1));
        el_error = relative_error_local(J_fd(:, 2), Jg(:, 2));
        [G_stage5, dG_stage5] = build_full_sequential_local_manifold( ...
            center, model, struct());
        stage5_g_error = relative_error_local(G_stage5(:, 1), g);
        stage5_J_error = relative_error_local( ...
            [dG_stage5.azimuth(:, 1), dG_stage5.elevation(:, 1)], Jg);
        pass = max([az_error, el_error]) <= ...
            plan.controls.first_derivative_relative_error_gate && ...
            max(stage5_g_error, stage5_J_error) <= ...
            plan.controls.stage5_manifold_consistency_gate && ...
            strcmp(info.derivative_unit, 'per_radian');
        first_rows{row_index} = struct( ...
            'config_id', string(model.config_id), ...
            'center_az_deg', center(1), 'center_el_deg', center(2), ...
            'finite_difference_step_rad', h, ...
            'azimuth_relative_error', az_error, ...
            'elevation_relative_error', el_error, ...
            'stage5_manifold_relative_error', stage5_g_error, ...
            'stage5_jacobian_relative_error', stage5_J_error, ...
            'derivative_unit', string(info.derivative_unit), ...
            'fixed_measurement_hash', string(model.fixed_measurement_hash), ...
            'pass_flag', pass);

        [metric, debug] = compute_projected_jacobian_metric(g, Jg, ...
            metric_options_local(plan));
        q_check = zeros(numel(plan.directions), 1);
        for direction_index = 1:numel(plan.directions)
            v = plan.directions(direction_index).vector_rad;
            q_check(direction_index) = abs(real(v' * metric.T * v) - ...
                norm(metric.Pg_perp * Jg * v) ^ 2);
        end
        metric_pass = debug.hermitian_error <= 1e-12 && ...
            debug.idempotence_error <= 1e-12 && ...
            debug.projected_center_error <= 1e-12 && ...
            debug.T_symmetry_error <= 1e-12 && ...
            metric.min_eigenvalue >= -metric.negative_eigenvalue_tolerance && ...
            max(q_check) <= 1e-9 * max(metric.max_eigenvalue, 1);
        metric_rows{row_index} = struct( ...
            'config_id', string(model.config_id), ...
            'center_az_deg', center(1), 'center_el_deg', center(2), ...
            'g_norm', norm(g), 'Jg_frobenius_norm', norm(Jg, 'fro'), ...
            'projector_hermitian_error', debug.hermitian_error, ...
            'projector_idempotence_error', debug.idempotence_error, ...
            'projected_center_relative_error', debug.projected_center_error, ...
            'metric_symmetry_error', debug.T_symmetry_error, ...
            'max_q_identity_absolute_error', max(q_check), ...
            'negative_eigenvalue_tolerance', metric.negative_eigenvalue_tolerance, ...
            'fixed_measurement_hash', string(model.fixed_measurement_hash), ...
            'pass_flag', metric_pass);
        eigen_rows{row_index} = struct( ...
            'config_id', string(model.config_id), ...
            'center_az_deg', center(1), 'center_el_deg', center(2), ...
            'lambda_min', metric.min_eigenvalue, ...
            'lambda_max', metric.max_eigenvalue, ...
            'lambda_min_to_max_ratio', metric.min_eigenvalue / ...
            max(metric.max_eigenvalue, realmin), ...
            'rank_T', metric.rank_T, 'condition_T', metric.condition_T, ...
            'null_tolerance', metric.null_tolerance, ...
            'tangent_class', string(metric.tangent_class), ...
            'fixed_measurement_hash', string(model.fixed_measurement_hash), ...
            'pass_flag', metric.min_eigenvalue >= ...
            -metric.negative_eigenvalue_tolerance);
    end
end
first_table = add_metadata_local(struct2table(vertcat(first_rows{:})), context, "");
metric_table = add_metadata_local(struct2table(vertcat(metric_rows{:})), context, "");
eigenvalue_table = add_metadata_local(struct2table(vertcat(eigen_rows{:})), context, "");
end

function table_out = higher_derivative_table_local(context)
plan = context.plan;
h1 = plan.controls.first_derivative_step_rad;
h2 = plan.controls.second_derivative_step_rad;
h3 = plan.controls.third_derivative_step_rad;
scales = plan.controls.derivative_sensitivity_scales;
count = numel(context.models) * size(plan.centers_deg, 1) * numel(plan.directions);
rows = cell(count, 1);
row_index = 0;
for model_index = 1:numel(context.models)
    model = context.models{model_index};
    for center_index = 1:size(plan.centers_deg, 1)
        center = plan.centers_deg(center_index, :);
        for direction_index = 1:numel(plan.directions)
            row_index = row_index + 1;
            direction = plan.directions(direction_index);
            v = direction.vector_rad;
            analytic = build_fixed_whitened_directional_derivatives( ...
                center, v, model, struct());
            g_first_plus = manifold_offset_local(center, v, h1, model);
            g_first_minus = manifold_offset_local(center, v, -h1, model);
            g1_fd = (g_first_plus - g_first_minus) / (2 * h1);
            g2_fd = second_difference_local(center, v, h2, model, analytic.g0);
            g3_fd = third_difference_local(center, v, h3, model);
            first_error = relative_error_local(g1_fd, analytic.g1);
            second_error = relative_error_local(g2_fd, analytic.g2);
            third_error = relative_error_local(g3_fd, analytic.g3);
            second_sensitivity = zeros(size(scales));
            third_sensitivity = zeros(size(scales));
            for scale_index = 1:numel(scales)
                second_sensitivity(scale_index) = relative_error_local( ...
                    second_difference_local(center, v, h2 * scales(scale_index), ...
                    model, analytic.g0), analytic.g2);
                third_sensitivity(scale_index) = relative_error_local( ...
                    third_difference_local(center, v, h3 * scales(scale_index), ...
                    model), analytic.g3);
            end
            pass = first_error <= plan.controls.first_derivative_relative_error_gate && ...
                second_error <= plan.controls.second_derivative_relative_error_gate && ...
                third_error <= plan.controls.third_derivative_relative_error_gate;
            rows{row_index} = struct( ...
                'config_id', string(model.config_id), ...
                'center_az_deg', center(1), 'center_el_deg', center(2), ...
                'direction_id', string(direction.direction_id), ...
                'direction_az_component', v(1), 'direction_el_component', v(2), ...
                'first_step_rad', h1, 'second_step_rad', h2, 'third_step_rad', h3, ...
                'first_relative_error', first_error, ...
                'second_relative_error', second_error, ...
                'third_relative_error', third_error, ...
                'second_sensitivity_max_error', max(second_sensitivity), ...
                'third_sensitivity_max_error', max(third_sensitivity), ...
                'derivative_unit', "per_radian", ...
                'fixed_measurement_hash', string(model.fixed_measurement_hash), ...
                'pass_flag', pass);
        end
    end
end
table_out = add_metadata_local(struct2table(vertcat(rows{:})), context, "");
end

function table_out = secant_table_local(context)
plan = context.plan;
primary_indices = find([plan.configs.is_primary_configuration]);
count = numel(primary_indices) * size(plan.centers_deg, 1) * ...
    numel(plan.directions) * numel(plan.separation_rad);
rows = cell(count, 1);
row_index = 0;
for model_index = primary_indices
    model = context.models{model_index};
    for center_index = 1:size(plan.centers_deg, 1)
        center = plan.centers_deg(center_index, :);
        [g, J] = build_fixed_whitened_sequential_derivatives(center, model, struct());
        metric = compute_projected_jacobian_metric(g, J, metric_options_local(plan));
        for direction_index = 1:numel(plan.directions)
            direction = plan.directions(direction_index);
            v = direction.vector_rad;
            q = real(v' * metric.T * v);
            ratio = q / max(metric.max_eigenvalue, realmin);
            if q <= metric.null_tolerance
                direction_class = "EXACT_TANGENT_NULL";
            elseif ratio < plan.controls.near_null_ratio
                direction_class = "NEAR_TANGENT_NULL";
            else
                direction_class = "NONDEGENERATE_TANGENT";
            end
            for separation_index = 1:numel(plan.separation_rad)
                row_index = row_index + 1;
                opts = struct('direction_id', direction.direction_id, ...
                    'numeric_floor_multiplier', plan.controls.numeric_floor_multiplier, ...
                    'near_null_ratio', plan.controls.near_null_ratio, ...
                    'metric_options', metric_options_local(plan), ...
                    'stage6_experiment_plan_hash', plan.stage6_experiment_plan_hash);
                row = evaluate_secant_tangent_case(center, v, ...
                    plan.separation_rad(separation_index), model, opts);
                row.direction_class = direction_class;
                rows{row_index} = row;
            end
        end
    end
end
table_out = struct2table(vertcat(rows{:}));
table_out = add_metadata_local(table_out, context, "");
end

function summary = tail_summary_local(secant, context)
plan = context.plan;
primary_ids = string({plan.configs([plan.configs.is_primary_configuration]).config_id});
count = numel(primary_ids) * size(plan.centers_deg, 1) * numel(plan.directions);
rows = cell(count, 1);
row_index = 0;
for config_id = primary_ids
    for center_index = 1:size(plan.centers_deg, 1)
        center = plan.centers_deg(center_index, :);
        for direction_index = 1:numel(plan.directions)
            direction_id = string(plan.directions(direction_index).direction_id);
            row_index = row_index + 1;
            selected = secant(secant.config_id == config_id & ...
                secant.center_az_deg == center(1) & ...
                secant.center_el_deg == center(2) & ...
                secant.direction_id == direction_id, :);
            selected = sortrows(selected, 'separation_norm_rad', 'ascend');
            valid = ~selected.numeric_floor_reached_flag & ...
                isfinite(selected.sigma2_ratio) & isfinite(selected.coherence_ratio) & ...
                isfinite(selected.normalized_gram_ratio);
            valid_rows = selected(valid, :);
            tail_count = min(3, height(valid_rows));
            tail = valid_rows(1:tail_count, :);
            if tail_count > 0
                sigma_error = max(abs(tail.sigma2_ratio - 1));
                coherence_error = max(abs(tail.coherence_ratio - 1));
                gram_error = max(abs(tail.normalized_gram_ratio - 1));
                minimum_r = min(tail.separation_norm_rad);
            else
                sigma_error = Inf; coherence_error = Inf; gram_error = Inf;
                minimum_r = NaN;
            end
            sigma_slope = error_slope_local(valid_rows.separation_norm_rad, ...
                abs(valid_rows.sigma2_ratio - 1));
            coherence_slope = error_slope_local(valid_rows.separation_norm_rad, ...
                abs(valid_rows.coherence_ratio - 1));
            gram_slope = error_slope_local(valid_rows.separation_norm_rad, ...
                abs(valid_rows.normalized_gram_ratio - 1));
            taylor_sum_slope = error_slope_local(selected.separation_norm_rad, ...
                selected.taylor_sum_residual);
            taylor_difference_slope = error_slope_local( ...
                selected.separation_norm_rad, selected.taylor_difference_residual);
            taylor_decrease = taylor_decrease_local(selected.taylor_sum_residual) && ...
                taylor_decrease_local(selected.taylor_difference_residual);
            pass = tail_count == 3 && ...
                sigma_error <= plan.controls.sigma2_ratio_error_gate && ...
                coherence_error <= plan.controls.coherence_ratio_error_gate && ...
                gram_error <= plan.controls.normalized_gram_ratio_error_gate && ...
                taylor_decrease;
            if tail_count < 3
                status = "INSUFFICIENT_ASYMPTOTIC_TAIL";
            elseif pass
                status = "NONDEGENERATE_ASYMPTOTIC_SUPPORTED";
            else
                status = "NONDEGENERATE_ASYMPTOTIC_FAILED";
            end
            fixed_hash = selected.fixed_measurement_hash(1);
            rows{row_index} = struct( ...
                'config_id', config_id, 'center_az_deg', center(1), ...
                'center_el_deg', center(2), 'direction_id', direction_id, ...
                'valid_point_count', height(valid_rows), ...
                'tail_point_count', tail_count, 'minimum_valid_r_rad', minimum_r, ...
                'max_sigma2_ratio_error', sigma_error, ...
                'max_coherence_ratio_error', coherence_error, ...
                'max_normalized_gram_ratio_error', gram_error, ...
                'sigma2_ratio_error_slope', sigma_slope, ...
                'coherence_ratio_error_slope', coherence_slope, ...
                'normalized_gram_ratio_error_slope', gram_slope, ...
                'taylor_sum_residual_slope', taylor_sum_slope, ...
                'taylor_difference_residual_slope', taylor_difference_slope, ...
                'taylor_residual_decrease_flag', taylor_decrease, ...
                'tail_status', status, 'fixed_measurement_hash', fixed_hash, ...
                'pass_flag', pass);
        end
    end
end
summary = add_metadata_local(struct2table(vertcat(rows{:})), context, "");
end

function table_out = exact_identity_table_local(secant, context)
valid = isfinite(secant.normalized_gram_condition) & ...
    isfinite(secant.normalized_gram_exact_from_rho) & ...
    secant.normalized_gram_exact_from_rho > 0;
selected = secant(valid, {'config_id','center_az_deg','center_el_deg', ...
    'direction_id','separation_norm_rad','normalized_gram_condition', ...
    'normalized_gram_exact_from_rho','fixed_measurement_hash'});
selected.relative_identity_error = abs(selected.normalized_gram_condition - ...
    selected.normalized_gram_exact_from_rho) ./ ...
    selected.normalized_gram_exact_from_rho;
selected.identity_roundoff_bound = ...
    context.plan.controls.exact_identity_roundoff_multiplier * ...
    eps .* selected.normalized_gram_exact_from_rho;
selected.identity_numerically_saturated_flag = ...
    selected.identity_roundoff_bound > ...
    context.plan.controls.exact_identity_relative_error_gate;
selected.pass_flag = selected.identity_numerically_saturated_flag | ...
    selected.relative_identity_error <= ...
    context.plan.controls.exact_identity_relative_error_gate;
table_out = add_metadata_local(selected, context, "");
end

function table_out = column_asymmetry_table_local(secant, context)
