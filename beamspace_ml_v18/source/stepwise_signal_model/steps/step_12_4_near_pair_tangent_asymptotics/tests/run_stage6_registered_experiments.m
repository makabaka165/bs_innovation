    'direction_id','separation_norm_rad','separation_norm_deg', ...
    'column_norm_minus','column_norm_plus','column_norm_ratio', ...
    'column_norm_log_ratio','raw_gram_condition', ...
    'normalized_gram_condition','fixed_measurement_hash'});
table_out.pass_flag = isfinite(table_out.column_norm_ratio) & ...
    table_out.column_norm_minus > 0 & table_out.column_norm_plus > 0;
table_out = add_metadata_local(table_out, context, "");
end

function table_out = synthetic_null_table_local(context)
r_values = context.plan.separation_rad(:);
rows = cell(numel(r_values), 1);
for index = 1:numel(r_values)
    r = r_values(index);
    g0 = [1; 0; 0]; g1 = [0; 0; 0]; g2 = [0; 0; 0]; g3 = [0; 0; 6];
    g_minus = [1; 0; (-r / 2) ^ 3];
    g_plus = [1; 0; (r / 2) ^ 3];
    out = compute_tangent_null_sixth_order( ...
        g0, g1, g2, g3, g_minus, g_plus, r);
    rows{index} = struct( ...
        'config_id', "SYNTHETIC_ANALYTIC_NULL", ...
        'center_az_deg', 0, 'center_el_deg', 0, ...
        'direction_id', "SYNTHETIC_Y", ...
        'separation_norm_rad', r, 'separation_norm_deg', rad2deg(r), ...
        'sigma2_sq', out.sigma2_sq, ...
        'exact_sigma2_sq', r ^ 6 / 32, ...
        'null_sigma2_prediction', out.null_sigma2_prediction, ...
        'null_sigma2_ratio', out.null_sigma2_ratio, ...
        'v3_eff_norm', out.v3_eff_norm, ...
        'projected_first_derivative_norm', out.projected_first_derivative_norm, ...
        'numeric_floor', 4096 * realmin, ...
        'fixed_measurement_hash', "SYNTHETIC_ANALYTIC_NULL", ...
        'pass_flag', abs(out.null_sigma2_ratio - 1) <= ...
        context.plan.controls.synthetic_null_ratio_error_gate);
end
table_out = struct2table(vertcat(rows{:}));
slope = polyfit(log(table_out.separation_norm_rad), log(table_out.sigma2_sq), 1);
table_out.fitted_order = repmat(slope(1), height(table_out), 1);
table_out.pass_flag = table_out.pass_flag & ...
    abs(slope(1) - 6) <= context.plan.controls.synthetic_null_slope_gate;
table_out = add_metadata_local(table_out, context, "");
end

function table_out = invariance_table_local(context)
primary_indices = find([context.plan.configs.is_primary_configuration]);
rows = cell(numel(primary_indices) * 3, 1);
row_index = 0;
center = [8, 10];
v = [1; 1] / sqrt(2);
r = deg2rad(0.05);
for model_index = primary_indices
    model = context.models{model_index};
    [g, J] = build_fixed_whitened_sequential_derivatives(center, model, struct());
    gm = manifold_offset_local(center, v, -r / 2, model);
    gp = manifold_offset_local(center, v, r / 2, model);
    base = quantities_local(g, J, gm, gp, v, r, context.plan);

    rng(4100 + model_index, 'twister');
    [Q, ~] = qr(complex(randn(numel(g), numel(g)), ...
        randn(numel(g), numel(g))), 0);
    unitary = quantities_local(Q * g, Q * J, Q * gm, Q * gp, ...
        v, r, context.plan);
    row_index = row_index + 1;
    rows{row_index} = invariance_row_local(model, 'FIXED_LEFT_UNITARY', ...
        base, unitary, 1, context);

    beta = 1.7 - 0.4j;
    scaled = quantities_local(beta * g, beta * J, beta * gm, beta * gp, ...
        v, r, context.plan);
    row_index = row_index + 1;
    rows{row_index} = invariance_row_local(model, 'FIXED_COMPLEX_SCALE', ...
        base, scaled, abs(beta) ^ 2, context);

    grad_psi = [0.3; -0.2];
    psi_center = grad_psi' * deg2rad(center(:));
    psi_minus = grad_psi' * (deg2rad(center(:)) - r * v / 2);
    psi_plus = grad_psi' * (deg2rad(center(:)) + r * v / 2);
    phase_g = exp(1j * psi_center) * g;
    phase_J = exp(1j * psi_center) * (J + 1j * g * grad_psi.');
    phase_case = quantities_local(phase_g, phase_J, ...
        exp(1j * psi_minus) * gm, exp(1j * psi_plus) * gp, ...
        v, r, context.plan);
    row_index = row_index + 1;
    rows{row_index} = invariance_row_local(model, ...
        'ANGLE_DEPENDENT_PHASE_GAUGE', base, phase_case, 1, context);
end
table_out = add_metadata_local(struct2table(vertcat(rows{:})), context, "");
end

function row = invariance_row_local(model, transform_id, base, transformed, ...
    scale_sq, context)
T_error = relative_error_local(transformed.T, scale_sq * base.T);
sigma_error = relative_scalar_error_local( ...
    transformed.sigma2_sq, scale_sq * base.sigma2_sq);
q_error = relative_scalar_error_local(transformed.q, scale_sq * base.q);
rho_error = abs(transformed.abs_rho - base.abs_rho);
condition_error = relative_scalar_error_local( ...
    transformed.normalized_condition, base.normalized_condition);
sigma_ratio_error = abs(transformed.sigma2_ratio - base.sigma2_ratio);
coherence_ratio_error = abs(transformed.coherence_ratio - base.coherence_ratio);
gram_ratio_error = abs(transformed.gram_ratio - base.gram_ratio);
maximum_error = max([T_error, sigma_error, q_error, rho_error, ...
    condition_error, sigma_ratio_error, coherence_ratio_error, gram_ratio_error]);
row = struct('config_id', string(model.config_id), ...
    'transform_id', string(transform_id), 'T_relative_error', T_error, ...
    'sigma2_relative_error', sigma_error, 'q_relative_error', q_error, ...
    'abs_rho_absolute_error', rho_error, ...
    'normalized_condition_relative_error', condition_error, ...
    'sigma2_ratio_absolute_error', sigma_ratio_error, ...
    'coherence_ratio_absolute_error', coherence_ratio_error, ...
    'normalized_gram_ratio_absolute_error', gram_ratio_error, ...
    'maximum_invariance_error', maximum_error, ...
    'fixed_measurement_hash', string(model.fixed_measurement_hash), ...
    'pass_flag', maximum_error <= ...
    context.plan.controls.invariance_relative_error_gate);
end

function q = quantities_local(g, J, gm, gp, v, r, plan)
metric = compute_projected_jacobian_metric(g, J, metric_options_local(plan));
q.q = real(v' * metric.T * v);
s = svd([gm, gp], 'econ');
q.sigma2_sq = s(2) ^ 2;
rho = abs((gm' * gp) / (norm(gm) * norm(gp)));
q.abs_rho = rho;
Gbar = [gm / norm(gm), gp / norm(gp)];
q.normalized_condition = cond(Gbar' * Gbar);
q.sigma2_ratio = q.sigma2_sq / (0.5 * r ^ 2 * q.q);
q.coherence_ratio = (1 - rho ^ 2) / (r ^ 2 * q.q / norm(g) ^ 2);
q.gram_ratio = q.normalized_condition / (4 * norm(g) ^ 2 / (r ^ 2 * q.q));
q.T = metric.T;
end

