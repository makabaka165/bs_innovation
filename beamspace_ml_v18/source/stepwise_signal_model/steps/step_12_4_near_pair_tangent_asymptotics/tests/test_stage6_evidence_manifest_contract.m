    "stage6_reproduction_comparison"; "stage6_evidence_manifest"; ...
    "stage6_self_reproduction_check"];
relative_path = ["results/core.csv"; "results/runtime.csv"; ...
    "figures/plot.png"; "results/comparison.csv"; ...
    "results/manifest.csv"; "results/self.csv"];
artifact_type = ["CSV"; "CSV"; "PNG"; "CSV"; "CSV"; "CSV"];
evidence_class = ["DETERMINISTIC_CORE"; "RUNTIME_DIAGNOSTIC"; ...
    "FIGURE_DIAGNOSTIC"; "COMPARISON_EVIDENCE"; "MANIFEST_META"; ...
    "SELF_REPRODUCTION_META"];
required_by_core_runner = [true; true; true; false; false; false];
required_by_final_freeze = true(6, 1);
included_in_deterministic_bundle = [true; false; false; true; false; false];
self_referential_exclusion_flag = [false; false; false; false; true; true];
registry = table(artifact_id, relative_path, artifact_type, evidence_class, ...
    required_by_core_runner, required_by_final_freeze, ...
    included_in_deterministic_bundle, self_referential_exclusion_flag);
end

function write_fixture_local(root)
write_text_local(root, 'results/core.csv', 'core');
write_text_local(root, 'results/runtime.csv', 'runtime');
write_text_local(root, 'figures/plot.png', 'png');
writetable(comparison_table_local(), ...
    fullfile(root, 'results', 'comparison.csv'));
end

