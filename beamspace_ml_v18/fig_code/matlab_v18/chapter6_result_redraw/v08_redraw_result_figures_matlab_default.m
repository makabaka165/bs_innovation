    'results_step11_2_b_budget_strategy_tradeoff', 'step11_2_b_budget_summary.csv'));
budget = budget(strcmp(budget.method_name, 'greedy_combined'), :);
[bvals, ~, g] = unique(budget.B);
succB = splitapply(@mean, budget.overall_joint_success_rate, g);
rmseB = splitapply(@mean, budget.overall_az_rmse_deg + budget.overall_el_rmse_deg, g);
[~, idxB7] = min(abs(bvals - 7));
fig = figure('Visible', 'off', 'Position', [100, 100, 1450, 440]);
subplot(1, 3, 1);
bar(categorical(methods), success, 'FaceColor', paper_color('blue'));
ylabel('overall joint success');
title('A. W strategy comparison');
ylim([0, 1]);
xtickangle(28);
grid on;
subplot(1, 3, 2);
yyaxis left;
plot(bvals, succB, '-o', 'LineWidth', 1.4);
ylabel('success');
ylim([0, 1.05]);
yyaxis right;
plot(bvals, rmseB, '-s', 'LineWidth', 1.4);
ylabel('RMSE proxy');
xlabel('B');
title('B. greedy-combined B budget');
xline(7, '--k', 'B=7');
grid on;
subplot(1, 3, 3);
bar(categorical({'B=7 success', 'B=7 RMSE', 'worst success'}), [succB(idxB7), rmseB(idxB7), 1], 'FaceColor', paper_color('green'));
title('C. Recommended point summary');
ylim([0, max(1.05, rmseB(idxB7) * 1.3)]);
