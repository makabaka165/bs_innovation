        otherwise
            labels(i) = strrep(policyNames(i), "_", " ");
    end
end
end

function kp = read_keypoints(path)
t = readtable(path, 'TextType', 'string');
kp = containers.Map('KeyType', 'char', 'ValueType', 'double');
if any(strcmp(t.Properties.VariableNames, 'keypoint')) && any(strcmp(t.Properties.VariableNames, 'value'))
    metricName = 'keypoint';
    valueName = 'value';
elseif any(strcmp(t.Properties.VariableNames, 'metric_value'))
    valueName = 'metric_value';
    metricName = t.Properties.VariableNames{1};
elseif any(strcmp(t.Properties.VariableNames, 'value'))
    valueName = 'value';
    metricName = t.Properties.VariableNames{1};
else
    for c = 1:numel(t.Properties.VariableNames)
        name = t.Properties.VariableNames{c};
        value = str2double(string(t.(name)(1)));
        if ~isnan(value)
            kp(name) = value;
        end
    end
    return;
end
for i = 1:height(t)
    key = char(t.(metricName)(i));
    val = str2double(string(t.(valueName)(i)));
    if ~isnan(val)
        kp(key) = val;
    end
end
end

function v = get_metric(kp, key, fallback)
if isKey(kp, key)
    v = kp(key);
else
    v = fallback;
end
end

function v = mean_num_pairs_by_model(summary, modelMode, fallback)
mask = strcmp(string(summary.model_mode), string(modelMode));
if any(mask)
    v = mean(summary.mean_num_pairs(mask), 'omitnan');
else
    v = fallback;
end
end

