function draw_c05_decision(v07CsvDir, figDir, localFigDir)
topk = readtable(fullfile(v07CsvDir, 'v07_likelihood_surface_topk_and_refine.csv'));
scores = topk.score;
scoreNorm = (scores - min(scores)) ./ (max(scores) - min(scores) + eps);
prob = exp(scoreNorm ./ 0.25 - max(scoreNorm ./ 0.25));
prob = prob ./ sum(prob);
hNorm = -sum(prob .* log(prob + eps)) ./ log(numel(prob));
gap13 = max(scoreNorm(1) - scoreNorm(3), 0);
gapRisk = 1 - min(gap13 / 0.45, 1);
boundary = 0;
condRisk = 0.18;
uSearch = 0.65 * gapRisk + 0.30 * boundary + 0.05 * min(hNorm, 0.5);
uConf = 0.35 * hNorm + 0.25 * gapRisk + 0.25 * condRisk + 0.15 * boundary;
fig = figure('Visible', 'off');
subplot(1, 2, 1);
plot(topk.rank, scoreNorm, '-o');
xlabel('候选排序');
ylabel('归一化 DML 评分');
title('top7 粗评分曲线');
grid on;
subplot(1, 2, 2);
bar([hNorm, gap13, boundary, condRisk, uSearch, uConf]);
set(gca, 'XTickLabel', {'H\_norm', 'gap\_13', '边界风险', '条件风险', 'U\_search', 'U\_conf'});
xtickangle(35);
ylabel('特征值');
title('C05 决策特征');
grid on;
save_fig(fig, figDir, localFigDir, 'fig_v08_08_c05_decision_real_case_cn.png');
end

function draw_three_case(v07CsvDir, figDir, localFigDir)
t = readtable(fullfile(v07CsvDir, 'v07_representative_backend_outputs.csv'));
names = containers.Map({'easy_noncoherent', 'strong_coherent', 'low_snr_hard'}, ...
    {'简单非相干', '强相干', '低信噪比困难'});
fig = figure('Visible', 'off', 'Position', [100, 100, 660, 920]);
for i = 1:height(t)
    subplot(3, 1, i);
    hold on;
    truthAz = [t.truth_az1(i), t.truth_az2(i)];
    truthEl = [t.truth_el1(i), t.truth_el2(i)];
    fixedAz = [t.fixed_az1(i), t.fixed_az2(i)];
    fixedEl = [t.fixed_el1(i), t.fixed_el2(i)];
    directAz = [t.c05_direct_az1(i), t.c05_direct_az2(i)];
    directEl = [t.c05_direct_el1(i), t.c05_direct_el2(i)];
    cachedAz = [t.c05_cached_az1(i), t.c05_cached_az2(i)];
    cachedEl = [t.c05_cached_el1(i), t.c05_cached_el2(i)];
    plot(truthAz, truthEl, 'ko', 'MarkerSize', 8, 'LineWidth', 1.2);
    plot(fixedAz, fixedEl, 's', 'MarkerSize', 8, 'LineWidth', 1.2);
    plot(directAz, directEl, '^', 'MarkerSize', 8, 'LineWidth', 1.2);
    plot(cachedAz, cachedEl, 'x', 'MarkerSize', 8, 'LineWidth', 1.2);
    xlabel('方位角 / deg');
    ylabel('俯仰角 / deg');
    caseName = string(t.case_name{i});
    if isKey(names, char(caseName))
        cnName = names(char(caseName));
    else
        cnName = char(caseName);
    end
    title({cnName, sprintf('policy=%s, 候选比=%.3f', t.policy_name{i}, t.candidate_ratio(i))});
    grid on;
    xs = [truthAz, fixedAz, directAz, cachedAz];
    ys = [truthEl, fixedEl, directEl, cachedEl];
    xPad = max(0.08, 0.18 * max(max(xs) - min(xs), eps));
    yPad = max(0.08, 0.18 * max(max(ys) - min(ys), eps));
    xlim([min(xs) - xPad, max(xs) + xPad]);
    ylim([min(ys) - yPad, max(ys) + yPad]);
    if i == 1
        legend({'truth', 'fixed TopK3', 'C05 direct', 'C05 cached'}, ...
            'Location', 'eastoutside');
    end
end
save_fig(fig, figDir, localFigDir, 'fig_v08_09_three_case_estimation_cn.png');
end

function draw_error_vectors(v07CsvDir, figDir, localFigDir)
t = readtable(fullfile(v07CsvDir, 'v07_representative_backend_outputs.csv'));
names = containers.Map({'easy_noncoherent', 'strong_coherent', 'low_snr_hard'}, ...
    {'简单非相干', '强相干', '低信噪比困难'});
fig = figure('Visible', 'off', 'Position', [100, 100, 660, 920]);
truthAll = [];
fixedAll = [];
c05All = [];
for k = 1:height(t)
    truthAll = [truthAll; mean([t.truth_az1(k), t.truth_az2(k)]), mean([t.truth_el1(k), t.truth_el2(k)])]; %#ok<AGROW>
    fixedAll = [fixedAll; mean([t.fixed_az1(k), t.fixed_az2(k)]), mean([t.fixed_el1(k), t.fixed_el2(k)])]; %#ok<AGROW>
    c05All = [c05All; mean([t.c05_direct_az1(k), t.c05_direct_az2(k)]), mean([t.c05_direct_el1(k), t.c05_direct_el2(k)])]; %#ok<AGROW>
end
allPts = [truthAll; fixedAll; c05All];
span = max(max(allPts, [], 1) - min(allPts, [], 1));
span = max(span, 0.4);
halfSpan = span * 0.58;
for i = 1:height(t)
    subplot(3, 1, i);
    hold on;
    truth = [mean([t.truth_az1(i), t.truth_az2(i)]), mean([t.truth_el1(i), t.truth_el2(i)])];
    fixed = [mean([t.fixed_az1(i), t.fixed_az2(i)]), mean([t.fixed_el1(i), t.fixed_el2(i)])];
    c05 = [mean([t.c05_direct_az1(i), t.c05_direct_az2(i)]), mean([t.c05_direct_el1(i), t.c05_direct_el2(i)])];
    plot(truth(1), truth(2), 'ko', 'MarkerSize', 8, 'LineWidth', 1.2);
    quiver(truth(1), truth(2), fixed(1) - truth(1), fixed(2) - truth(2), 0, ...
        'LineWidth', 1.3, 'Color', paper_color('blue'), 'MaxHeadSize', 0.8);
    quiver(truth(1), truth(2), c05(1) - truth(1), c05(2) - truth(2), 0, ...
        'LineWidth', 1.3, 'Color', paper_color('green'), 'MaxHeadSize', 0.8);
    xlabel('方位角 / deg');
    ylabel('俯仰角 / deg');
    caseName = string(t.case_name{i});
    if isKey(names, char(caseName))
        cnName = names(char(caseName));
    else
        cnName = char(caseName);
    end
    if norm(c05 - truth) < 1e-6 || norm(c05 - fixed) < 1e-6
        title({cnName, 'C05 与 truth/fixed 近重合'});
    else
        title(cnName);
    end
    grid on;
    xlim([truth(1) - halfSpan, truth(1) + halfSpan]);
    ylim([truth(2) - halfSpan, truth(2) + halfSpan]);
    axis square;
    if i == 1
        legend({'truth center', 'fixed topK3', 'C05'}, 'Location', 'eastoutside');
    end
end
save_fig(fig, figDir, localFigDir, 'fig_v08_10_error_vector_comparison_cn.png');
end

