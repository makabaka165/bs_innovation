function labels = case_labels_cn(caseNames)
caseNames = string(caseNames);
labels = strings(size(caseNames));
for i = 1:numel(caseNames)
    switch char(caseNames(i))
        case 'easy_noncoherent'
            labels(i) = "简单非相干";
        case 'low_snr_hard'
            labels(i) = "低信噪比困难";
        case 'strong_coherent'
            labels(i) = "强相干";
        otherwise
            labels(i) = strrep(caseNames(i), "_", " ");
    end
end
end

function labels = policy_labels_cn(policyNames)
policyNames = string(policyNames);
labels = strings(size(policyNames));
for i = 1:numel(policyNames)
