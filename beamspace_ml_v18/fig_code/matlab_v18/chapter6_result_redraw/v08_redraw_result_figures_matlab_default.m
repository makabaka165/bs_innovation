function v08_redraw_result_figures_matlab_default(target)
% Redraw selected v0.12 figures with MATLAB-default-like styling.
% This script lives in the paper project and only reads archived CSV outputs.
if nargin < 1
    target = "all";
end
target = string(target);

scriptDir = fileparts(mfilename('fullpath'));
figureCodeRoot = fileparts(scriptDir);
packageRoot = fileparts(fileparts(figureCodeRoot));
algRoot = fullfile(packageRoot, 'source', 'stepwise_signal_model');
figDir = fullfile(figureCodeRoot, 'outputs', 'chapter6_figures');
localFigDir = fullfile(figureCodeRoot, 'outputs', 'chapter6_local_copy');
v07CsvDir = fullfile(packageRoot, 'evidence', 'visual_v07', 'csv');
if ~exist(figDir, 'dir'), mkdir(figDir); end
if ~exist(localFigDir, 'dir'), mkdir(localFigDir); end

if any(target == ["all", "pair2d"])
    draw_pair2d_parameterization(figDir, localFigDir);
end
if any(target == ["all", "likelihood_surface"])
    draw_likelihood_surface(v07CsvDir, figDir, localFigDir);
end
if any(target == ["all", "c05_decision"])
    draw_c05_decision(v07CsvDir, figDir, localFigDir);
end
if any(target == ["all", "three_case"])
    draw_three_case(v07CsvDir, figDir, localFigDir);
end
if any(target == ["all", "error_vectors"])
    draw_error_vectors(v07CsvDir, figDir, localFigDir);
end
if any(target == ["all", "model_comparison"])
    draw_model_comparison(algRoot, figDir, localFigDir);
end
if any(target == ["all", "w_selection"])
    draw_w_selection_budget(algRoot, figDir, localFigDir);
end
if any(target == ["all", "coarse_to_fine"])
    draw_coarse_to_fine(algRoot, figDir, localFigDir);
end
if any(target == ["all", "c05_policy"])
    draw_c05_policy_curve(algRoot, v07CsvDir, figDir, localFigDir);
end
if any(target == ["all", "cache_runtime"])
    draw_cache_backend_runtime(algRoot, figDir, localFigDir);
end
if any(target == ["all", "case_boundary"])
    draw_case_boundary_summary(v07CsvDir, figDir, localFigDir);
end

logDir = fullfile(figureCodeRoot, 'outputs', 'logs');
if ~exist(logDir, 'dir'), mkdir(logDir); end
fid = fopen(fullfile(logDir, 'v12_matlab_default_result_figures.log'), 'w');
fprintf(fid, 'Selected v0.12 figures redrawn with MATLAB default style on %s\n', datestr(now, 31));
fprintf(fid, 'Figure 3-1 pair2d parameterization is now generated by MATLAB in this paper project.\n');
fprintf(fid, 'Figure 5-4 keeps only the score and feature plots; policy prose is moved to the manuscript text.\n');
fprintf(fid, 'No stepwise_signal_model files were modified.\n');
fclose(fid);
end

function draw_pair2d_parameterization(figDir, localFigDir)
t1 = [-0.62, 10.08];
t2 = [0.62, 10.62];
c = (t1 + t2) ./ 2;
deltaAz = t2(1) - t1(1);
deltaEl = t2(2) - t1(2);

fig = figure('Visible', 'off', 'Position', [100, 100, 820, 520]);
hold on;
grid on;
axis equal;

hPair = plot([t1(1), t2(1)], [t1(2), t2(2)], '-o', 'LineWidth', 1.2);
hCenter = plot(c(1), c(2), 'x', 'MarkerSize', 10, 'LineWidth', 1.5);
hCommon = yline(c(2), '--');
hFull = plot([t1(1), t2(1)], [t1(2), t2(2)], 's', 'MarkerSize', 7, 'LineWidth', 1.0);

plot([t1(1), t2(1)], [t1(2), t1(2)], ':', 'HandleVisibility', 'off');
plot([t2(1), t2(1)], [t1(2), t2(2)], ':', 'HandleVisibility', 'off');
quiver(c(1), c(2), 0.32, 0.14, 0, 'LineWidth', 1.1, 'HandleVisibility', 'off');

text(t1(1) - 0.10, t1(2) - 0.07, '目标 1');
text(t2(1) + 0.03, t2(2) + 0.03, '目标 2');
text(c(1) + 0.04, c(2) - 0.05, '中心 (az_c, el_c)');
text(mean([t1(1), t2(1)]) - 0.10, t1(2) - 0.10, sprintf('\\Delta az=%.2f deg', deltaAz));
text(t2(1) + 0.05, mean([t1(2), t2(2)]), sprintf('\\Delta el=%.2f deg', deltaEl));
text(c(1) + 0.34, c(2) + 0.13, '方向 q');
text(-1.08, 10.82, {'common-el: \Delta el=0', 'full4D: 两个点独立'});

xlabel('方位角 / deg');
ylabel('俯仰角 / deg');
title('controlled pair2d 参数化示意');
legend([hPair, hCenter, hCommon, hFull], ...
    {'pair2d 目标连线', '中心点', 'common-el 退化线', 'full4D 独立目标'}, ...
    'Location', 'southoutside', 'Orientation', 'horizontal', 'NumColumns', 2);
xlim([-1.2, 1.35]);
ylim([9.7, 10.9]);
save_fig(fig, figDir, localFigDir, 'fig_v08_02_pair2d_parameterization_cn.png');
end

